import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=r=>fs.readFileSync(path.join(root,r),'utf8');
let pass=0,fail=0;
const check=(c,m)=>{console.log(`${c?'PASS':'FAIL'} | ${m}`);c?pass++:fail++;};
const java=read('backend/src/main/java/com/behsazan/corebanking/productbuilder/application/PdlReferenceOptionService.java');
const build=read('build-production.cmd');
const partyMap=java.match(/PARTY_RESOURCE_BY_COLUMN\s*=\s*Map\.ofEntries\(([\s\S]*?)\n\s*\);/m)?.[1] ?? '';
check(partyMap.length>0,'party reference resource map is present');
check(!/,\s*$/.test(partyMap.trim()),'party reference Map.ofEntries has no illegal trailing argument comma');
check(java.includes('Map.entry("RESIDENCY_STATUS_CODE", "ref-residence-status")\n    );'),'residency mapping closes with Java-valid syntax');
check(!/Map\.entry\([^\n]+\),\s*\n\s*\);/.test(java),'no Map.ofEntries block ends with a trailing comma before close');
check(build.includes('verify-pdl-r10t-hf1-java-compile.mjs'),'HF1 Java syntax regression guard is wired into production build');
console.log('------------------------------------------------------------');
console.log(`PDL_R10T_HF1_JAVA_COMPILE_PASS=${pass}`);
console.log(`PDL_R10T_HF1_JAVA_COMPILE_FAIL=${fail}`);
if(fail) process.exit(1);
console.log('PDL_R10T_HF1_JAVA_COMPILE_STATIC_PASS');
