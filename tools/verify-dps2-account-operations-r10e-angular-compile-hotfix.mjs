import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('frontend/src/app/features/four-deposits/deposit-account-operations.component.html');
const svc=read('frontend/src/app/features/four-deposits/deposit-account-operations.service.ts');
const build=read('build-production.cmd');
let pass=0,fail=0;
const check=(n,o)=>{if(o){pass++;console.log(`PASS | ${n}`)}else{fail++;console.log(`FAIL | ${n}`)}};
check('DepositTransactionRecord exposes amount',/interface DepositTransactionRecord\{[^}]*\bamount:number\b/.test(svc));
check('tax transaction selector uses canonical amount property',html.includes('moneyFa(t.transaction.amount)'));
check('obsolete transactionAmount binding is absent',!html.includes('t.transaction.transactionAmount'));
check('tax transaction selector still uses transaction id',html.includes('[value]="t.transaction.transactionId"'));
check('tax transaction selector still localizes transaction type',html.includes('uiLabel(t.transaction.transactionTypeCode)'));
check('R10E verifier is wired into production build',build.includes('verify-dps2-account-operations-r10e-angular-compile-hotfix.mjs'));
console.log('------------------------------------------------------------');
console.log(`DPS2_ACCOUNT_OPERATIONS_R10E_PASS=${pass}`);
console.log(`DPS2_ACCOUNT_OPERATIONS_R10E_FAIL=${fail}`);
if(!fail)console.log('DPS2_ACCOUNT_OPERATIONS_R10E_STATIC_PASS');else process.exitCode=1;
