import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('frontend/src/app/features/four-deposits/deposit-account-operations.component.html');
const r10d=read('tools/verify-dps2-account-operations-localization-r10d.mjs');
let pass=0,fail=0;
const check=(n,o)=>{if(o){pass++;console.log(`PASS | ${n}`)}else{fail++;console.log(`FAIL | ${n}`)}};
check('R10I lifecycle grid keeps business event reference',html.includes('lifecycleEventReferenceDisplay(e)'));
check('R10I current hold grid keeps business request reference',html.includes('holdRequestReferenceDisplay(h)'));
check('R10I status history keeps business reference',html.includes('statusHistoryReferenceDisplay(h)'));
check('R10I hold history keeps business reference',html.includes('holdHistoryReferenceDisplay(h)'));
check('R10D verifier accepts R10I lifecycle business reference',r10d.includes("lifecycle.includes('lifecycleEventReferenceDisplay(e)')"));
check('R10D verifier accepts R10I hold business reference',r10d.includes("lifecycle.includes('holdRequestReferenceDisplay(h)')"));
check('R10D verifier accepts R10I status-history business reference',r10d.includes("lifecycle.includes('statusHistoryReferenceDisplay(h)')"));
check('R10D verifier accepts R10I hold-history business reference',r10d.includes("lifecycle.includes('holdHistoryReferenceDisplay(h)')"));
check('no legacy raw lifecycle UUID expression restored to visible UI',!html.includes("{{referenceDisplay(e.correlationId,'مرجع رویداد')}}"));
check('no legacy raw hold request expression restored to visible UI',!html.includes("{{referenceDisplay(h.originRequestRef,'مرجع درخواست')}}"));
console.log('------------------------------------------------------------');
console.log(`DPS2_ACCOUNT_OPERATIONS_R10J_PASS=${pass}`);
console.log(`DPS2_ACCOUNT_OPERATIONS_R10J_FAIL=${fail}`);
if(!fail)console.log('DPS2_ACCOUNT_OPERATIONS_R10J_STATIC_PASS');else process.exitCode=1;
