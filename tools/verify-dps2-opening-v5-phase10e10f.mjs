import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const checks=[];
const ok=(name,cond)=>checks.push([name,!!cond]);
const batchSvc=read('backend/src/main/java/com/behsazan/corebanking/deposit/opening/batch/application/DepositOpeningBatchService.java');
const batchRepo=read('backend/src/main/java/com/behsazan/corebanking/deposit/opening/batch/oracle/DepositOpeningBatchRepository.java');
const aggSvc=read('backend/src/main/java/com/behsazan/corebanking/deposit/opening/application/DepositOpeningAggregateService.java');
const aggRepo=read('backend/src/main/java/com/behsazan/corebanking/deposit/opening/oracle/DepositOpeningAggregateRepository.java');
const models=read('backend/src/main/java/com/behsazan/corebanking/deposit/opening/domain/DepositOpeningModels.java');
const controller=read('backend/src/main/java/com/behsazan/corebanking/deposit/opening/web/DepositOpeningController.java');
const batchTs=read('frontend/src/app/features/four-deposits/deposit-opening-batch.component.ts');
const batchHtml=read('frontend/src/app/features/four-deposits/deposit-opening-batch.component.html');
const wizTs=read('frontend/src/app/features/four-deposits/deposit-opening-wizard.component.ts');
const feSvc=read('frontend/src/app/features/four-deposits/deposit-opening.service.ts');
const runtime=read('tools/runtime-dps2-phase10f-e2e.mjs');

ok('v5 batch legal basis enforced',batchSvc.includes('GOV_EMPLOYEE_SAVINGS_1376'));
ok('v5 batch family QARD only',batchSvc.includes('QARD_SAVINGS'));
ok('batch direct process remains blocked',batchSvc.includes('پردازش مستقیم Batch') && batchSvc.includes('Create Gate فردی'));
ok('batch direct activation remains blocked',batchSvc.includes('فعال‌سازی مستقیم گروهی'));
ok('batch refresh endpoint',controller.includes('/batches/{batchId}/refresh'));
ok('batch refresh service',batchSvc.includes('BatchView refresh('));
ok('batch progress derives success only from ACTIVE/CLOSED account',batchSvc.includes('"ACTIVE".equals') && batchSvc.includes('"CLOSED".equals'));
ok('processing item protected from revalidation',batchSvc.includes('"PROCESSING".equals(upper(item.itemStatusCode()))'));
ok('batch item account link derives from request account',batchRepo.includes('COALESCE(I.ACCOUNT_ID, R.CREATED_ACCOUNT_ID)'));
ok('opening request carries BATCH_ITEM_ID',models.includes('@JsonProperty("BATCH_ITEM_ID") Long batchItemId'));
ok('request SQL persists BATCH_ITEM_ID',aggRepo.includes('REQUEST_STATUS_CODE, BATCH_ITEM_ID, CREATED_BY'));
ok('batch opening link is VALID-only',aggRepo.includes("ITEM_STATUS_CODE='VALID'") && aggRepo.includes('OPENING_REQUEST_ID IS NULL'));
ok('batch request must be BULK',aggSvc.includes('REQUEST_TYPE_CODE=BULK'));
ok('aggregate links batch item transactionally',aggSvc.includes('repository.linkBatchItemOpening'));
ok('frontend batch refresh wiring',feSvc.includes('refreshBatch(batchId:number)') && batchTs.includes('refreshBatch():Promise<void>'));
ok('frontend batch handoff router',batchHtml.includes('تکمیل Opening فردی') && batchHtml.includes('[queryParams]="openingQuery(item)"'));
ok('wizard consumes batchItemId query param',wizTs.includes("params.get('batchItemId')"));
ok('wizard forces BULK request type for batch handoff',wizTs.includes("requestType.setValue('BULK')"));
ok('wizard prefills item party without CDD fabrication',wizTs.includes("role:'OWNER',primary:true,share:100") && !wizTs.includes('BATCH_CDD_AUTO_PASS'));
ok('wizard payload sends BATCH_ITEM_ID',wizTs.includes('BATCH_ITEM_ID:v.batchItemId'));
ok('four deposit families remain present', ['QARD_SAVINGS','CURRENT_ACCOUNT','SHORT_TERM_DEPOSIT','LONG_TERM_DEPOSIT'].every(x=>wizTs.includes(x)));
ok('opening order create settlement readiness activate retained',wizTs.includes('createAccount') && wizTs.includes('settle') && wizTs.includes('readiness') && wizTs.includes('activate'));
ok('runtime e2e harness exists',runtime.includes('QARD_SAVINGS') && runtime.includes('CURRENT_ACCOUNT') && runtime.includes('SHORT_TERM_DEPOSIT') && runtime.includes('LONG_TERM_DEPOSIT'));
ok('runtime harness validates before persist',runtime.includes('/requests/validate'));
ok('runtime harness creates account',runtime.includes('/account'));
ok('runtime harness settles',runtime.includes('/account/settlement'));
ok('runtime harness checks readiness',runtime.includes('/account/readiness'));
ok('runtime harness activates',runtime.includes('/account/activate'));
ok('runtime harness supports optional close',runtime.includes('/api/v1/deposit-accounts/') && runtime.includes('/close'));
ok('runtime harness refuses placeholder evidence',runtime.includes('assertNoPlaceholders'));

let failed=0;
for(const [name,pass] of checks){console.log(`${pass?'OK ':'FAIL'} ${name}`);if(!pass)failed++;}
console.log(`DPS2 Operational Opening v5 Phase 10E/10F verification: ${checks.length-failed}/${checks.length} passed.`);
if(failed) process.exit(1);
