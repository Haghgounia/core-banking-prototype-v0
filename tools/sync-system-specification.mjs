import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const frontendPackage = JSON.parse(readFileSync(join(root, 'frontend', 'package.json'), 'utf8'));
const pom = readFileSync(join(root, 'backend', 'pom.xml'), 'utf8');
const release = readFileSync(join(root, 'VERSION'), 'utf8').trim();

function xmlValue(tag, source = pom) {
  const match = source.match(new RegExp(`<${tag}>([^<]+)</${tag}>`));
  if (!match) {
    throw new Error(`Cannot resolve <${tag}> from backend/pom.xml`);
  }
  return match[1].trim();
}

function dependencyVersion(groupId, artifactId) {
  const dependencyPattern = new RegExp(
    `<dependency>\\s*<groupId>${groupId.replaceAll('.', '\\.')}</groupId>\\s*` +
    `<artifactId>${artifactId}</artifactId>\\s*<version>([^<]+)</version>`,
    'm'
  );
  const match = pom.match(dependencyPattern);
  if (!match) {
    throw new Error(`Cannot resolve dependency version for ${groupId}:${artifactId}`);
  }
  return match[1].trim();
}

function packageVersion(name, section) {
  const value = frontendPackage[section]?.[name];
  if (!value) {
    throw new Error(`Cannot resolve ${name} from frontend/package.json`);
  }
  return value.replace(/^[~^]/, '');
}

const springBootParent = pom.match(
  /<parent>\s*<groupId>org\.springframework\.boot<\/groupId>\s*<artifactId>spring-boot-starter-parent<\/artifactId>\s*<version>([^<]+)<\/version>/m
)?.[1]?.trim();

if (!springBootParent) {
  throw new Error('Cannot resolve Spring Boot parent version from backend/pom.xml');
}

const output = `// Generated by tools/sync-system-specification.mjs. Do not edit manually.\n` +
`export const GENERATED_SYSTEM_VERSIONS = {\n` +
`  release: ${JSON.stringify(release)},\n` +
`  java: ${JSON.stringify(xmlValue('java.version'))},\n` +
`  springBoot: ${JSON.stringify(springBootParent)},\n` +
`  oracleJdbc: ${JSON.stringify(dependencyVersion('com.oracle.database.jdbc', 'ojdbc11'))},\n` +
`  angular: ${JSON.stringify(packageVersion('@angular/core', 'dependencies'))},\n` +
`  angularMaterial: ${JSON.stringify(packageVersion('@angular/material', 'dependencies'))},\n` +
`  rxjs: ${JSON.stringify(packageVersion('rxjs', 'dependencies'))},\n` +
`  typescript: ${JSON.stringify(packageVersion('typescript', 'devDependencies'))}\n` +
`} as const;\n`;

const target = join(
  root,
  'frontend', 'src', 'app', 'features', 'system-specification',
  'system-version.generated.ts'
);
writeFileSync(target, output, 'utf8');
console.log(`System specification versions synchronized for ${release}.`);
