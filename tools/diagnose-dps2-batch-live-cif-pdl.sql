-- Oracle read-only diagnostics for Batch Opening / Operational v5
-- Run using an account with SELECT privileges on CIF and PDL.

PROMPT === Available, currently open QARD_SAVINGS deposit product versions (IRR) ===
SELECT PV.PRODUCT_VERSION_ID, PV.PRODUCT_ID, P.PRODUCT_CODE, P.PRODUCT_NAME,
       P.DEFAULT_CURRENCY_CODE, PV.VERSION_STATUS_CODE,
       PV.ORIGINATION_STATUS_CODE, PV.RECORD_STATUS_CODE,
       PV.VALID_FROM, PV.VALID_TO
  FROM PDL.PRODUCT_VERSION PV
  JOIN PDL.PRODUCT P ON P.PRODUCT_ID = PV.PRODUCT_ID
 WHERE UPPER(P.PRODUCT_CLASS_CODE) = 'DEPOSIT'
   AND UPPER(P.PRODUCT_FAMILY_CODE) = 'QARD_SAVINGS'
   AND (P.PRODUCT_STATUS_CODE IS NULL OR UPPER(P.PRODUCT_STATUS_CODE) IN ('ACTIVE','APPROVED'))
   AND (P.DEFAULT_CURRENCY_CODE IS NULL OR UPPER(P.DEFAULT_CURRENCY_CODE) = 'IRR')
   AND (PV.VERSION_STATUS_CODE IS NULL OR UPPER(PV.VERSION_STATUS_CODE) IN ('ACTIVE','APPROVED'))
   AND (PV.ORIGINATION_STATUS_CODE IS NULL OR UPPER(PV.ORIGINATION_STATUS_CODE) = 'OPEN')
   AND (PV.RECORD_STATUS_CODE IS NULL OR UPPER(PV.RECORD_STATUS_CODE) = 'ACTIVE')
   AND (PV.VALID_FROM IS NULL OR TRUNC(PV.VALID_FROM) <= TRUNC(SYSDATE))
   AND (PV.VALID_TO IS NULL OR TRUNC(PV.VALID_TO) >= TRUNC(SYSDATE))
 ORDER BY P.PRODUCT_CODE, PV.PRODUCT_VERSION_ID;

PROMPT === Original sample identifiers: availability check ===
SELECT 'CIF.PARTY 100001' AS SOURCE_ID, COUNT(*) AS FOUND
  FROM CIF.PARTY WHERE PARTY_ID = 100001
UNION ALL
SELECT 'PDL.PRODUCT_VERSION 3102', COUNT(*)
  FROM PDL.PRODUCT_VERSION WHERE PRODUCT_VERSION_ID = 3102;

