PROMPT === R4C3 A. QARD ITEMS (FOUR EXPECTED REFERENCE CODES) ===
SELECT I.CALC_CODE,I.TITLE_FA,I.OPERATION_CODE,I.AMOUNT_KIND_CODE,
       I.IS_ENABLED,V.STATUS_CODE,V.IS_ACTIVE,V.TARIFF_ORIGIN_CODE,
       V.BASE_METHOD_CODE,V.TAX_MODE_CODE,R.FORMULA_CODE,
       R.RATE_SOURCE_CODE,R.RATE_PERCENT
FROM FEE3.FCE_CALC_ITEM I
JOIN FEE3.FCE_TARIFF_VERSION V ON V.CALC_ITEM_ID=I.CALC_ITEM_ID
JOIN FEE3.FCE_CALC_RULE R ON R.TARIFF_VERSION_ID=V.TARIFF_VERSION_ID
WHERE I.CALC_CODE IN ('FCE-000235','FCE-000236','FCE-000237','FCE-000238')
ORDER BY I.CALC_CODE,V.VERSION_NO,R.RULE_ORDER;
PROMPT === R4C3 B. QARD TIMING AND YEAR START SOURCED FROM ORACLE JSON ===
SELECT I.CALC_CODE,
       JSON_VALUE(V.FINANCIAL_POLICY_JSON,'$.loanPolicy.qardChargeTiming'
           RETURNING VARCHAR2(50)) AS QARD_CHARGE_TIMING,
       JSON_VALUE(V.FINANCIAL_POLICY_JSON,'$.loanPolicy.yearStartBasis'
           RETURNING VARCHAR2(50)) AS YEAR_START_BASIS,
       JSON_VALUE(V.FINANCIAL_POLICY_JSON,'$.loanPolicy.dayCountBasis'
           RETURNING VARCHAR2(50)) AS DAY_COUNT_BASIS,
       JSON_VALUE(V.FINANCIAL_POLICY_JSON,'$.loanPolicy.holidayPolicy'
           RETURNING VARCHAR2(50)) AS HOLIDAY_POLICY
FROM FEE3.FCE_CALC_ITEM I
JOIN FEE3.FCE_TARIFF_VERSION V ON V.CALC_ITEM_ID=I.CALC_ITEM_ID
WHERE I.CALC_CODE IN ('FCE-000235','FCE-000236','FCE-000237','FCE-000238')
ORDER BY I.CALC_CODE,V.VERSION_NO;
PROMPT === R4C3 C. QARD OPERATION REFERENCE ===
SELECT O.OPERATION_CODE,O.MODULE_CODE,O.IS_ACTIVE,
       DBMS_LOB.SUBSTR(O.ALLOWED_AMOUNT_KINDS_JSON,1000,1) AS ALLOWED_KINDS
FROM FEE3.FCE_REF_OPERATION O
WHERE O.MODULE_CODE='LOAN' AND O.OPERATION_CODE='QARD_FEE';
PROMPT === R4C3 D. CAL2 PERSIAN ACTIVE DEFAULT CALENDAR MAPPING FOR BANK DAY ===
SELECT D.ISO_DATE_TEXT,C.YEAR_NO,C.MONTH_NO,C.DAY_NO,C.DAY_OF_YEAR,
       C.IS_LEAP_YEAR,C.CALENDAR_VARIANT_ID,C.DATASET_VERSION_ID
FROM CAL2.CALENDAR_DATE C
JOIN CAL2.CANONICAL_DAY D ON D.DAY_ID=C.DAY_ID
JOIN CAL2.CALENDAR_VARIANT V ON V.CALENDAR_VARIANT_ID=C.CALENDAR_VARIANT_ID
JOIN CAL2.CALENDAR_SYSTEM S ON S.CALENDAR_SYSTEM_ID=V.CALENDAR_SYSTEM_ID
WHERE S.CALENDAR_CODE='PERSIAN' AND S.ACTIVE_FLAG='Y'
  AND V.ACTIVE_FLAG='Y' AND V.IS_DEFAULT='Y'
  AND D.CANONICAL_DATE=TRUNC(CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Tehran' AS DATE));
PROMPT === R4C3 E. ITEM AND VERSION COUNTS (BEFORE/AFTER RUNTIME) ===
SELECT 'FCE_CALC_ITEM' AS OBJECT_NAME,COUNT(*) AS ROW_COUNT FROM FEE3.FCE_CALC_ITEM
UNION ALL SELECT 'FCE_TARIFF_VERSION',COUNT(*) FROM FEE3.FCE_TARIFF_VERSION;
