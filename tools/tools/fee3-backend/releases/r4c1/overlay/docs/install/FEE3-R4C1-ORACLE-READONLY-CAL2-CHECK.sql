-- FEE3 R4-C1 | SELECT ONLY | Oracle SQL Developer F5
-- Checks reference-code drift, CAL2 active Persian variant, canonical day coverage and FEE3 baseline.
-- NO DML / DDL / COMMIT. Does not repair FEE3 data.
SET SERVEROUTPUT ON SIZE UNLIMITED
PROMPT === R4C1 A. ORACLE BANK BUSINESS DATE ===
SELECT TRUNC(CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Tehran' AS DATE)) AS BANK_BUSINESS_DATE FROM DUAL;
PROMPT === R4C1 B. HOLIDAY POLICY REF/SEED MISMATCH (EXPECT 9 ROWS OF UNMAPPED CODE) ===
SELECT P.HOLIDAY_POLICY,COUNT(*) AS UNMAPPED_VERSION_COUNT
FROM (SELECT JSON_VALUE(V.FINANCIAL_POLICY_JSON,'$.loanPolicy.holidayPolicy' RETURNING VARCHAR2(80)) AS HOLIDAY_POLICY
      FROM FEE3.FCE_TARIFF_VERSION V
      JOIN FEE3.FCE_CALC_ITEM I ON I.CALC_ITEM_ID=V.CALC_ITEM_ID
      WHERE I.AMOUNT_KIND_CODE='LATE_DAMAGE') P
WHERE P.HOLIDAY_POLICY IS NOT NULL
AND NOT EXISTS (SELECT 1 FROM FEE3.FCE_REF_CODE C
                WHERE C.CODE_GROUP='HOLIDAY_POLICY' AND C.CODE_VALUE=P.HOLIDAY_POLICY AND C.IS_ACTIVE=1)
GROUP BY P.HOLIDAY_POLICY;
PROMPT === R4C1 C. VERIFIED-STATUS CALENDAR REFERENCES FOR LATE DAMAGE (QA REFERENCES SHOULD REMAIN UNAPPROVED) ===
SELECT JSON_VALUE(V.FINANCIAL_POLICY_JSON,'$.loanPolicy.businessCalendarRef' RETURNING VARCHAR2(128)) AS CALENDAR_REF,
       COUNT(*) AS VERSION_COUNT
FROM FEE3.FCE_TARIFF_VERSION V JOIN FEE3.FCE_CALC_ITEM I ON I.CALC_ITEM_ID=V.CALC_ITEM_ID
WHERE I.AMOUNT_KIND_CODE='LATE_DAMAGE'
GROUP BY JSON_VALUE(V.FINANCIAL_POLICY_JSON,'$.loanPolicy.businessCalendarRef' RETURNING VARCHAR2(128));
PROMPT === R4C1 D. CAL2 ACTIVE DEFAULT PERSIAN VARIANT (EXPECT EXACTLY ONE) ===
SELECT V.CALENDAR_VARIANT_ID,V.VARIANT_CODE,V.IS_DEFAULT,V.ACTIVE_FLAG,S.CALENDAR_CODE
FROM CAL2.CALENDAR_VARIANT V JOIN CAL2.CALENDAR_SYSTEM S ON S.CALENDAR_SYSTEM_ID=V.CALENDAR_SYSTEM_ID
WHERE S.CALENDAR_CODE='PERSIAN' AND S.ACTIVE_FLAG='Y' AND V.ACTIVE_FLAG='Y' AND V.IS_DEFAULT='Y';
PROMPT === R4C1 E. CAL2 CANONICAL DATE COVERAGE FOR NEXT 10 DAYS (EXPECT 10 DISTINCT, NO DUPLICATES) ===
SELECT COUNT(*) AS ROW_COUNT,COUNT(DISTINCT D.CANONICAL_DATE) AS DISTINCT_DAYS,
       MIN(D.CANONICAL_DATE) AS FIRST_DATE,MAX(D.CANONICAL_DATE) AS LAST_DATE,
       MIN(C.YEAR_NO) AS FIRST_JALALI_YEAR,MAX(C.YEAR_NO) AS LAST_JALALI_YEAR,
       COUNT(DISTINCT C.CALENDAR_VARIANT_ID) AS VARIANT_COUNT,
       COUNT(DISTINCT C.DATASET_VERSION_ID) AS DATASET_COUNT
FROM CAL2.CALENDAR_DATE C JOIN CAL2.CANONICAL_DAY D ON D.DAY_ID=C.DAY_ID
JOIN CAL2.CALENDAR_VARIANT V ON V.CALENDAR_VARIANT_ID=C.CALENDAR_VARIANT_ID
JOIN CAL2.CALENDAR_SYSTEM S ON S.CALENDAR_SYSTEM_ID=V.CALENDAR_SYSTEM_ID
WHERE S.CALENDAR_CODE='PERSIAN' AND S.ACTIVE_FLAG='Y' AND V.IS_DEFAULT='Y' AND V.ACTIVE_FLAG='Y'
AND D.CANONICAL_DATE>=TRUNC(CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Tehran' AS DATE))
AND D.CANONICAL_DATE<TRUNC(CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Tehran' AS DATE))+10;
PROMPT === R4C1 F. SOURCE YEAR DENOMINATORS / ORDINALS ===
SELECT C.YEAR_NO,C.IS_LEAP_YEAR,MIN(C.DAY_OF_YEAR) AS MIN_DAY_OF_YEAR,
       MAX(C.DAY_OF_YEAR) AS MAX_DAY_OF_YEAR,COUNT(*) AS DAYS,
       COUNT(DISTINCT C.DATASET_VERSION_ID) AS DATASET_COUNT
FROM CAL2.CALENDAR_DATE C JOIN CAL2.CANONICAL_DAY D ON D.DAY_ID=C.DAY_ID
JOIN CAL2.CALENDAR_VARIANT V ON V.CALENDAR_VARIANT_ID=C.CALENDAR_VARIANT_ID
JOIN CAL2.CALENDAR_SYSTEM S ON S.CALENDAR_SYSTEM_ID=V.CALENDAR_SYSTEM_ID
WHERE S.CALENDAR_CODE='PERSIAN' AND S.ACTIVE_FLAG='Y' AND V.IS_DEFAULT='Y' AND V.ACTIVE_FLAG='Y'
AND D.CANONICAL_DATE>=TRUNC(CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Tehran' AS DATE))
AND D.CANONICAL_DATE<TRUNC(CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Tehran' AS DATE))+10
GROUP BY C.YEAR_NO,C.IS_LEAP_YEAR
ORDER BY C.YEAR_NO;
PROMPT === R4C1 G. PERSISTED LOAN PROFIT SEED VERSIONS NOT ELIGIBLE FOR PUBLICATION ===
SELECT V.TAX_MODE_CODE,V.STATUS_CODE,V.IS_ACTIVE,COUNT(*) AS VERSION_COUNT
FROM FEE3.FCE_TARIFF_VERSION V JOIN FEE3.FCE_CALC_ITEM I ON I.CALC_ITEM_ID=V.CALC_ITEM_ID
WHERE I.AMOUNT_KIND_CODE='FINANCING_PROFIT'
GROUP BY V.TAX_MODE_CODE,V.STATUS_CODE,V.IS_ACTIVE;
PROMPT === R4C1 H. 11 TABLES ROW BASELINE ===
SELECT 'FCE_CALC_ITEM' AS TABLE_NAME,COUNT(*) AS ROW_COUNT FROM FEE3.FCE_CALC_ITEM
UNION ALL SELECT 'FCE_TARIFF_VERSION',COUNT(*) FROM FEE3.FCE_TARIFF_VERSION
UNION ALL SELECT 'FCE_VERSION_SCOPE',COUNT(*) FROM FEE3.FCE_VERSION_SCOPE
UNION ALL SELECT 'FCE_CALC_RULE',COUNT(*) FROM FEE3.FCE_CALC_RULE
UNION ALL SELECT 'FCE_TEST_CASE',COUNT(*) FROM FEE3.FCE_TEST_CASE
UNION ALL SELECT 'FCE_CHANGE_REQUEST',COUNT(*) FROM FEE3.FCE_CHANGE_REQUEST
UNION ALL SELECT 'FCE_AUDIT_EVENT',COUNT(*) FROM FEE3.FCE_AUDIT_EVENT
UNION ALL SELECT 'FCE_REF_CODE',COUNT(*) FROM FEE3.FCE_REF_CODE
UNION ALL SELECT 'FCE_REF_OPERATION',COUNT(*) FROM FEE3.FCE_REF_OPERATION
UNION ALL SELECT 'FCE_REF_SOURCE',COUNT(*) FROM FEE3.FCE_REF_SOURCE
UNION ALL SELECT 'FCE_REF_FORMULA',COUNT(*) FROM FEE3.FCE_REF_FORMULA
ORDER BY TABLE_NAME;
PROMPT FEE3_R4C1_READONLY_COMPLETED_NO_COMMIT
