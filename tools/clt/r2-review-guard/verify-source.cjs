#!/usr/bin/env node
'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../../..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
let count=0;
const check=(name,value)=>{if(!value)throw Error('CLT_R2_REVIEW_GUARD_CHECK_FAILED='+name);count++;console.log('PASS | '+name)};
const intro='backend/src/main/java/com/behsazan/corebanking/collateral/introduction/';
const reg='backend/src/main/java/com/behsazan/corebanking/collateral/registration/';
const decision=read(intro+'CollateralIntroductionReviewService.java');
const guard=read(intro+'CollateralReviewDecisionGuard.java');
const readiness=read(reg+'CollateralRegistrationReadinessService.java');
const gate=read(reg+'CollateralRegistrationGatePolicy.java');
const base=read(intro+'CollateralIntroductionService.java');
const repo=read(intro+'CollateralIntroductionRepository.java');
const roadmap=read('docs/collateral/CLT-ROADMAP-R1.0-FA.md');
const gaps=read('docs/collateral/CLT-GAP-REGISTER-R1.0-FA.md');
check('decision requires independent checker',decision.includes('separateActors(current.makerSubject(), who.subject())'));
check('maker and checker unchanged code path',decision.includes('CLT_REVIEW_MAKER_CHECKER_MUST_DIFFER')||read(intro+'CollateralIntroductionReviewPolicy.java').includes('CLT_REVIEW_MAKER_CHECKER_MUST_DIFFER'));
check('only REVIEWED decision is newly gated',decision.includes('if ("REVIEWED".equals(decision.decision()))'));
check('RETURNED remains available',decision.includes('RETURNED decision is always available'));
check('checker reuses actual stored JSON',decision.includes('drafts.findForReviewer(p, reviewId, branch, checker)'));
check('checker recomputes exact canonical fingerprint',decision.includes('sha256(normalized.canonical())'));
check('checker validates creation audit',decision.includes('drafts.matchingCreationAudit(p, draft.draftId()'));
check('checker rechecks child Oracle ranges',decision.includes('drafts.persistedRangesMatch(p, draft.draftId(), draft.itemRanges())'));
check('checker rechecks CIF and CLT live',decision.includes('introduction.validate(storedRequest, authentication)'));
check('checker compares candidate against other owners',decision.includes('stageCandidateMatches(p, draft).otherOwner()'));
check('no other owner identity exposed',!guard.includes('otherOwnerParty')&&!guard.includes('otherOwnerBranch'));
check('policy fails closed when child mismatched',guard.includes('CLT_REVIEW_SERIAL_ROWS_MISMATCH'));
check('policy fails closed when audit missing',guard.includes('CLT_REVIEW_CREATION_AUDIT_INVALID'));
check('checker snapshot also rechecked',decision.includes('CLT_REVIEW_STORED_SNAPSHOT_INVALID'));
check('readiness validates creation audit in Oracle',readiness.includes('creationAuditValid = storedMatches && recomputedMatches'));
check('readiness compares child ranges in Oracle',readiness.includes('persistedSerialRowsValid = drafts.persistedRangesMatch'));
check('readiness rechecks Stage asset collisions',readiness.includes('crossOwnerStageConflict = drafts.stageCandidateMatches'));
check('report has creation audit item',gate.includes('"CREATION_AUDIT"'));
check('report has child rows evidence',gate.includes('"SERIAL_CHILD_READBACK"'));
check('report has collision evidence',gate.includes('"ASSET_STAGE_COLLISION"'));
check('no false final registration from decisions',gate.includes('return new Report')&&gate.includes('false, false,'));
check('G14 and G17 still decisions',gate.includes('"G-14"')&&gate.includes('"G-17"')&&gate.includes('"DECISION_REQUIRED"'));
check('no registered collateral DML new files',!decision.includes('INSERT INTO CLT.COLLATERAL')&&!readiness.includes('INSERT INTO CLT.COLLATERAL'));
check('no separate IAM or new datasource introduced',!guard.includes('Jwt')&&!gate.includes('DataSource'));
check('existing G17 remains unapproved',base.includes('G-17_REGISTRATION_NUMBERING_NOT_APPROVED'));
check('existing G03 writer remains independent',repo.includes('persistedRangesMatch('));
check('roadmap updated and phases preserved',roadmap.includes('CLT-R2-REVIEW-DECISION-INTEGRITY') && ['R0','R1','R2','R3','R4','R5','R6','R7'].every(x=>roadmap.includes(`**${x}**`)));
check('gap register updated without false closure',gaps.includes('کنترل تصمیم بازبین')&&gaps.includes('OPEN'));
check('new checkpoint committed',read('docs/collateral/CLT-R2-REVIEW-DECISION-CHECKPOINT-2026-11-09.md').includes('G-17'));
check('policy tests retained',read('backend/src/test/java/com/behsazan/corebanking/collateral/introduction/CollateralReviewDecisionGuardTest.java').includes('corruptedSerialChildRowsCannotBeReviewed'));
console.log('CLT_R2_REVIEW_GUARD_SOURCE_PASS='+count+'/'+count);
