PROMPT =========================================================
PROMPT A. Reference catalog and actual operational counts
PROMPT =========================================================
SELECT (SELECT COUNT(*) FROM CLT.COLLATERAL_GROUP) AS TOTAL_GROUPS,
       (SELECT COUNT(*) FROM CLT.COLLATERAL_GROUP WHERE STATUS = 'ACTIVE') AS ACTIVE_GROUPS,
       (SELECT COUNT(*) FROM CLT.COLLATERAL_GROUP WHERE CREATED_BY = 'EXCEL_TASHILAT_14030514') AS EXCEL_IMPORTED_GROUPS,
       (SELECT COUNT(*) FROM CLT.COLLATERAL_TYPE) AS TOTAL_TYPES,
       (SELECT COUNT(*) FROM CLT.COLLATERAL_TYPE WHERE STATUS = 'ACTIVE') AS ACTIVE_TYPES,
       (SELECT COUNT(*) FROM CLT.COLLATERAL) AS OPERATIONAL_COLLATERALS
  FROM DUAL;

PROMPT =========================================================
PROMPT B. Each reference group with policy types and collateral rows
PROMPT =========================================================
SELECT g.COLLATERAL_GROUP_CODE AS GROUP_CODE,
       g.COLLATERAL_GROUP_NAME AS GROUP_NAME,
       g.STATUS AS GROUP_STATUS,
       COUNT(DISTINCT t.COLLATERAL_TYPE_ID) AS TYPES_ALL,
       COUNT(DISTINCT CASE WHEN t.STATUS = 'ACTIVE' THEN t.COLLATERAL_TYPE_ID END) AS TYPES_ACTIVE,
       COUNT(DISTINCT c.COLLATERAL_ID) AS COLLATERALS
  FROM CLT.COLLATERAL_GROUP g
  LEFT JOIN CLT.COLLATERAL_TYPE t ON t.COLLATERAL_GROUP_ID = g.COLLATERAL_GROUP_ID
  LEFT JOIN CLT.COLLATERAL c ON c.COLLATERAL_TYPE_ID = t.COLLATERAL_TYPE_ID
 GROUP BY g.COLLATERAL_GROUP_CODE, g.COLLATERAL_GROUP_NAME, g.STATUS
 ORDER BY g.COLLATERAL_GROUP_CODE;

PROMPT =========================================================
PROMPT C. Type-to-group integrity (missing or inactive groups)
PROMPT =========================================================
SELECT t.COLLATERAL_TYPE_CODE, t.COLLATERAL_TYPE_NAME, t.STATUS AS TYPE_STATUS,
       t.COLLATERAL_GROUP_ID, g.COLLATERAL_GROUP_CODE, g.STATUS AS GROUP_STATUS
  FROM CLT.COLLATERAL_TYPE t
  LEFT JOIN CLT.COLLATERAL_GROUP g ON g.COLLATERAL_GROUP_ID = t.COLLATERAL_GROUP_ID
 WHERE g.COLLATERAL_GROUP_ID IS NULL OR g.STATUS <> 'ACTIVE'
 ORDER BY t.COLLATERAL_TYPE_CODE
 FETCH FIRST 100 ROWS ONLY;

PROMPT =========================================================
PROMPT D. Collateral rows missing a valid type or group
PROMPT =========================================================
SELECT c.COLLATERAL_ID, c.COLLATERAL_NUMBER, c.BRANCH_CODE,
       c.COLLATERAL_TYPE_ID, t.COLLATERAL_TYPE_CODE, t.STATUS AS TYPE_STATUS,
       g.COLLATERAL_GROUP_CODE, g.STATUS AS GROUP_STATUS
  FROM CLT.COLLATERAL c
  LEFT JOIN CLT.COLLATERAL_TYPE t ON t.COLLATERAL_TYPE_ID = c.COLLATERAL_TYPE_ID
  LEFT JOIN CLT.COLLATERAL_GROUP g ON g.COLLATERAL_GROUP_ID = t.COLLATERAL_GROUP_ID
 WHERE t.COLLATERAL_TYPE_ID IS NULL OR g.COLLATERAL_GROUP_ID IS NULL
 ORDER BY c.COLLATERAL_ID
 FETCH FIRST 100 ROWS ONLY;

PROMPT =========================================================
PROMPT E. Branch coverage (aggregate counts only)
PROMPT =========================================================
SELECT BRANCH_CODE, COUNT(*) AS COLLATERAL_COUNT
  FROM CLT.COLLATERAL
 GROUP BY BRANCH_CODE
 ORDER BY COLLATERAL_COUNT DESC, BRANCH_CODE
 FETCH FIRST 50 ROWS ONLY;

PROMPT =========================================================
PROMPT F. Possible UAT registration number in the local auto branch
PROMPT (The Backend local resolver uses MIN(BRANCH_CODE).)
PROMPT =========================================================
SELECT c.COLLATERAL_NUMBER, c.COLLATERAL_ID, c.BRANCH_CODE,
       t.COLLATERAL_TYPE_NAME, g.COLLATERAL_GROUP_NAME
  FROM CLT.COLLATERAL c
  JOIN CLT.COLLATERAL_TYPE t ON t.COLLATERAL_TYPE_ID = c.COLLATERAL_TYPE_ID
  LEFT JOIN CLT.COLLATERAL_GROUP g ON g.COLLATERAL_GROUP_ID = t.COLLATERAL_GROUP_ID
 WHERE c.BRANCH_CODE = (SELECT MIN(BRANCH_CODE) FROM CLT.COLLATERAL WHERE BRANCH_CODE IS NOT NULL)
 ORDER BY c.COLLATERAL_ID DESC
 FETCH FIRST 10 ROWS ONLY;
