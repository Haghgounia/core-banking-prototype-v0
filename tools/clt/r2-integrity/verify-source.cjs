#!/usr/bin/env node
'use strict';
const fs=require('node:fs');const path=require('node:path');
const root=path.resolve(__dirname,'../../..');
const load=p=>fs.readFileSync(path.join(root,p),'utf8');
const checks=[];
function ok(label,condition){checks.push([label,condition]);if(!condition)console.error('FAIL | '+label);else console.log('PASS | '+label)}
const jdir='backend/src/main/java/com/behsazan/corebanking/collateral/introduction/';
const udir='frontend/src/app/features/collateral/';
const controller=load(jdir+'CollateralIntroductionController.java');
const service=load(jdir+'CollateralIntroductionService.java');
const repository=load(jdir+'CollateralIntroductionRepository.java');
const review=load(jdir+'CollateralIntroductionReviewService.java');
const policy=load(jdir+'CollateralDraftIntegrityPolicy.java');
const models=load(jdir+'CollateralIntroductionModels.java');
const ui=load(udir+'collateral-introduction.component.html');
const ts=load(udir+'collateral-introduction.component.ts');
const client=load(udir+'collateral-introduction.service.ts');
const security=load('backend/src/main/java/com/behsazan/corebanking/collateral/prototype/CltUnifiedPrototypeSecurityConfiguration.java');
const config=load('config/clt-unified-local.yml');
ok('read-only owned draft integrity API', controller.includes('@GetMapping("/{draftId}/integrity")'));
ok('client uses read-only inspection', client.includes('this.http.get<IntroductionDraftIntegrity>'));
ok('UI provides manual integrity inspection', ui.includes('(click)="inspectSavedDraft()"'));
ok('current status and version validated',policy.includes('CLT_R2_DRAFT_STATUS_NOT_DRAFT')&&policy.includes('CLT_R2_DRAFT_VERSION_CHANGED'));
ok('fingerprint rederived from saved JSON, not request', service.includes('CollateralIntroductionPolicy.sha256(normalized.canonical())'));
ok('persisted digest checked',service.includes('repository.previousHash(pool, id)'));
ok('creation audit checked',repository.includes('FROM CLT.CLT_INTRODUCTION_DRAFT_AUDIT a'));
ok('audit crosschecks immutable maker/branch',repository.includes('a.EVENT_SUBJECT = d.MAKER_SUBJECT')&&repository.includes('a.BRANCH_CODE = d.BRANCH_CODE'));
ok('record fetched with server-derived maker & branch',service.includes('repository.find(pool, id, who.subject(), who.branch())'));
ok('current CIF and CLT validations executed',service.includes('validateNormalized(normalized)'));
ok('serial ranges assessed with type policy',service.includes('CollateralSerialRangePolicy.assess(typeRules.countable()'));
ok('server review submission cannot bypass integrity gate',review.includes('introduction.inspectDraft(auth, id)')&&review.includes('if (!integrity.eligibleForReview())'));
ok('idempotent review replays checked before current validation',review.indexOf('if (existing != null) return replayOrConflict')<review.indexOf('introduction.inspectDraft(auth, id)'));
ok('snapshot preview distinguishes draft from final',ui.includes('شماره انتظامی همچنان غیرفعال'));
ok('no client-requested final issuance',!controller.includes('@PostMapping("/final-registration")')&&!controller.includes('@PostMapping("/register")'));
ok('same local shared datasource retained',config.includes('draft-writes-enabled:')&&config.includes('review-workflow-enabled: false'));
ok('no external POST final issuance in unified chain', !security.includes('.requestMatchers(HttpMethod.POST, "/api/v1/collaterals").permitAll()'));
ok('R0..R7 roadmap still present',load('docs/collateral/CLT-ROADMAP-R1.0-FA.md').includes('R0..R7'));
const passed=checks.filter(x=>x[1]).length;
console.log('CLT_R2_INTEGRITY_SOURCE_PASS='+passed+'/'+checks.length);
if(passed!==checks.length)process.exitCode=1;
