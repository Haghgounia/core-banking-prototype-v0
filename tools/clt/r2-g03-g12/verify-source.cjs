#!/usr/bin/env node
'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../../..');
const source=p=>fs.readFileSync(path.join(root,p),'utf8');
let successes=0;
function ck(label,check){if(!check)throw Error('CLT_R2_G03_G12_SOURCE_FAIL '+label);console.log('PASS | '+label);successes++;}
const base='backend/src/main/java/com/behsazan/corebanking/collateral/introduction/';
const repo=source(base+'CollateralIntroductionRepository.java');
const type=source(base+'CollateralCountabilityPolicy.java');
const logic=source(base+'CollateralIntroductionService.java');
const api=source(base+'CollateralIntroductionController.java');
const form=source('frontend/src/app/features/collateral/collateral-introduction.component.html');
const component=source('frontend/src/app/features/collateral/collateral-introduction.component.ts');
const client=source('frontend/src/app/features/collateral/collateral-introduction.service.ts');
const optin=source('database/clt/r2-g03-g12/01_G12_FLAG_AND_G03_DRAFT_RANGES_DBA_OPT_IN.sql');
const proposed=source('database/clt/r2-g03-g12/02_G03_REGISTERED_RANGES_DBA_OPT_IN.sql');
const backfill=source('database/clt/r2-g03-g12/03_BACKFILL_EXISTING_DRAFT_RANGES_DBA_OPT_IN.sql');
ck('G12 separate Oracle countability flag',repo.includes('IS_COUNTABLE_FLAG') && repo.includes('HAS_MULTIPLICITY'));
ck('G12 NULL means not configured',type.includes('countableFlag != null') && logic.includes('G12_IS_COUNTABLE_FLAG_NOT_CONFIGURED'));
ck('G12 no inference from multiplicity',!component.includes("this.value(selected, 'HAS_MULTIPLICITY') === 'Y'") && type.includes('countableFlag'));
ck('G12 optional schema is additive',optin.includes('ALTER TABLE CLT.COLLATERAL_TYPE ADD (IS_COUNTABLE_FLAG') && !optin.includes('DEFAULT \'Y\''));
ck('G12 independent flag visible in UI',form.includes('data-clt-g12-countability="independent"'));
ck('G12 typed Oracle read contract',api.includes('types/{typeId}/countability')&&client.includes('typeCountability(typeId: string)'));
ck('G03 child model is immutable',optin.includes('CLT_INTRODUCTION_DRAFT_SERIAL_RANGE') && optin.includes('FOREIGN KEY (DRAFT_ID)'));
ck('G03 child row amount stored as numeric IRR',optin.includes('TOTAL_AMOUNT_IRR  NUMBER(16,0)'));
ck('G03 serial long digits preserved as string',optin.includes('SERIAL_FROM       VARCHAR2(100 CHAR)'));
ck('G03 explicit schema readiness check',repo.includes('serialRangeTableReady(')&&repo.includes('G03_SERIAL_RANGE_MIGRATION_REQUIRED'));
ck('G03 child insert with parent transaction',logic.includes('pool.transaction().execute(')&&repo.includes('insertSerialRanges(pool, newId'));
ck('G03 readback equality required',repo.includes('persistedRangesMatch(pool, newId.toPlainString(), request.itemRanges())'));
ck('G03 integrity fail-closed on child mismatch',logic.includes('&& repository.persistedRangesMatch(pool, id, draft.itemRanges())'));
ck('G03 per-maker branch scoping retained',logic.includes('repository.find(stage, id, who.subject(), who.branch())'));
ck('G03 retrieval endpoint exposed',api.includes('/{draftId}/item-ranges')&&client.includes('persistedSerialRanges(draftId: string)'));
ck('G03 readback status shown in form',form.includes('data-clt-g03-range-readback'));
ck('G03 backfill is explicit and no hash rewrite',backfill.includes('JSON_TABLE(')&&!backfill.includes('UPDATE CLT.CLT_INTRODUCTION_DRAFT SET'));
ck('final table proposed without writer',proposed.includes('CLT_COLLATERAL_SERIAL_RANGE')&&!logic.includes('INSERT INTO CLT.COLLATERAL'));
ck('no automatic Oracle DDL in Java',!/(CREATE TABLE|ALTER TABLE|DROP TABLE) CLT\./.test(logic+repo+api));
ck('G14 and G17 still remain open',logic.includes('G-14_STABLE_ASSET_IDENTITY_NOT_APPROVED') &&logic.includes('G-17_REGISTRATION_NUMBERING_NOT_APPROVED'));
ck('no independent starter or datasource created',!repo.includes('HikariDataSource')&&!logic.includes('HikariDataSource'));
ck('canonical R0-R7 phases remain',source('docs/collateral/CLT-ROADMAP-R1.0-FA.md').includes('R0')&&source('docs/collateral/CLT-ROADMAP-R1.0-FA.md').includes('R7'));
console.log('CLT_R2_G03_G12_STATIC_PASS='+successes+'/'+successes);
