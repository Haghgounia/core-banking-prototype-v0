#!/usr/bin/env node
'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../../..');
const source=p=>fs.readFileSync(path.join(root,p),'utf8');
const j='backend/src/main/java/com/behsazan/corebanking/collateral/introduction/';
const f='frontend/src/app/features/collateral/';
const check=[];
const ok=(label,pass)=>{check.push([label,!!pass]);console.log((pass?'PASS':'FAIL')+' | '+label)};
const policy=source(j+'CollateralAssetCandidatePolicy.java');
const repo=source(j+'CollateralIntroductionRepository.java');
const controller=source(j+'CollateralIntroductionController.java');
const service=source(j+'CollateralIntroductionService.java');
const reviews=source(j+'CollateralIntroductionReviewService.java');
const models=source(j+'CollateralIntroductionModels.java');
const client=source(f+'collateral-introduction.service.ts');
const cmp=source(f+'collateral-introduction.component.ts');
const html=source(f+'collateral-introduction.component.html');
const security=source('backend/src/main/java/com/behsazan/corebanking/collateral/prototype/CltUnifiedPrototypeSecurityConfiguration.java');
const cfg=source('config/clt-unified-local.yml');
ok('pure candidate policy cannot certify asset identity',policy.includes('false, false, status, explanation'));
ok('no final registration from candidate report',models.includes('boolean finalRegistrationEnabled'));
ok('comparison is scoped to same collateral type',repo.includes('WHERE COLLATERAL_TYPE_ID = ?'));
ok('current own draft excluded from duplicate aggregation',repo.includes('AND DRAFT_ID <> ?'));
ok('staged reference match is case and whitespace normalized',repo.includes('UPPER(TRIM(ASSET_REFERENCE)) = ?'));
ok('aggregate only: no other Party or draft IDs disclosed',repo.includes('SELECT COUNT(*) AS TOTAL_COUNT')&&!repo.includes('SELECT PARTY_ID FROM CLT.CLT_INTRODUCTION_DRAFT'));
ok('cross-owner comparison uses trusted saved PARTY_ID',repo.includes('new BigDecimal(current.partyId())'));
ok('data access uses parameterized Oracle statements',repo.includes('new BigDecimal(current.draftId()), normalized'));
ok('missing Stage extension is not interpreted as no conflict',policy.includes('STAGE_EXTENSION_REQUIRED')&&service.includes('!repository.candidateColumnReady(pool)'));
ok('other-owner collision prevents review submission on server',reviews.includes('!candidate.eligibleForReviewSubmission()'));
ok('same-owner revisions are allowed',policy.includes('SAME_OWNER_DRAFTS_FOUND'));
ok('owned draft lookup uses backend maker/branch',service.includes('repository.find(pool, id, who.subject(), who.branch())'));
ok('read-only API available',controller.includes('@GetMapping("/{draftId}/asset-candidate")'));
ok('frontend requests candidate report via GET',client.includes('get<IntroductionAssetCandidateInspection>'));
ok('single integrity button loads both reports',cmp.includes('Promise.all([')&&cmp.includes('this.api.assetCandidate(draft.draftId)'));
ok('conflict and identity warning visible in UI',html.includes('data-clt-asset-candidate-inspection')&&html.includes('هویت معتبر دارایی'));
ok('prototype no JWT uploaded to frontend',!cmp.includes('دسترسی به معرفی وثیقه نیازمند JWT'));
ok('local same starter, no new auth layer',cfg.includes('review-workflow-enabled: false')&&security.includes('LocalCltAuthenticationFilter'));
ok('business final DML remains blocked',!controller.includes('@PostMapping("/register")')&&security.includes('.anyRequest().denyAll()'));
ok('R0 to R7 roadmap unchanged',source('docs/collateral/CLT-ROADMAP-R1.0-FA.md').includes('R0..R7'));
const total=check.filter(a=>a[1]).length;
console.log('CLT_R2_ASSET_CANDIDATE_STATIC_PASS='+total+'/'+check.length);
if(total!==check.length)process.exitCode=1;
