import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('frontend/src/app/features/four-deposits/deposit-account-operations.component.html');
const build=read('build-production.cmd');
let pass=0,fail=0;
const check=(n,o)=>{console.log(`${o?'PASS':'FAIL'} | ${n}`);o?pass++:fail++};
const between=(a,b)=>{const i=html.indexOf(a),j=html.indexOf(b,i+1);return i>=0?html.slice(i,j>i?j:html.length):''};
const step12=between('id="ops-step12"','id="ops-step13"');
const step13=between('id="ops-step13"','id="ops-step14"');
const step14=between('id="ops-step14"','id="ops-step15"');
const step15=between('id="ops-step15"','id="ops-step16"');
const step16=between('id="ops-step16"','id="ops-step17"');
const step17=between('id="ops-step17"','class="card detail-card timeline-card"');
check('tax exemption document keeps R10D Persian contract',step13.includes('مرجع سند معتبر معافیت')&&!step13.includes('Exemption Document'));
check('Step12 canonical marker retained but hidden',step12.includes('data-contract-marker="phase11l-step12"')&&step12.includes('Step 12')&&step12.includes('hidden aria-hidden="true"'));
for(const [n,s,marker] of [[14,step14,'phase11m-step14'],[15,step15,'phase11m-step15'],[16,step16,'phase11m-step16'],[17,step17,'phase11m-step17']])check(`Step${n} canonical marker retained but hidden`,s.includes(`data-contract-marker="${marker}"`)&&s.includes(`Step ${n}`)&&s.includes('hidden aria-hidden="true"'));
check('non-destructive Step05 contract retained source-only',step15.includes('Non-destructive')&&step15.includes('Step 05'));
check('reward RC trace contract retained source-only',step17.includes('تثبیت &amp; قرعه‌کشی')&&step17.includes('Program/Eligibility')&&step17.includes('Step 05'));
check('R10G verifier is wired into production build',build.includes('verify-dps2-account-operations-r10g-regression-compat.mjs'));
console.log('------------------------------------------------------------');
console.log(`DPS2_ACCOUNT_OPERATIONS_R10G_PASS=${pass}`);
console.log(`DPS2_ACCOUNT_OPERATIONS_R10G_FAIL=${fail}`);
if(fail)process.exit(1);
console.log('DPS2_ACCOUNT_OPERATIONS_R10G_STATIC_PASS');
