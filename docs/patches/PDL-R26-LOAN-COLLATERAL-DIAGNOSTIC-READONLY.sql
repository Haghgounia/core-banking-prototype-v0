PROMPT R26-1: Active collateral master types
SELECT LOAN_PRODUCT_COLLATERAL_ID, PRODUCT_COLLATERAL_CODE,
       PRODUCT_COLLATERAL_NAME, RECORD_STATUS_CODE
FROM PDL.LOAN_PRODUCT_COLLATERAL
WHERE RECORD_STATUS_CODE = 'ACTIVE'
ORDER BY PRODUCT_COLLATERAL_NAME;

PROMPT R26-2: Collateral priority by product version
SELECT PRODUCT_VERSION_ID, LOAN_COLLATERAL_RULE_ID,
       LOAN_PRODUCT_COLLATERAL_ID, PRIORITY_NO,
       MIN_COVERAGE_PERCENT, MAX_COVERAGE_PERCENT, IS_REQUIRED
FROM PDL.LOAN_PRODUCT_COLLATERAL_RULE
ORDER BY PRODUCT_VERSION_ID DESC, PRIORITY_NO ASC, LOAN_COLLATERAL_RULE_ID ASC;

PROMPT R26-3: Duplicate collateral rank within a version
SELECT PRODUCT_VERSION_ID, PRIORITY_NO, COUNT(*) AS DUPLICATE_COUNT
FROM PDL.LOAN_PRODUCT_COLLATERAL_RULE
GROUP BY PRODUCT_VERSION_ID, PRIORITY_NO
HAVING COUNT(*) > 1;

PROMPT R26-4: Deposit operations historically attached to LOAN
SELECT pco.CHANNEL_OPERATION_ID, pco.CHANNEL_RULE_ID,
       pco.OPERATION_CODE, pco.IS_ALLOWED, pv.PRODUCT_VERSION_ID
FROM PDL.PRODUCT_CHANNEL_OPERATION pco
JOIN PDL.PRODUCT_CHANNEL_RULE pcr ON pcr.CHANNEL_RULE_ID = pco.CHANNEL_RULE_ID
JOIN PDL.PRODUCT_VERSION pv ON pv.PRODUCT_VERSION_ID = pcr.PRODUCT_VERSION_ID
JOIN PDL.PRODUCT p ON p.PRODUCT_ID = pv.PRODUCT_ID
WHERE p.PRODUCT_CLASS_CODE = 'LOAN'
  AND pco.OPERATION_CODE IN ('TRANSFER_OUT','CASH_WITHDRAWAL','CHEQUE','ALL_OPERATIONS')
ORDER BY pv.PRODUCT_VERSION_ID DESC, pco.CHANNEL_OPERATION_ID;

