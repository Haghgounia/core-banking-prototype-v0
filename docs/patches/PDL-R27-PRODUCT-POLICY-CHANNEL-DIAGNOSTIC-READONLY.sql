PROMPT === Database context ===
SELECT SYS_CONTEXT('USERENV','CON_NAME') AS PDB, SYS_CONTEXT('USERENV','SESSION_USER') AS DB_USER FROM DUAL;

PROMPT === Family source: ACTIVE PDL.LOAN_TYPE groups ===
SELECT LOAN_GROUP, RECORD_STATUS_CODE, COUNT(*) AS CONTRACT_COUNT
  FROM PDL.LOAN_TYPE
 GROUP BY LOAN_GROUP, RECORD_STATUS_CODE
 ORDER BY LOAN_GROUP, RECORD_STATUS_CODE;

PROMPT === Expected endpoint rows (groups with at least one active contract) ===
SELECT DISTINCT LOAN_GROUP,
       CASE LOAN_GROUP
         WHEN 1 THEN 'QARD_HASAN_LOAN'
         WHEN 2 THEN 'EXCHANGE_LOAN'
         WHEN 3 THEN 'PARTICIPATORY_LOAN'
         WHEN 4 THEN 'COMMITMENT_LOAN'
       END AS PRODUCT_FAMILY_CODE
  FROM PDL.LOAN_TYPE
 WHERE RECORD_STATUS_CODE = 'ACTIVE' AND LOAN_GROUP BETWEEN 1 AND 4
 ORDER BY LOAN_GROUP;

PROMPT === Lite policy storage and record counts ===
SELECT TABLE_NAME FROM ALL_TABLES
 WHERE OWNER='PDL' AND TABLE_NAME IN ('RULE_POLICY_VERSION','RULE_CONTROL_POLICY')
 ORDER BY TABLE_NAME;
SELECT POLICY_CODE, POLICY_VERSION_NO, POLICY_NAME_FA, STATE_CODE,
       CREATED_BY, APPROVED_BY, APPROVAL_REFERENCE,
       VALID_FROM, VALID_TO
  FROM PDL.RULE_POLICY_VERSION
 ORDER BY POLICY_CODE, POLICY_VERSION_NO DESC;

PROMPT === Operations that must be translated in the grid ===
SELECT OPERATION_CODE, COUNT(*) AS ROW_COUNT
  FROM PDL.PRODUCT_CHANNEL_OPERATION
 GROUP BY OPERATION_CODE ORDER BY OPERATION_CODE;

