-- IAM-S1B-RO2 | DBA/SEC handoff | RUN ONLY WHEN APPROVED, as the dedicated IAM read user.
-- This is a SELECT-only evidence script. It makes no DB/DDL/DML/COMMIT changes.
-- The dedicated reader must have only CREATE SESSION, no roles, and direct SELECT/READ on four IAM tables.
SET HEADING ON FEEDBACK ON PAGESIZE 200 LINESIZE 200
PROMPT === IAM-S1B-RO2: READER AND EFFECTIVE PRIVILEGES ===
SELECT SYS_CONTEXT('USERENV','SESSION_USER') AS READER_USERNAME FROM DUAL;
SELECT PRIVILEGE FROM SESSION_PRIVS ORDER BY PRIVILEGE;
SELECT ROLE FROM SESSION_ROLES ORDER BY ROLE;
SELECT OWNER, TABLE_NAME, PRIVILEGE FROM USER_TAB_PRIVS_RECD
ORDER BY OWNER, TABLE_NAME, PRIVILEGE;
PROMPT === IAM-S1B-RO2: REQUIRED IAM TABLES/COLUMNS ===
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, NULLABLE
FROM ALL_TAB_COLUMNS
WHERE OWNER = 'IAM' AND TABLE_NAME IN
 ('SECURITY_DOMAINS','PRINCIPALS','USER_ACCOUNTS','IDENTITY_LINKS')
ORDER BY TABLE_NAME, COLUMN_ID;
PROMPT === IAM-S1B-RO2: NON-DESTRUCTIVE SELECT PRIVILEGE PROOF ===
SELECT COUNT(*) AS ZERO_EXPECTED FROM IAM.SECURITY_DOMAINS WHERE 1 = 0;
SELECT COUNT(*) AS ZERO_EXPECTED FROM IAM.PRINCIPALS WHERE 1 = 0;
SELECT COUNT(*) AS ZERO_EXPECTED FROM IAM.USER_ACCOUNTS WHERE 1 = 0;
SELECT COUNT(*) AS ZERO_EXPECTED FROM IAM.IDENTITY_LINKS WHERE 1 = 0;
PROMPT === IAM-S1B-RO2: DATA QUALITY, AGGREGATE COUNTS ONLY ===
SELECT COUNT(*) AS ACTIVE_DOMAINS FROM IAM.SECURITY_DOMAINS WHERE IS_ACTIVE = 'Y';
SELECT COUNT(*) AS USERNAME_NORMALIZED_NULLS FROM IAM.USER_ACCOUNTS WHERE USERNAME_NORMALIZED IS NULL;
SELECT COUNT(*) AS ACCOUNTS_WITH_PRINCIPAL_CONTEXT_MISMATCH FROM IAM.USER_ACCOUNTS ua
JOIN IAM.PRINCIPALS p ON p.PRINCIPAL_ID = ua.PRINCIPAL_ID
WHERE ua.IDENTITY_CONTEXT_CODE <> p.IDENTITY_CONTEXT_CODE;
SELECT COUNT(*) AS MULTI_ACCOUNT_PRINCIPALS FROM
(SELECT PRINCIPAL_ID FROM IAM.USER_ACCOUNTS GROUP BY PRINCIPAL_ID HAVING COUNT(*) > 1);
PROMPT === IAM-S1B-RO2: END OF READ-ONLY EVIDENCE (NO COMMIT) ===
