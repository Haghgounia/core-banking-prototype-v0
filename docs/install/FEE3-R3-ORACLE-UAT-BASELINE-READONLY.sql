-- FEE3 R3 UAT qualification: SELECT only. No DDL, DML, PL/SQL, COMMIT or locks.
-- Run in SQL Developer with a read-only user; save output before and after HTTP smoke.
PROMPT FEE3_R3_A_BANK_DATE
SELECT TO_CHAR(TRUNC(CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Tehran' AS DATE)), 'YYYY-MM-DD') AS BANK_BUSINESS_DATE FROM DUAL;

PROMPT FEE3_R3_B_REQUIRED_TABLES
WITH REQUIRED AS (
  SELECT 'FCE_AUDIT_EVENT' AS NAME FROM DUAL UNION ALL
  SELECT 'FCE_CALC_ITEM' FROM DUAL UNION ALL
  SELECT 'FCE_CALC_RULE' FROM DUAL UNION ALL
  SELECT 'FCE_CHANGE_REQUEST' FROM DUAL UNION ALL
  SELECT 'FCE_REF_CODE' FROM DUAL UNION ALL
  SELECT 'FCE_REF_FORMULA' FROM DUAL UNION ALL
  SELECT 'FCE_REF_OPERATION' FROM DUAL UNION ALL
  SELECT 'FCE_REF_SOURCE' FROM DUAL UNION ALL
  SELECT 'FCE_TARIFF_VERSION' FROM DUAL UNION ALL
  SELECT 'FCE_TEST_CASE' FROM DUAL UNION ALL
  SELECT 'FCE_VERSION_SCOPE' FROM DUAL
)
SELECT R.NAME AS REQUIRED_TABLE,
       CASE WHEN T.TABLE_NAME IS NULL THEN 'MISSING' ELSE 'PRESENT' END AS STATUS
FROM REQUIRED R LEFT JOIN ALL_TABLES T ON T.OWNER = 'FEE3' AND T.TABLE_NAME = R.NAME
ORDER BY R.NAME;

PROMPT FEE3_R3_C_REQUIRED_SEQUENCES
SELECT SEQUENCE_NAME FROM ALL_SEQUENCES
WHERE SEQUENCE_OWNER='FEE3' AND SEQUENCE_NAME IN ('SEQ_FCE_CHANGE_REQUEST','SEQ_FCE_AUDIT_EVENT')
ORDER BY SEQUENCE_NAME;

PROMPT FEE3_R3_D_GOVERNANCE_CONSTRAINT_STATUS
SELECT TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE, STATUS, VALIDATED
FROM ALL_CONSTRAINTS
WHERE OWNER='FEE3'
  AND TABLE_NAME IN ('FCE_CHANGE_REQUEST','FCE_TARIFF_VERSION','FCE_AUDIT_EVENT')
  AND CONSTRAINT_NAME IN (
     'CHK_FCE_CHANGE_REQUEST_CHANGE_TYPE_CODE',
     'CHK_FCE_CHANGE_REQUEST_REQUEST_STATUS_CODE',
     'CHK_FCE_TARIFF_VERSION_STATUS_CODE',
     'CHK_FCE_TARIFF_VERSION_IS_ACTIVE_STATUS_CODE',
     'CHK_FCE_AUDIT_EVENT_DETAILS_JSON',
     'CHK_FCE_CHANGE_REQUEST_CHANGE_PAYLOAD_JSON'
  )
ORDER BY TABLE_NAME, CONSTRAINT_NAME;

PROMPT FEE3_R3_E_ROW_BASELINE
SELECT 'ITEM' AS ENTITY_NAME, COUNT(*) AS ROW_COUNT FROM FEE3.FCE_CALC_ITEM
UNION ALL SELECT 'TARIFF_VERSION',COUNT(*) FROM FEE3.FCE_TARIFF_VERSION
UNION ALL SELECT 'SCOPE',COUNT(*) FROM FEE3.FCE_VERSION_SCOPE
UNION ALL SELECT 'RULE',COUNT(*) FROM FEE3.FCE_CALC_RULE
UNION ALL SELECT 'TEST_CASE',COUNT(*) FROM FEE3.FCE_TEST_CASE
UNION ALL SELECT 'CHANGE_REQUEST',COUNT(*) FROM FEE3.FCE_CHANGE_REQUEST
UNION ALL SELECT 'AUDIT_EVENT',COUNT(*) FROM FEE3.FCE_AUDIT_EVENT;

PROMPT FEE3_R3_F_ALL_VERSION_STATUSES
SELECT STATUS_CODE, IS_ACTIVE, COUNT(*) AS VERSION_COUNT
FROM FEE3.FCE_TARIFF_VERSION
GROUP BY STATUS_CODE, IS_ACTIVE ORDER BY STATUS_CODE, IS_ACTIVE;

PROMPT FEE3_R3_G_UAT_REQUEST_STATUSES
SELECT REQUEST_STATUS_CODE, COUNT(*) AS ROW_COUNT
FROM FEE3.FCE_CHANGE_REQUEST
WHERE REQUEST_NO LIKE 'F3-UAT-CR-%'
GROUP BY REQUEST_STATUS_CODE ORDER BY REQUEST_STATUS_CODE;

PROMPT FEE3_R3_H_UAT_ACTIVATION_GUARD_EXPECT_ZERO
SELECT COUNT(*) AS UNEXPECTED_ACTIVE_OR_PUBLISHED_UAT_VERSIONS
FROM FEE3.FCE_TARIFF_VERSION V JOIN FEE3.FCE_CALC_ITEM I
  ON I.CALC_ITEM_ID=V.CALC_ITEM_ID
WHERE I.CALC_CODE LIKE 'F3-UAT-%'
  AND (V.IS_ACTIVE = 1 OR V.PUBLISHED_AT IS NOT NULL OR V.STATUS_CODE = 'ACTIVE');

PROMPT FEE3_R3_I_SAME_MAKER_CHECKER_GUARD_EXPECT_ZERO
SELECT COUNT(*) AS SELF_DECIDED_UAT_REQUESTS
FROM FEE3.FCE_CHANGE_REQUEST R
WHERE R.REQUEST_NO LIKE 'F3-UAT-CR-%'
  AND R.REQUESTED_BY IS NOT NULL AND R.DECIDED_BY IS NOT NULL
  AND UPPER(TRIM(R.REQUESTED_BY)) = UPPER(TRIM(R.DECIDED_BY));

PROMPT FEE3_R3_J_UAT_APPLIED_GUARD_EXPECT_ZERO
SELECT COUNT(*) AS APPLIED_UAT_CHANGE_REQUESTS
FROM FEE3.FCE_CHANGE_REQUEST
WHERE REQUEST_NO LIKE 'F3-UAT-CR-%'
  AND (APPLIED_AT IS NOT NULL OR REQUEST_STATUS_CODE='APPLIED');

PROMPT FEE3_R3_K_REFERENCE_OPERATION_COUNTS
SELECT MODULE_CODE, IS_ACTIVE, COUNT(*) AS OPERATION_COUNT
FROM FEE3.FCE_REF_OPERATION
GROUP BY MODULE_CODE, IS_ACTIVE ORDER BY MODULE_CODE, IS_ACTIVE;

