-- FEE3-BE-R3 preflight: SELECT only. No DDL, DML, locks or COMMIT.
SELECT TABLE_NAME FROM ALL_TABLES WHERE OWNER='FEE3'
  AND TABLE_NAME IN ('FCE_CALC_ITEM','FCE_TARIFF_VERSION',
  'FCE_CHANGE_REQUEST','FCE_AUDIT_EVENT','FCE_CALC_RULE','FCE_VERSION_SCOPE','FCE_TEST_CASE')
ORDER BY TABLE_NAME;

SELECT 'ITEM' AS ROW_TYPE,COUNT(*) AS ROW_COUNT FROM FEE3.FCE_CALC_ITEM
UNION ALL SELECT 'VERSION',COUNT(*) FROM FEE3.FCE_TARIFF_VERSION
UNION ALL SELECT 'CHANGE_REQUEST',COUNT(*) FROM FEE3.FCE_CHANGE_REQUEST
UNION ALL SELECT 'AUDIT',COUNT(*) FROM FEE3.FCE_AUDIT_EVENT;

SELECT V.STATUS_CODE,V.IS_ACTIVE,COUNT(*) AS VERSION_COUNT
FROM FEE3.FCE_TARIFF_VERSION V
GROUP BY V.STATUS_CODE,V.IS_ACTIVE ORDER BY V.STATUS_CODE,V.IS_ACTIVE;

SELECT R.REQUEST_STATUS_CODE,COUNT(*) AS REQUEST_COUNT
FROM FEE3.FCE_CHANGE_REQUEST R GROUP BY R.REQUEST_STATUS_CODE
ORDER BY R.REQUEST_STATUS_CODE;

SELECT COUNT(*) AS UNPUBLISHED_UAT_ITEMS
FROM FEE3.FCE_CALC_ITEM I
WHERE I.CALC_CODE LIKE 'F3-UAT-%' AND I.IS_ENABLED=0;

SELECT COUNT(*) AS UAT_UNEXPECTED_ACTIVE_VERSIONS
FROM FEE3.FCE_TARIFF_VERSION V
JOIN FEE3.FCE_CALC_ITEM I ON I.CALC_ITEM_ID=V.CALC_ITEM_ID
WHERE I.CALC_CODE LIKE 'F3-UAT-%' AND (V.IS_ACTIVE=1 OR V.PUBLISHED_AT IS NOT NULL);
