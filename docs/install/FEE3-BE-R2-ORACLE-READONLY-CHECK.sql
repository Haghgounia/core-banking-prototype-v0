-- FEE3-BE-R2: only SELECT, no commit, no DDL/DML.
SELECT 'FEE3_CALC_ITEMS' METRIC, COUNT(*) ROW_COUNT FROM FEE3.FCE_CALC_ITEM
UNION ALL
SELECT 'FEE3_TARIFF_VERSIONS', COUNT(*) FROM FEE3.FCE_TARIFF_VERSION
UNION ALL
SELECT 'FEE3_UAT_ITEMS', COUNT(*) FROM FEE3.FCE_CALC_ITEM WHERE CALC_CODE LIKE 'F3-UAT-%'
UNION ALL
SELECT 'FEE3_UAT_DRAFTS', COUNT(*) FROM FEE3.FCE_TARIFF_VERSION v JOIN FEE3.FCE_CALC_ITEM i ON i.CALC_ITEM_ID=v.CALC_ITEM_ID WHERE i.CALC_CODE LIKE 'F3-UAT-%' AND v.STATUS_CODE='DRAFT'
UNION ALL
SELECT 'FEE3_UAT_AUDIT', COUNT(*) FROM FEE3.FCE_AUDIT_EVENT WHERE ACTION_CODE IN ('UAT_DRAFT_CREATED','UAT_DRAFT_UPDATED');

SELECT i.CALC_CODE,v.TARIFF_VERSION_ID,v.VERSION_NO,v.STATUS_CODE,v.IS_ACTIVE,v.RECORD_VERSION
FROM FEE3.FCE_CALC_ITEM i JOIN FEE3.FCE_TARIFF_VERSION v ON i.CALC_ITEM_ID=v.CALC_ITEM_ID
WHERE i.CALC_CODE LIKE 'F3-UAT-%'
ORDER BY i.CALC_ITEM_ID DESC,v.VERSION_NO DESC FETCH FIRST 25 ROWS ONLY;
