SELECT SYS_CONTEXT('USERENV','SESSION_USER') AS SESSION_USER,
       SYS_CONTEXT('USERENV','CON_NAME') AS PDB_NAME,
       CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Tehran' AS TIMESTAMP) AS BANK_TEHRAN_NOW
FROM DUAL;

WITH expected AS (
 SELECT 'FCE_AUDIT_EVENT' table_name FROM DUAL UNION ALL
 SELECT 'FCE_CALC_ITEM' FROM DUAL UNION ALL
 SELECT 'FCE_CALC_RULE' FROM DUAL UNION ALL
 SELECT 'FCE_CHANGE_REQUEST' FROM DUAL UNION ALL
 SELECT 'FCE_REF_CODE' FROM DUAL UNION ALL
 SELECT 'FCE_REF_FORMULA' FROM DUAL UNION ALL
 SELECT 'FCE_REF_OPERATION' FROM DUAL UNION ALL
 SELECT 'FCE_REF_SOURCE' FROM DUAL UNION ALL
 SELECT 'FCE_TARIFF_VERSION' FROM DUAL UNION ALL
 SELECT 'FCE_TEST_CASE' FROM DUAL UNION ALL
 SELECT 'FCE_VERSION_SCOPE' FROM DUAL
)
SELECT e.table_name,
       CASE WHEN t.table_name IS NULL THEN 'MISSING_OR_NO_PRIVILEGE' ELSE 'VISIBLE' END visibility
FROM expected e LEFT JOIN ALL_TABLES t
 ON t.owner='FEE3' AND t.table_name=e.table_name
ORDER BY e.table_name;

SELECT 'FCE_CALC_ITEM' entity_name, COUNT(*) row_count FROM FEE3.FCE_CALC_ITEM
UNION ALL SELECT 'FCE_TARIFF_VERSION',COUNT(*) FROM FEE3.FCE_TARIFF_VERSION
UNION ALL SELECT 'FCE_CALC_RULE',COUNT(*) FROM FEE3.FCE_CALC_RULE
UNION ALL SELECT 'FCE_VERSION_SCOPE',COUNT(*) FROM FEE3.FCE_VERSION_SCOPE
UNION ALL SELECT 'FCE_REF_OPERATION',COUNT(*) FROM FEE3.FCE_REF_OPERATION
UNION ALL SELECT 'FCE_REF_FORMULA',COUNT(*) FROM FEE3.FCE_REF_FORMULA
UNION ALL SELECT 'FCE_REF_SOURCE',COUNT(*) FROM FEE3.FCE_REF_SOURCE
UNION ALL SELECT 'FCE_AUDIT_EVENT',COUNT(*) FROM FEE3.FCE_AUDIT_EVENT;

SELECT sequence_name FROM ALL_SEQUENCES
WHERE sequence_owner='FEE3' AND sequence_name IN
 ('SEQ_FCE_CALC_ITEM','SEQ_FCE_TARIFF_VERSION','SEQ_FCE_CALC_RULE',
 'SEQ_FCE_VERSION_SCOPE','SEQ_FCE_TEST_CASE','SEQ_FCE_AUDIT_EVENT')
ORDER BY sequence_name;
