PROMPT === Active type -> plan mappings ===
SELECT lt.LOAN_TYPE_ID, lt.LOAN_TYPE_NAME, pt.PLAN_TYPE_ID, pt.PLAN_TYPE_NAME
FROM PDL.LOAN_TYPE_PLAN_TYPE link
JOIN PDL.LOAN_TYPE lt ON lt.LOAN_TYPE_ID = link.LOAN_TYPE_ID
JOIN PDL.PLAN_TYPE pt ON pt.PLAN_TYPE_ID = link.PLAN_TYPE_ID
WHERE link.RECORD_STATUS_CODE = 'ACTIVE' AND lt.RECORD_STATUS_CODE = 'ACTIVE'
  AND pt.RECORD_STATUS_CODE = 'ACTIVE'
ORDER BY lt.LOAN_TYPE_ID, pt.PLAN_TYPE_ID FETCH FIRST 100 ROWS ONLY;
