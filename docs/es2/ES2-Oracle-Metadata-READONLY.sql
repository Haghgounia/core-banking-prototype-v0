-- Run with an authorized read-only account in SQL Developer / SQLcl.
-- Stop if PST schema is incomplete; do NOT auto-migrate any Oracle schema.

-- A) Required Oracle columns, corresponding to EventStreamSchemaGuard.java.
WITH REQUIRED_COLUMNS AS (
 SELECT 'POSTING_OUTBOX_EVENTS' TABLE_NAME, 'IDENTIFIER' COLUMN_NAME FROM DUAL UNION ALL
 SELECT 'POSTING_OUTBOX_EVENTS', 'EVENT_IDENTIFIER' FROM DUAL UNION ALL
 SELECT 'POSTING_OUTBOX_EVENTS', 'AGGREGATE_REFERENCE' FROM DUAL UNION ALL
 SELECT 'POSTING_OUTBOX_EVENTS', 'EVENT_TYPE' FROM DUAL UNION ALL
 SELECT 'POSTING_OUTBOX_EVENTS', 'PAYLOAD_HASH' FROM DUAL UNION ALL
 SELECT 'POSTING_OUTBOX_EVENTS', 'DELIVERY_STATE' FROM DUAL UNION ALL
 SELECT 'POSTING_OUTBOX_EVENTS', 'CREATED_AT' FROM DUAL UNION ALL
 SELECT 'POSTING_OUTBOX_EVENTS', 'STREAM_PAYLOAD' FROM DUAL UNION ALL
 SELECT 'POSTING_OUTBOX_EVENTS', 'ATTEMPT_COUNT' FROM DUAL UNION ALL
 SELECT 'POSTING_OUTBOX_EVENTS', 'NEXT_ATTEMPT_AT' FROM DUAL UNION ALL
 SELECT 'POSTING_OUTBOX_EVENTS', 'LEASE_TOKEN' FROM DUAL UNION ALL
 SELECT 'POSTING_OUTBOX_EVENTS', 'LEASE_UNTIL' FROM DUAL UNION ALL
 SELECT 'POSTING_OUTBOX_EVENTS', 'PUBLISHED_AT' FROM DUAL UNION ALL
 SELECT 'POSTING_OUTBOX_EVENTS', 'LAST_ERROR' FROM DUAL UNION ALL
 SELECT 'POSTING_INBOX_RECEIPTS', 'IDENTIFIER' FROM DUAL UNION ALL
 SELECT 'POSTING_INBOX_RECEIPTS', 'SOURCE_DOMAIN' FROM DUAL UNION ALL
 SELECT 'POSTING_INBOX_RECEIPTS', 'SOURCE_EVENT_IDENTIFIER' FROM DUAL UNION ALL
 SELECT 'POSTING_INBOX_RECEIPTS', 'ACCOUNTING_PURPOSE' FROM DUAL UNION ALL
 SELECT 'POSTING_INBOX_RECEIPTS', 'PAYLOAD_HASH' FROM DUAL UNION ALL
 SELECT 'POSTING_INBOX_RECEIPTS', 'RECEIVED_AT' FROM DUAL
)
SELECT R.TABLE_NAME, R.COLUMN_NAME,
       CASE WHEN C.COLUMN_NAME IS NULL THEN 'MISSING' ELSE 'OK' END AS CHECK_RESULT
FROM REQUIRED_COLUMNS R
LEFT JOIN ALL_TAB_COLUMNS C ON C.OWNER='PST' AND C.TABLE_NAME=R.TABLE_NAME
 AND C.COLUMN_NAME=R.COLUMN_NAME
ORDER BY R.TABLE_NAME, R.COLUMN_NAME;

-- B) Required EXACT enabled/validated unique constraints (U, not PK) in source guard.
-- Expected: OUTBOX EVENT_IDENTIFIER; INBOX ACCOUNTING_PURPOSE,SOURCE_DOMAIN,SOURCE_EVENT_IDENTIFIER.
SELECT C.TABLE_NAME, C.CONSTRAINT_NAME, C.STATUS, C.VALIDATED,
       LISTAGG(CC.COLUMN_NAME, ',') WITHIN GROUP (ORDER BY CC.COLUMN_NAME) AS UNIQUE_COLUMNS
FROM ALL_CONSTRAINTS C
JOIN ALL_CONS_COLUMNS CC ON C.OWNER=CC.OWNER AND C.CONSTRAINT_NAME=CC.CONSTRAINT_NAME
 AND C.TABLE_NAME=CC.TABLE_NAME
WHERE C.OWNER='PST' AND C.TABLE_NAME IN ('POSTING_OUTBOX_EVENTS','POSTING_INBOX_RECEIPTS')
  AND C.CONSTRAINT_TYPE='U' AND C.STATUS='ENABLED' AND C.VALIDATED='VALIDATED'
GROUP BY C.TABLE_NAME, C.CONSTRAINT_NAME, C.STATUS, C.VALIDATED
ORDER BY C.TABLE_NAME, C.CONSTRAINT_NAME;

-- C) OPTIONAL AFTER SCHEMA VALIDATION. Non-PII aggregate counts of streaming outbox states.
SELECT DELIVERY_STATE, COUNT(*) AS RECORD_COUNT
FROM PST.POSTING_OUTBOX_EVENTS
WHERE STREAM_PAYLOAD IS NOT NULL
GROUP BY DELIVERY_STATE
ORDER BY DELIVERY_STATE;

-- D) OPTIONAL AFTER SCHEMA VALIDATION. Aggregate audit receipts; no payload inspection.
SELECT COUNT(*) AS STREAM_AUDIT_RECEIPT_COUNT
FROM PST.POSTING_INBOX_RECEIPTS
WHERE ACCOUNTING_PURPOSE LIKE 'STREAM_AUDIT:%';
