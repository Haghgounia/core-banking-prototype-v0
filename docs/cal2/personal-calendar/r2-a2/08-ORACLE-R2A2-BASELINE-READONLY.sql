PROMPT === R2A2 current CAL2 objects ===
SELECT OWNER, TABLE_NAME
  FROM ALL_TABLES
 WHERE OWNER='CAL2'
   AND TABLE_NAME IN ('USER_CALENDAR_ITEMS','USER_CALENDAR_ENTRIES',
     'USER_CALENDAR_RECURRENCE_RULES','USER_CALENDAR_OCCURRENCES',
     'USER_CALENDAR_REMINDER_RULES','USER_CALENDAR_ALERTS',
     'USER_CALENDAR_AUDIT_LOG','USER_CALENDAR_REQUEST_KEYS',
     'USER_CALENDAR_ALERT_DELIVERIES')
 ORDER BY TABLE_NAME;

PROMPT === R2A2 sequences: LAST_NUMBER is not exact next ID for cached sequences ===
SELECT SEQUENCE_OWNER, SEQUENCE_NAME, LAST_NUMBER, CACHE_SIZE, CYCLE_FLAG
  FROM ALL_SEQUENCES
 WHERE SEQUENCE_OWNER='CAL2'
   AND (SEQUENCE_NAME LIKE 'SEQ_CAL2_UC%'
        OR SEQUENCE_NAME IN ('SEQ_CAL2_USER_CALENDAR_ITEMS',
                            'SEQ_CAL2_USER_CALENDAR_ENTRIES'))
 ORDER BY SEQUENCE_NAME;

