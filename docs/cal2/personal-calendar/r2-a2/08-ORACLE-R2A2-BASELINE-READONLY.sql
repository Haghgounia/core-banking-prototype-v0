PROMPT === R2A2 base table counts, ID range and Demo actor checks ===
DECLARE
 v_r1b NUMBER;
 v_r1c NUMBER;
 v_count NUMBER;
 v_low NUMBER;
 v_high NUMBER;
 v_demo NUMBER;
 v_incoming NUMBER;
BEGIN
 SELECT COUNT(*) INTO v_r1b FROM ALL_TABLES
  WHERE OWNER='CAL2' AND TABLE_NAME='USER_CALENDAR_ITEMS';
 SELECT COUNT(*) INTO v_r1c FROM ALL_TABLES
  WHERE OWNER='CAL2' AND TABLE_NAME='USER_CALENDAR_ENTRIES';
 IF v_r1b=1 THEN
   EXECUTE IMMEDIATE
     'SELECT COUNT(*), MIN(USER_CALENDAR_ITEM_ID), MAX(USER_CALENDAR_ITEM_ID) FROM CAL2.USER_CALENDAR_ITEMS'
      INTO v_count, v_low, v_high;
   DBMS_OUTPUT.PUT_LINE('R1B_ROWS='||v_count||'; MIN_ID='||NVL(TO_CHAR(v_low),'NULL')||'; MAX_ID='||NVL(TO_CHAR(v_high),'NULL'));
   EXECUTE IMMEDIATE
     'SELECT COUNT(*) FROM CAL2.USER_CALENDAR_ITEMS WHERE ACTOR_KEY = :actor'
      INTO v_demo USING 'prototype-admin';
   DBMS_OUTPUT.PUT_LINE('R1B_DEMO_ACTOR_ROWS='||v_demo||' (do not auto-map to IAM)');
   SELECT COUNT(*) INTO v_incoming
     FROM ALL_CONSTRAINTS FK JOIN ALL_CONSTRAINTS PK
       ON FK.R_OWNER=PK.OWNER AND FK.R_CONSTRAINT_NAME=PK.CONSTRAINT_NAME
      WHERE FK.CONSTRAINT_TYPE='R' AND PK.OWNER='CAL2'
        AND PK.TABLE_NAME='USER_CALENDAR_ITEMS';
   DBMS_OUTPUT.PUT_LINE('R1B_INCOMING_FOREIGN_KEYS='||v_incoming);
 END IF;
 IF v_r1c=1 THEN
   DBMS_OUTPUT.PUT_LINE('WARNING: USER_CALENDAR_ENTRIES exists. This preflight cannot infer R1C vs R2 schema.');
 END IF;
 IF v_r1b=1 AND v_r1c=1 THEN
   DBMS_OUTPUT.PUT_LINE('STOP: BOTH legacy and target names present; manual inventory mandatory.');
 ELSIF v_r1b=1 THEN
   DBMS_OUTPUT.PUT_LINE('R1B source present; NO MIGRATION performed.');
 ELSE
   DBMS_OUTPUT.PUT_LINE('R1B source absent. Check environment/version before any migration.');
 END IF;
 DBMS_OUTPUT.PUT_LINE('R2A2_READONLY_INSPECTION_COMPLETE');
END;
