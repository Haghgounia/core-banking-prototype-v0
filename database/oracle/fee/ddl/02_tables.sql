-- Fee Prototype P1 - core standalone physical model
CREATE TABLE FEE.FEE_DEFINITION (
  FEE_DEFINITION_ID NUMBER(19,0) NOT NULL,
  FEE_CODE VARCHAR2(50 CHAR) NOT NULL,
  NAME_FA VARCHAR2(200 CHAR) NOT NULL,
  NAME_EN VARCHAR2(200 CHAR),
  DESCRIPTION VARCHAR2(1000 CHAR),
  CATEGORY_CODE VARCHAR2(50 CHAR),
  CLASSIFICATION_CODE VARCHAR2(30 CHAR) DEFAULT 'FEE' NOT NULL,
  STATUS_CODE VARCHAR2(30 CHAR) DEFAULT 'ACTIVE' NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY VARCHAR2(100 CHAR) NOT NULL,
  UPDATED_AT TIMESTAMP(6), UPDATED_BY VARCHAR2(100 CHAR),
  RECORD_VERSION NUMBER(10,0) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_FEE_DEFINITION PRIMARY KEY (FEE_DEFINITION_ID),
  CONSTRAINT UK_FEE_DEFINITION_CODE UNIQUE (FEE_CODE)
);

CREATE TABLE FEE.FEE_DEFINITION_VERSION (
  FEE_DEFINITION_VERSION_ID NUMBER(19,0) NOT NULL,
  FEE_DEFINITION_ID NUMBER(19,0) NOT NULL,
  VERSION_NO NUMBER(10,0) NOT NULL,
  LIFECYCLE_STATUS_CODE VARCHAR2(30 CHAR) DEFAULT 'DRAFT' NOT NULL,
  EFFECTIVE_FROM DATE NOT NULL, EFFECTIVE_TO DATE,
  APPROVED_AT TIMESTAMP(6), APPROVED_BY VARCHAR2(100 CHAR),
  ACTIVATED_AT TIMESTAMP(6), ACTIVATED_BY VARCHAR2(100 CHAR),
  CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL, CREATED_BY VARCHAR2(100 CHAR) NOT NULL,
  UPDATED_AT TIMESTAMP(6), UPDATED_BY VARCHAR2(100 CHAR), RECORD_VERSION NUMBER(10,0) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_FEE_DEF_VERSION PRIMARY KEY (FEE_DEFINITION_VERSION_ID),
  CONSTRAINT FK_FEE_DEF_VERSION_DEF FOREIGN KEY (FEE_DEFINITION_ID) REFERENCES FEE.FEE_DEFINITION(FEE_DEFINITION_ID),
  CONSTRAINT UK_FEE_DEF_VERSION UNIQUE (FEE_DEFINITION_ID, VERSION_NO),
  CONSTRAINT CK_FEE_DEF_VERSION_DATES CHECK (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO >= EFFECTIVE_FROM)
);

CREATE TABLE FEE.FEE_APPLICABILITY_RULE (
  APPLICABILITY_RULE_ID NUMBER(19,0) NOT NULL, FEE_DEFINITION_VERSION_ID NUMBER(19,0) NOT NULL,
  RULE_CODE VARCHAR2(50 CHAR) NOT NULL, NAME_FA VARCHAR2(200 CHAR), PRIORITY_NO NUMBER(10,0) DEFAULT 100 NOT NULL,
  MATCH_MODE_CODE VARCHAR2(20 CHAR) DEFAULT 'ALL' NOT NULL, ACTION_CODE VARCHAR2(20 CHAR) DEFAULT 'APPLY' NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL, CREATED_BY VARCHAR2(100 CHAR) NOT NULL,
  CONSTRAINT PK_FEE_APPLICABILITY_RULE PRIMARY KEY (APPLICABILITY_RULE_ID),
  CONSTRAINT FK_FEE_APP_RULE_VERSION FOREIGN KEY (FEE_DEFINITION_VERSION_ID) REFERENCES FEE.FEE_DEFINITION_VERSION(FEE_DEFINITION_VERSION_ID),
  CONSTRAINT UK_FEE_APP_RULE UNIQUE (FEE_DEFINITION_VERSION_ID, RULE_CODE)
);

CREATE TABLE FEE.FEE_APPLICABILITY_CONDITION (
  CONDITION_ID NUMBER(19,0) NOT NULL, APPLICABILITY_RULE_ID NUMBER(19,0) NOT NULL, SEQUENCE_NO NUMBER(5,0) NOT NULL,
