  TEXT_VALUE VARCHAR2(200 CHAR), NUMBER_VALUE_FROM NUMBER(23,4), NUMBER_VALUE_TO NUMBER(23,4), DATE_VALUE_FROM DATE, DATE_VALUE_TO DATE,
  CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL, CREATED_BY VARCHAR2(100 CHAR) NOT NULL,
  CONSTRAINT PK_FEE_APP_CONDITION PRIMARY KEY (CONDITION_ID),
  CONSTRAINT FK_FEE_APP_COND_RULE FOREIGN KEY (APPLICABILITY_RULE_ID) REFERENCES FEE.FEE_APPLICABILITY_RULE(APPLICABILITY_RULE_ID)
