  CONSTRAINT PK_FEE_CALC_TIER PRIMARY KEY (CALCULATION_TIER_ID),
  CONSTRAINT FK_FEE_CALC_TIER_RULE FOREIGN KEY (CALCULATION_RULE_ID) REFERENCES FEE.FEE_CALCULATION_RULE(CALCULATION_RULE_ID),
