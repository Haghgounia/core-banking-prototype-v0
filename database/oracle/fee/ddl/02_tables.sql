CREATE TABLE FEE.FEE_CALCULATION_RULE (
  CALCULATION_RULE_ID NUMBER(19,0) NOT NULL, FEE_DEFINITION_VERSION_ID NUMBER(19,0) NOT NULL, APPLICABILITY_RULE_ID NUMBER(19,0),
  RULE_CODE VARCHAR2(50 CHAR) NOT NULL, PRIORITY_NO NUMBER(10,0) DEFAULT 100 NOT NULL,
  CALCULATION_STRATEGY_CODE VARCHAR2(40 CHAR) NOT NULL, BASIS_TYPE_CODE VARCHAR2(30 CHAR) DEFAULT 'AMOUNT' NOT NULL,
  FIXED_AMOUNT NUMBER(23,4), RATE_VALUE NUMBER(18,10), MIN_FEE_AMOUNT NUMBER(23,4), MAX_FEE_AMOUNT NUMBER(23,4),
  CURRENCY_CODE VARCHAR2(50 CHAR), ROUNDING_MODE_CODE VARCHAR2(30 CHAR) DEFAULT 'HALF_UP' NOT NULL, ROUNDING_SCALE NUMBER(2,0) DEFAULT 0 NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL, CREATED_BY VARCHAR2(100 CHAR) NOT NULL,
  CONSTRAINT PK_FEE_CALC_RULE PRIMARY KEY (CALCULATION_RULE_ID),
  CONSTRAINT FK_FEE_CALC_RULE_VERSION FOREIGN KEY (FEE_DEFINITION_VERSION_ID) REFERENCES FEE.FEE_DEFINITION_VERSION(FEE_DEFINITION_VERSION_ID),
  CONSTRAINT FK_FEE_CALC_RULE_APP FOREIGN KEY (APPLICABILITY_RULE_ID) REFERENCES FEE.FEE_APPLICABILITY_RULE(APPLICABILITY_RULE_ID),
  CONSTRAINT UK_FEE_CALC_RULE UNIQUE (FEE_DEFINITION_VERSION_ID, RULE_CODE),
  CONSTRAINT CK_FEE_CALC_RATE CHECK (RATE_VALUE IS NULL OR RATE_VALUE >= 0),
  CONSTRAINT CK_FEE_CALC_MINMAX CHECK (MIN_FEE_AMOUNT IS NULL OR MAX_FEE_AMOUNT IS NULL OR MAX_FEE_AMOUNT >= MIN_FEE_AMOUNT)
);

CREATE TABLE FEE.FEE_CALCULATION_TIER (
