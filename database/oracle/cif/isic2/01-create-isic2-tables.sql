-- ============================================================================
-- CIF ISIC2 Reference Data - release-aware, hierarchical design
-- Oracle 19c+
-- IMPORTANT: this script DOES NOT change/drop CIF.REF_ISIC_ACTIVITY (legacy).
-- It creates CIF.REF_ISIC_RELEASE, CIF.REF_ISIC_ACTIVITY2 and lookup view V_REF_ISIC_ACTIVITY_LOOKUP2.
-- ============================================================================

DECLARE
    V_COUNT NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_COUNT FROM ALL_TABLES WHERE OWNER='CIF' AND TABLE_NAME='REF_ISIC_RELEASE';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE q'~
CREATE TABLE CIF.REF_ISIC_RELEASE (
    ISIC_RELEASE_ID       NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CLASSIFICATION_CODE   VARCHAR2(20 CHAR) DEFAULT 'ISIC' NOT NULL,
    REVISION_CODE         VARCHAR2(10 CHAR) NOT NULL,
    VARIANT_CODE          VARCHAR2(30 CHAR) NOT NULL,
    COUNTRY_CODE          VARCHAR2(2 CHAR),
    NAME_FA               VARCHAR2(500 CHAR),
    NAME_EN               VARCHAR2(500 CHAR) NOT NULL,
    SOURCE_AUTHORITY      VARCHAR2(100 CHAR) NOT NULL,
    SOURCE_URI            VARCHAR2(1000 CHAR),
    PUBLICATION_DATE      DATE,
    DATASET_STATUS_CODE   VARCHAR2(20 CHAR) DEFAULT 'COMPLETE' NOT NULL,
    IS_CURRENT            NUMBER(1) DEFAULT 0 NOT NULL,
    IS_ACTIVE             NUMBER(1) DEFAULT 1 NOT NULL,
    VALID_FROM            DATE,
    VALID_TO              DATE,
    RECORD_VERSION        NUMBER(10) DEFAULT 1 NOT NULL,
    CREATED_BY            VARCHAR2(100 CHAR) DEFAULT 'SYSTEM' NOT NULL,
    CREATED_DATE          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_MODIFIED_BY      VARCHAR2(100 CHAR),
    LAST_MODIFIED_DATE    TIMESTAMP(6),
    CONSTRAINT PK_REF_ISIC_RELEASE PRIMARY KEY (ISIC_RELEASE_ID) USING INDEX TABLESPACE ITS_CIF,
    CONSTRAINT UK_REF_ISIC_RELEASE_NK UNIQUE (CLASSIFICATION_CODE, REVISION_CODE, VARIANT_CODE) USING INDEX TABLESPACE ITS_CIF,
    CONSTRAINT CK_REF_ISIC_REL_COUNTRY CHECK (COUNTRY_CODE IS NULL OR REGEXP_LIKE(COUNTRY_CODE, '^[A-Z]{2}$')),
    CONSTRAINT CK_REF_ISIC_REL_DATASET CHECK (DATASET_STATUS_CODE IN ('DRAFT','PARTIAL','COMPLETE','RETIRED')),
    CONSTRAINT CK_REF_ISIC_REL_CURRENT CHECK (IS_CURRENT IN (0,1)),
    CONSTRAINT CK_REF_ISIC_REL_ACTIVE CHECK (IS_ACTIVE IN (0,1)),
    CONSTRAINT CK_REF_ISIC_REL_DATES CHECK (VALID_TO IS NULL OR VALID_FROM IS NULL OR VALID_TO >= VALID_FROM)
) TABLESPACE TS_CIF
~';
    END IF;
END;
/

DECLARE
    V_COUNT NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_COUNT FROM ALL_TABLES WHERE OWNER='CIF' AND TABLE_NAME='REF_ISIC_ACTIVITY2';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE q'~
CREATE TABLE CIF.REF_ISIC_ACTIVITY2 (
    ISIC_ACTIVITY_ID      NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ISIC_RELEASE_ID       NUMBER(19) NOT NULL,
    ISIC_CODE             VARCHAR2(30 CHAR) NOT NULL,
    BASE_ISIC_CODE        VARCHAR2(4 CHAR),
    LEVEL_CODE            VARCHAR2(20 CHAR) NOT NULL,
    PARENT_ISIC_CODE      VARCHAR2(30 CHAR),
    SECTION_CODE          VARCHAR2(1 CHAR) NOT NULL,
    NAME_FA               VARCHAR2(500 CHAR),
    NAME_EN               VARCHAR2(500 CHAR) NOT NULL,
    DESCRIPTION_FA        CLOB,
    DESCRIPTION_EN        CLOB,
    INCLUSIONS_FA         CLOB,
    INCLUSIONS_EN         CLOB,
    EXCLUSIONS_FA         CLOB,
    EXCLUSIONS_EN         CLOB,
    TRANSLATION_STATUS    VARCHAR2(20 CHAR) DEFAULT 'NOT_AVAILABLE' NOT NULL,
    IS_SELECTABLE         NUMBER(1) DEFAULT 0 NOT NULL,
    IS_ACTIVE             NUMBER(1) DEFAULT 1 NOT NULL,
    VALID_FROM            DATE,
    VALID_TO              DATE,
    SORT_ORDER            NUMBER(10) DEFAULT 0 NOT NULL,
    RECORD_VERSION        NUMBER(10) DEFAULT 1 NOT NULL,
    CREATED_BY            VARCHAR2(100 CHAR) DEFAULT 'SYSTEM' NOT NULL,
    CREATED_DATE          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_MODIFIED_BY      VARCHAR2(100 CHAR),
    LAST_MODIFIED_DATE    TIMESTAMP(6),
    CONSTRAINT PK_REF_ISIC_ACTIVITY2 PRIMARY KEY (ISIC_ACTIVITY_ID) USING INDEX TABLESPACE ITS_CIF,
    CONSTRAINT UK_REF_ISIC_ACTIVITY2_NK UNIQUE (ISIC_RELEASE_ID, ISIC_CODE) USING INDEX TABLESPACE ITS_CIF,
    CONSTRAINT FK_REF_ISIC_ACTIVITY2_REL FOREIGN KEY (ISIC_RELEASE_ID)
        REFERENCES CIF.REF_ISIC_RELEASE (ISIC_RELEASE_ID),
    CONSTRAINT FK_REF_ISIC_ACTIVITY2_PAR FOREIGN KEY (ISIC_RELEASE_ID, PARENT_ISIC_CODE)
        REFERENCES CIF.REF_ISIC_ACTIVITY2 (ISIC_RELEASE_ID, ISIC_CODE)
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT CK_REF_ISIC2_LEVEL CHECK (LEVEL_CODE IN ('SECTION','DIVISION','GROUP','CLASS','NATIONAL_SUBCLASS')),
    CONSTRAINT CK_REF_ISIC2_SECTION CHECK (REGEXP_LIKE(SECTION_CODE, '^[A-U]$')),
    CONSTRAINT CK_REF_ISIC2_CODE_FORMAT CHECK (
           (LEVEL_CODE = 'SECTION'  AND REGEXP_LIKE(ISIC_CODE, '^[A-U]$'))
        OR (LEVEL_CODE = 'DIVISION' AND REGEXP_LIKE(ISIC_CODE, '^[0-9]{2}$'))
        OR (LEVEL_CODE = 'GROUP'    AND REGEXP_LIKE(ISIC_CODE, '^[0-9]{3}$'))
        OR (LEVEL_CODE = 'CLASS'    AND REGEXP_LIKE(ISIC_CODE, '^[0-9]{4}$'))
        OR (LEVEL_CODE = 'NATIONAL_SUBCLASS' AND REGEXP_LIKE(ISIC_CODE, '^[0-9A-Z./-]+$'))
    ),
    CONSTRAINT CK_REF_ISIC2_PARENT CHECK (
        (LEVEL_CODE = 'SECTION' AND PARENT_ISIC_CODE IS NULL)
        OR (LEVEL_CODE <> 'SECTION' AND PARENT_ISIC_CODE IS NOT NULL)
    ),
    CONSTRAINT CK_REF_ISIC2_SELECTABLE CHECK (IS_SELECTABLE IN (0,1)),
    CONSTRAINT CK_REF_ISIC2_SELECT_CLASS CHECK (IS_SELECTABLE = 0 OR LEVEL_CODE IN ('CLASS','NATIONAL_SUBCLASS')),
    CONSTRAINT CK_REF_ISIC2_ACTIVE CHECK (IS_ACTIVE IN (0,1)),
    CONSTRAINT CK_REF_ISIC2_TRANSLATION CHECK (TRANSLATION_STATUS IN ('OFFICIAL','BANK_VERIFIED','BANK_TRANSLATED','NOT_AVAILABLE')),
    CONSTRAINT CK_REF_ISIC2_DATES CHECK (VALID_TO IS NULL OR VALID_FROM IS NULL OR VALID_TO >= VALID_FROM)
) TABLESPACE TS_CIF
~';
    END IF;
END;
/

DECLARE V_COUNT NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_COUNT FROM ALL_INDEXES WHERE OWNER='CIF' AND INDEX_NAME='IX_REF_ISIC2_PARENT';
    IF V_COUNT=0 THEN EXECUTE IMMEDIATE 'CREATE INDEX CIF.IX_REF_ISIC2_PARENT ON CIF.REF_ISIC_ACTIVITY2 (ISIC_RELEASE_ID, PARENT_ISIC_CODE, LEVEL_CODE, SORT_ORDER) TABLESPACE ITS_CIF'; END IF;
    SELECT COUNT(*) INTO V_COUNT FROM ALL_INDEXES WHERE OWNER='CIF' AND INDEX_NAME='IX_REF_ISIC2_LOOKUP';
    IF V_COUNT=0 THEN EXECUTE IMMEDIATE 'CREATE INDEX CIF.IX_REF_ISIC2_LOOKUP ON CIF.REF_ISIC_ACTIVITY2 (ISIC_RELEASE_ID, IS_ACTIVE, IS_SELECTABLE, ISIC_CODE) TABLESPACE ITS_CIF'; END IF;
    SELECT COUNT(*) INTO V_COUNT FROM ALL_INDEXES WHERE OWNER='CIF' AND INDEX_NAME='IX_REF_ISIC2_NAME_EN';
    IF V_COUNT=0 THEN EXECUTE IMMEDIATE 'CREATE INDEX CIF.IX_REF_ISIC2_NAME_EN ON CIF.REF_ISIC_ACTIVITY2 (NAME_EN) TABLESPACE ITS_CIF'; END IF;
    SELECT COUNT(*) INTO V_COUNT FROM ALL_INDEXES WHERE OWNER='CIF' AND INDEX_NAME='IX_REF_ISIC2_NAME_FA';
    IF V_COUNT=0 THEN EXECUTE IMMEDIATE 'CREATE INDEX CIF.IX_REF_ISIC2_NAME_FA ON CIF.REF_ISIC_ACTIVITY2 (NAME_FA) TABLESPACE ITS_CIF'; END IF;
END;
/

COMMENT ON TABLE CIF.REF_ISIC_RELEASE IS 'ISIC classification release/variant registry. Separates international UNSD releases from national adaptations such as IR-SCI.';
COMMENT ON TABLE CIF.REF_ISIC_ACTIVITY2 IS 'New release-aware hierarchical ISIC activity table. Legacy CIF.REF_ISIC_ACTIVITY remains unchanged.';
COMMENT ON COLUMN CIF.REF_ISIC_ACTIVITY2.ISIC_CODE IS 'Code is unique only inside one ISIC release/variant.';
COMMENT ON COLUMN CIF.REF_ISIC_ACTIVITY2.IS_SELECTABLE IS '1 only for selectable leaf codes (CLASS or NATIONAL_SUBCLASS).';
COMMENT ON COLUMN CIF.REF_ISIC_ACTIVITY2.TRANSLATION_STATUS IS 'OFFICIAL/BANK_VERIFIED/BANK_TRANSLATED/NOT_AVAILABLE.';

CREATE OR REPLACE VIEW CIF.V_REF_ISIC_ACTIVITY_LOOKUP2 AS
SELECT
    A.ISIC_ACTIVITY_ID,
    A.ISIC_RELEASE_ID,
    R.CLASSIFICATION_CODE,
    R.REVISION_CODE,
    R.VARIANT_CODE,
    R.COUNTRY_CODE,
    A.ISIC_CODE,
    A.BASE_ISIC_CODE,
    A.LEVEL_CODE,
    A.PARENT_ISIC_CODE,
    A.SECTION_CODE,
    A.NAME_FA,
    A.NAME_EN,
    COALESCE(A.NAME_FA, A.NAME_EN) AS DISPLAY_NAME,
    A.TRANSLATION_STATUS,
    A.IS_SELECTABLE,
    A.IS_ACTIVE,
    R.IS_CURRENT AS RELEASE_IS_CURRENT
FROM CIF.REF_ISIC_ACTIVITY2 A
JOIN CIF.REF_ISIC_RELEASE R ON R.ISIC_RELEASE_ID = A.ISIC_RELEASE_ID
WHERE R.IS_ACTIVE = 1
  AND A.IS_ACTIVE = 1;

