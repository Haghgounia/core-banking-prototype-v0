-- ============================================================================
-- CIF ISIC Reference Data - release-aware hierarchy + normalized notes
-- Oracle 19c+
--
-- ISIC defines classification structure/content, not Oracle physical types.
-- The core hierarchy is stored in REF_ISIC_ACTIVITY2. Long explanatory content
-- is normalized into REF_ISIC_ACTIVITY_NOTE by note type and language.
-- ============================================================================

CREATE TABLE CIF.REF_ISIC_RELEASE (
    ISIC_RELEASE_ID       NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CLASSIFICATION_CODE   VARCHAR2(20 CHAR) DEFAULT 'ISIC' NOT NULL,
    REVISION_CODE         VARCHAR2(10 CHAR) NOT NULL,
    VARIANT_CODE          VARCHAR2(30 CHAR) NOT NULL,
    COUNTRY_CODE          VARCHAR2(2 CHAR),
    NAME_FA               VARCHAR2(500 CHAR) NOT NULL,
    NAME_EN               VARCHAR2(500 CHAR) NOT NULL,
    SOURCE_AUTHORITY      VARCHAR2(200 CHAR) NOT NULL,
    SOURCE_URI            VARCHAR2(1000 CHAR),
    PUBLICATION_DATE      DATE,
    DATASET_STATUS_CODE   VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
    IS_CURRENT            NUMBER(1) DEFAULT 0 NOT NULL,
    IS_ACTIVE             NUMBER(1) DEFAULT 1 NOT NULL,
    VALID_FROM            DATE,
    VALID_TO              DATE,
    RECORD_VERSION        NUMBER(10) DEFAULT 1 NOT NULL,
    CREATED_BY            VARCHAR2(100 CHAR) DEFAULT 'SYSTEM' NOT NULL,
    CREATED_DATE          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_MODIFIED_BY      VARCHAR2(100 CHAR),
    LAST_MODIFIED_DATE    TIMESTAMP(6),
    CONSTRAINT PK_REF_ISIC_RELEASE PRIMARY KEY (ISIC_RELEASE_ID) USING INDEX TABLESPACE ITS_CIF,
    CONSTRAINT CK_REF_ISIC_REL_COUNTRY CHECK (COUNTRY_CODE IS NULL OR REGEXP_LIKE(COUNTRY_CODE, '^[A-Z]{2}$')),
    CONSTRAINT CK_REF_ISIC_REL_DATASET CHECK (DATASET_STATUS_CODE IN ('DRAFT','PARTIAL','COMPLETE','RETIRED')),
    CONSTRAINT CK_REF_ISIC_REL_CURRENT CHECK (IS_CURRENT IN (0,1)),
    CONSTRAINT CK_REF_ISIC_REL_ACTIVE CHECK (IS_ACTIVE IN (0,1)),
    CONSTRAINT CK_REF_ISIC_REL_DATES CHECK (VALID_TO IS NULL OR VALID_FROM IS NULL OR VALID_TO >= VALID_FROM),
    CONSTRAINT CK_REF_ISIC_REL_VERSION CHECK (RECORD_VERSION >= 1)
) TABLESPACE TS_CIF;

CREATE UNIQUE INDEX CIF.UX_REF_ISIC_RELEASE_NK
    ON CIF.REF_ISIC_RELEASE (
        CLASSIFICATION_CODE,
        REVISION_CODE,
        VARIANT_CODE,
        NVL(COUNTRY_CODE, '~')
    ) TABLESPACE ITS_CIF;

CREATE TABLE CIF.REF_ISIC_ACTIVITY2 (
    ISIC_ACTIVITY_ID        NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ISIC_RELEASE_ID         NUMBER(19) NOT NULL,
    PARENT_ACTIVITY_ID      NUMBER(19),
    ISIC_CODE               VARCHAR2(30 CHAR) NOT NULL,
    LEVEL_CODE              VARCHAR2(20 CHAR) NOT NULL,
    LEVEL_NO                NUMBER(2) NOT NULL,
    NAME_FA                 VARCHAR2(500 CHAR) NOT NULL,
    NAME_EN                 VARCHAR2(500 CHAR) NOT NULL,
    TRANSLATION_STATUS_CODE VARCHAR2(20 CHAR) DEFAULT 'BANK_TRANSLATED' NOT NULL,
    IS_SELECTABLE           NUMBER(1) DEFAULT 0 NOT NULL,
    IS_ACTIVE               NUMBER(1) DEFAULT 1 NOT NULL,
    SORT_ORDER              NUMBER(10) DEFAULT 0 NOT NULL,
    VALID_FROM              DATE,
    VALID_TO                DATE,
    RECORD_VERSION          NUMBER(10) DEFAULT 1 NOT NULL,
    CREATED_BY              VARCHAR2(100 CHAR) DEFAULT 'SYSTEM' NOT NULL,
    CREATED_DATE            TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_MODIFIED_BY        VARCHAR2(100 CHAR),
    LAST_MODIFIED_DATE      TIMESTAMP(6),
    CONSTRAINT PK_REF_ISIC_ACTIVITY2 PRIMARY KEY (ISIC_ACTIVITY_ID) USING INDEX TABLESPACE ITS_CIF,
    CONSTRAINT UK_REF_ISIC_ACTIVITY2_NK UNIQUE (ISIC_RELEASE_ID, ISIC_CODE) USING INDEX TABLESPACE ITS_CIF,
    CONSTRAINT UK_REF_ISIC_ACTIVITY2_RID UNIQUE (ISIC_RELEASE_ID, ISIC_ACTIVITY_ID) USING INDEX TABLESPACE ITS_CIF,
    CONSTRAINT FK_REF_ISIC_ACTIVITY2_REL FOREIGN KEY (ISIC_RELEASE_ID)
        REFERENCES CIF.REF_ISIC_RELEASE (ISIC_RELEASE_ID),
    CONSTRAINT FK_REF_ISIC_ACTIVITY2_PAR FOREIGN KEY (ISIC_RELEASE_ID, PARENT_ACTIVITY_ID)
        REFERENCES CIF.REF_ISIC_ACTIVITY2 (ISIC_RELEASE_ID, ISIC_ACTIVITY_ID),
    CONSTRAINT CK_REF_ISIC2_LEVEL CHECK (LEVEL_CODE IN ('SECTION','DIVISION','GROUP','CLASS','NATIONAL_SUBCLASS')),
    CONSTRAINT CK_REF_ISIC2_LEVEL_NO CHECK (
           (LEVEL_CODE='SECTION' AND LEVEL_NO=1)
        OR (LEVEL_CODE='DIVISION' AND LEVEL_NO=2)
        OR (LEVEL_CODE='GROUP' AND LEVEL_NO=3)
        OR (LEVEL_CODE='CLASS' AND LEVEL_NO=4)
        OR (LEVEL_CODE='NATIONAL_SUBCLASS' AND LEVEL_NO=5)
    ),
    CONSTRAINT CK_REF_ISIC2_CODE_FORMAT CHECK (
           (LEVEL_CODE = 'SECTION'  AND REGEXP_LIKE(ISIC_CODE, '^[A-U]$'))
        OR (LEVEL_CODE = 'DIVISION' AND REGEXP_LIKE(ISIC_CODE, '^[0-9]{2}$'))
        OR (LEVEL_CODE = 'GROUP'    AND REGEXP_LIKE(ISIC_CODE, '^[0-9]{3}$'))
        OR (LEVEL_CODE = 'CLASS'    AND REGEXP_LIKE(ISIC_CODE, '^[0-9]{4}$'))
        OR (LEVEL_CODE = 'NATIONAL_SUBCLASS' AND REGEXP_LIKE(ISIC_CODE, '^[0-9A-Z./-]+$'))
    ),
    CONSTRAINT CK_REF_ISIC2_PARENT CHECK (
        (LEVEL_CODE='SECTION' AND PARENT_ACTIVITY_ID IS NULL)
        OR (LEVEL_CODE<>'SECTION' AND PARENT_ACTIVITY_ID IS NOT NULL)
    ),
    CONSTRAINT CK_REF_ISIC2_PARENT_SELF CHECK (PARENT_ACTIVITY_ID IS NULL OR PARENT_ACTIVITY_ID <> ISIC_ACTIVITY_ID),
    CONSTRAINT CK_REF_ISIC2_SELECTABLE CHECK (IS_SELECTABLE IN (0,1)),
    CONSTRAINT CK_REF_ISIC2_SELECT_LEVEL CHECK (
           (LEVEL_CODE IN ('SECTION','DIVISION','GROUP') AND IS_SELECTABLE=0)
        OR (LEVEL_CODE IN ('CLASS','NATIONAL_SUBCLASS') AND IS_SELECTABLE=1)
    ),
    CONSTRAINT CK_REF_ISIC2_ACTIVE CHECK (IS_ACTIVE IN (0,1)),
    CONSTRAINT CK_REF_ISIC2_TRANSLATION CHECK (TRANSLATION_STATUS_CODE IN ('OFFICIAL','BANK_VERIFIED','BANK_TRANSLATED','NOT_AVAILABLE')),
    CONSTRAINT CK_REF_ISIC2_DATES CHECK (VALID_TO IS NULL OR VALID_FROM IS NULL OR VALID_TO >= VALID_FROM),
    CONSTRAINT CK_REF_ISIC2_SORT CHECK (SORT_ORDER >= 0),
    CONSTRAINT CK_REF_ISIC2_VERSION CHECK (RECORD_VERSION >= 1)
) TABLESPACE TS_CIF;

-- Long explanatory content is separated from the hierarchy. The four note
-- concepts reflect the structure commonly used in UNSD ISIC explanatory notes:
-- EXPLANATORY, INCLUDES, ALSO_INCLUDES and EXCLUDES.
CREATE TABLE CIF.REF_ISIC_ACTIVITY_NOTE (
    ISIC_ACTIVITY_NOTE_ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ISIC_ACTIVITY_ID      NUMBER(19) NOT NULL,
    NOTE_TYPE_CODE        VARCHAR2(30 CHAR) NOT NULL,
    LANGUAGE_CODE         VARCHAR2(5 CHAR) NOT NULL,
    NOTE_TEXT             CLOB NOT NULL,
    SORT_ORDER            NUMBER(10) DEFAULT 0 NOT NULL,
    RECORD_VERSION        NUMBER(10) DEFAULT 1 NOT NULL,
    CREATED_BY            VARCHAR2(100 CHAR) DEFAULT 'SYSTEM' NOT NULL,
    CREATED_DATE          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_MODIFIED_BY      VARCHAR2(100 CHAR),
    LAST_MODIFIED_DATE    TIMESTAMP(6),
    CONSTRAINT PK_REF_ISIC_ACTIVITY_NOTE PRIMARY KEY (ISIC_ACTIVITY_NOTE_ID) USING INDEX TABLESPACE ITS_CIF,
    CONSTRAINT UK_REF_ISIC_ACTIVITY_NOTE UNIQUE (ISIC_ACTIVITY_ID, NOTE_TYPE_CODE, LANGUAGE_CODE) USING INDEX TABLESPACE ITS_CIF,
    CONSTRAINT FK_REF_ISIC_ACTIVITY_NOTE FOREIGN KEY (ISIC_ACTIVITY_ID)
        REFERENCES CIF.REF_ISIC_ACTIVITY2 (ISIC_ACTIVITY_ID) ON DELETE CASCADE,
    CONSTRAINT CK_REF_ISIC_NOTE_TYPE CHECK (NOTE_TYPE_CODE IN ('EXPLANATORY','INCLUDES','ALSO_INCLUDES','EXCLUDES')),
    CONSTRAINT CK_REF_ISIC_NOTE_LANG CHECK (REGEXP_LIKE(LANGUAGE_CODE, '^[a-z]{2}(-[A-Z]{2})?$')),
    CONSTRAINT CK_REF_ISIC_NOTE_SORT CHECK (SORT_ORDER >= 0),
    CONSTRAINT CK_REF_ISIC_NOTE_VERSION CHECK (RECORD_VERSION >= 1)
) TABLESPACE TS_CIF
LOB (NOTE_TEXT) STORE AS SECUREFILE (
    TABLESPACE TS_CIF ENABLE STORAGE IN ROW 4000 CHUNK 8192 NOCACHE LOGGING NOCOMPRESS KEEP_DUPLICATES
);

CREATE INDEX CIF.IX_REF_ISIC2_PARENT
    ON CIF.REF_ISIC_ACTIVITY2 (ISIC_RELEASE_ID, PARENT_ACTIVITY_ID, LEVEL_NO, SORT_ORDER) TABLESPACE ITS_CIF;
CREATE INDEX CIF.IX_REF_ISIC2_LOOKUP
    ON CIF.REF_ISIC_ACTIVITY2 (ISIC_RELEASE_ID, IS_ACTIVE, IS_SELECTABLE, ISIC_CODE) TABLESPACE ITS_CIF;
CREATE INDEX CIF.IX_REF_ISIC2_NAME_FA
    ON CIF.REF_ISIC_ACTIVITY2 (NAME_FA) TABLESPACE ITS_CIF;
CREATE INDEX CIF.IX_REF_ISIC2_NAME_EN
    ON CIF.REF_ISIC_ACTIVITY2 (NAME_EN) TABLESPACE ITS_CIF;
CREATE INDEX CIF.IX_REF_ISIC_NOTE_ACTIVITY
    ON CIF.REF_ISIC_ACTIVITY_NOTE (ISIC_ACTIVITY_ID, SORT_ORDER, NOTE_TYPE_CODE, LANGUAGE_CODE) TABLESPACE ITS_CIF;

COMMENT ON TABLE CIF.REF_ISIC_RELEASE IS 'Registry of ISIC releases, revisions and national/international variants.';
COMMENT ON TABLE CIF.REF_ISIC_ACTIVITY2 IS 'Release-aware hierarchical ISIC activity tree with mandatory bilingual names.';
COMMENT ON TABLE CIF.REF_ISIC_ACTIVITY_NOTE IS 'Language-aware explanatory content for an ISIC activity; note types are EXPLANATORY/INCLUDES/ALSO_INCLUDES/EXCLUDES.';
COMMENT ON COLUMN CIF.REF_ISIC_ACTIVITY2.PARENT_ACTIVITY_ID IS 'Self FK to the parent node in the same ISIC release.';
COMMENT ON COLUMN CIF.REF_ISIC_ACTIVITY2.LEVEL_NO IS '1=SECTION, 2=DIVISION, 3=GROUP, 4=CLASS, 5=NATIONAL_SUBCLASS.';
COMMENT ON COLUMN CIF.REF_ISIC_ACTIVITY2.TRANSLATION_STATUS_CODE IS 'OFFICIAL/BANK_VERIFIED/BANK_TRANSLATED/NOT_AVAILABLE.';
COMMENT ON COLUMN CIF.REF_ISIC_ACTIVITY2.IS_SELECTABLE IS '1 only for CLASS or NATIONAL_SUBCLASS nodes selectable by business forms.';
COMMENT ON COLUMN CIF.REF_ISIC_ACTIVITY_NOTE.NOTE_TYPE_CODE IS 'EXPLANATORY/INCLUDES/ALSO_INCLUDES/EXCLUDES.';
COMMENT ON COLUMN CIF.REF_ISIC_ACTIVITY_NOTE.LANGUAGE_CODE IS 'BCP-47-like short language tag; current UI uses fa/en.';

CREATE OR REPLACE VIEW CIF.V_REF_ISIC_ACTIVITY_LOOKUP2 AS
SELECT
    A.ISIC_ACTIVITY_ID,
    A.ISIC_RELEASE_ID,
    R.CLASSIFICATION_CODE,
    R.REVISION_CODE,
    R.VARIANT_CODE,
    R.COUNTRY_CODE,
    A.PARENT_ACTIVITY_ID,
    P.ISIC_CODE AS PARENT_ISIC_CODE,
    P.NAME_FA AS PARENT_NAME_FA,
    A.ISIC_CODE,
    A.LEVEL_CODE,
    A.LEVEL_NO,
    A.NAME_FA,
    A.NAME_EN,
    A.NAME_FA AS DISPLAY_NAME,
    A.TRANSLATION_STATUS_CODE,
    A.IS_SELECTABLE,
    A.IS_ACTIVE,
    A.SORT_ORDER,
    R.IS_CURRENT AS RELEASE_IS_CURRENT,
    R.DATASET_STATUS_CODE AS RELEASE_DATASET_STATUS
FROM CIF.REF_ISIC_ACTIVITY2 A
JOIN CIF.REF_ISIC_RELEASE R ON R.ISIC_RELEASE_ID = A.ISIC_RELEASE_ID
LEFT JOIN CIF.REF_ISIC_ACTIVITY2 P ON P.ISIC_ACTIVITY_ID = A.PARENT_ACTIVITY_ID
WHERE R.IS_ACTIVE = 1
  AND A.IS_ACTIVE = 1;

