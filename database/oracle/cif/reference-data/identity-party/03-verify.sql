PROMPT === Operational lookup smoke checks ===
SELECT PARTY_TYPE_CODE, NAME_FA, IS_ACTIVE FROM CIF.REF_PARTY_TYPE WHERE PARTY_TYPE_CODE IN ('PERSON','ORGANIZATION') ORDER BY PARTY_TYPE_CODE;
SELECT LIFECYCLE_STATUS_CODE, NAME_FA, IS_ACTIVE FROM CIF.REF_PARTY_LIFECYCLE_STATUS WHERE LIFECYCLE_STATUS_CODE = 'ACTIVE';
SELECT DATA_QUALITY_STATUS_CODE, NAME_FA, IS_ACTIVE FROM CIF.REF_DATA_QUALITY_STATUS WHERE DATA_QUALITY_STATUS_CODE = 'INCOMPLETE';
SELECT LEGAL_CAPACITY_CODE, NAME_FA, IS_ACTIVE FROM CIF.REF_LEGAL_CAPACITY WHERE LEGAL_CAPACITY_CODE = 'FULL';
SELECT LIFE_STATUS_CODE, NAME_FA, IS_ACTIVE FROM CIF.REF_LIFE_STATUS WHERE LIFE_STATUS_CODE = 'ALIVE';

SELECT AUTHORITY_DOCUMENT_TYPE_CODE, NAME_FA, IS_ACTIVE FROM CIF.REF_AUTHORITY_DOCUMENT_TYPE WHERE AUTHORITY_DOCUMENT_TYPE_CODE IN ('POWER_OF_ATTORNEY','BOARD_RESOLUTION','COURT_ORDER') ORDER BY SORT_ORDER;

