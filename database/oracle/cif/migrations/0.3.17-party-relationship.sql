-- Core Banking Prototype 0.3.17
-- Create PARTY_RELATIONSHIP when upgrading from the historical CIF DDL snapshot.
-- Idempotent: existing table/sequence are preserved.
DECLARE
  v_count NUMBER;
  v_table_exists NUMBER;
  v_start_with NUMBER := 1;
BEGIN
  SELECT COUNT(*) INTO v_table_exists
    FROM ALL_TABLES
   WHERE OWNER='CIF' AND TABLE_NAME='PARTY_RELATIONSHIP';

  SELECT COUNT(*) INTO v_count
    FROM ALL_SEQUENCES
   WHERE SEQUENCE_OWNER='CIF' AND SEQUENCE_NAME='SEQ_PARTY_RELATIONSHIP';
  IF v_count = 0 THEN
    IF v_table_exists > 0 THEN
      EXECUTE IMMEDIATE 'SELECT NVL(MAX(PARTY_RELATIONSHIP_ID),0)+1 FROM CIF.PARTY_RELATIONSHIP' INTO v_start_with;
    END IF;
    EXECUTE IMMEDIATE 'CREATE SEQUENCE CIF.SEQ_PARTY_RELATIONSHIP START WITH ' || v_start_with || ' INCREMENT BY 1 NOCACHE NOCYCLE';
  END IF;

  IF v_table_exists = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE CIF.PARTY_RELATIONSHIP (
        PARTY_RELATIONSHIP_ID NUMBER(19,0) DEFAULT CIF.SEQ_PARTY_RELATIONSHIP.NEXTVAL NOT NULL,
        PARTY_ID NUMBER(19,0) NOT NULL,
        RELATED_PARTY_ID NUMBER(19,0) NOT NULL,
        RELATIONSHIP_TYPE_CODE VARCHAR2(30 CHAR) NOT NULL,
        OWNERSHIP_PERCENT NUMBER(19,0),
        POSITION_TITLE VARCHAR2(100 CHAR),
        SIGNING_RIGHT_CODE VARCHAR2(30 CHAR),
        AUTHORITY_LIMIT_AMOUNT NUMBER(19,0),
        START_DATE DATE NOT NULL,
        END_DATE DATE,
        EVIDENCE_DOCUMENT_ID NUMBER(19,0),
        VERIFICATION_STATUS_CODE VARCHAR2(30 CHAR),
        CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
        CREATED_BY VARCHAR2(50 CHAR) NOT NULL,
        UPDATED_AT TIMESTAMP(6),
        UPDATED_BY VARCHAR2(100 CHAR),
        RECORD_VERSION NUMBER(19,0) DEFAULT 1 NOT NULL,
        CONSTRAINT PK_PARTY_RELATIONSHIP PRIMARY KEY (PARTY_RELATIONSHIP_ID),
        CONSTRAINT CK_PARTY_REL_DIFFERENT CHECK (PARTY_ID <> RELATED_PARTY_ID),
        CONSTRAINT CK_PARTY_REL_OWNERSHIP CHECK (OWNERSHIP_PERCENT IS NULL OR (OWNERSHIP_PERCENT BETWEEN 0 AND 100)),
        CONSTRAINT CK_PARTY_REL_AUTH_LIMIT CHECK (AUTHORITY_LIMIT_AMOUNT IS NULL OR AUTHORITY_LIMIT_AMOUNT >= 0),
        CONSTRAINT CK_PARTY_REL_DATES CHECK (END_DATE IS NULL OR END_DATE >= START_DATE),
        CONSTRAINT CK_PARTY_REL_VERSION CHECK (RECORD_VERSION >= 1),
        CONSTRAINT FK_PARTY_REL_PARTY FOREIGN KEY (PARTY_ID) REFERENCES CIF.PARTY(PARTY_ID),
        CONSTRAINT FK_PARTY_REL_RELATED FOREIGN KEY (RELATED_PARTY_ID) REFERENCES CIF.PARTY(PARTY_ID)
      )
    ]';
    EXECUTE IMMEDIATE 'CREATE INDEX CIF.IX_PARTY_REL_PARTY ON CIF.PARTY_RELATIONSHIP(PARTY_ID)';
    EXECUTE IMMEDIATE 'CREATE INDEX CIF.IX_PARTY_REL_RELATED ON CIF.PARTY_RELATIONSHIP(RELATED_PARTY_ID)';
  END IF;
END;
/
COMMENT ON TABLE CIF.PARTY_RELATIONSHIP IS 'رابطه میان Partyها و اشخاص/سازمان‌های مرتبط';
COMMENT ON COLUMN CIF.PARTY_RELATIONSHIP.PARTY_RELATIONSHIP_ID IS 'شناسه رابطه';
COMMENT ON COLUMN CIF.PARTY_RELATIONSHIP.PARTY_ID IS 'Party مبدأ';
COMMENT ON COLUMN CIF.PARTY_RELATIONSHIP.RELATED_PARTY_ID IS 'Party مرتبط';
COMMENT ON COLUMN CIF.PARTY_RELATIONSHIP.RELATIONSHIP_TYPE_CODE IS 'نوع رابطه';
COMMENT ON COLUMN CIF.PARTY_RELATIONSHIP.OWNERSHIP_PERCENT IS 'درصد مالکیت';
COMMENT ON COLUMN CIF.PARTY_RELATIONSHIP.POSITION_TITLE IS 'عنوان سمت شخص مرتبط در رابطه ثبت‌شده';
COMMENT ON COLUMN CIF.PARTY_RELATIONSHIP.SIGNING_RIGHT_CODE IS 'کد نوع حق امضا در رابطه میان پارتی‌ها';
COMMENT ON COLUMN CIF.PARTY_RELATIONSHIP.AUTHORITY_LIMIT_AMOUNT IS 'سقف اختیار';
COMMENT ON COLUMN CIF.PARTY_RELATIONSHIP.START_DATE IS 'شروع رابطه';
COMMENT ON COLUMN CIF.PARTY_RELATIONSHIP.END_DATE IS 'پایان رابطه';
COMMENT ON COLUMN CIF.PARTY_RELATIONSHIP.EVIDENCE_DOCUMENT_ID IS 'مدرک رابطه';
COMMENT ON COLUMN CIF.PARTY_RELATIONSHIP.VERIFICATION_STATUS_CODE IS 'وضعیت تأیید';
