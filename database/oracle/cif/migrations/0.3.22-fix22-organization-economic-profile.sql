MERGE INTO CIF.REF_ORGANIZATION_ACTIVITY_STATUS T
USING (
  SELECT 'ACTIVE' ACTIVITY_STATUS_CODE,'فعال' NAME_FA,'Active' NAME_EN,'فعالیت اقتصادی شخص حقوقی فعال است.' DESCRIPTION_FA,10 SORT_ORDER FROM DUAL
  UNION ALL SELECT 'INACTIVE','غیرفعال','Inactive','فعالیت اقتصادی شخص حقوقی غیرفعال است.',20 FROM DUAL
  UNION ALL SELECT 'SUSPENDED','تعلیق‌شده','Suspended','فعالیت اقتصادی شخص حقوقی موقتاً تعلیق شده است.',30 FROM DUAL
  UNION ALL SELECT 'UNDER_REVIEW','در حال بررسی','Under Review','وضعیت فعالیت اقتصادی شخص حقوقی در حال بررسی است.',40 FROM DUAL
) S
ON (T.ACTIVITY_STATUS_CODE=S.ACTIVITY_STATUS_CODE)
WHEN MATCHED THEN UPDATE SET T.NAME_FA=S.NAME_FA,T.NAME_EN=S.NAME_EN,T.DESCRIPTION_FA=S.DESCRIPTION_FA,T.SORT_ORDER=S.SORT_ORDER,T.IS_ACTIVE=1
WHEN NOT MATCHED THEN INSERT (ACTIVITY_STATUS_CODE,NAME_FA,NAME_EN,DESCRIPTION_FA,SORT_ORDER,IS_ACTIVE,PARENT_CODE,VALID_FROM,VALID_TO,RECORD_VERSION)
VALUES (S.ACTIVITY_STATUS_CODE,S.NAME_FA,S.NAME_EN,S.DESCRIPTION_FA,S.SORT_ORDER,1,NULL,NULL,NULL,1);

