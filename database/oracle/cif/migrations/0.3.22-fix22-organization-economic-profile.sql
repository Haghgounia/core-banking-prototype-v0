-- Enforce new values without rejecting legacy data already present in ORGANIZATION.
DECLARE
  PROCEDURE ADD_FK_IF_POSSIBLE(P_CONSTRAINT VARCHAR2, P_COLUMN VARCHAR2, P_REF_TABLE VARCHAR2, P_REF_COLUMN VARCHAR2) IS
    V_CONSTRAINT NUMBER;
    V_COLUMN NUMBER;
  BEGIN
    SELECT COUNT(*) INTO V_CONSTRAINT FROM ALL_CONSTRAINTS WHERE OWNER='CIF' AND CONSTRAINT_NAME=UPPER(P_CONSTRAINT);
    SELECT COUNT(*) INTO V_COLUMN FROM ALL_TAB_COLUMNS WHERE OWNER='CIF' AND TABLE_NAME='ORGANIZATION' AND COLUMN_NAME=UPPER(P_COLUMN);
    IF V_CONSTRAINT=0 AND V_COLUMN=1 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE CIF.ORGANIZATION ADD CONSTRAINT '||P_CONSTRAINT||' FOREIGN KEY ('||P_COLUMN||') REFERENCES CIF.'||P_REF_TABLE||' ('||P_REF_COLUMN||') ENABLE NOVALIDATE';
    END IF;
  END;
BEGIN
  ADD_FK_IF_POSSIBLE('FK_ORG_ACTIVITY_STATUS','ACTIVITY_STATUS_CODE','REF_ORGANIZATION_ACTIVITY_STATUS','ACTIVITY_STATUS_CODE');
  ADD_FK_IF_POSSIBLE('FK_ORG_ENTERPRISE_SIZE','ENTERPRISE_SIZE_CODE','REF_ENTERPRISE_SIZE','ENTERPRISE_SIZE_CODE');
  ADD_FK_IF_POSSIBLE('FK_ORG_OWNERSHIP_TYPE','OWNERSHIP_TYPE_CODE','REF_OWNERSHIP_TYPE','OWNERSHIP_TYPE_CODE');
END;
