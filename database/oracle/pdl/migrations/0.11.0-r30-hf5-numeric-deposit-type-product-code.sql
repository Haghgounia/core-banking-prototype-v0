-- R30-HF5: numeric deposit TYPE code issuance (approved 2510..6510), DDL ONLY.
-- DBA REVIEW + BACKUP REQUIRED. Oracle DDL auto-commits. Do not run from application.
-- NO UPDATE/DELETE/INSERT of existing products or R30 legacy code registry.
-- The R30 legacy PDL.PRODUCT_DEPOSIT_CODE_REGISTRY remains unchanged.
SET DEFINE OFF;
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM ALL_TABLES
   WHERE OWNER = 'PDL' AND TABLE_NAME = 'PRODUCT_DEPOSIT_CODE_REGISTRY';
  IF v_count <> 1 THEN
    RAISE_APPLICATION_ERROR(-20071, 'R30 deposit registry prerequisite is missing.');
  END IF;
  SELECT COUNT(*) INTO v_count FROM ALL_TABLES
   WHERE OWNER = 'PDL' AND TABLE_NAME = 'PRODUCT_LOAN_WORK_YEAR';
  IF v_count <> 1 THEN
    RAISE_APPLICATION_ERROR(-20072, 'Bank-controlled working-year prerequisite is missing.');
  END IF;
  SELECT COUNT(*) INTO v_count FROM ALL_CONSTRAINTS
   WHERE OWNER = 'PDL' AND TABLE_NAME = 'PRODUCT'
     AND CONSTRAINT_NAME = 'UQ_PRODUCT_CODE' AND STATUS = 'ENABLED';
  IF v_count <> 1 THEN
    RAISE_APPLICATION_ERROR(-20073, 'UQ_PRODUCT_CODE must remain enabled across both domains.');
  END IF;
  SELECT COUNT(*) INTO v_count FROM ALL_TABLES
   WHERE OWNER = 'PDL' AND TABLE_NAME = 'PRODUCT_DEPOSIT_TYPE_CODE_REGISTRY';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE PDL.PRODUCT_DEPOSIT_TYPE_CODE_REGISTRY (
        PRODUCT_ID NUMBER(19) NOT NULL,
        PRODUCT_FAMILY_CODE VARCHAR2(30 CHAR) NOT NULL,
        DEPOSIT_TYPE_CODE VARCHAR2(30 CHAR) NOT NULL,
        ISSUANCE_TYPE_CODE VARCHAR2(4 CHAR) NOT NULL,
        WORK_YEAR NUMBER(4) NOT NULL,
        SERIAL_NO NUMBER(3) NOT NULL,
        PRODUCT_CODE VARCHAR2(30 CHAR) NOT NULL,
        CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        CREATED_BY VARCHAR2(128),
        CONSTRAINT PK_PDL_PDTCR PRIMARY KEY (PRODUCT_ID),
        CONSTRAINT FK_PDL_PDTCR_PRODUCT FOREIGN KEY (PRODUCT_ID)
          REFERENCES PDL.PRODUCT(PRODUCT_ID),
        CONSTRAINT UQ_PDL_PDTCR_TYPE_YEAR UNIQUE (ISSUANCE_TYPE_CODE, WORK_YEAR, SERIAL_NO),
        CONSTRAINT UQ_PDL_PDTCR_CODE UNIQUE (PRODUCT_CODE),
        CONSTRAINT CK_PDL_PDTCR_SERIAL CHECK (SERIAL_NO BETWEEN 1 AND 999),
        CONSTRAINT CK_PDL_PDTCR_YEAR CHECK (WORK_YEAR BETWEEN 1300 AND 1600),
        CONSTRAINT CK_PDL_PDTCR_MAPPING CHECK (
          (DEPOSIT_TYPE_CODE = 'CURRENT_NO_INTEREST' AND ISSUANCE_TYPE_CODE = '2510') OR
          (DEPOSIT_TYPE_CODE = 'SAVINGS' AND ISSUANCE_TYPE_CODE = '3510') OR
          (DEPOSIT_TYPE_CODE = 'SHORT_TERM_DEPOSIT' AND ISSUANCE_TYPE_CODE = '4510') OR
          (DEPOSIT_TYPE_CODE = 'LONG_TERM_DEPOSIT' AND ISSUANCE_TYPE_CODE = '5510') OR
          (DEPOSIT_TYPE_CODE = 'CERTIFICATE_OF_DEPOSIT' AND ISSUANCE_TYPE_CODE = '6510')
        ),
        CONSTRAINT CK_PDL_PDTCR_FORMAT CHECK (
          PRODUCT_CODE = ISSUANCE_TYPE_CODE || TO_CHAR(WORK_YEAR, 'FM0000')
                         || TO_CHAR(SERIAL_NO, 'FM000')
        )
      )]';
  END IF;
  -- Fail closed on a pre-existing but incomplete/incorrect target table.
  SELECT COUNT(*) INTO v_count FROM ALL_TAB_COLUMNS
   WHERE OWNER = 'PDL' AND TABLE_NAME = 'PRODUCT_DEPOSIT_TYPE_CODE_REGISTRY'
     AND COLUMN_NAME IN ('PRODUCT_ID', 'PRODUCT_FAMILY_CODE', 'DEPOSIT_TYPE_CODE',
                         'ISSUANCE_TYPE_CODE', 'WORK_YEAR', 'SERIAL_NO',
                         'PRODUCT_CODE', 'CREATED_AT', 'CREATED_BY');
  IF v_count <> 9 THEN
    RAISE_APPLICATION_ERROR(-20074, 'HF5 numeric registry has missing columns.');
  END IF;
  SELECT COUNT(*) INTO v_count FROM ALL_CONSTRAINTS
   WHERE OWNER = 'PDL' AND TABLE_NAME = 'PRODUCT_DEPOSIT_TYPE_CODE_REGISTRY'
     AND CONSTRAINT_NAME IN ('PK_PDL_PDTCR', 'FK_PDL_PDTCR_PRODUCT',
       'UQ_PDL_PDTCR_TYPE_YEAR', 'UQ_PDL_PDTCR_CODE',
       'CK_PDL_PDTCR_SERIAL', 'CK_PDL_PDTCR_YEAR',
       'CK_PDL_PDTCR_MAPPING', 'CK_PDL_PDTCR_FORMAT')
     AND STATUS = 'ENABLED' AND VALIDATED = 'VALIDATED';
  IF v_count <> 8 THEN
    RAISE_APPLICATION_ERROR(-20075, 'HF5 numeric registry constraints are incomplete.');
  END IF;
END;
