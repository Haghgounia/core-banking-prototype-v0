-- R30: system-only code issuance for both DEPOSIT and LOAN products at stage six.
-- Requires successful R28 and R29 migrations. Run only after backup and DBA review.
-- Oracle DDL auto-commits: do not interpret this script as an all-or-nothing transaction.
-- No data resets, no working-year changes, no rewrite of existing PRODUCT_CODE.
SET DEFINE OFF;
DECLARE
  v_count NUMBER;
  v_nullable VARCHAR2(1);
BEGIN
  SELECT COUNT(*) INTO v_count FROM ALL_TABLES
   WHERE OWNER='PDL' AND TABLE_NAME='PRODUCT_LOAN_WORK_YEAR';
  IF v_count <> 1 THEN
    RAISE_APPLICATION_ERROR(-20030, 'R30 requires R28 controlled working-year table.');
  END IF;
  SELECT COUNT(*) INTO v_count FROM PDL.PRODUCT_LOAN_WORK_YEAR WHERE SETTING_ID=1;
  IF v_count <> 1 THEN
    RAISE_APPLICATION_ERROR(-20031, 'R30 requires an authorized active bank working year.');
  END IF;
  SELECT COUNT(*) INTO v_count FROM ALL_CONSTRAINTS
   WHERE OWNER='PDL' AND TABLE_NAME='PRODUCT' AND CONSTRAINT_NAME='CK_PDL_PRODUCT_CODE_ISSUED';
  IF v_count <> 1 THEN
    SELECT COUNT(*) INTO v_count FROM ALL_CONSTRAINTS
     WHERE OWNER='PDL' AND TABLE_NAME='PRODUCT' AND CONSTRAINT_NAME='CK_PDL_PRODUCT_CODE_DRAFT';
    IF v_count <> 1 THEN
      RAISE_APPLICATION_ERROR(-20032, 'R30 requires successful R29 code issuance migration.');
    END IF;
  END IF;
  SELECT NULLABLE INTO v_nullable FROM ALL_TAB_COLUMNS
   WHERE OWNER='PDL' AND TABLE_NAME='PRODUCT' AND COLUMN_NAME='PRODUCT_CODE';
  IF v_nullable <> 'Y' THEN
    RAISE_APPLICATION_ERROR(-20033, 'R30 requires PRODUCT_CODE nullable from R29.');
  END IF;

  -- Register the stronger *shared* draft-only NULL rule BEFORE removing R29's
  -- deposit-specific rule, so partial deployment does not expose a no-rule gap.
  SELECT COUNT(*) INTO v_count FROM ALL_CONSTRAINTS
   WHERE OWNER='PDL' AND TABLE_NAME='PRODUCT' AND CONSTRAINT_NAME='CK_PDL_PRODUCT_CODE_DRAFT';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE PDL.PRODUCT ADD CONSTRAINT CK_PDL_PRODUCT_CODE_DRAFT ' ||
      'CHECK (PRODUCT_CODE IS NOT NULL OR ' ||
      '(PRODUCT_CLASS_CODE IN (''LOAN'',''DEPOSIT'') AND PRODUCT_STATUS_CODE = ''DRAFT'')) ENABLE VALIDATE';
  END IF;

  SELECT COUNT(*) INTO v_count FROM ALL_TABLES
   WHERE OWNER='PDL' AND TABLE_NAME='PRODUCT_DEPOSIT_CODE_REGISTRY';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE PDL.PRODUCT_DEPOSIT_CODE_REGISTRY (' ||
      'PRODUCT_ID NUMBER(19) NOT NULL, PRODUCT_FAMILY_CODE VARCHAR2(30 CHAR) NOT NULL, ' ||
      'WORK_YEAR NUMBER(4) NOT NULL, SERIAL_NO NUMBER(3) NOT NULL, ' ||
      'PRODUCT_CODE VARCHAR2(30 CHAR) NOT NULL, ' ||
      'CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, CREATED_BY VARCHAR2(128), ' ||
      'CONSTRAINT PK_PDL_PDCR PRIMARY KEY (PRODUCT_ID), ' ||
      'CONSTRAINT FK_PDL_PDCR_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PDL.PRODUCT(PRODUCT_ID), ' ||
      'CONSTRAINT UK_PDL_PDCR_FAMILY_YEAR_NO UNIQUE (PRODUCT_FAMILY_CODE,WORK_YEAR,SERIAL_NO), ' ||
      'CONSTRAINT UK_PDL_PDCR_CODE UNIQUE (PRODUCT_CODE), ' ||
      'CONSTRAINT CK_PDL_PDCR_SERIAL CHECK (SERIAL_NO BETWEEN 1 AND 999))';
  END IF;

  SELECT COUNT(*) INTO v_count FROM ALL_CONSTRAINTS
   WHERE OWNER='PDL' AND TABLE_NAME='PRODUCT' AND CONSTRAINT_NAME='CK_PDL_PRODUCT_CODE_ISSUED';
  IF v_count = 1 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE PDL.PRODUCT DROP CONSTRAINT CK_PDL_PRODUCT_CODE_ISSUED';
  END IF;
END;
/
-- Retain UQ_PRODUCT_CODE: UNIQUE permits multiple NULLs in Oracle.
-- R30 retains PDL.PRODUCT_LOAN_WORK_YEAR as ONE bank-controlled year for BOTH domains.
-- No creation-time code generation. Legacy product codes are not modified.
-- A draft cannot become INACTIVE/ACTIVE/RETIRED without an issued code.
