BEGIN
  EXECUTE IMMEDIATE q'~
    CREATE TABLE PDL.PRODUCT_ELIGIBILITY_CRITERION (
      ELIGIBILITY_CRITERION_ID NUMBER(19)        NOT NULL,
      ELIGIBILITY_RULE_ID      NUMBER(19)        NOT NULL,
      CRITERION_TYPE_CODE      VARCHAR2(50 CHAR) NOT NULL,
      OPERATOR_CODE            VARCHAR2(20 CHAR) DEFAULT 'IN' NOT NULL,
      CRITERION_VALUE_CODE     VARCHAR2(100 CHAR),
      CRITERION_VALUE_NUMBER   NUMBER(20,4),
      VALUE_UNIT_CODE          VARCHAR2(20 CHAR),
      DISPLAY_ORDER            NUMBER(5) DEFAULT 100 NOT NULL,
      IS_ACTIVE                NUMBER(1) DEFAULT 1 NOT NULL,
      CREATED_AT               TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
      CREATED_BY               VARCHAR2(100 CHAR) NOT NULL,
      UPDATED_AT               TIMESTAMP(6),
      UPDATED_BY               VARCHAR2(100 CHAR),
      RECORD_VERSION           NUMBER(10) DEFAULT 1 NOT NULL,
      CONSTRAINT PK_PDL_ELIG_CRIT PRIMARY KEY (ELIGIBILITY_CRITERION_ID),
      CONSTRAINT FK_PDL_ELIG_CRIT_RULE FOREIGN KEY (ELIGIBILITY_RULE_ID)
        REFERENCES PDL.PRODUCT_ELIGIBILITY_RULE (ELIGIBILITY_RULE_ID),
      CONSTRAINT CK_PDL_ELIG_CRIT_TYPE CHECK (CRITERION_TYPE_CODE IN (
        'CUSTOMER_TYPE','CUSTOMER_SEGMENT','CUSTOMER_STATUS','GENDER',
        'RESIDENCY_STATUS','NATIONALITY_SCOPE','CUSTOMER_TENURE','ACCOUNT_TENURE'
      )),
      CONSTRAINT CK_PDL_ELIG_CRIT_OP CHECK (OPERATOR_CODE IN ('IN','EQ','MIN','MAX')),
      CONSTRAINT CK_PDL_ELIG_CRIT_UNIT CHECK (VALUE_UNIT_CODE IS NULL OR VALUE_UNIT_CODE IN ('DAY','MONTH','YEAR')),
      CONSTRAINT CK_PDL_ELIG_CRIT_ACTIVE CHECK (IS_ACTIVE IN (0,1)),
      CONSTRAINT CK_PDL_ELIG_CRIT_ORDER CHECK (DISPLAY_ORDER > 0),
      CONSTRAINT CK_PDL_ELIG_CRIT_RECVER CHECK (RECORD_VERSION > 0),
      CONSTRAINT CK_PDL_ELIG_CRIT_VALUE CHECK (
        (OPERATOR_CODE IN ('IN','EQ') AND CRITERION_VALUE_CODE IS NOT NULL AND CRITERION_VALUE_NUMBER IS NULL)
        OR
        (OPERATOR_CODE IN ('MIN','MAX') AND CRITERION_VALUE_CODE IS NULL AND CRITERION_VALUE_NUMBER IS NOT NULL)
      ),
      CONSTRAINT CK_PDL_ELIG_CRIT_TENURE CHECK (
        (CRITERION_TYPE_CODE IN ('CUSTOMER_TENURE','ACCOUNT_TENURE') AND OPERATOR_CODE='MIN' AND VALUE_UNIT_CODE IS NOT NULL AND CRITERION_VALUE_NUMBER >= 0)
        OR
        (CRITERION_TYPE_CODE NOT IN ('CUSTOMER_TENURE','ACCOUNT_TENURE') AND VALUE_UNIT_CODE IS NULL)
      )
    )~';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;
