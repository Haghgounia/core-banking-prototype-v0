-- --------------------------------------------------------------------------
-- Safe migration of existing scalar dimension values.
-- ALL / unrestricted values are deliberately not persisted as criterion rows;
-- absence of child rows means "all values" in the new model.
-- --------------------------------------------------------------------------
DECLARE
  PROCEDURE migrate_code(p_column VARCHAR2, p_type VARCHAR2, p_order NUMBER) IS
    l_count NUMBER;
    l_sql   VARCHAR2(32767);
  BEGIN
    SELECT COUNT(*) INTO l_count
      FROM ALL_TAB_COLUMNS
     WHERE OWNER='PDL' AND TABLE_NAME='PRODUCT_ELIGIBILITY_RULE' AND COLUMN_NAME=UPPER(p_column);
    IF l_count = 0 THEN RETURN; END IF;

    l_sql := 'INSERT INTO PDL.PRODUCT_ELIGIBILITY_CRITERION '
          || '(ELIGIBILITY_CRITERION_ID,ELIGIBILITY_RULE_ID,CRITERION_TYPE_CODE,OPERATOR_CODE,CRITERION_VALUE_CODE,DISPLAY_ORDER,IS_ACTIVE,CREATED_BY) '
          || 'SELECT NVL((SELECT MAX(ELIGIBILITY_CRITERION_ID) FROM PDL.PRODUCT_ELIGIBILITY_CRITERION),0) + ROW_NUMBER() OVER (ORDER BY ELIGIBILITY_RULE_ID), '
          || 'ELIGIBILITY_RULE_ID, :type, ''IN'', TRIM(' || p_column || '), :ord, 1, ''R10U_MIGRATION'' '
          || 'FROM PDL.PRODUCT_ELIGIBILITY_RULE r '
          || 'WHERE ' || p_column || ' IS NOT NULL AND TRIM(' || p_column || ') IS NOT NULL '
          || 'AND UPPER(TRIM(' || p_column || ')) NOT IN (''ALL'',''ANY'',''NONE'',''3'') '
          || 'AND NOT EXISTS (SELECT 1 FROM PDL.PRODUCT_ELIGIBILITY_CRITERION c '
          || 'WHERE c.ELIGIBILITY_RULE_ID=r.ELIGIBILITY_RULE_ID AND c.CRITERION_TYPE_CODE=:type2 '
          || 'AND c.OPERATOR_CODE=''IN'' AND c.CRITERION_VALUE_CODE=TRIM(r.' || p_column || '))';
    EXECUTE IMMEDIATE l_sql USING p_type, p_order, p_type;
  END;
BEGIN
  migrate_code('CUSTOMER_TYPE_CODE',      'CUSTOMER_TYPE',      10);
  migrate_code('CUSTOMER_SEGMENT_CODE',   'CUSTOMER_SEGMENT',   20);
  migrate_code('CUSTOMER_STATUS_CODE',    'CUSTOMER_STATUS',    30);
  migrate_code('GENDER_CODE',             'GENDER',             40);
  migrate_code('RESIDENCY_STATUS_CODE',   'RESIDENCY_STATUS',   50);
  migrate_code('NATIONALITY_SCOPE_CODE',  'NATIONALITY_SCOPE',  60);
END;
/

