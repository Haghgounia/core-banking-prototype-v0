-- ============================================================================
-- Core Banking Prototype 0.11.0 / PDL R10U
-- Product Eligibility Rule - business UX and multi-value criteria model
--
-- Runtime source of truth for multi-valued eligibility dimensions:
--   PDL.PRODUCT_ELIGIBILITY_CRITERION
--
-- Semantics:
--   * Multiple rows of the same CRITERION_TYPE_CODE are OR-ed (IN semantics).
--   * Different criterion types are AND-ed.
--   * Absence of rows for an IN criterion means "all values / no restriction".
--   * Threshold criteria use OPERATOR_CODE=MIN/MAX with VALUE_NUMBER and UNIT_CODE.
--
-- Existing scalar columns on PRODUCT_ELIGIBILITY_RULE are intentionally retained
-- for backwards compatibility during the prototype transition; they are no longer
-- authoritative for multi-valued dimensions once criterion rows exist.
-- ============================================================================

