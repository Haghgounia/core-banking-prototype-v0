-- R28 Product Builder: normalized loan code and eligibility employment choices.
-- Execute once as PDL owner (or DBA with schema DDL permission), before deploying R28.
-- This file intentionally does not seed the active bank working year.
SET DEFINE OFF;
DECLARE
  n NUMBER;
  nullable_flag VARCHAR2(1);
BEGIN
  SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='PDL' AND TABLE_NAME='PRODUCT_LOAN_WORK_YEAR';
  IF n=0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE PDL.PRODUCT_LOAN_WORK_YEAR (' ||
      'SETTING_ID NUMBER(1) NOT NULL PRIMARY KEY, WORK_YEAR NUMBER(4) NOT NULL, ' ||
      'UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, UPDATED_BY VARCHAR2(128) NOT NULL, ' ||
      'CONSTRAINT CK_PDL_PLWY_ID CHECK(SETTING_ID=1), CONSTRAINT CK_PDL_PLWY_YEAR CHECK(WORK_YEAR BETWEEN 1300 AND 1600))';
  END IF;
  SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='PDL' AND TABLE_NAME='PRODUCT_LOAN_CODE_REGISTRY';
  IF n=0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE PDL.PRODUCT_LOAN_CODE_REGISTRY (' ||
      'PRODUCT_ID NUMBER NOT NULL PRIMARY KEY, LOAN_TYPE_ID NUMBER NOT NULL, WORK_YEAR NUMBER(4) NOT NULL, ' ||
      'SERIAL_NO NUMBER(3) NOT NULL, PRODUCT_CODE VARCHAR2(30) NOT NULL, ' ||
      'CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, CREATED_BY VARCHAR2(128), ' ||
      'CONSTRAINT FK_PDL_PLCR_PRODUCT FOREIGN KEY(PRODUCT_ID) REFERENCES PDL.PRODUCT(PRODUCT_ID), ' ||
      'CONSTRAINT FK_PDL_PLCR_LOANTYPE FOREIGN KEY(LOAN_TYPE_ID) REFERENCES PDL.LOAN_TYPE(LOAN_TYPE_ID), ' ||
      'CONSTRAINT UK_PDL_PLCR_TYPE_YEAR_SERIAL UNIQUE(LOAN_TYPE_ID,WORK_YEAR,SERIAL_NO), ' ||
      'CONSTRAINT UK_PDL_PLCR_CODE UNIQUE(PRODUCT_CODE), ' ||
      'CONSTRAINT CK_PDL_PLCR_SERIAL CHECK(SERIAL_NO BETWEEN 1 AND 999))';
  END IF;
  -- An empty multi-selection means no employment restriction. The historical
  -- single-value field must therefore accept NULL even if an older schema
  -- declared it NOT NULL. Preserve all existing non-null historical values.
  SELECT NULLABLE INTO nullable_flag FROM ALL_TAB_COLUMNS
   WHERE OWNER='PDL' AND TABLE_NAME='LOAN_ELIGIBILITY_EXTENSION'
     AND COLUMN_NAME='EMPLOYMENT_TYPE_CODE';
  IF nullable_flag='N' THEN
    EXECUTE IMMEDIATE 'ALTER TABLE PDL.LOAN_ELIGIBILITY_EXTENSION MODIFY (EMPLOYMENT_TYPE_CODE NULL)';
  END IF;
  SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='PDL' AND TABLE_NAME='LOAN_ELIGIBLE_EMPLOYMENT_TYPE';
  IF n=0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE PDL.LOAN_ELIGIBLE_EMPLOYMENT_TYPE (' ||
      'ELIGIBILITY_RULE_ID NUMBER NOT NULL, EMPLOYMENT_TYPE_CODE VARCHAR2(30) NOT NULL, ' ||
      'CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, CREATED_BY VARCHAR2(128), ' ||
      'CONSTRAINT PK_PDL_LEET PRIMARY KEY(ELIGIBILITY_RULE_ID, EMPLOYMENT_TYPE_CODE), ' ||
      'CONSTRAINT FK_PDL_LEET_ELIG FOREIGN KEY(ELIGIBILITY_RULE_ID) REFERENCES PDL.LOAN_ELIGIBILITY_EXTENSION(ELIGIBILITY_RULE_ID))';
  END IF;
END;
