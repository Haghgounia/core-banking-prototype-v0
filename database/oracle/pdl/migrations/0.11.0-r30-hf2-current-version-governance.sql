-- R30-HF2: explicit, auditable current-version transition for Product Builder.
-- Run AFTER R30. DBA approval and backup are required. Oracle DDL commits automatically.
-- No existing PRODUCT/PRODUCT_VERSION data is rewritten by this migration.
-- The function-based index allows multiple IS_CURRENT=0 but at most one IS_CURRENT=1 per product.
SET DEFINE OFF;
DECLARE
  v_count NUMBER;
  v_duplicates NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM ALL_CONSTRAINTS
   WHERE OWNER='PDL' AND TABLE_NAME='PRODUCT' AND CONSTRAINT_NAME='CK_PDL_PRODUCT_CODE_DRAFT'
     AND STATUS='ENABLED' AND VALIDATED='VALIDATED';
  IF v_count <> 1 THEN
    RAISE_APPLICATION_ERROR(-20140, 'R30-HF2 requires the validated R30 product-code constraint.');
  END IF;
  SELECT COUNT(*) INTO v_duplicates FROM (
      SELECT PRODUCT_ID FROM PDL.PRODUCT_VERSION
       WHERE IS_CURRENT=1 GROUP BY PRODUCT_ID HAVING COUNT(*)>1
  );
  IF v_duplicates > 0 THEN
    RAISE_APPLICATION_ERROR(-20141, 'Duplicate current versions exist; reconcile with approved governance before installing R30-HF2.');
  END IF;

  SELECT COUNT(*) INTO v_count FROM ALL_INDEXES
   WHERE OWNER='PDL' AND INDEX_NAME='UX_PDL_PV_ONE_CURRENT';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX PDL.UX_PDL_PV_ONE_CURRENT ON PDL.PRODUCT_VERSION ' ||
      '(CASE WHEN IS_CURRENT=1 THEN PRODUCT_ID END)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM ALL_TABLES
   WHERE OWNER='PDL' AND TABLE_NAME='PRODUCT_VERSION_CURRENT_AUDIT';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE PDL.PRODUCT_VERSION_CURRENT_AUDIT (' ||
      'AUDIT_ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL, ' ||
      'PRODUCT_ID NUMBER(19) NOT NULL, ' ||
      'PREVIOUS_VERSION_ID NUMBER(19), ' ||
      'TARGET_VERSION_ID NUMBER(19) NOT NULL, ' ||
      'ACTION_CODE VARCHAR2(30 CHAR) DEFAULT ''MAKE_CURRENT'' NOT NULL, ' ||
      'CHANGE_REASON VARCHAR2(500 CHAR) NOT NULL, ' ||
      'ACTOR VARCHAR2(100 CHAR) NOT NULL, ' ||
      'CHANGED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL, ' ||
      'CONSTRAINT PK_PDL_PV_CURRENT_AUDIT PRIMARY KEY (AUDIT_ID), ' ||
      'CONSTRAINT FK_PDL_PVCA_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PDL.PRODUCT(PRODUCT_ID), ' ||
      'CONSTRAINT FK_PDL_PVCA_PREV FOREIGN KEY (PREVIOUS_VERSION_ID) REFERENCES PDL.PRODUCT_VERSION(PRODUCT_VERSION_ID), ' ||
      'CONSTRAINT FK_PDL_PVCA_TARGET FOREIGN KEY (TARGET_VERSION_ID) REFERENCES PDL.PRODUCT_VERSION(PRODUCT_VERSION_ID), ' ||
      'CONSTRAINT CK_PDL_PVCA_ACTION CHECK (ACTION_CODE=''MAKE_CURRENT''))';
  END IF;
END;
/
-- No COMMIT/UPDATE required. No changes to version status, origination, or PRODUCT_CODE.
-- This schema audit is a prototype trail; production authorization must use authenticated RBAC,
-- not the existing X-User-Name header.
