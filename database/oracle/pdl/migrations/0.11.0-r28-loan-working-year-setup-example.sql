-- R28 CONTROLLED SETUP EXAMPLE. BANK OPERATOR MUST VERIFY AND APPROVE WORK_YEAR.
-- Example 1405 below is ONLY for UAT on 2026-10-11. Replace with the bank's ACTIVE WORK YEAR.
-- Execute under approved change record; do not silently run on production.
MERGE INTO PDL.PRODUCT_LOAN_WORK_YEAR Y
USING (SELECT 1 SETTING_ID, 1405 WORK_YEAR FROM DUAL) S
ON (Y.SETTING_ID = S.SETTING_ID)
WHEN MATCHED THEN UPDATE SET Y.WORK_YEAR=S.WORK_YEAR, Y.UPDATED_AT=SYSTIMESTAMP, Y.UPDATED_BY='AUTHORIZED_BANK_OPERATOR'
WHEN NOT MATCHED THEN INSERT (SETTING_ID,WORK_YEAR,UPDATED_BY) VALUES(S.SETTING_ID,S.WORK_YEAR,'AUTHORIZED_BANK_OPERATOR');
COMMIT;
SELECT * FROM PDL.PRODUCT_LOAN_WORK_YEAR;
