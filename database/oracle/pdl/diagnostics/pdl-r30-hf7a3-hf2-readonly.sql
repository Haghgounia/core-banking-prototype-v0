-- Run as an account with SELECT on PDL and ALL_* dictionary views.
SET DEFINE ON
SET VERIFY OFF
SET PAGESIZE 200
SET LINESIZE 220
ACCEPT P_VERSION_ID NUMBER DEFAULT 0 PROMPT 'Product version ID (0 to skip version rows): '
PROMPT === Oracle CHECK constraints - original SQL source of allowed codes ===
SELECT TABLE_NAME, CONSTRAINT_NAME, SEARCH_CONDITION_VC
  FROM ALL_CONSTRAINTS
 WHERE OWNER = 'PDL'
   AND TABLE_NAME IN ('DEPOSIT_PRODUCT_JOINT_RULE',
                      'DEPOSIT_PRODUCT_CLOSURE_SETTLEMENT_RULE',
                      'PRODUCT_CHANNEL_RULE')
   AND CONSTRAINT_TYPE = 'C'
 ORDER BY TABLE_NAME, CONSTRAINT_NAME;
PROMPT === Column nullability; DESTINATION_CODE should be optional in the reviewed model ===
SELECT TABLE_NAME, COLUMN_NAME, NULLABLE, DATA_TYPE, DATA_LENGTH
  FROM ALL_TAB_COLUMNS
 WHERE OWNER = 'PDL'
   AND ((TABLE_NAME = 'DEPOSIT_PRODUCT_JOINT_RULE'
         AND COLUMN_NAME IN ('OWNERSHIP_TYPE_CODE','SIGNING_RULE_CODE','PROFIT_DISTRIBUTION_CODE'))
        OR (TABLE_NAME = 'DEPOSIT_PRODUCT_CLOSURE_SETTLEMENT_RULE'
         AND COLUMN_NAME IN ('SETTLEMENT_METHOD_CODE','DESTINATION_CODE','SETTLEMENT_COMPONENT_CODE'))
        OR (TABLE_NAME = 'PRODUCT_CHANNEL_RULE'
         AND COLUMN_NAME IN ('VALID_FROM','VALID_TO','RULE_STATUS_CODE')))
 ORDER BY TABLE_NAME, COLUMN_NAME;
PROMPT === Version validity interval - Gregorian dates including start/end ===
SELECT PRODUCT_VERSION_ID, PRODUCT_ID, VALID_FROM, VALID_TO, VERSION_STATUS_CODE
  FROM PDL.PRODUCT_VERSION
 WHERE PRODUCT_VERSION_ID = &P_VERSION_ID;
PROMPT === Saved channel rules; check ACTIVE status and validity through version end ===
SELECT CHANNEL_RULE_ID, PRODUCT_VERSION_ID, CHANNEL_CODE,
       IS_ALLOWED, VALID_FROM, VALID_TO, RULE_STATUS_CODE
  FROM PDL.PRODUCT_CHANNEL_RULE
 WHERE PRODUCT_VERSION_ID = &P_VERSION_ID
 ORDER BY CHANNEL_CODE, VALID_FROM, CHANNEL_RULE_ID;
PROMPT === End of read-only diagnostic ===
