-- R1-D5 - READ ONLY. Change the number below to the confirmed DPS2 transaction ID.
-- SQL*Plus/SQLcl syntax. In SQL Developer, use Run Script (F5).
DEFINE DPS2_TRANSACTION_ID = 0
PROMPT === DPS2 original transaction ===
SELECT TRANSACTION_ID,REFERENCE_NO,TRANSACTION_TYPE_CODE,TRANSACTION_STATUS_CODE,
       AMOUNT,CURRENCY_CODE,BOOKING_DATE,VALUE_DATE
FROM DPS2.DEPOSIT_TRANSACTION WHERE TRANSACTION_ID=&DPS2_TRANSACTION_ID;
PROMPT === PST instruction and transaction trace ===
SELECT I.IDENTIFIER,I.SOURCE_EVENT_IDENTIFIER,I.ACCOUNTING_PURPOSE,I.EXECUTION_STATE,
       P.IDENTIFIER AS POSTING_PLAN_ID,E.IDENTIFIER AS EXECUTION_ID,
       E.PROVIDER_TRANSACTION_REFERENCE,E.OUTCOME_STATE
FROM PST.POSTING_INSTRUCTIONS I
JOIN PST.POSTING_PLANS P ON P.POSTING_INSTRUCTION_IDENTIFIER=I.IDENTIFIER
JOIN PST.POSTING_EXECUTIONS E ON E.POSTING_PLAN_IDENTIFIER=P.IDENTIFIER
WHERE I.SOURCE_DOMAIN='DPS2' AND I.SOURCE_EVENT_IDENTIFIER='DPS2-TX-'||&DPS2_TRANSACTION_ID
 AND I.ACCOUNTING_PURPOSE='CASH_PRINCIPAL';
PROMPT === LGR immutable movement (Formance-style source to destination) ===
SELECT LT.IDENTIFIER AS LEDGER_TX_ID,LT.POSTING_STATE,M.SEQUENCE_NUMBER,
       M.SOURCE_POSITION_ACCOUNT_REFERENCE AS SOURCE_POSITION,
       M.DESTINATION_POSITION_ACCOUNT_REFERENCE AS DESTINATION_POSITION,
       M.AMOUNT,M.ASSET_CODE
FROM LGR.LEDGER_TRANSACTIONS LT
JOIN LGR.LEDGER_MOVEMENTS M ON M.LEDGER_TRANSACTION_IDENTIFIER=LT.IDENTIFIER
WHERE LT.SOURCE_INSTRUCTION_REFERENCE='DPS2-CASH-'||&DPS2_TRANSACTION_ID
ORDER BY M.SEQUENCE_NUMBER;
PROMPT === ACC formal journal lines ===
SELECT T.IDENTIFIER AS ACCOUNTING_TRANSACTION_ID,T.POSTING_STATE,E.SEQUENCE_NUMBER,
       G.ACCOUNT_CODE,G.ACCOUNT_NAME,E.POSTING_DIRECTION,E.AMOUNT,E.CURRENCY_CODE
FROM ACC.ACCOUNTING_FACTS F
JOIN ACC.ACCOUNTING_TRANSACTIONS T ON T.ACCOUNTING_FACT_IDENTIFIER=F.IDENTIFIER
JOIN ACC.ACCOUNTING_ENTRIES E ON E.ACCOUNTING_TRANSACTION_IDENTIFIER=T.IDENTIFIER
JOIN ACC.GENERAL_LEDGER_ACCOUNTS G ON G.IDENTIFIER=E.GENERAL_LEDGER_ACCOUNT_IDENTIFIER
WHERE F.SOURCE_FACT_IDENTIFIER='DPS2-TX-'||&DPS2_TRANSACTION_ID
 AND F.ACCOUNTING_PURPOSE='CASH_PRINCIPAL'
ORDER BY E.SEQUENCE_NUMBER;
PROMPT === Journal debit=credit, exactly two lines ===
SELECT T.IDENTIFIER AS ACCOUNTING_TX,
 SUM(CASE WHEN E.POSTING_DIRECTION='DEBIT' THEN E.AMOUNT ELSE 0 END) AS TOTAL_DEBIT,
 SUM(CASE WHEN E.POSTING_DIRECTION='CREDIT' THEN E.AMOUNT ELSE 0 END) AS TOTAL_CREDIT,
 COUNT(*) AS LINES
FROM ACC.ACCOUNTING_FACTS F
JOIN ACC.ACCOUNTING_TRANSACTIONS T ON T.ACCOUNTING_FACT_IDENTIFIER=F.IDENTIFIER
JOIN ACC.ACCOUNTING_ENTRIES E ON E.ACCOUNTING_TRANSACTION_IDENTIFIER=T.IDENTIFIER
WHERE F.SOURCE_FACT_IDENTIFIER='DPS2-TX-'||&DPS2_TRANSACTION_ID
 AND F.ACCOUNTING_PURPOSE='CASH_PRINCIPAL'
GROUP BY T.IDENTIFIER;
PROMPT === Unique receipt and journal counts: should be exactly 1 each ===
SELECT 'PST_INSTRUCTION' AS ENTITY,COUNT(*) CNT FROM PST.POSTING_INSTRUCTIONS
WHERE SOURCE_DOMAIN='DPS2' AND SOURCE_EVENT_IDENTIFIER='DPS2-TX-'||&DPS2_TRANSACTION_ID
AND ACCOUNTING_PURPOSE='CASH_PRINCIPAL'
UNION ALL SELECT 'ACC_FACT',COUNT(*) FROM ACC.ACCOUNTING_FACTS
WHERE SOURCE_FACT_IDENTIFIER='DPS2-TX-'||&DPS2_TRANSACTION_ID AND ACCOUNTING_PURPOSE='CASH_PRINCIPAL';
