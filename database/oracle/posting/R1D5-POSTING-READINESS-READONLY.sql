PROMPT === 01 Required ACC / PST / LGR base tables ===
SELECT OWNER, TABLE_NAME FROM ALL_TABLES
 WHERE OWNER IN ('PST','LGR','ACC') AND TABLE_NAME IN (
  'POSTING_INSTRUCTIONS','POSTING_INBOX_RECEIPTS','POSTING_PLANS','POSTING_PLAN_MOVEMENTS',
  'POSTING_EXECUTIONS','POSTING_EXECUTION_EVENTS','POSTING_ACCOUNT_RESOLUTIONS',
  'POSTING_PREFLIGHT_RESULTS','POSTING_RULES','POSTING_RULE_VERSIONS','POSTING_RULE_CONDITIONS',
  'POSTING_RULE_TEMPLATE_ASSIGNMENTS','POSTING_TEMPLATES','POSTING_TEMPLATE_VERSIONS',
  'POSTING_TEMPLATE_LINES','POSTING_APPROVALS',
  'LEDGERS','ASSETS','ACCOUNT_BINDINGS','POSITION_ACCOUNTS','POSITION_BALANCES',
  'LEDGER_TRANSACTIONS','LEDGER_MOVEMENTS','COMMIT_RECEIPTS',
  'ACCOUNTING_BOOKS','CHARTS_OF_ACCOUNTS','GENERAL_LEDGER_ACCOUNTS','FISCAL_PERIODS',
  'ACCOUNTING_MAPPING_VERSIONS','ACCOUNTING_MAPPING_ENTRIES','ACCOUNT_ROLE_ASSIGNMENTS',
  'ACCOUNTING_FACTS','ACCOUNTING_PLANS','ACCOUNTING_TRANSACTIONS','ACCOUNTING_ENTRIES',
  'ACCOUNT_BALANCE_PROJECTIONS')
ORDER BY OWNER,TABLE_NAME;
PROMPT === 02 Required DPS2 columns; missing column means no-go ===
SELECT OWNER,TABLE_NAME,COLUMN_NAME,DATA_TYPE
  FROM ALL_TAB_COLUMNS WHERE OWNER='DPS2' AND TABLE_NAME='DEPOSIT_ACCOUNT'
  AND COLUMN_NAME IN ('ACCOUNT_ID','ACCOUNT_NO','CURRENT_PRODUCT_VERSION_ID','ORG_UNIT_CODE','CURRENCY_CODE')
ORDER BY COLUMN_ID;
PROMPT === 03 Published posting configuration counts (no business data modified) ===
SELECT 'CASH_DEPOSIT_RULE' AS KIND,COUNT(*) AS ROWS_FOUND FROM PST.POSTING_RULES WHERE RULE_CODE LIKE '%CASH%DEPOSIT%'
UNION ALL SELECT 'CASH_WITHDRAWAL_RULE',COUNT(*) FROM PST.POSTING_RULES WHERE RULE_CODE LIKE '%CASH%WITHDRAW%'
UNION ALL SELECT 'PUBLISHED_TEMPLATES',COUNT(*) FROM PST.POSTING_TEMPLATE_VERSIONS WHERE PUBLICATION_STATE='PUBLISHED'
UNION ALL SELECT 'PUBLISHED_MAPPING',COUNT(*) FROM ACC.ACCOUNTING_MAPPING_VERSIONS WHERE PUBLICATION_STATE='PUBLISHED'
UNION ALL SELECT 'PUBLISHED_ROLE_ASSIGNMENT',COUNT(*) FROM ACC.ACCOUNT_ROLE_ASSIGNMENTS WHERE PUBLICATION_STATE='PUBLISHED'
UNION ALL SELECT 'OPEN_FISCAL_PERIOD',COUNT(*) FROM ACC.FISCAL_PERIODS WHERE PERIOD_STATE='OPEN'
UNION ALL SELECT 'ACTIVE_LEDGER',COUNT(*) FROM LGR.LEDGERS WHERE LEDGER_STATE='ACTIVE'
UNION ALL SELECT 'ACTIVE_ASSET_IRR',COUNT(*) FROM LGR.ASSETS WHERE ASSET_CODE='IRR' AND ASSET_STATE='ACTIVE';
PROMPT === 04 Current cash-related reference mappings (bank-approved codes required) ===
SELECT V.MAPPING_CODE,V.VERSION_NUMBER,M.SOURCE_EVENT_TYPE,M.SEQUENCE_NUMBER,M.ACCOUNT_ROLE,M.POSTING_DIRECTION
 FROM ACC.ACCOUNTING_MAPPING_VERSIONS V JOIN ACC.ACCOUNTING_MAPPING_ENTRIES M
 ON M.ACCOUNTING_MAPPING_VERSION_IDENTIFIER=V.IDENTIFIER
 WHERE M.SOURCE_EVENT_TYPE IN ('CASH_DEPOSIT','CASH_WITHDRAWAL')
 ORDER BY V.MAPPING_CODE,V.VERSION_NUMBER,M.SEQUENCE_NUMBER;
