-- R1-D8I READ ONLY: Oracle E2E journal trace for a specific DPS2 test transaction.
-- This script does NOT initiate, post, or approve any financial transaction.
-- Replace 0 with the two NEW transaction IDs created through the DPS2 API.
SET DEFINE ON
DEFINE DEPOSIT_TX_ID = 0
DEFINE WITHDRAW_TX_ID = 0
SET LINESIZE 220
SET PAGESIZE 200
PROMPT === 01. DPS2 pilot transactions (no full account numbers) ===
SELECT T.TRANSACTION_ID, T.ACCOUNT_ID, T.TRANSACTION_TYPE_CODE, T.AMOUNT,
       T.CURRENCY_CODE, T.BOOKING_DATE, T.TRANSACTION_STATUS_CODE
  FROM DPS2.DEPOSIT_TRANSACTION T
 WHERE T.ACCOUNT_ID=1 AND T.TRANSACTION_ID IN (&DEPOSIT_TX_ID, &WITHDRAW_TX_ID)
 ORDER BY T.TRANSACTION_ID;

PROMPT === 02. Journal trace, amount parity and DEV_ONLY tag ===
WITH TX AS (
    SELECT T.TRANSACTION_ID,T.TRANSACTION_TYPE_CODE,T.TRANSACTION_STATUS_CODE,T.AMOUNT
      FROM DPS2.DEPOSIT_TRANSACTION T
     WHERE T.ACCOUNT_ID=1 AND T.TRANSACTION_ID IN (&DEPOSIT_TX_ID, &WITHDRAW_TX_ID)
), J AS (
    SELECT F.SOURCE_FACT_IDENTIFIER,AT.POSTING_STATE,
           COUNT(E.IDENTIFIER) AS LINES,
           NVL(SUM(CASE WHEN E.POSTING_DIRECTION='DEBIT' THEN E.AMOUNT ELSE 0 END),0) AS DEBITS,
           NVL(SUM(CASE WHEN E.POSTING_DIRECTION='CREDIT' THEN E.AMOUNT ELSE 0 END),0) AS CREDITS,
           NVL(SUM(CASE WHEN DBMS_LOB.INSTR(E.DIMENSION_SNAPSHOT,'"postingMode":"DEV_ONLY"')>0 THEN 1 ELSE 0 END),0) AS DEV_ONLY_LINES
      FROM ACC.ACCOUNTING_FACTS F
      JOIN ACC.ACCOUNTING_TRANSACTIONS AT ON AT.ACCOUNTING_FACT_IDENTIFIER=F.IDENTIFIER
      LEFT JOIN ACC.ACCOUNTING_ENTRIES E ON E.ACCOUNTING_TRANSACTION_IDENTIFIER=AT.IDENTIFIER
     WHERE F.ACCOUNTING_PURPOSE='CASH_PRINCIPAL'
     GROUP BY F.SOURCE_FACT_IDENTIFIER,AT.POSTING_STATE
)
SELECT TX.TRANSACTION_ID,TX.TRANSACTION_TYPE_CODE,TX.TRANSACTION_STATUS_CODE,
       J.POSTING_STATE AS ACC_STATE,J.LINES,J.DEBITS,J.CREDITS,J.DEV_ONLY_LINES,
       CASE WHEN TX.TRANSACTION_STATUS_CODE='POSTED' AND J.POSTING_STATE='POSTED'
                 AND J.LINES=2 AND J.DEV_ONLY_LINES=2 AND J.DEBITS=TX.AMOUNT
                 AND J.CREDITS=TX.AMOUNT THEN 'PASS' ELSE 'FAIL_OR_NOT_POSTED' END AS R1D8I_GL_RESULT
  FROM TX LEFT JOIN J ON J.SOURCE_FACT_IDENTIFIER='DPS2-TX-'||TO_CHAR(TX.TRANSACTION_ID)
 ORDER BY TX.TRANSACTION_ID;

PROMPT === 03. PST committed instruction and one DEV_ONLY plan per pilot transaction ===
SELECT T.TRANSACTION_ID,T.TRANSACTION_TYPE_CODE,
       (SELECT COUNT(*) FROM PST.POSTING_INSTRUCTIONS I
         WHERE I.SOURCE_DOMAIN='DPS2' AND I.SOURCE_EVENT_IDENTIFIER='DPS2-TX-'||TO_CHAR(T.TRANSACTION_ID)
           AND I.ACCOUNTING_PURPOSE='CASH_PRINCIPAL' AND I.EXECUTION_STATE='COMMITTED') AS COMMITTED_INSTRUCTIONS,
       (SELECT COUNT(*) FROM PST.POSTING_PLANS P JOIN PST.POSTING_INSTRUCTIONS I
             ON I.IDENTIFIER=P.POSTING_INSTRUCTION_IDENTIFIER
         WHERE I.SOURCE_DOMAIN='DPS2' AND I.SOURCE_EVENT_IDENTIFIER='DPS2-TX-'||TO_CHAR(T.TRANSACTION_ID)
           AND P.PUBLICATION_STATE='DEV_ONLY') AS DEV_ONLY_PLANS
  FROM DPS2.DEPOSIT_TRANSACTION T
 WHERE T.ACCOUNT_ID=1 AND T.TRANSACTION_ID IN (&DEPOSIT_TX_ID, &WITHDRAW_TX_ID)
 ORDER BY T.TRANSACTION_ID;

PROMPT === 04. LGR committed movement and explicitly DEV_ONLY provider receipt ===
SELECT T.TRANSACTION_ID,T.TRANSACTION_TYPE_CODE,
       (SELECT COUNT(*) FROM LGR.LEDGER_TRANSACTIONS LT
             JOIN LGR.LEDGER_MOVEMENTS LM ON LM.LEDGER_TRANSACTION_IDENTIFIER=LT.IDENTIFIER
         WHERE LT.SOURCE_INSTRUCTION_REFERENCE='DPS2-CASH-'||TO_CHAR(T.TRANSACTION_ID)
           AND LT.POSTING_STATE='COMMITTED') AS COMMITTED_MOVEMENTS,
       (SELECT COUNT(*) FROM LGR.COMMIT_RECEIPTS CR
         WHERE CR.SOURCE_INSTRUCTION_REFERENCE='DPS2-CASH-'||TO_CHAR(T.TRANSACTION_ID)
           AND CR.PROVIDER_NAME='ORACLE_POSITION_LEDGER_DEV_ONLY') AS DEV_ONLY_RECEIPTS
  FROM DPS2.DEPOSIT_TRANSACTION T
 WHERE T.ACCOUNT_ID=1 AND T.TRANSACTION_ID IN (&DEPOSIT_TX_ID, &WITHDRAW_TX_ID)
 ORDER BY T.TRANSACTION_ID;

PROMPT === 05. Current pilot position balances (units: IRR minor units = IRR) ===
SELECT P.POSITION_ACCOUNT_CODE, B.ASSET_CODE, B.POSTED_BALANCE, B.RESERVED_AMOUNT,
       B.RECORD_VERSION
  FROM LGR.POSITION_ACCOUNTS P LEFT JOIN LGR.POSITION_BALANCES B
    ON B.POSITION_ACCOUNT_REFERENCE=P.POSITION_ACCOUNT_CODE AND B.ASSET_CODE=P.ASSET_CODE
 WHERE P.LEDGER_IDENTIFIER=1 AND P.POSITION_ACCOUNT_CODE IN
       ('UAT1405-POS-CASH','UAT1405-POS-CUSTOMER')
 ORDER BY P.POSITION_ACCOUNT_CODE;
PROMPT === End: read only; no posting flags or approval status changed ===
