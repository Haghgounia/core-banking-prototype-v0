CREATE SEQUENCE CLT.SEQ_CLT_INTRO_REVIEW START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE CLT.SEQ_CLT_INTRO_REVIEW_EVENT START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE CLT.CLT_INTRODUCTION_REVIEW (
  REVIEW_ID NUMBER(19,0) NOT NULL,
  DRAFT_ID NUMBER(19,0) NOT NULL,
  MAKER_SUBJECT VARCHAR2(100 CHAR) NOT NULL,
  BRANCH_CODE VARCHAR2(30 CHAR) NOT NULL,
  IDEMPOTENCY_KEY VARCHAR2(100 CHAR) NOT NULL,
  DRAFT_HASH CHAR(64 CHAR) NOT NULL,
  REVIEW_STATUS VARCHAR2(20 CHAR) DEFAULT 'PENDING_REVIEW' NOT NULL,
  SUBMITTED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  CHECKER_SUBJECT VARCHAR2(100 CHAR),
  DECISION_KEY VARCHAR2(100 CHAR),
  DECISION_REASON VARCHAR2(500 CHAR),
  DECIDED_AT TIMESTAMP(6),
  RECORD_VERSION NUMBER(10,0) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_CLT_INTRO_REVIEW PRIMARY KEY (REVIEW_ID),
  CONSTRAINT UK_CLT_INTRO_REVIEW_DRAFT UNIQUE (DRAFT_ID),
  CONSTRAINT UK_CLT_INTRO_REVIEW_KEY UNIQUE (MAKER_SUBJECT,BRANCH_CODE,IDEMPOTENCY_KEY),
  CONSTRAINT FK_CLT_INTRO_REVIEW_DRAFT FOREIGN KEY (DRAFT_ID)
     REFERENCES CLT.CLT_INTRODUCTION_DRAFT(DRAFT_ID),
  CONSTRAINT CHK_CLT_INTRO_REVIEW_STATUS CHECK
     (REVIEW_STATUS IN ('PENDING_REVIEW','REVIEWED','RETURNED')),
  CONSTRAINT CHK_CLT_INTRO_REVIEW_VERSION CHECK (RECORD_VERSION IN (1,2)),
  CONSTRAINT CHK_CLT_INTRO_REVIEW_DECISION CHECK
     ((REVIEW_STATUS = 'PENDING_REVIEW' AND CHECKER_SUBJECT IS NULL
        AND DECISION_KEY IS NULL AND DECISION_REASON IS NULL
        AND DECIDED_AT IS NULL AND RECORD_VERSION = 1)
       OR
      (REVIEW_STATUS IN ('REVIEWED','RETURNED') AND CHECKER_SUBJECT IS NOT NULL
        AND DECISION_KEY IS NOT NULL AND DECISION_REASON IS NOT NULL
        AND DECIDED_AT IS NOT NULL AND RECORD_VERSION = 2
        AND CHECKER_SUBJECT <> MAKER_SUBJECT))
);

CREATE TABLE CLT.CLT_INTRODUCTION_REVIEW_EVENT (
  EVENT_ID NUMBER(19,0) NOT NULL,
  REVIEW_ID NUMBER(19,0) NOT NULL,
  EVENT_CODE VARCHAR2(30 CHAR) NOT NULL,
  ACTOR_SUBJECT VARCHAR2(100 CHAR) NOT NULL,
  BRANCH_CODE VARCHAR2(30 CHAR) NOT NULL,
  CORRELATION_ID VARCHAR2(100 CHAR) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_CLT_INTRO_REVIEW_EVENT PRIMARY KEY (EVENT_ID),
  CONSTRAINT FK_CLT_INTRO_REVIEW_EVENT FOREIGN KEY (REVIEW_ID)
      REFERENCES CLT.CLT_INTRODUCTION_REVIEW(REVIEW_ID),
  CONSTRAINT CHK_CLT_INTRO_REVIEW_EVENT CHECK
      (EVENT_CODE IN ('SUBMITTED','REVIEWED','RETURNED'))
);
CREATE INDEX CLT.IX_CLT_INTRO_REVIEW_QUEUE ON CLT.CLT_INTRODUCTION_REVIEW
  (BRANCH_CODE, REVIEW_STATUS, SUBMITTED_AT);
CREATE INDEX CLT.IX_CLT_INTRO_REVIEW_MAKER ON CLT.CLT_INTRODUCTION_REVIEW
  (MAKER_SUBJECT, BRANCH_CODE, SUBMITTED_AT);
CREATE INDEX CLT.IX_CLT_INTRO_REVIEW_EVENTS ON CLT.CLT_INTRODUCTION_REVIEW_EVENT
  (REVIEW_ID, CREATED_AT);

