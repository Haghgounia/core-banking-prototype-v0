-- R4D diagnostic. READ-ONLY metadata inspection. Do not execute as a schema owner with privilege escalation.
-- This script has NO DDL, DML, commit, begin, or FOR UPDATE.
SELECT OWNER,TABLE_NAME,COLUMN_NAME,DATA_TYPE,DATA_PRECISION,DATA_SCALE
  FROM ALL_TAB_COLUMNS
 WHERE OWNER='CLT'
   AND ((TABLE_NAME='COLLATERAL' AND COLUMN_NAME IN
           ('COLLATERAL_ID','BRANCH_CODE','RECORD_VERSION','CURRENCY_CODE',
            'COLLATERAL_STATUS_CODE','CURRENT_VALUATION_HISTORY_ID'))
     OR (TABLE_NAME='COLLATERAL_ALLOCATION' AND COLUMN_NAME IN
           ('COLLATERAL_ID','BRANCH_CODE','USED','ALLOCATE_AMOUNT','MODULE_ID','CURRENCY_CODE'))
     OR (TABLE_NAME='CLT_ALLOCATION_REQUEST' AND COLUMN_NAME IN
           ('REQUEST_ID','COLLATERAL_ID','BRANCH_CODE','CLIENT_ID','CONSUMER_DOMAIN','REQUEST_STATUS'))
     OR (TABLE_NAME='CLT_ALLOCATION_REQUEST_DEBTOR' AND COLUMN_NAME IN
           ('REQUEST_ID','PARTY_ID','DEBTOR_ROLE')))
 ORDER BY TABLE_NAME,COLUMN_NAME;
SELECT OWNER,TABLE_NAME,CONSTRAINT_NAME,CONSTRAINT_TYPE,STATUS,VALIDATED
  FROM ALL_CONSTRAINTS
 WHERE OWNER='CLT' AND TABLE_NAME IN
       ('COLLATERAL','COLLATERAL_ALLOCATION','CLT_ALLOCATION_REQUEST',
        'CLT_ALLOCATION_REQUEST_DEBTOR')
 ORDER BY TABLE_NAME,CONSTRAINT_NAME;
SELECT OWNER,TABLE_NAME,GRANTEE,PRIVILEGE
  FROM ALL_TAB_PRIVS
 WHERE OWNER='CLT' AND TABLE_NAME IN
       ('COLLATERAL','COLLATERAL_ALLOCATION','CLT_ALLOCATION_REQUEST',
        'CLT_ALLOCATION_REQUEST_DEBTOR','COLLATERAL_SPONSOR',
        'COLLATERAL_TYPE','REF_COLLATERAL_STATUS','COLLATERAL_VALUATION_HISTORY')
 ORDER BY TABLE_NAME,GRANTEE,PRIVILEGE;
