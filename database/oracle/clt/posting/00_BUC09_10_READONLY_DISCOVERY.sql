-- BUC-09/BUC-10 / Oracle DBA READ ONLY discovery, zero DDL/DML/COMMIT.
SELECT TABLE_NAME,COLUMN_NAME,DATA_TYPE,DATA_PRECISION,DATA_SCALE,NULLABLE,
       DEFAULT_LENGTH,IDENTITY_COLUMN,VIRTUAL_COLUMN
  FROM ALL_TAB_COLUMNS
 WHERE OWNER='CLT' AND TABLE_NAME IN
       ('COLLATERAL','COLLATERAL_ALLOCATION','COLLATERAL_TRANSACTION',
        'CLT_ALLOCATION_REQUEST','CLT_UNALLOC_REQ','CLT_COVERAGE_POST_PERMIT',
        'REF_COLL_TXN_TYPE','REF_COLL_TXN_STATUS')
 ORDER BY TABLE_NAME,COLUMN_ID;

SELECT TABLE_NAME,CONSTRAINT_NAME,CONSTRAINT_TYPE,STATUS,VALIDATED
  FROM ALL_CONSTRAINTS
 WHERE OWNER='CLT' AND TABLE_NAME IN
       ('COLLATERAL_ALLOCATION','COLLATERAL_TRANSACTION','CLT_COVERAGE_POST_PERMIT')
 ORDER BY TABLE_NAME,CONSTRAINT_NAME;

SELECT SEQUENCE_NAME,LAST_NUMBER FROM ALL_SEQUENCES
 WHERE SEQUENCE_OWNER='CLT' ORDER BY SEQUENCE_NAME;

SELECT TRANSACTION_TYPE_CODE FROM CLT.REF_COLL_TXN_TYPE ORDER BY TRANSACTION_TYPE_CODE;
SELECT TRANSACTION_STATUS_CODE FROM CLT.REF_COLL_TXN_STATUS ORDER BY TRANSACTION_STATUS_CODE;

SELECT COUNT(*) AS ACTIVE_ALLOCATION_COUNT
  FROM CLT.COLLATERAL_ALLOCATION WHERE USED='YES';
SELECT COUNT(*) AS PENDING_TRANSACTION_COUNT
  FROM CLT.COLLATERAL_TRANSACTION WHERE TRANSACTION_STATUS_CODE='PENDING';
