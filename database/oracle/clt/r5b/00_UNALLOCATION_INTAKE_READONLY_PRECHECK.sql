-- CLT R5B: SAFE read-only metadata checks. No DDL/DML/COMMIT.
SELECT TABLE_NAME, COUNT(*) COLUMN_COUNT
  FROM ALL_TAB_COLUMNS
 WHERE OWNER = 'CLT'
   AND TABLE_NAME IN ('COLLATERAL','COLLATERAL_ALLOCATION',
                      'CLT_UNALLOC_REQ','CLT_UNALLOC_REQ_EVENT')
 GROUP BY TABLE_NAME ORDER BY TABLE_NAME;

SELECT OWNER,TABLE_NAME,CONSTRAINT_NAME,CONSTRAINT_TYPE,STATUS,VALIDATED
  FROM ALL_CONSTRAINTS
 WHERE OWNER='CLT'
   AND TABLE_NAME IN ('CLT_UNALLOC_REQ','CLT_UNALLOC_REQ_EVENT')
 ORDER BY TABLE_NAME,CONSTRAINT_NAME;

SELECT SEQUENCE_OWNER,SEQUENCE_NAME
  FROM ALL_SEQUENCES
 WHERE SEQUENCE_OWNER='CLT'
   AND SEQUENCE_NAME IN ('SEQ_CLT_UNALLOC_REQ','SEQ_CLT_UNALLOC_EVT')
 ORDER BY SEQUENCE_NAME;

SELECT GRANTEE,OWNER,TABLE_NAME,PRIVILEGE
  FROM ALL_TAB_PRIVS
 WHERE OWNER='CLT'
   AND TABLE_NAME IN ('CLT_UNALLOC_REQ','CLT_UNALLOC_REQ_EVENT',
                      'COLLATERAL_ALLOCATION','COLLATERAL')
 ORDER BY GRANTEE,TABLE_NAME,PRIVILEGE;
