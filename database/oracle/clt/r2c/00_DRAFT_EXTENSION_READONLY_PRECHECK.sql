-- CLT R2C: metadata-only, no DDL, DML or COMMIT.
-- Use SQL Developer F5 in the authorized environment. R2B draft table
-- is a separately approved candidate; this script never creates it.
SET DEFINE OFF
PROMPT CLT_R2C_PRECHECK_BEGIN
SELECT OWNER, TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_LENGTH, CHAR_USED
  FROM ALL_TAB_COLUMNS
 WHERE OWNER = 'CLT'
   AND TABLE_NAME IN ('CLT_INTRODUCTION_DRAFT', 'COLLATERAL', 'COLLATERAL_TYPE')
   AND COLUMN_NAME IN ('ASSET_REFERENCE', 'ITEM_RANGES_JSON',
     'DRAFT_ID', 'COLLATERAL_NUMBER', 'HAS_MULTIPLICITY', 'PARTY_ID')
 ORDER BY TABLE_NAME, COLUMN_ID;
SELECT OWNER, TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE, STATUS
  FROM ALL_CONSTRAINTS
 WHERE OWNER = 'CLT' AND TABLE_NAME = 'CLT_INTRODUCTION_DRAFT'
 ORDER BY CONSTRAINT_NAME;
PROMPT CLT_R2C_PRECHECK_READONLY_COMPLETED
