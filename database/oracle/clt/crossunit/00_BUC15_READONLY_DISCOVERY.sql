SELECT TABLE_NAME,COUNT(*) AS COLUMN_COUNT FROM ALL_TAB_COLUMNS
 WHERE OWNER='CLT' AND TABLE_NAME IN ('CLT_CROSS_UNIT_GRANT',
 'CLT_CROSS_UNIT_GRANT_EVENT','CLT_CROSS_UNIT_INTENT','CLT_CROSS_UNIT_INTENT_DEBTOR')
 GROUP BY TABLE_NAME ORDER BY TABLE_NAME;
SELECT CONSTRAINT_NAME,CONSTRAINT_TYPE,STATUS,VALIDATED
 FROM ALL_CONSTRAINTS WHERE OWNER='CLT' AND TABLE_NAME LIKE 'CLT_CROSS_UNIT_%'
 ORDER BY TABLE_NAME,CONSTRAINT_NAME;
SELECT INDEX_NAME,STATUS,UNIQUENESS FROM ALL_INDEXES
 WHERE OWNER='CLT' AND INDEX_NAME='UQ_CLT_CU_GRANT_ACTIVE';
SELECT SEQUENCE_NAME FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER='CLT'
 AND SEQUENCE_NAME IN ('SEQ_CLT_CU_GRANT','SEQ_CLT_CU_GRANT_EVENT','SEQ_CLT_CU_INTENT');
