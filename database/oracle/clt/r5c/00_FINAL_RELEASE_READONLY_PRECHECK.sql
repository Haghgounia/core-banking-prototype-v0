SELECT OWNER,TABLE_NAME FROM ALL_TABLES
 WHERE OWNER='CLT' AND TABLE_NAME IN
 ('COLLATERAL','COLLATERAL_TYPE','REF_COLLATERAL_STATUS',
  'COLLATERAL_ALLOCATION','COLLATERAL_TRANSACTION','COLLATERAL_STATUS_HISTORY')
 ORDER BY TABLE_NAME;
SELECT TABLE_NAME,COLUMN_NAME,DATA_TYPE FROM ALL_TAB_COLUMNS
 WHERE OWNER='CLT' AND
 ((TABLE_NAME='COLLATERAL_TYPE' AND COLUMN_NAME='REQUIRED_RELEASE_INQUIRY')
 OR (TABLE_NAME='COLLATERAL_ALLOCATION' AND COLUMN_NAME IN ('USED','BRANCH_CODE','COLLATERAL_ID'))
 OR (TABLE_NAME='COLLATERAL' AND COLUMN_NAME IN ('COLLATERAL_STATUS_CODE','RECORD_VERSION','BRANCH_CODE'))
 OR (TABLE_NAME='COLLATERAL_STATUS_HISTORY' AND COLUMN_NAME IN ('FROM_STATUS_CODE','TO_STATUS_CODE','STATUS_SEQUENCE_NO')))
 ORDER BY TABLE_NAME,COLUMN_NAME;
SELECT TABLE_NAME,CONSTRAINT_NAME,STATUS,VALIDATED FROM ALL_CONSTRAINTS
 WHERE OWNER='CLT' AND TABLE_NAME IN
 ('COLLATERAL','COLLATERAL_ALLOCATION','COLLATERAL_STATUS_HISTORY')
 ORDER BY TABLE_NAME,CONSTRAINT_NAME;
