-- CLT R1A: READ-ONLY precheck. Run from a DBA-authorized read session or a CLT reader.
-- Intentionally NO DDL, DML, PL/SQL blocks, COMMIT or GRANT.
-- ALL_TABLES shows only objects visible to this user; missing may mean insufficient SELECT grants.
SET PAGESIZE 200
SET LINESIZE 180
COLUMN TABLE_NAME FORMAT A52
COLUMN CHECK_STATUS FORMAT A15
WITH expected (table_name) AS (
  SELECT 'COLLATERAL_TYPE_ATTRIBUTE' FROM DUAL
  UNION ALL SELECT 'REF_COLLATERAL_ATTRIBUTE_DATA_TYPE' FROM DUAL
  UNION ALL SELECT 'REF_COLL_TXN_STATUS' FROM DUAL
  UNION ALL SELECT 'REF_CURRENCY' FROM DUAL
  UNION ALL SELECT 'REF_VALUATION_TYPE' FROM DUAL
  UNION ALL SELECT 'REF_COLL_REVERSAL_REASON' FROM DUAL
  UNION ALL SELECT 'COLLATERAL_ATTRIBUTE_DEFINITION' FROM DUAL
  UNION ALL SELECT 'COLLATERAL_TYPE' FROM DUAL
  UNION ALL SELECT 'COLLATERAL_GROUP' FROM DUAL
  UNION ALL SELECT 'REF_SOURCE_SYSTEM' FROM DUAL
  UNION ALL SELECT 'REF_COLLATERAL_STATUS' FROM DUAL
  UNION ALL SELECT 'COLLATERAL_INSURANCE_TYPE' FROM DUAL
  UNION ALL SELECT 'REF_CHANNEL' FROM DUAL
  UNION ALL SELECT 'INSURANCE_COMPANY' FROM DUAL
  UNION ALL SELECT 'REF_VALUATION_METHOD' FROM DUAL
  UNION ALL SELECT 'REF_VALUATION_STATUS' FROM DUAL
  UNION ALL SELECT 'REF_COLL_TXN_TYPE' FROM DUAL
 )
SELECT e.table_name,
       CASE WHEN t.table_name IS NULL THEN 'NOT_VISIBLE' ELSE 'VISIBLE' END AS check_status
FROM expected e
LEFT JOIN ALL_TABLES t ON t.owner = 'CLT' AND t.table_name = e.table_name
ORDER BY e.table_name;

-- Compare expected table inventory, NOT live row counts.
SELECT COUNT(*) AS VISIBLE_REFERENCE_TABLES
FROM ALL_TABLES t
WHERE t.owner = 'CLT' AND t.table_name IN (
   'COLLATERAL_TYPE_ATTRIBUTE',
   'REF_COLLATERAL_ATTRIBUTE_DATA_TYPE',
   'REF_COLL_TXN_STATUS',
   'REF_CURRENCY',
   'REF_VALUATION_TYPE',
   'REF_COLL_REVERSAL_REASON',
   'COLLATERAL_ATTRIBUTE_DEFINITION',
   'COLLATERAL_TYPE',
   'COLLATERAL_GROUP',
   'REF_SOURCE_SYSTEM',
   'REF_COLLATERAL_STATUS',
   'COLLATERAL_INSURANCE_TYPE',
   'REF_CHANNEL',
   'INSURANCE_COMPANY',
   'REF_VALUATION_METHOD',
   'REF_VALUATION_STATUS',
   'REF_COLL_TXN_TYPE'
);
