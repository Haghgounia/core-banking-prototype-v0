-- CLT R2E: READ ONLY dictionary and reference checks. Do not change bank data.
-- Run as an authorized read-only user with visibility on CLT objects.
SET DEFINE OFF
SET PAGESIZE 100
PROMPT === CLT R2E A. Current physical number shape ===
SELECT OWNER, TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_PRECISION, DATA_SCALE, NULLABLE
  FROM ALL_TAB_COLUMNS WHERE OWNER = 'CLT' AND TABLE_NAME = 'COLLATERAL'
   AND COLUMN_NAME = 'COLLATERAL_NUMBER';
PROMPT === CLT R2E B. Number uniqueness and state constraints ===
SELECT c.CONSTRAINT_NAME, c.CONSTRAINT_TYPE, c.STATUS, cc.COLUMN_NAME, cc.POSITION
  FROM ALL_CONSTRAINTS c JOIN ALL_CONS_COLUMNS cc
    ON c.OWNER = cc.OWNER AND c.CONSTRAINT_NAME = cc.CONSTRAINT_NAME
 WHERE c.OWNER = 'CLT' AND c.TABLE_NAME = 'COLLATERAL'
   AND cc.COLUMN_NAME = 'COLLATERAL_NUMBER'
 ORDER BY c.CONSTRAINT_NAME, cc.POSITION;
PROMPT === CLT R2E C. Transaction status and type (G-16) ===
SELECT TRANSACTION_STATUS_CODE, STATUS FROM CLT.REF_COLL_TXN_STATUS
 WHERE TRANSACTION_STATUS_CODE IN ('PENDING','PENDING_APPROVAL','POSTED')
 ORDER BY TRANSACTION_STATUS_CODE;
SELECT TRANSACTION_TYPE_CODE, STATUS FROM CLT.REF_COLL_TXN_TYPE
 WHERE TRANSACTION_TYPE_CODE = 'INTRODUCTION';
PROMPT === CLT R2E D. Collateral status choices ===
SELECT COLLATERAL_STATUS_CODE, STATUS FROM CLT.REF_COLLATERAL_STATUS
 WHERE COLLATERAL_STATUS_CODE IN ('DRAFT','ACTIVE','PLEDGED')
 ORDER BY COLLATERAL_STATUS_CODE;
PROMPT === CLT R2E E. Proposed staging and addendum tables ===
SELECT TABLE_NAME FROM ALL_TABLES WHERE OWNER = 'CLT'
 AND TABLE_NAME IN ('CLT_INTRODUCTION_DRAFT','CLT_INTRODUCTION_REVIEW',
   'CLT_ASSET_IDENTITY','CLT_ASSET_COLLATERAL_LINK',
   'CLT_COLLATERAL_SERIAL_RANGE','CLT_REGISTRATION_LEDGER',
   'CLT_REGISTRATION_NUMBER_AUTHORITY','CLT_COLLATERAL_AMENDMENT_REQUEST')
 ORDER BY TABLE_NAME;
PROMPT CLT_R2E_READONLY_PRECHECK_COMPLETE; NO DDL; NO DML; NO COMMIT.
