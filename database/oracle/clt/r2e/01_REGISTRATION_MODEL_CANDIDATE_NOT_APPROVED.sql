-- 1. Verified asset master: source-specific canonicalization rules pending.
CREATE TABLE CLT.CLT_ASSET_IDENTITY (
  ASSET_ID NUMBER(19,0) NOT NULL,
  COLLATERAL_TYPE_ID NUMBER(19,0) NOT NULL,
  IDENTITY_SCHEME_CODE VARCHAR2(40 CHAR) NOT NULL,
  CANONICAL_IDENTITY_HASH CHAR(64 CHAR) NOT NULL,
  SOURCE_REFERENCE VARCHAR2(200 CHAR) NOT NULL,
  VERIFICATION_EVIDENCE VARCHAR2(200 CHAR) NOT NULL,
  VERIFIED_BY VARCHAR2(100 CHAR) NOT NULL,
  VERIFIED_AT TIMESTAMP(6) NOT NULL,
  IDENTITY_STATUS VARCHAR2(20 CHAR) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_CLT_ASSET_IDENTITY PRIMARY KEY (ASSET_ID),
  CONSTRAINT FK_CLT_ASSET_TYPE FOREIGN KEY (COLLATERAL_TYPE_ID)
    REFERENCES CLT.COLLATERAL_TYPE(COLLATERAL_TYPE_ID),
  CONSTRAINT UQ_CLT_ASSET_CANONICAL UNIQUE
    (COLLATERAL_TYPE_ID,IDENTITY_SCHEME_CODE,CANONICAL_IDENTITY_HASH),
  CONSTRAINT CK_CLT_ASSET_STATUS CHECK (IDENTITY_STATUS IN ('VERIFIED','RETIRED')),
  CONSTRAINT CK_CLT_ASSET_HASH CHECK
    (REGEXP_LIKE(CANONICAL_IDENTITY_HASH,'^[0-9a-f]{64}$'))
);
-- 2. Same asset across separate, historically traceable collateral registrations.
CREATE TABLE CLT.CLT_ASSET_COLLATERAL_LINK (
  ASSET_COLLATERAL_LINK_ID NUMBER(19,0) NOT NULL,
  ASSET_ID NUMBER(19,0) NOT NULL,
  COLLATERAL_ID NUMBER(19,0) NOT NULL,
  PREVIOUS_COLLATERAL_ID NUMBER(19,0),
  IS_CURRENT_FLAG CHAR(1 CHAR) NOT NULL,
  LINKED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  LINKED_BY VARCHAR2(100 CHAR) NOT NULL,
  CONSTRAINT PK_CLT_ASSET_COLLATERAL_LINK PRIMARY KEY (ASSET_COLLATERAL_LINK_ID),
  CONSTRAINT UQ_CLT_LINK_COLLATERAL UNIQUE (COLLATERAL_ID),
  CONSTRAINT FK_CLT_LINK_ASSET FOREIGN KEY (ASSET_ID)
    REFERENCES CLT.CLT_ASSET_IDENTITY(ASSET_ID),
  CONSTRAINT FK_CLT_LINK_COLLATERAL FOREIGN KEY (COLLATERAL_ID)
    REFERENCES CLT.COLLATERAL(COLLATERAL_ID),
  CONSTRAINT FK_CLT_LINK_PREVIOUS FOREIGN KEY (PREVIOUS_COLLATERAL_ID)
    REFERENCES CLT.COLLATERAL(COLLATERAL_ID),
  CONSTRAINT CK_CLT_LINK_CURRENT CHECK (IS_CURRENT_FLAG IN ('Y','N'))
);
-- Oracle function-based index: at most one current collateral per verified asset.
CREATE UNIQUE INDEX CLT.UQ_CLT_ASSET_ONE_CURRENT
  ON CLT.CLT_ASSET_COLLATERAL_LINK
  (CASE WHEN IS_CURRENT_FLAG='Y' THEN ASSET_ID END);
-- 3. Durable, explicit serial ranges; compare numeric meaning under ASSET lock
--    in application/DB, not lexical VARCHAR ordering; leading zeroes are retained.
CREATE TABLE CLT.CLT_COLLATERAL_SERIAL_RANGE (
  COLLATERAL_SERIAL_RANGE_ID NUMBER(19,0) NOT NULL,
  COLLATERAL_ID NUMBER(19,0) NOT NULL,
  RANGE_SEQUENCE_NO NUMBER(5,0) NOT NULL,
  SERIAL_FROM VARCHAR2(100 CHAR) NOT NULL,
  SERIAL_TO VARCHAR2(100 CHAR) NOT NULL,
  ITEM_COUNT NUMBER(2,0) NOT NULL,
  RANGE_AMOUNT NUMBER(20,4) NOT NULL,
  CURRENCY_CODE CHAR(3 CHAR) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY VARCHAR2(100 CHAR) NOT NULL,
  CONSTRAINT PK_CLT_SERIAL_RANGE PRIMARY KEY (COLLATERAL_SERIAL_RANGE_ID),
  CONSTRAINT UQ_CLT_SERIAL_RANGE_SEQUENCE UNIQUE (COLLATERAL_ID,RANGE_SEQUENCE_NO),
  CONSTRAINT FK_CLT_SERIAL_RANGE_COLLATERAL FOREIGN KEY (COLLATERAL_ID)
    REFERENCES CLT.COLLATERAL(COLLATERAL_ID),
  CONSTRAINT CK_CLT_SERIAL_RANGE_FROM CHECK (REGEXP_LIKE(SERIAL_FROM,'^[0-9]{1,100}$')),
  CONSTRAINT CK_CLT_SERIAL_RANGE_TO CHECK (REGEXP_LIKE(SERIAL_TO,'^[0-9]{1,100}$')),
  CONSTRAINT CK_CLT_SERIAL_RANGE_COUNT CHECK (ITEM_COUNT BETWEEN 1 AND 20),
  CONSTRAINT CK_CLT_SERIAL_RANGE_AMOUNT CHECK (RANGE_AMOUNT > 0)
);
-- 4. One durable finalization outcome for each reviewed draft; all inserted
--    transactionally with actual COLLATERAL and status history after approvals.
CREATE TABLE CLT.CLT_REGISTRATION_LEDGER (
  REGISTRATION_ID NUMBER(19,0) NOT NULL,
  REVIEW_ID NUMBER(19,0) NOT NULL,
  DRAFT_ID NUMBER(19,0) NOT NULL,
  COLLATERAL_ID NUMBER(19,0) NOT NULL,
  COLLATERAL_NUMBER NUMBER(19,0) NOT NULL,
  DRAFT_HASH CHAR(64 CHAR) NOT NULL,
  IDENTITY_SCHEME_CODE VARCHAR2(40 CHAR) NOT NULL,
  NUMBER_SCHEME_CODE VARCHAR2(40 CHAR) NOT NULL,
  BANK_APPROVAL_REFERENCE VARCHAR2(100 CHAR) NOT NULL,
  REGISTRATION_STATUS VARCHAR2(20 CHAR) NOT NULL,
  REGISTERED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  REGISTERED_BY VARCHAR2(100 CHAR) NOT NULL,
  BRANCH_CODE VARCHAR2(30 CHAR) NOT NULL,
  CONSTRAINT PK_CLT_REGISTRATION_LEDGER PRIMARY KEY (REGISTRATION_ID),
  CONSTRAINT UQ_CLT_REG_REVIEW UNIQUE (REVIEW_ID),
  CONSTRAINT UQ_CLT_REG_DRAFT UNIQUE (DRAFT_ID),
  CONSTRAINT UQ_CLT_REG_COLLATERAL UNIQUE (COLLATERAL_ID),
  CONSTRAINT UQ_CLT_REG_NUMBER UNIQUE (COLLATERAL_NUMBER),
  CONSTRAINT FK_CLT_REG_REVIEW FOREIGN KEY (REVIEW_ID)
    REFERENCES CLT.CLT_INTRODUCTION_REVIEW(REVIEW_ID),
  CONSTRAINT FK_CLT_REG_DRAFT FOREIGN KEY (DRAFT_ID)
    REFERENCES CLT.CLT_INTRODUCTION_DRAFT(DRAFT_ID),
  CONSTRAINT FK_CLT_REG_COLLATERAL FOREIGN KEY (COLLATERAL_ID)
    REFERENCES CLT.COLLATERAL(COLLATERAL_ID),
  CONSTRAINT CK_CLT_REG_STATUS CHECK (REGISTRATION_STATUS='REGISTERED')
);
-- 5. Authority-controlled number inventory, not operator-entered / not auto-seeded.
CREATE TABLE CLT.CLT_REGISTRATION_NUMBER_AUTHORITY (
  COLLATERAL_NUMBER NUMBER(19,0) NOT NULL,
  SCHEME_CODE VARCHAR2(40 CHAR) NOT NULL,
  APPROVAL_REFERENCE VARCHAR2(100 CHAR) NOT NULL,
  ISSUE_STATUS VARCHAR2(20 CHAR) NOT NULL,
  ISSUED_TO_REVIEW_ID NUMBER(19,0),
  ISSUED_AT TIMESTAMP(6),
  CONSTRAINT PK_CLT_NUMBER_AUTHORITY PRIMARY KEY (COLLATERAL_NUMBER),
  CONSTRAINT UQ_CLT_NUMBER_ISSUED_TO UNIQUE (ISSUED_TO_REVIEW_ID),
  CONSTRAINT FK_CLT_NUMBER_REVIEW FOREIGN KEY (ISSUED_TO_REVIEW_ID)
    REFERENCES CLT.CLT_INTRODUCTION_REVIEW(REVIEW_ID),
  CONSTRAINT CK_CLT_NUMBER_POSITIVE CHECK (COLLATERAL_NUMBER > 0),
  CONSTRAINT CK_CLT_NUMBER_STATUS CHECK (ISSUE_STATUS IN ('AVAILABLE','ISSUED','RETIRED')),
  CONSTRAINT CK_CLT_NUMBER_STATE CHECK
    ((ISSUE_STATUS='ISSUED' AND ISSUED_TO_REVIEW_ID IS NOT NULL AND ISSUED_AT IS NOT NULL)
      OR (ISSUE_STATUS IN ('AVAILABLE','RETIRED') AND ISSUED_TO_REVIEW_ID IS NULL AND ISSUED_AT IS NULL))
);
