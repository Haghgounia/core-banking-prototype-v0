SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

CREATE SEQUENCE CLT.SEQ_CLT_INTRODUCTION_DRAFT START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE CLT.SEQ_CLT_INTRODUCTION_DRAFT_AUDIT START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE CLT.CLT_INTRODUCTION_DRAFT (
  DRAFT_ID NUMBER(19,0) NOT NULL,
  MAKER_SUBJECT VARCHAR2(100 CHAR) NOT NULL,
  BRANCH_CODE VARCHAR2(30 CHAR) NOT NULL,
  PARTY_ID NUMBER(19,0) NOT NULL,
  COLLATERAL_TYPE_ID NUMBER(19,0) NOT NULL,
  ESTIMATE_AMOUNT NUMBER(20,4) NOT NULL,
  CURRENCY_CODE CHAR(3 CHAR) NOT NULL,
  VALID_FROM DATE NOT NULL,
  VALID_TO DATE,
  DEPOSIT_NUMBER VARCHAR2(15 CHAR),
  REMARKS VARCHAR2(150 CHAR),
  ATTRIBUTES_JSON CLOB NOT NULL,
  IDEMPOTENCY_KEY VARCHAR2(100 CHAR) NOT NULL,
  REQUEST_HASH CHAR(64 CHAR) NOT NULL,
  CORRELATION_ID VARCHAR2(100 CHAR) NOT NULL,
  STATUS VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY VARCHAR2(100 CHAR) NOT NULL,
  RECORD_VERSION NUMBER(10,0) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_CLT_INTRODUCTION_DRAFT PRIMARY KEY (DRAFT_ID),
  CONSTRAINT UK_CLT_INTRO_DRAFT_REPLAY UNIQUE (MAKER_SUBJECT, BRANCH_CODE, IDEMPOTENCY_KEY),
  CONSTRAINT FK_CLT_INTRO_DRAFT_TYPE FOREIGN KEY (COLLATERAL_TYPE_ID)
    REFERENCES CLT.COLLATERAL_TYPE(COLLATERAL_TYPE_ID),
  CONSTRAINT FK_CLT_INTRO_DRAFT_CURRENCY FOREIGN KEY (CURRENCY_CODE)
    REFERENCES CLT.REF_CURRENCY(CURRENCY_CODE),
  CONSTRAINT CHK_CLT_INTRO_DRAFT_AMOUNT CHECK (ESTIMATE_AMOUNT > 0),
  CONSTRAINT CHK_CLT_INTRO_DRAFT_DATE CHECK (VALID_TO IS NULL OR VALID_TO >= VALID_FROM),
  CONSTRAINT CHK_CLT_INTRO_DRAFT_STATUS CHECK (STATUS = 'DRAFT'),
  CONSTRAINT CHK_CLT_INTRO_DRAFT_JSON CHECK (ATTRIBUTES_JSON IS JSON),
  CONSTRAINT CHK_CLT_INTRO_DRAFT_VERSION CHECK (RECORD_VERSION = 1)
);

CREATE TABLE CLT.CLT_INTRODUCTION_DRAFT_AUDIT (
  AUDIT_ID NUMBER(19,0) DEFAULT CLT.SEQ_CLT_INTRODUCTION_DRAFT_AUDIT.NEXTVAL NOT NULL,
  DRAFT_ID NUMBER(19,0) NOT NULL,
  EVENT_CODE VARCHAR2(30 CHAR) NOT NULL,
  EVENT_SUBJECT VARCHAR2(100 CHAR) NOT NULL,
  BRANCH_CODE VARCHAR2(30 CHAR) NOT NULL,
  REQUEST_HASH CHAR(64 CHAR) NOT NULL,
  CORRELATION_ID VARCHAR2(100 CHAR) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_CLT_INTRO_DRAFT_AUDIT PRIMARY KEY (AUDIT_ID),
  CONSTRAINT FK_CLT_INTRO_DRAFT_AUDIT FOREIGN KEY (DRAFT_ID)
    REFERENCES CLT.CLT_INTRODUCTION_DRAFT(DRAFT_ID),
  CONSTRAINT CHK_CLT_INTRO_DRAFT_EVENT CHECK (EVENT_CODE = 'DRAFT_CREATED')
);
CREATE INDEX CLT.IX_CLT_INTRO_DRAFT_MAKER ON CLT.CLT_INTRODUCTION_DRAFT
  (BRANCH_CODE, MAKER_SUBJECT, CREATED_AT);
CREATE INDEX CLT.IX_CLT_INTRO_DRAFT_AUDIT ON CLT.CLT_INTRODUCTION_DRAFT_AUDIT
  (DRAFT_ID, CREATED_AT);

