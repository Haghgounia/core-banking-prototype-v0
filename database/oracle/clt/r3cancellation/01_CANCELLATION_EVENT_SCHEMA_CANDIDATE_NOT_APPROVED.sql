CREATE TABLE CLT.R3_INS_CANCEL_REQUEST (
 CANCEL_REQUEST_ID NUMBER(19,0) CONSTRAINT PK_R3_INS_CANCEL_REQ PRIMARY KEY,
 COLLATERAL_ID NUMBER(19,0) NOT NULL,
 INSURANCE_ID NUMBER(19,0) NOT NULL,
 BRANCH_CODE VARCHAR2(30 CHAR) NOT NULL,
 STATUS_CODE VARCHAR2(20 CHAR) NOT NULL,
 MAKER_SUBJECT VARCHAR2(100 CHAR) NOT NULL,
 REVIEWER_SUBJECT VARCHAR2(100 CHAR),
 REVIEW_REASON VARCHAR2(500 CHAR),
 REQUEST_REASON VARCHAR2(500 CHAR) NOT NULL,
 REQUEST_HASH VARCHAR2(64 CHAR) NOT NULL,
 IDEMPOTENCY_KEY VARCHAR2(100 CHAR) NOT NULL,
 EXPECTED_INSURANCE_VERSION NUMBER(10,0) NOT NULL,
 RECORD_VERSION NUMBER(10,0) DEFAULT 1 NOT NULL,
 CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
 UPDATED_AT TIMESTAMP(6),
 CONSTRAINT UQ_R3_INS_CAN_REQ_IDEMP UNIQUE (BRANCH_CODE, IDEMPOTENCY_KEY),
 CONSTRAINT FK_R3_INS_CAN_REQ_POLICY FOREIGN KEY (INSURANCE_ID)
  REFERENCES CLT.COLLATERAL_INSURANCE (COLLATERAL_INSURANCE_ID),
 CONSTRAINT FK_R3_INS_CAN_REQ_COLL FOREIGN KEY (COLLATERAL_ID)
  REFERENCES CLT.COLLATERAL (COLLATERAL_ID),
 CONSTRAINT CK_R3_INS_CAN_REQ_STATE CHECK
  (STATUS_CODE IN ('DRAFT','SUBMITTED','REVIEWED','REJECTED','WITHDRAWN','COMMITTED')),
 CONSTRAINT CK_R3_INS_CAN_REQ_VERS CHECK
  (EXPECTED_INSURANCE_VERSION>=1 AND RECORD_VERSION>=1),
 CONSTRAINT CK_R3_INS_CAN_REQ_REVIEW CHECK
  (STATUS_CODE NOT IN ('REVIEWED','COMMITTED') OR
   (REVIEWER_SUBJECT IS NOT NULL AND REVIEWER_SUBJECT<>MAKER_SUBJECT))
);
CREATE INDEX CLT.IX_R3_INS_CAN_REQ_POLICY ON CLT.R3_INS_CANCEL_REQUEST (INSURANCE_ID,STATUS_CODE);

CREATE TABLE CLT.R3_INS_CANCEL_AUDIT (
 AUDIT_ID NUMBER(19,0) CONSTRAINT PK_R3_INS_CANCEL_AUD PRIMARY KEY,
 CANCEL_REQUEST_ID NUMBER(19,0) NOT NULL,
 ACTION_CODE VARCHAR2(25 CHAR) NOT NULL,
 ACTOR_SUBJECT VARCHAR2(100 CHAR) NOT NULL,
 REASON VARCHAR2(500 CHAR) NOT NULL,
 VERSION_BEFORE NUMBER(10,0) NOT NULL,
 VERSION_AFTER NUMBER(10,0) NOT NULL,
 EVENT_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT FK_R3_INS_CAN_AUD_REQ FOREIGN KEY (CANCEL_REQUEST_ID)
  REFERENCES CLT.R3_INS_CANCEL_REQUEST (CANCEL_REQUEST_ID),
 CONSTRAINT CK_R3_INS_CAN_AUD_ACT CHECK
  (ACTION_CODE IN ('CREATED','SUBMIT','REVIEW','REJECT','WITHDRAW','COMMITTED')),
 CONSTRAINT CK_R3_INS_CAN_AUD_VERS CHECK (VERSION_AFTER=VERSION_BEFORE+1)
);

CREATE TABLE CLT.R3_INS_CANCEL_RELEASE (
 RELEASE_ID NUMBER(1,0) CONSTRAINT PK_R3_INS_CANCEL_REL PRIMARY KEY,
 RELEASE_STATUS VARCHAR2(20 CHAR) NOT NULL,
 POLICY_REVISION VARCHAR2(120 CHAR) NOT NULL,
 BUSINESS_DECISION_REF VARCHAR2(120 CHAR) NOT NULL,
 DATA_DECISION_REF VARCHAR2(120 CHAR) NOT NULL,
 COVERAGE_DECISION_REF VARCHAR2(120 CHAR) NOT NULL,
 ALLOCATION_DECISION_REF VARCHAR2(120 CHAR) NOT NULL,
 INTEGRATION_DECISION_REF VARCHAR2(120 CHAR) NOT NULL,
 DOWNSTREAM_BINDING_REF VARCHAR2(120 CHAR) NOT NULL,
 APPROVED_BY VARCHAR2(120 CHAR) NOT NULL,
 EFFECTIVE_FROM TIMESTAMP(6) NOT NULL,
 EFFECTIVE_TO TIMESTAMP(6),
 CONSTRAINT CK_R3_INS_CAN_REL_ONE CHECK (RELEASE_ID=1),
 CONSTRAINT CK_R3_INS_CAN_REL_STATUS CHECK (RELEASE_STATUS IN ('APPROVED','REVOKED')),
 CONSTRAINT CK_R3_INS_CAN_REL_DATE CHECK (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO>EFFECTIVE_FROM)
);

