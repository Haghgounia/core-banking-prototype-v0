-- CLT R3 SPONSOR POSTING - read only. Execute as DBA or dictionary reader.
-- A 0 count is not permission to auto-create: all installation remains opt-in.
SELECT table_name FROM ALL_TABLES WHERE OWNER='CLT' AND TABLE_NAME IN
 ('COLLATERAL_SPONSOR_REQUEST','COLLATERAL_SPONSOR_REQUEST_EVENT',
  'COLLATERAL_SPONSOR','R3_POSTING_RELEASE','R3_POSTING_LEDGER');
SELECT table_name, column_name, data_type, nullable FROM ALL_TAB_COLUMNS
 WHERE OWNER='CLT' AND TABLE_NAME IN ('R3_POSTING_LEDGER','R3_POSTING_RELEASE')
 ORDER BY table_name, column_id;
SELECT table_name, constraint_name, constraint_type, status, validated
  FROM ALL_CONSTRAINTS WHERE OWNER='CLT' AND TABLE_NAME IN
 ('R3_POSTING_LEDGER','R3_POSTING_RELEASE') ORDER BY table_name,constraint_name;
SELECT sequence_name FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER='CLT'
  AND SEQUENCE_NAME='SEQ_CLT_R3_POSTING_LEDGER';
-- Physical duplicates must be reconciled before the unique constraint is approved.
SELECT COLLATERAL_ID, PARTY_ID, COUNT(*) AS DUPLICATE_ROWS
 FROM CLT.COLLATERAL_SPONSOR GROUP BY COLLATERAL_ID, PARTY_ID HAVING COUNT(*) > 1;
-- Next SELECT requires the separately approved release table.
SELECT REQUEST_KIND, RELEASE_STATUS, POLICY_REVISION, BUSINESS_DECISION_REF,
       DATA_DECISION_REF, INTEGRATION_DECISION_REF, APPROVED_BY,
       EFFECTIVE_FROM, EFFECTIVE_TO FROM CLT.R3_POSTING_RELEASE;
