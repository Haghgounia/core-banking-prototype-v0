CREATE TABLE CLT.R3_POSTING_RELEASE (
 REQUEST_KIND VARCHAR2(20 CHAR) NOT NULL,
 RELEASE_STATUS VARCHAR2(20 CHAR) NOT NULL,
 POLICY_REVISION VARCHAR2(120 CHAR) NOT NULL,
 BUSINESS_DECISION_REF VARCHAR2(120 CHAR) NOT NULL,
 DATA_DECISION_REF VARCHAR2(120 CHAR) NOT NULL,
 INTEGRATION_DECISION_REF VARCHAR2(120 CHAR) NOT NULL,
 APPROVED_BY VARCHAR2(120 CHAR) NOT NULL,
 EFFECTIVE_FROM TIMESTAMP(6) NOT NULL,
 EFFECTIVE_TO TIMESTAMP(6),
 CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT PK_CLT_R3_POST_RELEASE PRIMARY KEY (REQUEST_KIND),
 CONSTRAINT CK_CLT_R3_POST_RELEASE_KIND CHECK (REQUEST_KIND IN ('SPONSOR')),
 CONSTRAINT CK_CLT_R3_POST_RELEASE_STATUS CHECK (RELEASE_STATUS IN ('APPROVED','REVOKED','EXPIRED')),
 CONSTRAINT CK_CLT_R3_POST_RELEASE_RANGE CHECK (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO > EFFECTIVE_FROM)
);
