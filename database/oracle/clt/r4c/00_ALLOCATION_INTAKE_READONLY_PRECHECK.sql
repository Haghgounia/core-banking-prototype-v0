SELECT TABLE_NAME,COUNT(*) AS COLUMN_COUNT FROM ALL_TAB_COLUMNS
 WHERE OWNER='CLT' AND TABLE_NAME IN ('COLLATERAL','COLLATERAL_ALLOCATION',
  'CLT_ALLOCATION_REQUEST','CLT_ALLOCATION_REQUEST_DEBTOR','CLT_ALLOCATION_REQUEST_EVENT')
 GROUP BY TABLE_NAME ORDER BY TABLE_NAME;
SELECT TABLE_NAME,CONSTRAINT_NAME,CONSTRAINT_TYPE,STATUS,VALIDATED
  FROM ALL_CONSTRAINTS WHERE OWNER='CLT' AND TABLE_NAME IN
  ('CLT_ALLOCATION_REQUEST','CLT_ALLOCATION_REQUEST_DEBTOR','CLT_ALLOCATION_REQUEST_EVENT')
 ORDER BY TABLE_NAME,CONSTRAINT_NAME;
SELECT SEQUENCE_NAME FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER='CLT'
 AND SEQUENCE_NAME IN ('SEQ_CLT_ALLOCATION_REQUEST','SEQ_CLT_ALLOCATION_REQUEST_EVENT')
 ORDER BY SEQUENCE_NAME;
-- Intentionally does not select debtor values or sensitive request data.
