SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

CREATE SEQUENCE CLT.SEQ_CLT_REFERENCE_CHANGE_REQUEST START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE CLT.SEQ_CLT_REFERENCE_CHANGE_AUDIT START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE CLT.CLT_REFERENCE_CHANGE_REQUEST (
  CHANGE_ID NUMBER(19,0) DEFAULT CLT.SEQ_CLT_REFERENCE_CHANGE_REQUEST.NEXTVAL NOT NULL,
  TABLE_NAME VARCHAR2(80 CHAR) NOT NULL,
  OPERATION VARCHAR2(10 CHAR) NOT NULL,
  TARGET_ID NUMBER(19,0),
  EXPECTED_VERSION NUMBER(10,0),
  PROPOSED_JSON CLOB NOT NULL,
  REASON VARCHAR2(500 CHAR) NOT NULL,
  STATUS VARCHAR2(20 CHAR) DEFAULT 'PENDING_APPROVAL' NOT NULL,
  MAKER_SUBJECT VARCHAR2(160 CHAR) NOT NULL,
  CHECKER_SUBJECT VARCHAR2(160 CHAR),
  CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  DECIDED_AT TIMESTAMP(6),
  DECISION_REASON VARCHAR2(500 CHAR),
  IDEMPOTENCY_KEY VARCHAR2(100 CHAR) NOT NULL,
  REQUEST_FINGERPRINT CHAR(64 CHAR) NOT NULL,
  CORRELATION_ID VARCHAR2(100 CHAR) NOT NULL,
  RECORD_VERSION NUMBER(10,0) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_CLT_REFERENCE_CHANGE_REQUEST PRIMARY KEY (CHANGE_ID),
  CONSTRAINT UK_CLT_REFERENCE_CHANGE_KEY UNIQUE (MAKER_SUBJECT, IDEMPOTENCY_KEY),
  CONSTRAINT CK_CLT_REF_CHANGE_OP CHECK (OPERATION IN ('CREATE','UPDATE')),
  CONSTRAINT CK_CLT_REF_CHANGE_STATUS CHECK (STATUS IN ('PENDING_APPROVAL','APPLIED','REJECTED')),
  CONSTRAINT CK_CLT_REF_CHANGE_JSON CHECK (PROPOSED_JSON IS JSON STRICT),
  CONSTRAINT CK_CLT_REF_CHANGE_VERSION CHECK (RECORD_VERSION >= 1),
  CONSTRAINT CK_CLT_REF_CHANGE_TARGET CHECK (
       (OPERATION='CREATE' AND EXPECTED_VERSION IS NULL)
       OR (OPERATION='UPDATE' AND TARGET_ID IS NOT NULL AND EXPECTED_VERSION >= 1))
);
CREATE INDEX CLT.IX_CLT_REF_CHANGE_QUEUE ON CLT.CLT_REFERENCE_CHANGE_REQUEST (STATUS, CREATED_AT);

CREATE TABLE CLT.CLT_REFERENCE_CHANGE_AUDIT (
  AUDIT_ID NUMBER(19,0) DEFAULT CLT.SEQ_CLT_REFERENCE_CHANGE_AUDIT.NEXTVAL NOT NULL,
  CHANGE_ID NUMBER(19,0) NOT NULL,
  EVENT_TYPE VARCHAR2(20 CHAR) NOT NULL,
  ACTOR_SUBJECT VARCHAR2(160 CHAR) NOT NULL,
  EVENT_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  BEFORE_JSON CLOB,
  AFTER_JSON CLOB,
  REASON VARCHAR2(500 CHAR) NOT NULL,
  CORRELATION_ID VARCHAR2(100 CHAR) NOT NULL,
  CONSTRAINT PK_CLT_REFERENCE_CHANGE_AUDIT PRIMARY KEY (AUDIT_ID),
  CONSTRAINT FK_CLT_REF_CHANGE_AUDIT_REQ FOREIGN KEY (CHANGE_ID)
     REFERENCES CLT.CLT_REFERENCE_CHANGE_REQUEST (CHANGE_ID),
  CONSTRAINT CK_CLT_REF_AUDIT_EVENT CHECK (EVENT_TYPE IN ('SUBMITTED','APPLIED','REJECTED')),
  CONSTRAINT CK_CLT_REF_AUDIT_BEFORE_JSON CHECK (BEFORE_JSON IS NULL OR BEFORE_JSON IS JSON STRICT),
  CONSTRAINT CK_CLT_REF_AUDIT_AFTER_JSON CHECK (AFTER_JSON IS NULL OR AFTER_JSON IS JSON STRICT)
);
CREATE INDEX CLT.IX_CLT_REF_AUDIT_CHANGE ON CLT.CLT_REFERENCE_CHANGE_AUDIT (CHANGE_ID, EVENT_AT);

