-- R5A read-only Oracle dictionary precheck: execute manually as an authorized SELECT-only DBA.
-- NO DDL, DML, FOR UPDATE, ALTER SESSION or COMMIT.
SELECT TABLE_NAME, COUNT(*) AS COLUMN_COUNT
  FROM ALL_TAB_COLUMNS
 WHERE OWNER='CLT' AND TABLE_NAME IN ('COLLATERAL', 'COLLATERAL_ALLOCATION',
                                      'COLLATERAL_TRANSACTION', 'REF_COLL_TXN_TYPE',
                                      'REF_COLL_TXN_STATUS')
 GROUP BY TABLE_NAME ORDER BY TABLE_NAME;

SELECT TABLE_NAME,COLUMN_NAME,DATA_TYPE,DATA_PRECISION,DATA_SCALE,NULLABLE
  FROM ALL_TAB_COLUMNS
 WHERE OWNER='CLT' AND (
       (TABLE_NAME='COLLATERAL_ALLOCATION' AND COLUMN_NAME IN
         ('COLLATERAL_ALLOCATION_ID','COLLATERAL_ID','MODULE_ID','FILE_NUMBER',
          'ALLOCATE_AMOUNT','USED','CURRENCY_CODE','BRANCH_CODE','RECORD_VERSION','CREATED_AT','UPDATED_AT'))
       OR (TABLE_NAME='COLLATERAL_TRANSACTION' AND COLUMN_NAME IN
         ('COLLATERAL_TRANSACTION_ID','COLLATERAL_ALLOCATION_ID','COLLATERAL_TRANSACTION_NUMBER',
          'TRANSACTION_TYPE_CODE','TRANSACTION_STATUS_CODE','TRANSACTION_DIRECTION_CODE',
          'TRANSACTION_AMOUNT','CURRENCY_CODE','EFFECTIVE_AT','ORIGINAL_TRANSACTION_ID',
          'REVERSAL_REASON_CODE'))
       OR (TABLE_NAME='COLLATERAL' AND COLUMN_NAME IN ('COLLATERAL_ID','BRANCH_CODE')))
 ORDER BY TABLE_NAME,COLUMN_NAME;

SELECT TABLE_NAME,CONSTRAINT_NAME,CONSTRAINT_TYPE,STATUS,VALIDATED
  FROM ALL_CONSTRAINTS
 WHERE OWNER='CLT' AND TABLE_NAME IN ('COLLATERAL_ALLOCATION','COLLATERAL_TRANSACTION')
   AND CONSTRAINT_TYPE IN ('P','R','U','C')
 ORDER BY TABLE_NAME,CONSTRAINT_NAME;
