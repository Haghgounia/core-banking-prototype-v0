SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_PRECISION, DATA_SCALE, NULLABLE
  FROM ALL_TAB_COLUMNS
 WHERE OWNER = 'CLT'
   AND TABLE_NAME IN ('COLLATERAL', 'COLLATERAL_ALLOCATION', 'COLLATERAL_SPONSOR',
                      'COLLATERAL_TYPE', 'COLLATERAL_VALUATION_HISTORY')
   AND COLUMN_NAME IN ('COLLATERAL_ID', 'COLLATERAL_NUMBER', 'BRANCH_CODE',
                       'PARTY_ID', 'MODULE_ID', 'FILE_NUMBER', 'ALLOCATE_AMOUNT',
                       'USED', 'CURRENCY_CODE', 'RECORD_VERSION',
                       'ELIGIBLE_VALUE', 'COLLATERAL_STATUS_CODE')
 ORDER BY TABLE_NAME, COLUMN_ID;
