SET PAGESIZE 100
SELECT TABLE_NAME FROM ALL_TABLES WHERE OWNER='CLT' AND TABLE_NAME IN
 ('COLLATERAL','COLLATERAL_STATUS_HISTORY','CLT_FINAL_RELEASE_PERMIT',
  'CLT_ASSET_IDENTITY','CLT_ASSET_COLLATERAL_LINK','CLT_REGISTRATION_LEDGER',
  'CLT_REGISTRATION_NUMBER_AUTHORITY','CLT_REINTRODUCTION_PERMIT',
  'CLT_INTRODUCTION_REVIEW','CLT_INTRODUCTION_DRAFT',
  'CLT_INTRODUCTION_DRAFT_SERIAL_RANGE','CLT_COLLATERAL_SERIAL_RANGE')
 ORDER BY TABLE_NAME;
SELECT TABLE_NAME,COLUMN_NAME,DATA_TYPE,DATA_PRECISION,DATA_SCALE
  FROM ALL_TAB_COLUMNS
 WHERE OWNER='CLT' AND TABLE_NAME IN ('CLT_REINTRODUCTION_PERMIT',
  'CLT_ASSET_COLLATERAL_LINK','CLT_REGISTRATION_NUMBER_AUTHORITY','CLT_REGISTRATION_LEDGER')
 ORDER BY TABLE_NAME,COLUMN_ID;
SELECT INDEX_NAME,TABLE_NAME,UNIQUENESS,STATUS FROM ALL_INDEXES
 WHERE OWNER='CLT' AND INDEX_NAME IN ('UQ_CLT_ASSET_ONE_CURRENT','UQ_CLT_REINTRO_ONE_POSTED');
SELECT SEQUENCE_NAME FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER='CLT'
 AND SEQUENCE_NAME IN ('SEQ_CLT_ASSET_COLLATERAL_LINK',
  'SEQ_CLT_REGISTRATION_LEDGER','SEQ_CLT_COLLATERAL_SERIAL_RANGE') ORDER BY SEQUENCE_NAME;
-- Snapshot-only: never treat an unapproved STATUS code as a release proof.
SELECT COLLATERAL_STATUS_CODE,STATUS,IS_ACTIVE_STATUS_FLAG,IS_TERMINAL_STATUS_FLAG
 FROM CLT.REF_COLLATERAL_STATUS ORDER BY COLLATERAL_STATUS_CODE;
