SET DEFINE OFF
PROMPT === CLT R3C: existing valuation physical objects ===
SELECT TABLE_NAME, COUNT(*) AS COLUMN_COUNT
FROM ALL_TAB_COLUMNS
WHERE OWNER='CLT' AND TABLE_NAME IN
 ('COLLATERAL', 'COLLATERAL_TYPE', 'COLLATERAL_VALUATION_HISTORY',
  'REF_VALUATION_TYPE', 'REF_VALUATION_METHOD', 'REF_VALUATION_STATUS', 'REF_CURRENCY')
GROUP BY TABLE_NAME ORDER BY TABLE_NAME;
PROMPT === Valuation status technical references; not proof of bank approval ===
SELECT VALUATION_STATUS_CODE, IS_FINAL_FLAG, IS_EDITABLE_FLAG, STATUS
FROM CLT.REF_VALUATION_STATUS ORDER BY DISPLAY_ORDER;
PROMPT === Actual type fields for appraisal policy; compare to V1.42 prototype ===
SELECT COLUMN_NAME, DATA_TYPE, DATA_PRECISION, DATA_SCALE, DATA_LENGTH
FROM ALL_TAB_COLUMNS WHERE OWNER='CLT' AND TABLE_NAME='COLLATERAL_TYPE'
 AND COLUMN_NAME IN ('IS_APPRAISABLE_FLAG','REVALUATION_INTERVAL_VALUE','REVALUATION_INTERVAL_UNIT')
ORDER BY COLUMN_NAME;
PROMPT === Read-only population counts (no personal data returned) ===
SELECT 'COLLATERAL_VALUATION_HISTORY' AS SOURCE_TABLE, COUNT(*) AS RECORD_COUNT
FROM CLT.COLLATERAL_VALUATION_HISTORY;
SELECT 'COLLATERAL_CURRENT_POINTERS' AS INDICATOR, COUNT(*) AS RECORD_COUNT
FROM CLT.COLLATERAL WHERE CURRENT_VALUATION_HISTORY_ID IS NOT NULL;
PROMPT CLT_R3C_READ_ONLY_PRECHECK_COMPLETE; NO DDL, DML OR COMMIT.
