SELECT TABLE_NAME, COUNT(*) COLUMN_COUNT
  FROM ALL_TAB_COLUMNS
 WHERE OWNER = 'CLT'
   AND TABLE_NAME IN ('COLLATERAL', 'COLLATERAL_SPONSOR', 'COLLATERAL_TYPE',
                      'COLLATERAL_SPONSOR_REQUEST', 'COLLATERAL_SPONSOR_REQUEST_EVENT')
 GROUP BY TABLE_NAME ORDER BY TABLE_NAME;

SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_PRECISION, DATA_SCALE,
       CHAR_LENGTH, NULLABLE
  FROM ALL_TAB_COLUMNS
 WHERE OWNER = 'CLT'
   AND TABLE_NAME IN ('COLLATERAL_SPONSOR', 'COLLATERAL_TYPE')
 ORDER BY TABLE_NAME, COLUMN_ID;

SELECT TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE, STATUS, VALIDATED
  FROM ALL_CONSTRAINTS
 WHERE OWNER = 'CLT' AND TABLE_NAME IN ('COLLATERAL_SPONSOR',
                   'COLLATERAL_SPONSOR_REQUEST', 'COLLATERAL_SPONSOR_REQUEST_EVENT')
 ORDER BY TABLE_NAME, CONSTRAINT_NAME;

