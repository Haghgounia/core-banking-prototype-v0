  RELEASE_ID NUMBER(1) CONSTRAINT PK_CLT_R3_VAL_REL PRIMARY KEY,
  RELEASE_STATUS VARCHAR2(20 CHAR) NOT NULL,
  POLICY_REVISION VARCHAR2(120 CHAR) NOT NULL,
  FINAL_STATUS_DECISION_REF VARCHAR2(120 CHAR) NOT NULL,
  APPRAISABILITY_DECISION_REF VARCHAR2(120 CHAR) NOT NULL,
  INTERVAL_DECISION_REF VARCHAR2(120 CHAR) NOT NULL,
  BUSINESS_DATE_DECISION_REF VARCHAR2(120 CHAR) NOT NULL,
  VALUER_AUTHORITY_DECISION_REF VARCHAR2(120 CHAR) NOT NULL,
  VALUE_DECISION_REF VARCHAR2(120 CHAR) NOT NULL,
  SUPERSESSION_DECISION_REF VARCHAR2(120 CHAR) NOT NULL,
  APPROVED_BY VARCHAR2(120 CHAR) NOT NULL,
  EFFECTIVE_FROM TIMESTAMP(6) NOT NULL,
  EFFECTIVE_TO TIMESTAMP(6),
  CONSTRAINT CK_CLT_R3_VAL_REL_ONE CHECK (RELEASE_ID=1),
  CONSTRAINT CK_CLT_R3_VAL_REL_STATUS CHECK (RELEASE_STATUS IN ('APPROVED','REVOKED','EXPIRED')),
  CONSTRAINT CK_CLT_R3_VAL_REL_DATES CHECK (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO>EFFECTIVE_FROM)
);
CREATE TABLE CLT.R3_VAL_POSTING_TYPE_RULE (
  RULE_ID NUMBER(19) CONSTRAINT PK_CLT_R3_VAL_TYPE_RULE PRIMARY KEY,
  COLLATERAL_TYPE_ID NUMBER(19) NOT NULL,
  APPRAISABLE_FLAG VARCHAR2(3 CHAR) NOT NULL,
  INTERVAL_VALUE NUMBER(6) NOT NULL,
  INTERVAL_UNIT VARCHAR2(5 CHAR) NOT NULL,
  BOUNDARY_MODE VARCHAR2(30 CHAR) NOT NULL,
  ANCHOR_CODE VARCHAR2(20 CHAR) NOT NULL,
  POLICY_REVISION VARCHAR2(120 CHAR) NOT NULL,
  RULE_STATUS VARCHAR2(20 CHAR) NOT NULL,
  APPROVED_BY VARCHAR2(120 CHAR) NOT NULL,
  EFFECTIVE_FROM TIMESTAMP(6) NOT NULL,
  EFFECTIVE_TO TIMESTAMP(6),
  CONSTRAINT UQ_CLT_R3_VAL_TYPE_REV UNIQUE (COLLATERAL_TYPE_ID,POLICY_REVISION),
  CONSTRAINT FK_CLT_R3_VAL_TYPE FOREIGN KEY(COLLATERAL_TYPE_ID)
    REFERENCES CLT.COLLATERAL_TYPE(COLLATERAL_TYPE_ID),
  CONSTRAINT CK_CLT_R3_VAL_TYPE_APP CHECK (APPRAISABLE_FLAG IN ('YES','NO')),
  CONSTRAINT CK_CLT_R3_VAL_TYPE_PERIOD CHECK (INTERVAL_VALUE BETWEEN 1 AND 36500
    AND INTERVAL_UNIT IN ('DAY','MONTH','YEAR')
    AND BOUNDARY_MODE='EXCLUSIVE_NEXT_START'
    AND ANCHOR_CODE IN ('VALUATION_DATE','EFFECTIVE_FROM')
    AND (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO>EFFECTIVE_FROM)),
  CONSTRAINT CK_CLT_R3_VAL_TYPE_STATUS CHECK (RULE_STATUS IN ('APPROVED','REVOKED','EXPIRED'))
);
CREATE TABLE CLT.R3_VAL_POSTING_VALUER_RULE (
  RULE_ID NUMBER(19) CONSTRAINT PK_CLT_R3_VAL_VALUER_RULE PRIMARY KEY,
  VALUER_PARTY_ID NUMBER(19) NOT NULL,
  COLLATERAL_TYPE_ID NUMBER(19) NOT NULL,
  VALUATION_METHOD_CODE VARCHAR2(30 CHAR) NOT NULL,
  POLICY_REVISION VARCHAR2(120 CHAR) NOT NULL,
  RULE_STATUS VARCHAR2(20 CHAR) NOT NULL,
  APPROVED_BY VARCHAR2(120 CHAR) NOT NULL,
  EFFECTIVE_FROM TIMESTAMP(6) NOT NULL,
  EFFECTIVE_TO TIMESTAMP(6),
  CONSTRAINT UQ_CLT_R3_VAL_VALUER_REV UNIQUE
    (VALUER_PARTY_ID,COLLATERAL_TYPE_ID,VALUATION_METHOD_CODE,POLICY_REVISION),
  CONSTRAINT FK_CLT_R3_VAL_VALUER_TYPE FOREIGN KEY(COLLATERAL_TYPE_ID)
    REFERENCES CLT.COLLATERAL_TYPE(COLLATERAL_TYPE_ID),
  CONSTRAINT FK_CLT_R3_VAL_VALUER_METHOD FOREIGN KEY(VALUATION_METHOD_CODE)
    REFERENCES CLT.REF_VALUATION_METHOD(VALUATION_METHOD_CODE),
  CONSTRAINT CK_CLT_R3_VAL_VALUER_STATUS CHECK(RULE_STATUS IN ('APPROVED','REVOKED','EXPIRED'))
);
CREATE SEQUENCE CLT.SEQ_CLT_R3_VAL_POST_LEDGER START WITH 1 INCREMENT BY 1 CACHE 20 NOCYCLE;
CREATE TABLE CLT.R3_VAL_POSTING_LEDGER (
  LEDGER_ID NUMBER(19) CONSTRAINT PK_CLT_R3_VAL_LEDGER PRIMARY KEY,
  REQUEST_ID NUMBER(19) NOT NULL,
  COLLATERAL_ID NUMBER(19) NOT NULL,
  BRANCH_CODE VARCHAR2(30 CHAR) NOT NULL,
  IDEMPOTENCY_KEY VARCHAR2(100 CHAR) NOT NULL,
  REQUEST_HASH VARCHAR2(64 CHAR) NOT NULL,
  EXPECTED_VERSION NUMBER(10) NOT NULL,
  JUSTIFICATION VARCHAR2(500 CHAR) NOT NULL,
  COMMIT_STATUS VARCHAR2(20 CHAR) NOT NULL,
  DOMAIN_RECORD_ID NUMBER(19),
  PREVIOUS_VALUATION_ID NUMBER(19),
  TYPE_RULE_ID NUMBER(19) NOT NULL,
  VALUER_RULE_ID NUMBER(19) NOT NULL,
  POSTED_BY VARCHAR2(100 CHAR) NOT NULL,
  POLICY_REVISION VARCHAR2(120 CHAR) NOT NULL,
  RECORDED_EFFECTIVE_TO DATE NOT NULL,
  POSTED_AT TIMESTAMP(6),
  CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_CLT_R3_VAL_POST_REQ UNIQUE(REQUEST_ID),
  CONSTRAINT UQ_CLT_R3_VAL_POST_IDEMP UNIQUE(BRANCH_CODE,IDEMPOTENCY_KEY),
  CONSTRAINT FK_CLT_R3_VAL_POST_REQ FOREIGN KEY(REQUEST_ID)
    REFERENCES CLT.COLLATERAL_VALUATION_REQUEST(VALUATION_REQUEST_ID),
  CONSTRAINT FK_CLT_R3_VAL_POST_DOMAIN FOREIGN KEY(DOMAIN_RECORD_ID)
    REFERENCES CLT.COLLATERAL_VALUATION_HISTORY(COLLATERAL_VALUATION_HISTORY_ID),
  CONSTRAINT FK_CLT_R3_VAL_POST_TYPE FOREIGN KEY(TYPE_RULE_ID)
    REFERENCES CLT.R3_VAL_POSTING_TYPE_RULE(RULE_ID),
  CONSTRAINT FK_CLT_R3_VAL_POST_VALUER FOREIGN KEY(VALUER_RULE_ID)
    REFERENCES CLT.R3_VAL_POSTING_VALUER_RULE(RULE_ID),
  CONSTRAINT CK_CLT_R3_VAL_POST_STATUS CHECK(COMMIT_STATUS IN('PREPARED','COMMITTED')),
  CONSTRAINT CK_CLT_R3_VAL_POST_COMPLETE CHECK (
    (COMMIT_STATUS='PREPARED' AND DOMAIN_RECORD_ID IS NULL AND POSTED_AT IS NULL)
    OR (COMMIT_STATUS='COMMITTED' AND DOMAIN_RECORD_ID IS NOT NULL AND POSTED_AT IS NOT NULL))
);
