-- R3 Valuation operational posting: DBA read-only dictionary/quality evidence.
-- No DML, DDL, GRANT or COMMIT. Use on the bank Oracle before an approved migration.
SET DEFINE OFF
PROMPT === R3 valuation canonical history and current pointer: physical objects ===
SELECT TABLE_NAME,COUNT(*) AS COLUMN_COUNT FROM ALL_TAB_COLUMNS
 WHERE OWNER='CLT' AND TABLE_NAME IN
 ('COLLATERAL','COLLATERAL_VALUATION_HISTORY','REF_VALUATION_STATUS',
  'R3_VAL_POSTING_RELEASE','R3_VAL_POSTING_TYPE_RULE',
  'R3_VAL_POSTING_VALUER_RULE','R3_VAL_POSTING_LEDGER')
 GROUP BY TABLE_NAME ORDER BY TABLE_NAME;
PROMPT === Canonical constraints required for concurrency and reference integrity ===
SELECT TABLE_NAME,CONSTRAINT_NAME,CONSTRAINT_TYPE,STATUS,VALIDATED
 FROM ALL_CONSTRAINTS WHERE OWNER='CLT' AND CONSTRAINT_NAME IN
 ('UQ_COL_VAL_HIST_SEQUENCE','UQ_COL_VAL_HIST_SUPERSEDES','FK_COLL_CURRENT_VALUATION',
  'UQ_CLT_R3_VAL_TYPE_REV','UQ_CLT_R3_VAL_VALUER_REV',
  'UQ_CLT_R3_VAL_POST_REQ','UQ_CLT_R3_VAL_POST_IDEMP')
 ORDER BY TABLE_NAME,CONSTRAINT_NAME;
PROMPT === Identity of canonical valuation history primary key ===
SELECT TABLE_NAME,COLUMN_NAME,GENERATION_TYPE
 FROM ALL_TAB_IDENTITY_COLS WHERE OWNER='CLT'
 AND TABLE_NAME='COLLATERAL_VALUATION_HISTORY';
PROMPT === FINAL and SUPERSEDED references: metadata, not bank policy approval ===
SELECT VALUATION_STATUS_CODE,IS_FINAL_FLAG,STATUS FROM CLT.REF_VALUATION_STATUS
 WHERE VALUATION_STATUS_CODE IN ('FINAL','SUPERSEDED');
PROMPT === Anomaly counters; no business/personal identifiers exported ===
SELECT COUNT(*) AS ORPHAN_FINAL_WHEN_PARENT_HAS_NO_POINTER
 FROM CLT.COLLATERAL_VALUATION_HISTORY v
 JOIN CLT.COLLATERAL c ON c.COLLATERAL_ID=v.COLLATERAL_ID
 WHERE c.CURRENT_VALUATION_HISTORY_ID IS NULL AND v.VALUATION_STATUS_CODE='FINAL';
SELECT COUNT(*) AS INVALID_CURRENT_POINTER
 FROM CLT.COLLATERAL c
 LEFT JOIN CLT.COLLATERAL_VALUATION_HISTORY v
   ON v.COLLATERAL_ID=c.COLLATERAL_ID
  AND v.COLLATERAL_VALUATION_HISTORY_ID=c.CURRENT_VALUATION_HISTORY_ID
 WHERE c.CURRENT_VALUATION_HISTORY_ID IS NOT NULL
   AND (v.COLLATERAL_VALUATION_HISTORY_ID IS NULL OR v.VALUATION_STATUS_CODE<>'FINAL');
PROMPT R3_VALUATION_DICTIONARY_DONE_READ_ONLY;
