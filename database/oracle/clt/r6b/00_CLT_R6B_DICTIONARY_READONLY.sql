-- CLT R6B: OPTIONAL dictionary-only evidence for authorized DBA review.
-- STRICTLY SELECT ONLY. No BEGIN/EXEC/COMMIT/DDL/DML.
-- It does NOT enable report reads, account privileges or financial operations.

SELECT t.TABLE_NAME
  FROM ALL_TABLES t
 WHERE t.OWNER='CLT'
   AND t.TABLE_NAME IN ('COLLATERAL','COLLATERAL_TYPE','COLLATERAL_GROUP',
                        'COLLATERAL_ALLOCATION','COLLATERAL_STATUS_HISTORY')
 ORDER BY t.TABLE_NAME;

SELECT c.TABLE_NAME,c.COLUMN_NAME,c.DATA_TYPE,c.DATA_PRECISION,c.DATA_SCALE
  FROM ALL_TAB_COLUMNS c
 WHERE c.OWNER='CLT'
   AND ((c.TABLE_NAME='COLLATERAL' AND c.COLUMN_NAME IN ('COLLATERAL_ID','BRANCH_CODE','COLLATERAL_STATUS_CODE'))
    OR (c.TABLE_NAME='COLLATERAL_ALLOCATION' AND c.COLUMN_NAME IN ('COLLATERAL_ID','USED','CURRENCY_CODE','ALLOCATE_AMOUNT'))
    OR (c.TABLE_NAME='COLLATERAL_STATUS_HISTORY' AND c.COLUMN_NAME IN ('COLLATERAL_ID','CHANGED_AT','TO_STATUS_CODE')))
 ORDER BY c.TABLE_NAME,c.COLUMN_NAME;

SELECT c.TABLE_NAME,c.CONSTRAINT_NAME,c.CONSTRAINT_TYPE,c.STATUS,c.VALIDATED
  FROM ALL_CONSTRAINTS c
 WHERE c.OWNER='CLT'
   AND c.TABLE_NAME IN ('COLLATERAL','COLLATERAL_ALLOCATION','COLLATERAL_STATUS_HISTORY')
   AND c.CONSTRAINT_TYPE IN ('P','R','U','C')
 ORDER BY c.TABLE_NAME,c.CONSTRAINT_TYPE,c.CONSTRAINT_NAME;
