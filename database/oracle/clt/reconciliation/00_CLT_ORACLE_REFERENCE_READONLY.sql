-- CLT-ORACLE-REFERENCE-RECONCILIATION / P1 / READ ONLY.
-- DBA may execute independently. Never interpret privileges filtering ALL_* as absence.
-- No DDL, DML, commit, or activation of Collateral financial posting.
-- Record results together with environment/DB, connection scope and timestamp.
SELECT SYSTIMESTAMP AS OBSERVED_AT,
       SYS_CONTEXT('USERENV','DB_NAME') AS DATABASE_NAME,
       SYS_CONTEXT('USERENV','CURRENT_SCHEMA') AS CURRENT_SCHEMA_NAME
  FROM DUAL;

SELECT TABLE_NAME FROM ALL_TABLES WHERE OWNER='CLT'
   AND TABLE_NAME IN ('COLLATERAL','COLLATERAL_TRANSACTION','COLLATERAL_GROUP','COLLATERAL_TYPE',
      'COLLATERAL_TYPE_ATTRIBUTE','REF_COLLATERAL_ATTRIBUTE_DATA_TYPE','REF_COLL_TXN_STATUS',
      'REF_CURRENCY','REF_VALUATION_TYPE','REF_COLL_REVERSAL_REASON',
      'COLLATERAL_ATTRIBUTE_DEFINITION','REF_SOURCE_SYSTEM','REF_COLLATERAL_STATUS',
      'COLLATERAL_INSURANCE_TYPE','REF_CHANNEL','INSURANCE_COMPANY','REF_VALUATION_METHOD',
      'REF_VALUATION_STATUS','REF_COLL_TXN_TYPE','CLT_COLLATERAL_SERIAL_RANGE',
      'CLT_ASSET_IDENTITY','CLT_ASSET_COLLATERAL_LINK')
 ORDER BY TABLE_NAME;

SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_PRECISION, DATA_SCALE, NULLABLE
  FROM ALL_TAB_COLUMNS
 WHERE OWNER='CLT' AND (
       (TABLE_NAME='COLLATERAL' AND COLUMN_NAME IN ('COLLATERAL_NUMBER','BRANCH_CODE','PARTY_ID','COLLATERAL_TYPE_ID','RECORD_VERSION'))
       OR (TABLE_NAME='COLLATERAL_TRANSACTION' AND COLUMN_NAME='TRANSACTION_STATUS_CODE'))
 ORDER BY TABLE_NAME, COLUMN_NAME;

SELECT DATA_DEFAULT FROM ALL_TAB_COLUMNS
 WHERE OWNER='CLT' AND TABLE_NAME='COLLATERAL_TRANSACTION'
   AND COLUMN_NAME='TRANSACTION_STATUS_CODE';

SELECT c.CONSTRAINT_NAME, c.CONSTRAINT_TYPE, c.STATUS, cc.COLUMN_NAME
  FROM ALL_CONSTRAINTS c JOIN ALL_CONS_COLUMNS cc
    ON cc.OWNER=c.OWNER AND cc.CONSTRAINT_NAME=c.CONSTRAINT_NAME
 WHERE c.OWNER='CLT' AND c.TABLE_NAME='COLLATERAL'
   AND c.CONSTRAINT_TYPE IN ('U','P') AND cc.COLUMN_NAME='COLLATERAL_NUMBER'
 ORDER BY c.CONSTRAINT_NAME;

SELECT SEQUENCE_NAME FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER='CLT'
 ORDER BY SEQUENCE_NAME;

-- Below queries can fail if CLT reference SELECT privileges are missing: that means UNKNOWN,
-- not an observed zero. Unlike dictionary queries these run on actual CLT data.
SELECT TRANSACTION_STATUS_CODE, STATUS, COUNT(*) AS ROW_COUNT
  FROM CLT.REF_COLL_TXN_STATUS
 WHERE TRANSACTION_STATUS_CODE IN ('PENDING','PENDING_APPROVAL')
 GROUP BY TRANSACTION_STATUS_CODE, STATUS
 ORDER BY TRANSACTION_STATUS_CODE, STATUS;

SELECT 'COLLATERAL_GROUP' AS TABLE_NAME, COUNT(*) AS TOTAL_ROWS,
       COALESCE(SUM(CASE WHEN STATUS='ACTIVE' THEN 1 ELSE 0 END),0) AS ACTIVE_ROWS
  FROM CLT.COLLATERAL_GROUP
UNION ALL SELECT 'COLLATERAL_TYPE',COUNT(*),COALESCE(SUM(CASE WHEN STATUS='ACTIVE' THEN 1 ELSE 0 END),0)
  FROM CLT.COLLATERAL_TYPE
UNION ALL SELECT 'REF_COLL_TXN_STATUS',COUNT(*),COALESCE(SUM(CASE WHEN STATUS='ACTIVE' THEN 1 ELSE 0 END),0)
  FROM CLT.REF_COLL_TXN_STATUS;

