CREATE TABLE CLT.R3_INS_POSTING_RULE (
 RULE_ID NUMBER(19,0) CONSTRAINT PK_CLT_R3_INS_RULE PRIMARY KEY,
 COLLATERAL_TYPE_ID NUMBER(19,0) NOT NULL,
 INSURANCE_TYPE_ID NUMBER(19,0) NOT NULL,
 CURRENCY_CODE CHAR(3 CHAR) NOT NULL,
 MIN_COVERAGE_AMOUNT NUMBER(20,4) NOT NULL,
 POLICY_REVISION VARCHAR2(120 CHAR) NOT NULL,
 RULE_STATUS VARCHAR2(20 CHAR) NOT NULL,
 APPROVED_BY VARCHAR2(120 CHAR) NOT NULL,
 EFFECTIVE_FROM TIMESTAMP(6) NOT NULL,
 EFFECTIVE_TO TIMESTAMP(6),
 CONSTRAINT UQ_CLT_R3_INS_RULE_REV UNIQUE
  (COLLATERAL_TYPE_ID,INSURANCE_TYPE_ID,CURRENCY_CODE,POLICY_REVISION),
 CONSTRAINT FK_CLT_R3_INS_RULE_COLL_TYPE FOREIGN KEY (COLLATERAL_TYPE_ID)
  REFERENCES CLT.COLLATERAL_TYPE (COLLATERAL_TYPE_ID),
 CONSTRAINT FK_CLT_R3_INS_RULE_INS_TYPE FOREIGN KEY (INSURANCE_TYPE_ID)
  REFERENCES CLT.COLLATERAL_INSURANCE_TYPE (COLLATERAL_INSURANCE_TYPE_ID),
 CONSTRAINT CK_CLT_R3_INS_RULE_AMOUNT CHECK (MIN_COVERAGE_AMOUNT>0),
 CONSTRAINT CK_CLT_R3_INS_RULE_STATUS CHECK (RULE_STATUS IN ('APPROVED','REVOKED','EXPIRED')),
 CONSTRAINT CK_CLT_R3_INS_RULE_DATES CHECK (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO>EFFECTIVE_FROM)
);
