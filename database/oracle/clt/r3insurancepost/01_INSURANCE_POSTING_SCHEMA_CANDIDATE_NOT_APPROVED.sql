 LEDGER_ID NUMBER(19,0) CONSTRAINT PK_CLT_R3_INS_POST_LEDGER PRIMARY KEY,
 REQUEST_ID NUMBER(19,0) NOT NULL,
 COLLATERAL_ID NUMBER(19,0) NOT NULL,
 BRANCH_CODE VARCHAR2(30 CHAR) NOT NULL,
 IDEMPOTENCY_KEY VARCHAR2(100 CHAR) NOT NULL,
 REQUEST_HASH VARCHAR2(64 CHAR) NOT NULL,
 EXPECTED_VERSION NUMBER(10,0) NOT NULL,
 JUSTIFICATION VARCHAR2(500 CHAR) NOT NULL,
 COMMIT_STATUS VARCHAR2(20 CHAR) NOT NULL,
 DOMAIN_RECORD_ID NUMBER(19,0),
 PREVIOUS_INSURANCE_ID NUMBER(19,0),
 COVERAGE_RULE_ID NUMBER(19,0) NOT NULL,
 POSTED_BY VARCHAR2(100 CHAR) NOT NULL,
 POLICY_REVISION VARCHAR2(120 CHAR) NOT NULL,
 POSTED_AT TIMESTAMP(6),
 CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT UQ_CLT_R3_INS_POST_REQ UNIQUE (REQUEST_ID),
 CONSTRAINT UQ_CLT_R3_INS_POST_IDEMP UNIQUE (BRANCH_CODE,IDEMPOTENCY_KEY),
 CONSTRAINT FK_CLT_R3_INS_POST_RULE FOREIGN KEY (COVERAGE_RULE_ID)
  REFERENCES CLT.R3_INS_POSTING_RULE (RULE_ID),
 CONSTRAINT FK_CLT_R3_INS_POST_REQ FOREIGN KEY (REQUEST_ID)
  REFERENCES CLT.COLLATERAL_INSURANCE_REQUEST (INSURANCE_REQUEST_ID),
 CONSTRAINT FK_CLT_R3_INS_POST_DOMAIN FOREIGN KEY (DOMAIN_RECORD_ID)
  REFERENCES CLT.COLLATERAL_INSURANCE (COLLATERAL_INSURANCE_ID),
 CONSTRAINT CK_CLT_R3_INS_POST_STATUS CHECK (COMMIT_STATUS IN ('PREPARED','COMMITTED')),
 CONSTRAINT CK_CLT_R3_INS_POST_COMPLETE CHECK (
  (COMMIT_STATUS='PREPARED' AND DOMAIN_RECORD_ID IS NULL AND POSTED_AT IS NULL) OR
  (COMMIT_STATUS='COMMITTED' AND DOMAIN_RECORD_ID IS NOT NULL AND POSTED_AT IS NOT NULL))
