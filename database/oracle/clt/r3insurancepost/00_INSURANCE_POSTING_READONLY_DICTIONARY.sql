-- CLT R3 Insurance create/renew posting: READ ONLY dictionary and data precheck.
-- Neither this inspection nor source installation authorizes a new policy or cancellation.
SELECT TABLE_NAME FROM ALL_TABLES WHERE OWNER='CLT' AND TABLE_NAME IN
 ('COLLATERAL_INSURANCE_REQUEST','COLLATERAL_INSURANCE_REQUEST_EVENT',
  'COLLATERAL_INSURANCE','R3_INS_POSTING_RELEASE','R3_INS_POSTING_RULE','R3_INS_POSTING_LEDGER');
SELECT TABLE_NAME,COLUMN_NAME,DATA_TYPE,NULLABLE FROM ALL_TAB_COLUMNS WHERE OWNER='CLT'
 AND TABLE_NAME IN ('COLLATERAL_INSURANCE','R3_INS_POSTING_RELEASE',
  'R3_INS_POSTING_RULE','R3_INS_POSTING_LEDGER') ORDER BY TABLE_NAME,COLUMN_ID;
SELECT TABLE_NAME,CONSTRAINT_NAME,CONSTRAINT_TYPE,STATUS,VALIDATED FROM ALL_CONSTRAINTS
 WHERE OWNER='CLT' AND TABLE_NAME IN ('COLLATERAL_INSURANCE',
  'R3_INS_POSTING_RELEASE','R3_INS_POSTING_RULE','R3_INS_POSTING_LEDGER')
 ORDER BY TABLE_NAME,CONSTRAINT_NAME;
SELECT SEQUENCE_NAME FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER='CLT'
 AND SEQUENCE_NAME='SEQ_CLT_R3_INS_POST_LEDGER';
-- Existing policy number duplicates (must reconcile before approving uniqueness):
SELECT INSURANCE_COMPANY_ID,INSURANCE_NUMBER,COUNT(*) DUPLICATES
 FROM CLT.COLLATERAL_INSURANCE GROUP BY INSURANCE_COMPANY_ID,INSURANCE_NUMBER
 HAVING COUNT(*)>1;
-- Multiple renewals pointing to the same predecessor (D-05):
SELECT PREVIOUS_INSURANCE_ID,COUNT(*) DUPLICATES FROM CLT.COLLATERAL_INSURANCE
 WHERE PREVIOUS_INSURANCE_ID IS NOT NULL GROUP BY PREVIOUS_INSURANCE_ID HAVING COUNT(*)>1;
