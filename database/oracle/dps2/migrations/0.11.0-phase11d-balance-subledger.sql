-- Core Banking Prototype 0.11.0
-- DPS2 Phase 11D - Balance + Subledger
-- Scope: four deposits / DPS2 only.
-- Reconciles Package 17 as the monetary balance source of truth.

SET DEFINE OFF;
SET SERVEROUTPUT ON;
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

