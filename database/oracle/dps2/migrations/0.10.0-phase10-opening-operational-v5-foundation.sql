    v_count NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v_count FROM ALL_SEQUENCES
     WHERE SEQUENCE_OWNER='DPS2' AND SEQUENCE_NAME=UPPER(p_sequence);
    RETURN v_count > 0;
