      RAISE_APPLICATION_ERROR(-21000, 'Required table DPS2.'||p_table||' is missing. Apply 0.9.3 baseline first.');
    END IF;
  END;

  PROCEDURE add_col(p_table VARCHAR2, p_column VARCHAR2, p_ddl VARCHAR2) IS
  BEGIN
    IF column_exists(p_table,p_column) THEN
      DBMS_OUTPUT.PUT_LINE('OK  : '||p_table||'.'||p_column);
    ELSE
      EXECUTE IMMEDIATE 'ALTER TABLE DPS2.'||p_table||' ADD ('||p_column||' '||p_ddl||')';
      DBMS_OUTPUT.PUT_LINE('ADD : '||p_table||'.'||p_column);
    END IF;
  END;

  PROCEDURE add_constraint(p_name VARCHAR2, p_ddl VARCHAR2) IS
  BEGIN
    IF constraint_exists(p_name) THEN
      DBMS_OUTPUT.PUT_LINE('OK  : constraint '||p_name);
    ELSE
      BEGIN
        EXECUTE IMMEDIATE p_ddl;
        DBMS_OUTPUT.PUT_LINE('ADD : constraint '||p_name);
      EXCEPTION
        WHEN OTHERS THEN
          IF SQLCODE = -2275 THEN
            DBMS_OUTPUT.PUT_LINE('OK  : equivalent referential constraint already exists for '||p_name||' (preserved under existing name).');
          ELSE
            RAISE;
          END IF;
      END;
    END IF;
  END;

  PROCEDURE add_index(p_name VARCHAR2, p_ddl VARCHAR2) IS
  BEGIN
    IF index_exists(p_name) THEN
      DBMS_OUTPUT.PUT_LINE('OK  : index '||p_name);
    ELSE
      EXECUTE IMMEDIATE p_ddl;
      DBMS_OUTPUT.PUT_LINE('ADD : index '||p_name);
    END IF;
