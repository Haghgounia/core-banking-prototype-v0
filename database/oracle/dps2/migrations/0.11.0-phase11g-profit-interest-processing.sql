-- column set. Because CREATE TABLE above is idempotent (-955 ignored), reconcile the
-- full Repository contract here. Missing required columns are auto-added only when the
-- legacy table is empty; if rows exist, stop rather than fabricate financial data.
DECLARE
  v_rows NUMBER;
  v_col  NUMBER;

  PROCEDURE ensure_col(p_table VARCHAR2, p_name VARCHAR2, p_ddl VARCHAR2, p_required NUMBER DEFAULT 1) IS
  BEGIN
    SELECT COUNT(*) INTO v_col
      FROM ALL_TAB_COLUMNS
     WHERE OWNER='DPS2'
       AND TABLE_NAME=UPPER(p_table)
       AND COLUMN_NAME=UPPER(p_name);

    IF v_col=0 THEN
      EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM DPS2.'||p_table INTO v_rows;
      IF p_required=1 AND v_rows>0 THEN
        RAISE_APPLICATION_ERROR(-21181,
          'Legacy DPS2.'||UPPER(p_table)||' contains '||v_rows||
          ' row(s) but required column '||UPPER(p_name)||
          ' is missing. Manual legacy-data mapping is required; no financial value was fabricated.');
      END IF;
      EXECUTE IMMEDIATE 'ALTER TABLE DPS2.'||p_table||' ADD ('||p_name||' '||p_ddl||')';
      DBMS_OUTPUT.PUT_LINE('RECONCILE | DPS2.'||UPPER(p_table)||'.'||UPPER(p_name)||' added');
    ELSE
      DBMS_OUTPUT.PUT_LINE('RECONCILE | DPS2.'||UPPER(p_table)||'.'||UPPER(p_name)||' already exists');
    END IF;
  END;
