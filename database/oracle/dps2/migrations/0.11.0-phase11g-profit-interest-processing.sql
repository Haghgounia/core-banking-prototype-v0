-- Reconcile legacy-only accrual period column from pre-11G prototypes.
-- The canonical 11G accrual contract is date-range based (ACCRUAL_FROM_DATE / ACCRUAL_TO_DATE)
-- and DepositProfitRepository does not write PROFIT_PERIOD_ID. Never invent a period identifier.
-- If a legacy table is still empty, relax the obsolete NOT NULL requirement; if rows exist, stop.
DECLARE
  v_exists   NUMBER:=0;
  v_nullable VARCHAR2(1);
  v_rows     NUMBER:=0;
BEGIN
  SELECT COUNT(*) INTO v_exists
    FROM ALL_TAB_COLUMNS
   WHERE OWNER='DPS2'
     AND TABLE_NAME='DEPOSIT_PROFIT_ACCRUAL'
     AND COLUMN_NAME='PROFIT_PERIOD_ID';

  IF v_exists=1 THEN
    SELECT NULLABLE INTO v_nullable
      FROM ALL_TAB_COLUMNS
     WHERE OWNER='DPS2'
       AND TABLE_NAME='DEPOSIT_PROFIT_ACCRUAL'
       AND COLUMN_NAME='PROFIT_PERIOD_ID';

    IF v_nullable='N' THEN
      SELECT COUNT(*) INTO v_rows FROM DPS2.DEPOSIT_PROFIT_ACCRUAL;
      IF v_rows>0 THEN
        RAISE_APPLICATION_ERROR(-21182,
          'Legacy DPS2.DEPOSIT_PROFIT_ACCRUAL contains '||v_rows||
          ' row(s) and obsolete required column PROFIT_PERIOD_ID. Manual legacy-period mapping is required; no period identifier was fabricated.');
      END IF;
      EXECUTE IMMEDIATE 'ALTER TABLE DPS2.DEPOSIT_PROFIT_ACCRUAL MODIFY (PROFIT_PERIOD_ID NULL)';
      DBMS_OUTPUT.PUT_LINE('RECONCILE | DPS2.DEPOSIT_PROFIT_ACCRUAL.PROFIT_PERIOD_ID legacy NOT NULL relaxed (empty table)');
    ELSE
      DBMS_OUTPUT.PUT_LINE('RECONCILE | DPS2.DEPOSIT_PROFIT_ACCRUAL.PROFIT_PERIOD_ID legacy column already nullable');
    END IF;
  ELSE
    DBMS_OUTPUT.PUT_LINE('RECONCILE | DPS2.DEPOSIT_PROFIT_ACCRUAL.PROFIT_PERIOD_ID legacy column not present');
  END IF;
END;
