  PROFIT_CONTRACT_ID,ACCOUNT_ID,OPENING_REQUEST_ID,PRODUCT_VERSION_ID,PRICING_RULE_ID,PRICING_COMPONENT_ID,RATE_TIER_ID,PROFIT_PAYMENT_RULE_ID,
  ANNUAL_RATE,CALCULATION_METHOD_CODE,DAY_COUNT_BASIS_CODE,ACCRUAL_FREQUENCY_CODE,PAYMENT_FREQUENCY_CODE,PAYMENT_DAY_RULE_CODE,
  FIRST_PAYMENT_RULE_CODE,HOLIDAY_ADJUSTMENT_CODE,PAYMENT_DESTINATION_CODE,DESTINATION_ACCOUNT_REFERENCE,EFFECTIVE_FROM,EFFECTIVE_TO,
  ACCRUED_AMOUNT,PAID_AMOUNT,LAST_ACCRUAL_DATE,STATUS_CODE,SOURCE_OPENING_PROFIT_INSTRUCTION_ID,CREATED_AT,CREATED_BY,RECORD_VERSION)
SELECT DPS2.SEQ_DEP_PROFIT_CONTRACT.NEXTVAL,A.ACCOUNT_ID,A.OPENING_REQUEST_ID,A.CURRENT_PRODUCT_VERSION_ID,
       P.PRICING_RULE_ID,P.PRICING_COMPONENT_ID,P.RATE_TIER_ID,P.PROFIT_PAYMENT_RULE_ID,P.RATE_VALUE,
       NVL(P.CALCULATION_METHOD_CODE,'PERCENTAGE'),NVL(P.DAY_COUNT_BASIS_CODE,'ACT_365'),NVL(P.ACCRUAL_FREQUENCY_CODE,'DAILY'),
       NVL(P.PAYMENT_FREQUENCY_CODE,'MATURITY'),NVL(P.PAYMENT_DAY_RULE_CODE,'MATURITY_DATE'),NVL(P.FIRST_PAYMENT_RULE_CODE,'MATURITY_ONLY'),
       NVL(P.HOLIDAY_ADJUSTMENT_CODE,'NEXT_BUSINESS_DAY'),NVL(P.PAYMENT_DESTINATION_CODE,'SAME_DEPOSIT'),P.DESTINATION_ACCOUNT_REFERENCE,
       NVL(OT.START_DATE,NVL(A.OPENED_ON,TRUNC(SYSDATE))),OT.MATURITY_DATE,0,0,NVL(OT.START_DATE,NVL(A.OPENED_ON,TRUNC(SYSDATE))),
       'ACTIVE',P.OPENING_PROFIT_INSTRUCTION_ID,SYSTIMESTAMP,'PHASE11G_MIGRATION',1
  FROM DPS2.DEPOSIT_ACCOUNT A
  JOIN DPS2.DEPOSIT_OPENING_PROFIT_INSTRUCTION P ON P.OPENING_REQUEST_ID=A.OPENING_REQUEST_ID
  LEFT JOIN DPS2.DEPOSIT_OPENING_TERM OT ON OT.OPENING_REQUEST_ID=A.OPENING_REQUEST_ID
 WHERE P.RATE_VALUE IS NOT NULL AND P.RATE_VALUE>=0
   AND NOT EXISTS(SELECT 1 FROM DPS2.DEPOSIT_PROFIT_CONTRACT C WHERE C.ACCOUNT_ID=A.ACCOUNT_ID AND C.STATUS_CODE='ACTIVE');

UPDATE DPS2.DEPOSIT_TERM_CONTRACT T
   SET T.CONTRACT_RATE=(SELECT C.ANNUAL_RATE FROM DPS2.DEPOSIT_PROFIT_CONTRACT C WHERE C.ACCOUNT_ID=T.ACCOUNT_ID AND C.STATUS_CODE='ACTIVE'),
       T.UPDATED_AT=SYSTIMESTAMP,T.UPDATED_BY='PHASE11G_MIGRATION',T.RECORD_VERSION=T.RECORD_VERSION+1
 WHERE T.STATUS_CODE='ACTIVE' AND T.CONTRACT_RATE IS NULL
   AND EXISTS(SELECT 1 FROM DPS2.DEPOSIT_PROFIT_CONTRACT C WHERE C.ACCOUNT_ID=T.ACCOUNT_ID AND C.STATUS_CODE='ACTIVE');

COMMIT;
