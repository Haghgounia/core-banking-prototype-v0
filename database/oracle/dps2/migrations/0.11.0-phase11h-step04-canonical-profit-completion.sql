  FUNCTION seq_exists(p_name VARCHAR2) RETURN BOOLEAN IS n NUMBER; BEGIN SELECT COUNT(*) INTO n FROM all_sequences WHERE sequence_owner='DPS2' AND sequence_name=UPPER(p_name); RETURN n>0; END;
  PROCEDURE ddl(p_sql CLOB) IS BEGIN EXECUTE IMMEDIATE p_sql; END;
  PROCEDURE ensure_seq(p_name VARCHAR2,p_table VARCHAR2,p_pk VARCHAR2) IS
    v_start NUMBER:=1;
  BEGIN
    IF NOT seq_exists(p_name) THEN
      IF table_exists(p_table) THEN
        EXECUTE IMMEDIATE 'SELECT NVL(MAX('||p_pk||'),0)+1 FROM DPS2.'||p_table INTO v_start;
      END IF;
      ddl('CREATE SEQUENCE DPS2.'||p_name||' START WITH '||TO_CHAR(v_start)||' INCREMENT BY 1 NOCACHE');
      DBMS_OUTPUT.PUT_LINE('CREATE | DPS2.'||p_name||' START='||v_start);
