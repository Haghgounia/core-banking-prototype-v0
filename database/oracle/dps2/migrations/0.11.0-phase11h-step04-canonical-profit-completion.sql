PROMPT [11H] Recomputing Profit Period totals ...
MERGE INTO DPS2.DEPOSIT_PROFIT_PERIOD P
USING (
  SELECT P0.PROFIT_PERIOD_ID,
         NVL((SELECT SUM(A.ACCRUED_AMOUNT) FROM DPS2.DEPOSIT_PROFIT_ACCRUAL A WHERE A.PROFIT_PERIOD_ID=P0.PROFIT_PERIOD_ID),0) AS ACCRUED,
         NVL((SELECT SUM(CASE J.ADJUSTMENT_TYPE_CODE WHEN 'INCREASE' THEN J.ADJUSTMENT_AMOUNT ELSE -J.ADJUSTMENT_AMOUNT END) FROM DPS2.DEPOSIT_PROFIT_ADJUSTMENT J WHERE J.PROFIT_PERIOD_ID=P0.PROFIT_PERIOD_ID AND J.ADJUSTMENT_STATUS_CODE='POSTED'),0) AS ADJUSTED,
         NVL((SELECT SUM(X.PAYMENT_AMOUNT) FROM DPS2.DEPOSIT_PROFIT_PAYMENT X WHERE X.PROFIT_PERIOD_ID=P0.PROFIT_PERIOD_ID AND X.PAYMENT_STATUS_CODE='PAID'),0) AS PAID
    FROM DPS2.DEPOSIT_PROFIT_PERIOD P0
) S ON (S.PROFIT_PERIOD_ID=P.PROFIT_PERIOD_ID)
WHEN MATCHED THEN UPDATE SET
  P.TOTAL_ACCRUED_AMOUNT=S.ACCRUED,
  P.TOTAL_ADJUSTMENT_AMOUNT=S.ADJUSTED,
  P.PAYABLE_AMOUNT=GREATEST(S.ACCRUED+S.ADJUSTED,0),
  P.PAID_AMOUNT=S.PAID,
  P.PERIOD_STATUS_CODE=CASE WHEN S.ACCRUED+S.ADJUSTED>0 AND S.PAID>=S.ACCRUED+S.ADJUSTED THEN 'PAID' WHEN S.ACCRUED>0 THEN 'CALCULATED' ELSE 'OPEN' END,
  P.UPDATED_AT=SYSTIMESTAMP,P.UPDATED_BY='phase11h.migration',P.RECORD_VERSION=P.RECORD_VERSION+1;

COMMIT;
