-- R2-B2 contract verification against installed R2-B1. NO DDL / NO DML.
-- SQL Developer: connect as SYSTEM, press F5.
SET SERVEROUTPUT ON SIZE UNLIMITED
PROMPT ==== CAL2 R2-B2 READ-ONLY INSTALL CONTRACT ====
DECLARE
    v_tables NUMBER;
    v_sequences NUMBER;
    v_indexes NUMBER;
    v_pk NUMBER;
    v_fk NUMBER;
    v_bad_fk NUMBER;
    v_columns NUMBER;
    v_types NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_tables FROM ALL_TABLES WHERE OWNER='CAL2' AND TABLE_NAME IN (
      'USER_CALENDAR_ENTRIES','USER_CALENDAR_RECURRENCE_RULES','USER_CALENDAR_OCCURRENCES',
      'USER_CALENDAR_REMINDER_RULES','USER_CALENDAR_ALERTS','USER_CALENDAR_REQUEST_KEYS');
    SELECT COUNT(*) INTO v_sequences FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER='CAL2' AND SEQUENCE_NAME IN (
      'SEQ_CAL2_USER_CALENDAR_ENTRIES','SEQ_CAL2_UCR','SEQ_CAL2_UCO','SEQ_CAL2_URR','SEQ_CAL2_UCA','SEQ_CAL2_URK');
    SELECT COUNT(*) INTO v_indexes FROM ALL_INDEXES WHERE OWNER='CAL2' AND INDEX_NAME IN (
      'IX_CAL2_UCE_OWNER_DAY','UX_CAL2_UCR_ACTIVE','IX_CAL2_UCO_ENTRY_DAY',
      'IX_CAL2_UCA_DUE','IX_CAL2_UCA_INBOX') AND STATUS='VALID';
    SELECT COUNT(*) INTO v_pk FROM ALL_CONSTRAINTS WHERE OWNER='CAL2' AND CONSTRAINT_TYPE='P'
      AND TABLE_NAME IN ('USER_CALENDAR_ENTRIES','USER_CALENDAR_RECURRENCE_RULES',
      'USER_CALENDAR_OCCURRENCES','USER_CALENDAR_REMINDER_RULES','USER_CALENDAR_ALERTS',
      'USER_CALENDAR_REQUEST_KEYS') AND STATUS='ENABLED';
    SELECT COUNT(*) INTO v_fk FROM ALL_CONSTRAINTS WHERE OWNER='CAL2' AND CONSTRAINT_TYPE='R'
      AND TABLE_NAME IN ('USER_CALENDAR_ENTRIES','USER_CALENDAR_RECURRENCE_RULES',
      'USER_CALENDAR_OCCURRENCES','USER_CALENDAR_REMINDER_RULES','USER_CALENDAR_ALERTS',
      'USER_CALENDAR_REQUEST_KEYS') AND STATUS='ENABLED';
    SELECT COUNT(*) INTO v_bad_fk FROM ALL_CONSTRAINTS WHERE OWNER='CAL2' AND CONSTRAINT_TYPE='R'
      AND TABLE_NAME IN ('USER_CALENDAR_ENTRIES','USER_CALENDAR_RECURRENCE_RULES',
      'USER_CALENDAR_OCCURRENCES','USER_CALENDAR_REMINDER_RULES','USER_CALENDAR_ALERTS',
      'USER_CALENDAR_REQUEST_KEYS') AND (STATUS<>'ENABLED' OR VALIDATED<>'VALIDATED');
    SELECT COUNT(*) INTO v_columns FROM ALL_TAB_COLUMNS WHERE OWNER='CAL2' AND (
      (TABLE_NAME='USER_CALENDAR_ENTRIES' AND COLUMN_NAME='USER_CALENDAR_ENTRY_ID') OR
      (TABLE_NAME='USER_CALENDAR_ENTRIES' AND COLUMN_NAME='OWNER_ISSUER') OR
      (TABLE_NAME='USER_CALENDAR_ENTRIES' AND COLUMN_NAME='OWNER_SUBJECT_ID') OR
      (TABLE_NAME='USER_CALENDAR_ENTRIES' AND COLUMN_NAME='DESCRIPTION') OR
      (TABLE_NAME='USER_CALENDAR_RECURRENCE_RULES' AND COLUMN_NAME='USER_CALENDAR_RECURRENCE_RULE_ID') OR
      (TABLE_NAME='USER_CALENDAR_OCCURRENCES' AND COLUMN_NAME='RECURRENCE_RULE_ID') OR
      (TABLE_NAME='USER_CALENDAR_OCCURRENCES' AND COLUMN_NAME='USER_CALENDAR_OCCURRENCE_ID') OR
      (TABLE_NAME='USER_CALENDAR_REMINDER_RULES' AND COLUMN_NAME='USER_CALENDAR_REMINDER_RULE_ID') OR
      (TABLE_NAME='USER_CALENDAR_ALERTS' AND COLUMN_NAME='USER_CALENDAR_ALERT_ID') OR
      (TABLE_NAME='USER_CALENDAR_ALERTS' AND COLUMN_NAME='PLANNED_AT_UTC') OR
      (TABLE_NAME='USER_CALENDAR_ALERTS' AND COLUMN_NAME='NEXT_ELIGIBLE_AT_UTC') OR
      (TABLE_NAME='USER_CALENDAR_REQUEST_KEYS' AND COLUMN_NAME='REQUEST_SHA256'));
    SELECT COUNT(*) INTO v_types FROM ALL_TAB_COLUMNS WHERE OWNER='CAL2' AND (
      (TABLE_NAME='USER_CALENDAR_ENTRIES' AND COLUMN_NAME='USER_CALENDAR_ENTRY_ID' AND DATA_TYPE='NUMBER' AND DATA_PRECISION=12) OR
      (TABLE_NAME='USER_CALENDAR_ENTRIES' AND COLUMN_NAME='START_DAY_ID' AND DATA_TYPE='NUMBER' AND DATA_PRECISION=19) OR
      (TABLE_NAME='USER_CALENDAR_ENTRIES' AND COLUMN_NAME='DESCRIPTION' AND DATA_TYPE='CLOB') OR
      (TABLE_NAME='USER_CALENDAR_RECURRENCE_RULES' AND COLUMN_NAME='USER_CALENDAR_RECURRENCE_RULE_ID' AND DATA_PRECISION=12) OR
      (TABLE_NAME='USER_CALENDAR_RECURRENCE_RULES' AND COLUMN_NAME='CALENDAR_VARIANT_ID' AND DATA_PRECISION=19) OR
      (TABLE_NAME='USER_CALENDAR_OCCURRENCES' AND COLUMN_NAME='USER_CALENDAR_OCCURRENCE_ID' AND DATA_PRECISION=12) OR
      (TABLE_NAME='USER_CALENDAR_REMINDER_RULES' AND COLUMN_NAME='USER_CALENDAR_REMINDER_RULE_ID' AND DATA_PRECISION=12) OR
      (TABLE_NAME='USER_CALENDAR_ALERTS' AND COLUMN_NAME='USER_CALENDAR_ALERT_ID' AND DATA_PRECISION=12) OR
      (TABLE_NAME='USER_CALENDAR_REQUEST_KEYS' AND COLUMN_NAME='USER_CALENDAR_REQUEST_KEY_ID' AND DATA_PRECISION=12));
    DBMS_OUTPUT.PUT_LINE('TABLES='||v_tables||'/6; SEQUENCES='||v_sequences||'/6; INDEXES='||v_indexes||'/5');
    DBMS_OUTPUT.PUT_LINE('ENABLED_PKS='||v_pk||'/6; ENABLED_FKS='||v_fk||'/13; BAD_FKS='||v_bad_fk);
    DBMS_OUTPUT.PUT_LINE('KEY_COLUMNS='||v_columns||'/12; EXACT_TYPES='||v_types||'/9');
    IF v_tables=6 AND v_sequences=6 AND v_indexes=5 AND v_pk=6 AND v_fk=13
       AND v_bad_fk=0 AND v_columns=12 AND v_types=9 THEN
      DBMS_OUTPUT.PUT_LINE('CAL2_R2B2_READONLY_CONTRACT_PASS');
    ELSE
      DBMS_OUTPUT.PUT_LINE('CAL2_R2B2_READONLY_CONTRACT_FAIL');
      RAISE_APPLICATION_ERROR(-20821,'R2B2 schema contract mismatch; no data changed');
    END IF;
END;
