COMMENT ON COLUMN CAL2.EVENT_RECURRENCE_RULE.DAY_RESOLUTION_POLICY IS
  'سیاست حل روز نامعتبر: EXACT=فقط همان روز؛ LAST_DAY_IF_INVALID=اگر آن روز در ماه/سال وجود نداشت آخرین روز همان ماه';

UPDATE CAL2.EVENT_RECURRENCE_RULE R
   SET R.DAY_RESOLUTION_POLICY = 'LAST_DAY_IF_INVALID'
 WHERE NVL(R.DAY_RESOLUTION_POLICY, 'EXACT') <> 'LAST_DAY_IF_INVALID'
   AND R.RULE_TYPE = 'ANNUAL_FIXED_DATE'
   AND R.MONTH_NO = 2
   AND R.DAY_NO = 30
   AND EXISTS (
       SELECT 1
         FROM CAL2.EVENT E
        WHERE E.EVENT_ID = R.EVENT_ID
          AND E.EVENT_CODE = 'IR_IMAM_REZA_MARTYRDOM'
   );

