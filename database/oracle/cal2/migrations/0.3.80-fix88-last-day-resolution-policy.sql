-- Corrected rerunnable migration: avoids ORA-01442 when the column is already NOT NULL.
SET SERVEROUTPUT ON
SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
  v_count    NUMBER;
  v_nullable VARCHAR2(1);
BEGIN
  SELECT COUNT(*) INTO v_count
    FROM ALL_TAB_COLUMNS
   WHERE OWNER='CAL2'
     AND TABLE_NAME='EVENT_RECURRENCE_RULE'
     AND COLUMN_NAME='DAY_RESOLUTION_POLICY';

  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'~ALTER TABLE CAL2.EVENT_RECURRENCE_RULE
      ADD (DAY_RESOLUTION_POLICY VARCHAR2(40 CHAR) DEFAULT 'EXACT' NOT NULL)~';
    DBMS_OUTPUT.PUT_LINE('Added CAL2.EVENT_RECURRENCE_RULE.DAY_RESOLUTION_POLICY');
  ELSE
    DBMS_OUTPUT.PUT_LINE('DAY_RESOLUTION_POLICY already exists');

    EXECUTE IMMEDIATE q'~UPDATE CAL2.EVENT_RECURRENCE_RULE
                           SET DAY_RESOLUTION_POLICY = 'EXACT'
                         WHERE DAY_RESOLUTION_POLICY IS NULL~';

    SELECT NULLABLE INTO v_nullable
      FROM ALL_TAB_COLUMNS
     WHERE OWNER='CAL2'
       AND TABLE_NAME='EVENT_RECURRENCE_RULE'
       AND COLUMN_NAME='DAY_RESOLUTION_POLICY';

    IF v_nullable = 'Y' THEN
      EXECUTE IMMEDIATE q'~ALTER TABLE CAL2.EVENT_RECURRENCE_RULE
                             MODIFY (DAY_RESOLUTION_POLICY DEFAULT 'EXACT' NOT NULL)~';
      DBMS_OUTPUT.PUT_LINE('DAY_RESOLUTION_POLICY default/NOT NULL normalized');
    ELSE
      -- Column is already NOT NULL; only normalize the default.
      EXECUTE IMMEDIATE q'~ALTER TABLE CAL2.EVENT_RECURRENCE_RULE
                             MODIFY (DAY_RESOLUTION_POLICY DEFAULT 'EXACT')~';
      DBMS_OUTPUT.PUT_LINE('DAY_RESOLUTION_POLICY already NOT NULL; default normalized');
    END IF;
  END IF;
END;
/

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count
    FROM ALL_CONSTRAINTS
   WHERE OWNER='CAL2'
     AND CONSTRAINT_NAME='CK_CAL2_ER_DAY_POLICY';

  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'~ALTER TABLE CAL2.EVENT_RECURRENCE_RULE
      ADD CONSTRAINT CK_CAL2_ER_DAY_POLICY
      CHECK (DAY_RESOLUTION_POLICY IN ('EXACT','LAST_DAY_IF_INVALID'))~';
    DBMS_OUTPUT.PUT_LINE('Added CK_CAL2_ER_DAY_POLICY');
  ELSE
    DBMS_OUTPUT.PUT_LINE('CK_CAL2_ER_DAY_POLICY already exists');
  END IF;
END;
