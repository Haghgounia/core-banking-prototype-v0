-- FIX56 / 0.3.45: recurring-event rules for CAL2.
-- Run as CAL2 (or a privileged user) after the FIX54 base schema exists.
-- Safe to rerun: object/column/constraint/index existence is checked before creation.
SET SERVEROUTPUT ON
SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM ALL_TABLES WHERE OWNER = 'CAL2' AND TABLE_NAME = 'EVENT_RECURRENCE_RULE';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'~
      CREATE TABLE CAL2.EVENT_RECURRENCE_RULE (
        EVENT_RULE_ID        NUMBER(19) NOT NULL,
        EVENT_ID             NUMBER(19) NOT NULL,
        RULE_TYPE            VARCHAR2(40 CHAR) NOT NULL,
        CALENDAR_VARIANT_ID  NUMBER(19) NOT NULL,
        YEAR_NO              NUMBER(6),
        MONTH_NO             NUMBER(2) NOT NULL,
        DAY_NO               NUMBER(2) NOT NULL,
        START_YEAR_NO        NUMBER(6),
        END_YEAR_NO          NUMBER(6),
        SOURCE_ID            NUMBER(19),
        DESCRIPTION          VARCHAR2(1000 CHAR),
        ACTIVE_FLAG          CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
        CONSTRAINT PK_CAL2_EVENT_RULE PRIMARY KEY (EVENT_RULE_ID),
        CONSTRAINT FK_CAL2_ER_EVENT FOREIGN KEY (EVENT_ID) REFERENCES CAL2.EVENT (EVENT_ID),
        CONSTRAINT FK_CAL2_ER_VARIANT FOREIGN KEY (CALENDAR_VARIANT_ID) REFERENCES CAL2.CALENDAR_VARIANT (CALENDAR_VARIANT_ID),
        CONSTRAINT FK_CAL2_ER_SOURCE FOREIGN KEY (SOURCE_ID) REFERENCES CAL2.SOURCE_AUTHORITY (SOURCE_ID),
        CONSTRAINT CK_CAL2_ER_TYPE CHECK (RULE_TYPE IN ('ANNUAL_FIXED_DATE','ONE_TIME_DATE')),
        CONSTRAINT CK_CAL2_ER_MONTH CHECK (MONTH_NO BETWEEN 1 AND 13),
        CONSTRAINT CK_CAL2_ER_DAY CHECK (DAY_NO BETWEEN 1 AND 31),
        CONSTRAINT CK_CAL2_ER_ACTIVE CHECK (ACTIVE_FLAG IN ('Y','N')),
        CONSTRAINT CK_CAL2_ER_RANGE CHECK (END_YEAR_NO IS NULL OR START_YEAR_NO IS NULL OR END_YEAR_NO >= START_YEAR_NO),
        CONSTRAINT CK_CAL2_ER_SHAPE CHECK (
          (RULE_TYPE = 'ANNUAL_FIXED_DATE' AND YEAR_NO IS NULL)
          OR
          (RULE_TYPE = 'ONE_TIME_DATE' AND YEAR_NO IS NOT NULL AND START_YEAR_NO IS NULL AND END_YEAR_NO IS NULL)
        )
      )
    ~';
    DBMS_OUTPUT.PUT_LINE('Created CAL2.EVENT_RECURRENCE_RULE');
  ELSE
    DBMS_OUTPUT.PUT_LINE('CAL2.EVENT_RECURRENCE_RULE already exists');
  END IF;
END;
/

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM ALL_TAB_COLUMNS
   WHERE OWNER='CAL2' AND TABLE_NAME='EVENT_OCCURRENCE' AND COLUMN_NAME='EVENT_RULE_ID';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE CAL2.EVENT_OCCURRENCE ADD (EVENT_RULE_ID NUMBER(19))';
    DBMS_OUTPUT.PUT_LINE('Added EVENT_OCCURRENCE.EVENT_RULE_ID');
  END IF;

  SELECT COUNT(*) INTO v_count FROM ALL_TAB_COLUMNS
   WHERE OWNER='CAL2' AND TABLE_NAME='EVENT_OCCURRENCE' AND COLUMN_NAME='OCCURRENCE_SOURCE';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'~ALTER TABLE CAL2.EVENT_OCCURRENCE ADD (OCCURRENCE_SOURCE VARCHAR2(30 CHAR) DEFAULT 'MANUAL' NOT NULL)~';
    DBMS_OUTPUT.PUT_LINE('Added EVENT_OCCURRENCE.OCCURRENCE_SOURCE');
  END IF;
END;
/

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM ALL_CONSTRAINTS WHERE OWNER='CAL2' AND CONSTRAINT_NAME='FK_CAL2_EO_RULE';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE CAL2.EVENT_OCCURRENCE ADD CONSTRAINT FK_CAL2_EO_RULE FOREIGN KEY (EVENT_RULE_ID) REFERENCES CAL2.EVENT_RECURRENCE_RULE (EVENT_RULE_ID)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM ALL_CONSTRAINTS WHERE OWNER='CAL2' AND CONSTRAINT_NAME='CK_CAL2_EO_SOURCE';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'~ALTER TABLE CAL2.EVENT_OCCURRENCE ADD CONSTRAINT CK_CAL2_EO_SOURCE CHECK (OCCURRENCE_SOURCE IN ('GENERATED','MANUAL','OFFICIAL'))~';
  END IF;
END;
/

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM ALL_INDEXES WHERE OWNER='CAL2' AND INDEX_NAME='IX_CAL2_ER_EVENT';
  IF v_count = 0 THEN EXECUTE IMMEDIATE 'CREATE INDEX CAL2.IX_CAL2_ER_EVENT ON CAL2.EVENT_RECURRENCE_RULE (EVENT_ID)'; END IF;

  SELECT COUNT(*) INTO v_count FROM ALL_INDEXES WHERE OWNER='CAL2' AND INDEX_NAME='IX_CAL2_ER_VARIANT';
  IF v_count = 0 THEN EXECUTE IMMEDIATE 'CREATE INDEX CAL2.IX_CAL2_ER_VARIANT ON CAL2.EVENT_RECURRENCE_RULE (CALENDAR_VARIANT_ID)'; END IF;

  SELECT COUNT(*) INTO v_count FROM ALL_INDEXES WHERE OWNER='CAL2' AND INDEX_NAME='IX_CAL2_EO_RULE';
  IF v_count = 0 THEN EXECUTE IMMEDIATE 'CREATE INDEX CAL2.IX_CAL2_EO_RULE ON CAL2.EVENT_OCCURRENCE (EVENT_RULE_ID)'; END IF;
END;
/

