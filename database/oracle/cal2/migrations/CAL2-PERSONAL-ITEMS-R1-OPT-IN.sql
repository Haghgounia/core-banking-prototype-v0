-- CAL2 personal notes/reminders. Designed for SQL Developer F5 (Run Script).
-- IMPORTANT: Review PREVIEW output before changing NO to YES.
-- The table is independent of CAL2.EVENT and CAL2.EVENT_OCCURRENCE.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET DEFINE ON
DEFINE APPLY_CHANGES = NO
PROMPT === CAL2 personal notes/reminders migration: PREVIEW by default ===

DECLARE
  v_mode VARCHAR2(3) := UPPER(TRIM('&&APPLY_CHANGES'));
  v_tables NUMBER;
  v_columns NUMBER;
  v_day NUMBER;
BEGIN
  IF v_mode NOT IN ('YES', 'NO') THEN
    RAISE_APPLICATION_ERROR(-20701, 'APPLY_CHANGES must be YES or NO');
  END IF;

  SELECT COUNT(*) INTO v_day FROM ALL_TABLES WHERE OWNER='CAL2' AND TABLE_NAME='CANONICAL_DAY';
  IF v_day <> 1 THEN
    RAISE_APPLICATION_ERROR(-20702, 'Missing CAL2.CANONICAL_DAY: no changes made');
  END IF;

  SELECT COUNT(*) INTO v_tables FROM ALL_OBJECTS
   WHERE OWNER='CAL2' AND OBJECT_NAME='USER_CALENDAR_ITEMS' AND OBJECT_TYPE IN ('TABLE','VIEW','SYNONYM','MATERIALIZED VIEW');

  IF v_tables = 1 THEN
    SELECT COUNT(*) INTO v_day FROM ALL_TABLES WHERE OWNER='CAL2' AND TABLE_NAME='USER_CALENDAR_ITEMS';
    SELECT COUNT(*) INTO v_columns FROM ALL_TAB_COLUMNS
     WHERE OWNER='CAL2' AND TABLE_NAME='USER_CALENDAR_ITEMS'
       AND COLUMN_NAME IN ('ITEM_ID','ACTOR_KEY','DAY_ID','ITEM_TYPE','TITLE','DESCRIPTION','REMINDER_TIME',
                           'ADVANCE_DAYS','REPEAT_POLICY','STATUS','FIRST_ADVANCE_ACK',
                           'LAST_ALERT_ACK_DATE','CREATED_AT','UPDATED_AT');
    IF v_day <> 1 OR v_columns <> 14 THEN
      RAISE_APPLICATION_ERROR(-20703, 'USER_CALENDAR_ITEMS exists with incompatible columns; no changes made');
    END IF;
    DBMS_OUTPUT.PUT_LINE('ALREADY_PRESENT: CAL2.USER_CALENDAR_ITEMS (14 required columns)');
  ELSIF v_tables = 0 THEN
    DBMS_OUTPUT.PUT_LINE('PENDING: CREATE TABLE CAL2.USER_CALENDAR_ITEMS; FK -> CAL2.CANONICAL_DAY');
  ELSE
    RAISE_APPLICATION_ERROR(-20704, 'Unsafe existing object with name USER_CALENDAR_ITEMS');
  END IF;

  IF v_mode = 'NO' THEN
    DBMS_OUTPUT.PUT_LINE('PREVIEW COMPLETE. No writes.');
    RETURN;
  END IF;

  IF v_tables = 0 THEN
    EXECUTE IMMEDIATE q'~
      CREATE TABLE CAL2.USER_CALENDAR_ITEMS (
        ITEM_ID             VARCHAR2(36 CHAR) NOT NULL,
        ACTOR_KEY           VARCHAR2(80 CHAR) NOT NULL,
        DAY_ID              NUMBER(19,0) NOT NULL,
        ITEM_TYPE           VARCHAR2(12 CHAR) NOT NULL,
        TITLE               VARCHAR2(200 CHAR) NOT NULL,
        DESCRIPTION         VARCHAR2(2000 CHAR),
        REMINDER_TIME       VARCHAR2(5 CHAR),
        ADVANCE_DAYS        NUMBER(2,0) DEFAULT 3 NOT NULL,
        REPEAT_POLICY       VARCHAR2(10 CHAR) DEFAULT 'DAILY' NOT NULL,
        STATUS              VARCHAR2(12 CHAR) DEFAULT 'OPEN' NOT NULL,
        FIRST_ADVANCE_ACK   CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
        LAST_ALERT_ACK_DATE DATE,
        CREATED_AT          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
        UPDATED_AT          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT PK_CAL2_UCI PRIMARY KEY (ITEM_ID),
        CONSTRAINT FK_CAL2_UCI_DAY FOREIGN KEY (DAY_ID) REFERENCES CAL2.CANONICAL_DAY (DAY_ID),
        CONSTRAINT CK_CAL2_UCI_TYPE CHECK (ITEM_TYPE IN ('NOTE','REMINDER')),
        CONSTRAINT CK_CAL2_UCI_STATUS CHECK (STATUS IN ('OPEN','DONE')),
        CONSTRAINT CK_CAL2_UCI_ADV CHECK (ADVANCE_DAYS BETWEEN 0 AND 30),
        CONSTRAINT CK_CAL2_UCI_REPEAT CHECK (REPEAT_POLICY IN ('DAILY','ONCE')),
        CONSTRAINT CK_CAL2_UCI_ACK CHECK (FIRST_ADVANCE_ACK IN ('Y','N')),
        CONSTRAINT CK_CAL2_UCI_REM_TIME CHECK (
             (ITEM_TYPE = 'NOTE' AND REMINDER_TIME IS NULL)
             OR (ITEM_TYPE = 'REMINDER' AND REMINDER_TIME IS NOT NULL AND
                 REGEXP_LIKE(REMINDER_TIME, '^([01][0-9]|2[0-3]):[0-5][0-9]$')))
      ) TABLESPACE CAL2_DATA
    ~';
    DBMS_OUTPUT.PUT_LINE('CREATED TABLE: CAL2.USER_CALENDAR_ITEMS');
    EXECUTE IMMEDIATE 'CREATE INDEX CAL2.IX_CAL2_UCI_ACTOR_DAY ON CAL2.USER_CALENDAR_ITEMS (ACTOR_KEY, DAY_ID) TABLESPACE CAL2_DATA';
    EXECUTE IMMEDIATE 'CREATE INDEX CAL2.IX_CAL2_UCI_ALERT ON CAL2.USER_CALENDAR_ITEMS (ACTOR_KEY, ITEM_TYPE, STATUS) TABLESPACE CAL2_DATA';
    DBMS_OUTPUT.PUT_LINE('CREATED INDEXES: 2');
  END IF;

  DBMS_OUTPUT.PUT_LINE('CAL2_PERSONAL_R1_APPLY_COMPLETE. Oracle DDL is auto-committed.');
END;
/

