-- Run once BEFORE the matching backend is started. Re-runnable. No existing rows deleted.
-- The rule engine supports nth ISO weekday of month (ordinal 1..5, or -1 = last).
SET SERVEROUTPUT ON
SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
PROMPT === CAL2 B1: variable rule engine schema ===

DECLARE
  v_count NUMBER;
  v_nullable CHAR(1);
  PROCEDURE ensure_column(p_column VARCHAR2, p_ddl VARCHAR2) IS
    n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS
     WHERE OWNER='CAL2' AND TABLE_NAME='EVENT_RECURRENCE_RULE' AND COLUMN_NAME=p_column;
    IF n=0 THEN
      EXECUTE IMMEDIATE p_ddl;
      DBMS_OUTPUT.PUT_LINE('ADDED COLUMN '||p_column);
    ELSE
      DBMS_OUTPUT.PUT_LINE('COLUMN EXISTS '||p_column);
    END IF;
  END;
  PROCEDURE ensure_check(p_name VARCHAR2, p_expression VARCHAR2) IS
    n NUMBER;
    has_new NUMBER;
  BEGIN
    SELECT COUNT(*), NVL(MAX(CASE WHEN INSTR(SEARCH_CONDITION_VC,'ANNUAL_NTH_WEEKDAY')>0 THEN 1 ELSE 0 END),0)
      INTO n,has_new
      FROM ALL_CONSTRAINTS
     WHERE OWNER='CAL2' AND TABLE_NAME='EVENT_RECURRENCE_RULE' AND CONSTRAINT_NAME=p_name;
    IF n=0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE CAL2.EVENT_RECURRENCE_RULE ADD CONSTRAINT '||p_name||' CHECK ('||p_expression||')';
      DBMS_OUTPUT.PUT_LINE('CREATED CONSTRAINT '||p_name);
    ELSIF has_new=0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE CAL2.EVENT_RECURRENCE_RULE DROP CONSTRAINT '||p_name;
      EXECUTE IMMEDIATE 'ALTER TABLE CAL2.EVENT_RECURRENCE_RULE ADD CONSTRAINT '||p_name||' CHECK ('||p_expression||')';
      DBMS_OUTPUT.PUT_LINE('UPGRADED CONSTRAINT '||p_name);
    ELSE
      DBMS_OUTPUT.PUT_LINE('CONSTRAINT CURRENT '||p_name);
    END IF;
  END;
BEGIN
  ensure_column('WEEKDAY_NO','ALTER TABLE CAL2.EVENT_RECURRENCE_RULE ADD (WEEKDAY_NO NUMBER(1))');
  ensure_column('WEEKDAY_ORDINAL','ALTER TABLE CAL2.EVENT_RECURRENCE_RULE ADD (WEEKDAY_ORDINAL NUMBER(2))');

  SELECT NULLABLE INTO v_nullable FROM ALL_TAB_COLUMNS
   WHERE OWNER='CAL2' AND TABLE_NAME='EVENT_RECURRENCE_RULE' AND COLUMN_NAME='DAY_NO';
  IF v_nullable='N' THEN
    EXECUTE IMMEDIATE 'ALTER TABLE CAL2.EVENT_RECURRENCE_RULE MODIFY (DAY_NO NULL)';
    DBMS_OUTPUT.PUT_LINE('MADE DAY_NO NULLABLE FOR WEEKDAY-RELATIVE RULES');
  END IF;

  ensure_check('CK_CAL2_ER_TYPE',q'!RULE_TYPE IN ('ANNUAL_FIXED_DATE','ONE_TIME_DATE','ANNUAL_NTH_WEEKDAY')!');
  ensure_check('CK_CAL2_ER_SHAPE',q'!(
    RULE_TYPE='ANNUAL_FIXED_DATE' AND YEAR_NO IS NULL AND DAY_NO IS NOT NULL AND WEEKDAY_NO IS NULL AND WEEKDAY_ORDINAL IS NULL
  ) OR (
    RULE_TYPE='ONE_TIME_DATE' AND YEAR_NO IS NOT NULL AND DAY_NO IS NOT NULL AND START_YEAR_NO IS NULL AND END_YEAR_NO IS NULL AND WEEKDAY_NO IS NULL AND WEEKDAY_ORDINAL IS NULL
  ) OR (
    RULE_TYPE='ANNUAL_NTH_WEEKDAY' AND YEAR_NO IS NULL AND DAY_NO IS NULL AND WEEKDAY_NO IS NOT NULL AND WEEKDAY_ORDINAL IS NOT NULL AND DAY_RESOLUTION_POLICY='EXACT'
  )!');

  SELECT COUNT(*) INTO v_count FROM ALL_CONSTRAINTS
   WHERE OWNER='CAL2' AND TABLE_NAME='EVENT_RECURRENCE_RULE' AND CONSTRAINT_NAME='CK_CAL2_ER_WEEKDAY';
  IF v_count=0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE CAL2.EVENT_RECURRENCE_RULE ADD CONSTRAINT CK_CAL2_ER_WEEKDAY CHECK (WEEKDAY_NO BETWEEN 1 AND 7)';
  END IF;
  SELECT COUNT(*) INTO v_count FROM ALL_CONSTRAINTS
   WHERE OWNER='CAL2' AND TABLE_NAME='EVENT_RECURRENCE_RULE' AND CONSTRAINT_NAME='CK_CAL2_ER_ORDINAL';
  IF v_count=0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE CAL2.EVENT_RECURRENCE_RULE ADD CONSTRAINT CK_CAL2_ER_ORDINAL CHECK (WEEKDAY_ORDINAL IN (-1,1,2,3,4,5))';
  END IF;
END;
