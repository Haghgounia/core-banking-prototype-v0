COMMENT ON COLUMN CAL2.EVENT_RECURRENCE_RULE.WEEKDAY_NO IS 'ISO weekday number: Monday=1 .. Sunday=7';
COMMENT ON COLUMN CAL2.EVENT_RECURRENCE_RULE.WEEKDAY_ORDINAL IS 'Ordinal weekday of month: 1..5, or -1 for last';
