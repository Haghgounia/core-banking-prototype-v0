-- CAL2 personal calendar ENTRIES R1C: direct fresh installation only (NOT the R1B rename).
-- Execute from SQL Developer with F5. Default PREVIEW does not write.
-- If the R1B ITEMS table exists, run the R1C RENAME script instead of this fresh installer.
-- STOP the application and BACK UP CAL2 before any APPLY (Oracle DDL auto-commits).
SET SERVEROUTPUT ON SIZE UNLIMITED
SET DEFINE ON
DEFINE APPLY_CHANGES = NO
PROMPT === CAL2 personal R1C ENTRIES fresh setup: PREVIEW by default ===

DECLARE
  v_mode       VARCHAR2(3) := UPPER(TRIM('&&APPLY_CHANGES'));
  v_day        NUMBER;
  v_obj        NUMBER;
  v_table      NUMBER;
  v_old_id     NUMBER;
  v_old_table  NUMBER;
  v_old_seq    NUMBER;
  v_num_id     NUMBER;
  v_pk         NUMBER;
  v_seq        NUMBER;
  v_legacy_nn  NUMBER;
BEGIN
  IF v_mode NOT IN ('NO','YES') THEN
    RAISE_APPLICATION_ERROR(-20701, 'APPLY_CHANGES must be YES or NO');
  END IF;
  SELECT COUNT(*) INTO v_old_table FROM ALL_TABLES WHERE OWNER='CAL2' AND TABLE_NAME='USER_CALENDAR_ITEMS';
  SELECT COUNT(*) INTO v_old_seq FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER='CAL2' AND SEQUENCE_NAME='SEQ_CAL2_USER_CALENDAR_ITEMS';
  IF v_old_table<>0 OR v_old_seq<>0 THEN
    RAISE_APPLICATION_ERROR(-20719, 'R1B legacy table/sequence exists. Run the R1C RENAME script instead. NO CHANGES.');
  END IF;
  SELECT COUNT(*) INTO v_day FROM ALL_TABLES
    WHERE OWNER='CAL2' AND TABLE_NAME='CANONICAL_DAY';
  IF v_day <> 1 THEN
    RAISE_APPLICATION_ERROR(-20702, 'CAL2.CANONICAL_DAY is missing; NO CHANGES');
  END IF;

  SELECT COUNT(*) INTO v_obj FROM ALL_OBJECTS
    WHERE OWNER='CAL2' AND OBJECT_NAME='USER_CALENDAR_ENTRIES'
      AND OBJECT_TYPE IN ('TABLE','VIEW','SYNONYM','MATERIALIZED VIEW');
  SELECT COUNT(*) INTO v_table FROM ALL_TABLES
    WHERE OWNER='CAL2' AND TABLE_NAME='USER_CALENDAR_ENTRIES';
  SELECT COUNT(*) INTO v_seq FROM ALL_SEQUENCES
    WHERE SEQUENCE_OWNER='CAL2' AND SEQUENCE_NAME='SEQ_CAL2_USER_CALENDAR_ENTRIES';
  IF v_obj <> v_table OR v_obj > 1 THEN
    RAISE_APPLICATION_ERROR(-20703, 'Unsafe USER_CALENDAR_ENTRIES object; NO CHANGES');
  END IF;

  IF v_table = 1 THEN
    SELECT COUNT(*) INTO v_old_id FROM ALL_TAB_COLUMNS
      WHERE OWNER='CAL2' AND TABLE_NAME='USER_CALENDAR_ENTRIES' AND COLUMN_NAME='ITEM_ID';
    SELECT COUNT(*) INTO v_num_id FROM ALL_TAB_COLUMNS
      WHERE OWNER='CAL2' AND TABLE_NAME='USER_CALENDAR_ENTRIES'
        AND COLUMN_NAME='USER_CALENDAR_ENTRY_ID' AND DATA_TYPE='NUMBER'
        AND DATA_PRECISION=12 AND DATA_SCALE=0 AND NULLABLE='N';
    IF v_old_id > 0 THEN
      DBMS_OUTPUT.PUT_LINE('LEGACY_R1_UUID_TABLE: CAL2.USER_CALENDAR_ENTRIES still has ITEM_ID');
      DBMS_OUTPUT.PUT_LINE('Legacy UUID detected. Upgrade to R1B first, then run R1C rename.');
      IF v_mode = 'YES' THEN
        RAISE_APPLICATION_ERROR(-20704, 'Legacy table: run the separate data-preserving UUID upgrade; NO CHANGES');
      END IF;
      DBMS_OUTPUT.PUT_LINE('PREVIEW COMPLETE. No writes.');
      RETURN;
    END IF;
    SELECT COUNT(*) INTO v_pk FROM ALL_CONSTRAINTS C
      JOIN ALL_CONS_COLUMNS K ON K.OWNER=C.OWNER AND K.CONSTRAINT_NAME=C.CONSTRAINT_NAME
      WHERE C.OWNER='CAL2' AND C.TABLE_NAME='USER_CALENDAR_ENTRIES'
        AND C.CONSTRAINT_TYPE='P' AND K.COLUMN_NAME='USER_CALENDAR_ENTRY_ID';
    SELECT COUNT(*) INTO v_legacy_nn FROM ALL_TAB_COLUMNS
      WHERE OWNER='CAL2' AND TABLE_NAME='USER_CALENDAR_ENTRIES'
        AND COLUMN_NAME='LEGACY_ITEM_ID' AND NULLABLE='N';
    IF v_legacy_nn<>0 THEN
      RAISE_APPLICATION_ERROR(-20706, 'LEGACY_ITEM_ID is NOT NULL; use UUID-UPGRADE-OPT-IN to repair before new inserts');
    END IF;
    IF v_num_id <> 1 OR v_pk <> 1 OR v_seq <> 1 THEN
      RAISE_APPLICATION_ERROR(-20705, 'Existing numeric table/PK/sequence inconsistent; NO CHANGES');
    END IF;
    DBMS_OUTPUT.PUT_LINE('ALREADY_PRESENT: USER_CALENDAR_ENTRY_ID NUMBER(12) + sequence + primary key');
  ELSE
    IF v_seq = 0 THEN
      DBMS_OUTPUT.PUT_LINE('PENDING: CREATE SEQUENCE CAL2.SEQ_CAL2_USER_CALENDAR_ENTRIES');
    ELSE
      DBMS_OUTPUT.PUT_LINE('ALREADY_PRESENT: CAL2.SEQ_CAL2_USER_CALENDAR_ENTRIES');
    END IF;
    DBMS_OUTPUT.PUT_LINE('PENDING: CREATE TABLE CAL2.USER_CALENDAR_ENTRIES with NUMBER(12) sequence default');
  END IF;

  IF v_mode = 'NO' THEN
    DBMS_OUTPUT.PUT_LINE('PREVIEW COMPLETE. No writes.');
    RETURN;
  END IF;

  IF v_table = 0 THEN
    IF v_seq = 0 THEN
      EXECUTE IMMEDIATE 'CREATE SEQUENCE CAL2.SEQ_CAL2_USER_CALENDAR_ENTRIES START WITH 1 INCREMENT BY 1 MAXVALUE 999999999999 NOCACHE NOCYCLE';
      DBMS_OUTPUT.PUT_LINE('CREATED SEQUENCE: CAL2.SEQ_CAL2_USER_CALENDAR_ENTRIES');
    END IF;
    EXECUTE IMMEDIATE q'~
      CREATE TABLE CAL2.USER_CALENDAR_ENTRIES (
        USER_CALENDAR_ENTRY_ID NUMBER(12,0) DEFAULT CAL2.SEQ_CAL2_USER_CALENDAR_ENTRIES.NEXTVAL NOT NULL,
        ACTOR_KEY             VARCHAR2(80 CHAR) NOT NULL,
        DAY_ID                NUMBER(19,0) NOT NULL,
        ENTRY_TYPE             VARCHAR2(12 CHAR) NOT NULL,
        TITLE                 VARCHAR2(200 CHAR) NOT NULL,
        DESCRIPTION           VARCHAR2(2000 CHAR),
        REMINDER_TIME         VARCHAR2(5 CHAR),
        ADVANCE_DAYS          NUMBER(2,0) DEFAULT 3 NOT NULL,
        REPEAT_POLICY         VARCHAR2(10 CHAR) DEFAULT 'DAILY' NOT NULL,
        STATUS                VARCHAR2(12 CHAR) DEFAULT 'OPEN' NOT NULL,
        FIRST_ADVANCE_ACK     CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
        LAST_ALERT_ACK_DATE   DATE,
        CREATED_AT            TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
        UPDATED_AT            TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT PK_CAL2_UCE PRIMARY KEY (USER_CALENDAR_ENTRY_ID),
        CONSTRAINT FK_CAL2_UCE_DAY FOREIGN KEY (DAY_ID) REFERENCES CAL2.CANONICAL_DAY (DAY_ID),
        CONSTRAINT CK_CAL2_UCE_TYPE CHECK (ENTRY_TYPE IN ('NOTE','REMINDER')),
        CONSTRAINT CK_CAL2_UCE_STATUS CHECK (STATUS IN ('OPEN','DONE')),
        CONSTRAINT CK_CAL2_UCE_ADV CHECK (ADVANCE_DAYS BETWEEN 0 AND 30),
        CONSTRAINT CK_CAL2_UCE_REPEAT CHECK (REPEAT_POLICY IN ('DAILY','ONCE')),
        CONSTRAINT CK_CAL2_UCE_ACK CHECK (FIRST_ADVANCE_ACK IN ('Y','N')),
        CONSTRAINT CK_CAL2_UCE_REM_TIME CHECK (
             (ENTRY_TYPE = 'NOTE' AND REMINDER_TIME IS NULL)
             OR (ENTRY_TYPE = 'REMINDER' AND REMINDER_TIME IS NOT NULL AND
                 REGEXP_LIKE(REMINDER_TIME, '^([01][0-9]|2[0-3]):[0-5][0-9]$')))
      ) TABLESPACE CAL2_DATA
    ~';
    DBMS_OUTPUT.PUT_LINE('CREATED TABLE: CAL2.USER_CALENDAR_ENTRIES');
    EXECUTE IMMEDIATE 'CREATE INDEX CAL2.IX_CAL2_UCE_ACTOR_DAY ON CAL2.USER_CALENDAR_ENTRIES (ACTOR_KEY, DAY_ID) TABLESPACE CAL2_DATA';
    EXECUTE IMMEDIATE 'CREATE INDEX CAL2.IX_CAL2_UCE_ALERT ON CAL2.USER_CALENDAR_ENTRIES (ACTOR_KEY, ENTRY_TYPE, STATUS) TABLESPACE CAL2_DATA';
    DBMS_OUTPUT.PUT_LINE('CREATED INDEXES: 2');
  END IF;

  DBMS_OUTPUT.PUT_LINE('CAL2_PERSONAL_R1C_FRESH_APPLY_COMPLETE. Oracle DDL is auto-committed.');
END;
/

