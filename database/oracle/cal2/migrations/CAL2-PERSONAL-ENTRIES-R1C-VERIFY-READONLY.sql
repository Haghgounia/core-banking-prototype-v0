SET SERVEROUTPUT ON SIZE UNLIMITED
PROMPT === CAL2 PERSONAL R1C ENTRIES: read-only verification ===
DECLARE
  v_table      NUMBER;
  v_seq        NUMBER;
  v_old        NUMBER;
  v_id         NUMBER;
  v_type       NUMBER;
  v_pk         NUMBER;
  v_fk         NUMBER;
  v_checks     NUMBER;
  v_idx        NUMBER;
  v_stale      NUMBER;
  v_legacy_nn  NUMBER;
  v_rows       NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_table FROM ALL_TABLES
   WHERE OWNER='CAL2' AND TABLE_NAME='USER_CALENDAR_ENTRIES';
  SELECT COUNT(*) INTO v_seq FROM ALL_SEQUENCES
   WHERE SEQUENCE_OWNER='CAL2' AND SEQUENCE_NAME='SEQ_CAL2_USER_CALENDAR_ENTRIES';
  SELECT COUNT(*) INTO v_old FROM ALL_OBJECTS
   WHERE OWNER='CAL2' AND OBJECT_NAME IN ('USER_CALENDAR_ITEMS','SEQ_CAL2_USER_CALENDAR_ITEMS')
     AND OBJECT_TYPE IN ('TABLE','SEQUENCE');
  SELECT COUNT(*) INTO v_id FROM ALL_TAB_COLUMNS
   WHERE OWNER='CAL2' AND TABLE_NAME='USER_CALENDAR_ENTRIES' AND COLUMN_NAME='USER_CALENDAR_ENTRY_ID'
     AND DATA_TYPE='NUMBER' AND DATA_PRECISION=12 AND DATA_SCALE=0 AND NULLABLE='N';
  SELECT COUNT(*) INTO v_type FROM ALL_TAB_COLUMNS
   WHERE OWNER='CAL2' AND TABLE_NAME='USER_CALENDAR_ENTRIES' AND COLUMN_NAME='ENTRY_TYPE'
     AND DATA_TYPE='VARCHAR2' AND CHAR_LENGTH=12 AND NULLABLE='N';
  SELECT COUNT(*) INTO v_pk FROM ALL_CONSTRAINTS C
    JOIN ALL_CONS_COLUMNS K ON C.OWNER=K.OWNER AND C.CONSTRAINT_NAME=K.CONSTRAINT_NAME
   WHERE C.OWNER='CAL2' AND C.TABLE_NAME='USER_CALENDAR_ENTRIES' AND C.CONSTRAINT_NAME='PK_CAL2_UCE'
     AND C.CONSTRAINT_TYPE='P' AND C.STATUS='ENABLED' AND C.VALIDATED='VALIDATED'
     AND K.COLUMN_NAME='USER_CALENDAR_ENTRY_ID';
  SELECT COUNT(*) INTO v_fk FROM ALL_CONSTRAINTS C
    JOIN ALL_CONSTRAINTS P ON C.R_OWNER=P.OWNER AND C.R_CONSTRAINT_NAME=P.CONSTRAINT_NAME
    JOIN ALL_CONS_COLUMNS K ON K.OWNER=C.OWNER AND K.CONSTRAINT_NAME=C.CONSTRAINT_NAME
   WHERE C.OWNER='CAL2' AND C.TABLE_NAME='USER_CALENDAR_ENTRIES' AND C.CONSTRAINT_NAME='FK_CAL2_UCE_DAY'
     AND C.CONSTRAINT_TYPE='R' AND C.STATUS='ENABLED' AND C.VALIDATED='VALIDATED'
     AND P.OWNER='CAL2' AND P.TABLE_NAME='CANONICAL_DAY' AND P.CONSTRAINT_TYPE IN ('P','U')
     AND K.COLUMN_NAME='DAY_ID';
  SELECT COUNT(*) INTO v_checks FROM ALL_CONSTRAINTS
   WHERE OWNER='CAL2' AND TABLE_NAME='USER_CALENDAR_ENTRIES'
     AND CONSTRAINT_NAME IN ('CK_CAL2_UCE_TYPE','CK_CAL2_UCE_STATUS','CK_CAL2_UCE_ADV',
                             'CK_CAL2_UCE_REPEAT','CK_CAL2_UCE_ACK','CK_CAL2_UCE_REM_TIME')
     AND CONSTRAINT_TYPE='C' AND STATUS='ENABLED' AND VALIDATED='VALIDATED';
  SELECT COUNT(*) INTO v_idx FROM ALL_INDEXES
   WHERE OWNER='CAL2' AND TABLE_OWNER='CAL2' AND TABLE_NAME='USER_CALENDAR_ENTRIES'
     AND INDEX_NAME IN ('PK_CAL2_UCE','IX_CAL2_UCE_ACTOR_DAY','IX_CAL2_UCE_ALERT')
     AND STATUS='VALID';
  SELECT COUNT(*) INTO v_stale FROM ALL_TAB_COLUMNS
   WHERE OWNER='CAL2' AND TABLE_NAME='USER_CALENDAR_ENTRIES'
     AND COLUMN_NAME IN ('ITEM_TYPE','USER_CALENDAR_ITEM_ID');
  SELECT COUNT(*) INTO v_legacy_nn FROM ALL_TAB_COLUMNS
   WHERE OWNER='CAL2' AND TABLE_NAME='USER_CALENDAR_ENTRIES' AND COLUMN_NAME='LEGACY_ITEM_ID' AND NULLABLE='N';
  DBMS_OUTPUT.PUT_LINE('TABLE='||v_table||'; SEQUENCE='||v_seq||'; LEGACY_OBJECTS='||v_old||
    '; NUMERIC_ID='||v_id||'; ENTRY_TYPE='||v_type||'; PK='||v_pk||'; DAY_FK='||v_fk||
    '; CHECKS='||v_checks||'; INDEXES='||v_idx||'; STALE_COLUMNS='||v_stale||
    '; LEGACY_UUID_NOT_NULL='||v_legacy_nn);
  IF v_table<>1 OR v_seq<>1 OR v_old<>0 OR v_id<>1 OR v_type<>1 OR v_pk<>1 OR v_fk<>1
     OR v_checks<>6 OR v_idx<>3 OR v_stale<>0 OR v_legacy_nn<>0 THEN
    RAISE_APPLICATION_ERROR(-20761, 'CAL2 PERSONAL R1C SCHEMA VERIFICATION FAILED (read-only).');
  END IF;
  EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM CAL2.USER_CALENDAR_ENTRIES' INTO v_rows;
  DBMS_OUTPUT.PUT_LINE('ROW_COUNT='||v_rows);
  DBMS_OUTPUT.PUT_LINE('CAL2_PERSONAL_R1C_READONLY_VERIFY_PASS');
END;
