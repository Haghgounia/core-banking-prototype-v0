-- Optional when the app connects as a different user from CAL2 or SYSTEM.
-- SQL Developer F5. Default PREVIEW: no writes. Run after R1C table/sequence exists.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET DEFINE ON
DEFINE APPLY_CHANGES = NO
DEFINE APP_USER = CHANGE_ME
PROMPT === CAL2 PERSONAL ENTRIES R1C APP GRANTS: PREVIEW by default ===
DECLARE
  v_apply VARCHAR2(3) := UPPER(TRIM('&&APPLY_CHANGES'));
  v_app   VARCHAR2(128) := UPPER(TRIM('&&APP_USER'));
  v_count NUMBER;
BEGIN
  IF v_apply NOT IN ('YES', 'NO') THEN
    RAISE_APPLICATION_ERROR(-20901, 'APPLY_CHANGES must be YES or NO');
  END IF;
  IF NOT REGEXP_LIKE(v_app, '^[A-Z][A-Z0-9_$#]{0,127}$') OR v_app = 'CHANGE_ME' THEN
    IF v_apply = 'YES' THEN
      RAISE_APPLICATION_ERROR(-20902, 'Set APP_USER to an existing Oracle user first');
    END IF;
    DBMS_OUTPUT.PUT_LINE('PREVIEW: configure APP_USER for the application connection if needed');
    RETURN;
  END IF;
  SELECT COUNT(*) INTO v_count FROM ALL_USERS WHERE USERNAME = v_app;
  IF v_count <> 1 THEN
    RAISE_APPLICATION_ERROR(-20903, 'APP_USER does not exist');
  END IF;
  SELECT COUNT(*) INTO v_count FROM ALL_TABLES
    WHERE OWNER = 'CAL2' AND TABLE_NAME = 'USER_CALENDAR_ENTRIES';
  IF v_count <> 1 THEN
    RAISE_APPLICATION_ERROR(-20904, 'CAL2.USER_CALENDAR_ENTRIES missing');
  END IF;
  SELECT COUNT(*) INTO v_count FROM ALL_SEQUENCES
    WHERE SEQUENCE_OWNER = 'CAL2' AND SEQUENCE_NAME = 'SEQ_CAL2_USER_CALENDAR_ENTRIES';
  IF v_count <> 1 THEN
    RAISE_APPLICATION_ERROR(-20905, 'CAL2 personal sequence missing');
  END IF;
  DBMS_OUTPUT.PUT_LINE('PENDING: GRANT SELECT/INSERT/UPDATE/DELETE ON CAL2.USER_CALENDAR_ENTRIES TO '||v_app);
  DBMS_OUTPUT.PUT_LINE('PENDING: GRANT SELECT ON CAL2.SEQ_CAL2_USER_CALENDAR_ENTRIES TO '||v_app);
  IF v_apply = 'NO' THEN
    DBMS_OUTPUT.PUT_LINE('PREVIEW COMPLETE. No writes.');
    RETURN;
  END IF;
  EXECUTE IMMEDIATE 'GRANT SELECT, INSERT, UPDATE, DELETE ON CAL2.USER_CALENDAR_ENTRIES TO ' || DBMS_ASSERT.SIMPLE_SQL_NAME(v_app);
  EXECUTE IMMEDIATE 'GRANT SELECT ON CAL2.SEQ_CAL2_USER_CALENDAR_ENTRIES TO ' || DBMS_ASSERT.SIMPLE_SQL_NAME(v_app);
  DBMS_OUTPUT.PUT_LINE('CAL2_PERSONAL_R1C_APP_GRANTS_COMPLETE');
END;
