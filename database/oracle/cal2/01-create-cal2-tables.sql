    CONSTRAINT CK_CAL2_BUS_CAL_ACTIVE CHECK (ACTIVE_FLAG IN ('Y','N')),
    CONSTRAINT CK_CAL2_BUS_CAL_RANGE CHECK (VALID_TO IS NULL OR VALID_FROM IS NULL OR VALID_TO >= VALID_FROM)
);

CREATE TABLE CAL2.BUSINESS_CALENDAR_DAY (
    BUSINESS_CALENDAR_DAY_ID NUMBER(19) NOT NULL,
    BUSINESS_CALENDAR_ID     NUMBER(19) NOT NULL,
    DAY_ID                   NUMBER(19) NOT NULL,
    DAY_STATUS               VARCHAR2(30 CHAR),
    OPEN_TIME                TIMESTAMP(6),
    CLOSE_TIME               TIMESTAMP(6),
    IS_BUSINESS_DAY          CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    IS_SETTLEMENT_DAY        CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    IS_CLEARING_DAY          CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    IS_PROCESSING_DAY        CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    REASON_CODE              VARCHAR2(80 CHAR),
    SOURCE_ID                NUMBER(19),
    CONSTRAINT PK_CAL2_BUS_CAL_DAY PRIMARY KEY (BUSINESS_CALENDAR_DAY_ID),
    CONSTRAINT UQ_CAL2_BUS_CAL_DAY UNIQUE (BUSINESS_CALENDAR_ID, DAY_ID),
    CONSTRAINT FK_CAL2_BCD_CAL FOREIGN KEY (BUSINESS_CALENDAR_ID) REFERENCES CAL2.BUSINESS_CALENDAR (BUSINESS_CALENDAR_ID),
    CONSTRAINT FK_CAL2_BCD_DAY FOREIGN KEY (DAY_ID) REFERENCES CAL2.CANONICAL_DAY (DAY_ID),
    CONSTRAINT FK_CAL2_BCD_SOURCE FOREIGN KEY (SOURCE_ID) REFERENCES CAL2.SOURCE_AUTHORITY (SOURCE_ID),
    CONSTRAINT CK_CAL2_BCD_BUSINESS CHECK (IS_BUSINESS_DAY IN ('Y','N')),
    CONSTRAINT CK_CAL2_BCD_SETTLEMENT CHECK (IS_SETTLEMENT_DAY IN ('Y','N')),
    CONSTRAINT CK_CAL2_BCD_CLEARING CHECK (IS_CLEARING_DAY IN ('Y','N')),
    CONSTRAINT CK_CAL2_BCD_PROCESSING CHECK (IS_PROCESSING_DAY IN ('Y','N')),
    CONSTRAINT CK_CAL2_BCD_TIME_RANGE CHECK (CLOSE_TIME IS NULL OR OPEN_TIME IS NULL OR CLOSE_TIME >= OPEN_TIME)
);

CREATE TABLE CAL2.VALIDATION_RUN (
    VALIDATION_RUN_ID    NUMBER(19) NOT NULL,
    DATASET_VERSION_ID   NUMBER(19) NOT NULL,
    RUN_STARTED_AT       TIMESTAMP(6),
    RUN_FINISHED_AT      TIMESTAMP(6),
    VALIDATOR_NAME       VARCHAR2(250 CHAR),
    VALIDATOR_VERSION    VARCHAR2(80 CHAR),
    TOTAL_ASSERTIONS     NUMBER(19),
    PASSED_ASSERTIONS    NUMBER(19),
    FAILED_ASSERTIONS    NUMBER(19),
    RUN_STATUS           VARCHAR2(30 CHAR),
    EVIDENCE_CHECKSUM    VARCHAR2(64 CHAR),
    CONSTRAINT PK_CAL2_VALIDATION_RUN PRIMARY KEY (VALIDATION_RUN_ID),
    CONSTRAINT FK_CAL2_VR_DATASET FOREIGN KEY (DATASET_VERSION_ID) REFERENCES CAL2.DATASET_VERSION (DATASET_VERSION_ID),
    CONSTRAINT CK_CAL2_VR_TIME_RANGE CHECK (RUN_FINISHED_AT IS NULL OR RUN_STARTED_AT IS NULL OR RUN_FINISHED_AT >= RUN_STARTED_AT)
