CREATE TABLE CAL2.VALIDATION_RESULT (
    VALIDATION_RESULT_ID NUMBER(19) NOT NULL,
    VALIDATION_RUN_ID    NUMBER(19) NOT NULL,
    TEST_CODE            VARCHAR2(120 CHAR) NOT NULL,
    DAY_ID               NUMBER(19),
    CALENDAR_VARIANT_ID  NUMBER(19),
    RESULT_STATUS        VARCHAR2(30 CHAR) NOT NULL,
    EXPECTED_VALUE       VARCHAR2(1000 CHAR),
    ACTUAL_VALUE         VARCHAR2(1000 CHAR),
    ERROR_CODE           VARCHAR2(120 CHAR),
    DETAILS              VARCHAR2(2000 CHAR),
    CONSTRAINT PK_CAL2_VALIDATION_RESULT PRIMARY KEY (VALIDATION_RESULT_ID),
    CONSTRAINT FK_CAL2_VRES_RUN FOREIGN KEY (VALIDATION_RUN_ID) REFERENCES CAL2.VALIDATION_RUN (VALIDATION_RUN_ID),
    CONSTRAINT FK_CAL2_VRES_DAY FOREIGN KEY (DAY_ID) REFERENCES CAL2.CANONICAL_DAY (DAY_ID),
    CONSTRAINT FK_CAL2_VRES_VARIANT FOREIGN KEY (CALENDAR_VARIANT_ID) REFERENCES CAL2.CALENDAR_VARIANT (CALENDAR_VARIANT_ID)
);

