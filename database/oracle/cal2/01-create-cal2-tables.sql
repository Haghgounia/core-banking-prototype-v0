-- CAL2 physical model derived from BIAN_Calendar_400Y_Oracle_Import package.
-- Run while connected as CAL2 (recommended) or as a privileged account.

WHENEVER SQLERROR EXIT SQL.SQLCODE
SET DEFINE OFF

CREATE TABLE CAL2.CALENDAR_SYSTEM (
    CALENDAR_SYSTEM_ID NUMBER(19) NOT NULL,
    CALENDAR_CODE      VARCHAR2(30 CHAR) NOT NULL,
    NAME_FA            VARCHAR2(100 CHAR) NOT NULL,
    NAME_EN            VARCHAR2(120 CHAR),
    CALENDAR_TYPE      VARCHAR2(20 CHAR) NOT NULL,
    ACTIVE_FLAG        CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    CREATED_AT         TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CAL2_CALENDAR_SYSTEM PRIMARY KEY (CALENDAR_SYSTEM_ID),
    CONSTRAINT UQ_CAL2_CAL_SYSTEM_CODE UNIQUE (CALENDAR_CODE),
    CONSTRAINT CK_CAL2_CAL_SYSTEM_ACTIVE CHECK (ACTIVE_FLAG IN ('Y','N'))
);

CREATE TABLE CAL2.SOURCE_AUTHORITY (
    SOURCE_ID        NUMBER(19) NOT NULL,
    SOURCE_CODE      VARCHAR2(60 CHAR) NOT NULL,
    NAME_FA          VARCHAR2(200 CHAR) NOT NULL,
    NAME_EN          VARCHAR2(250 CHAR),
    SOURCE_TYPE      VARCHAR2(30 CHAR),
    SOURCE_URI       VARCHAR2(1000 CHAR),
    COUNTRY_CODE     VARCHAR2(3 CHAR),
    AUTHORITY_LEVEL  VARCHAR2(30 CHAR),
    ACTIVE_FLAG      CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_CAL2_SOURCE_AUTHORITY PRIMARY KEY (SOURCE_ID),
    CONSTRAINT UQ_CAL2_SOURCE_AUTH_CODE UNIQUE (SOURCE_CODE),
    CONSTRAINT CK_CAL2_SOURCE_AUTH_ACTIVE CHECK (ACTIVE_FLAG IN ('Y','N'))
);

CREATE TABLE CAL2.DATASET_VERSION (
    DATASET_VERSION_ID NUMBER(19) NOT NULL,
    VERSION_CODE       VARCHAR2(80 CHAR) NOT NULL,
    GENERATOR_VERSION  VARCHAR2(100 CHAR),
    ALGORITHM_VERSION  VARCHAR2(150 CHAR),
    SOURCE_VERSION     VARCHAR2(150 CHAR),
    RANGE_START_DATE   DATE NOT NULL,
    RANGE_END_DATE     DATE NOT NULL,
    STATUS             VARCHAR2(30 CHAR) NOT NULL,
    CHECKSUM_SHA256    VARCHAR2(64 CHAR),
    GENERATED_AT       TIMESTAMP(6),
    APPROVED_BY        VARCHAR2(120 CHAR),
    APPROVED_AT        TIMESTAMP(6),
    CONSTRAINT PK_CAL2_DATASET_VERSION PRIMARY KEY (DATASET_VERSION_ID),
    CONSTRAINT UQ_CAL2_DATASET_VERSION_CODE UNIQUE (VERSION_CODE),
    CONSTRAINT CK_CAL2_DATASET_RANGE CHECK (RANGE_END_DATE >= RANGE_START_DATE)
);

CREATE TABLE CAL2.CALENDAR_VARIANT (
    CALENDAR_VARIANT_ID NUMBER(19) NOT NULL,
    CALENDAR_SYSTEM_ID  NUMBER(19) NOT NULL,
    VARIANT_CODE        VARCHAR2(80 CHAR) NOT NULL,
    METHOD_TYPE         VARCHAR2(30 CHAR) NOT NULL,
    ALGORITHM_CODE      VARCHAR2(100 CHAR),
    AUTHORITY_ID        NUMBER(19),
    VALID_FROM          DATE,
    VALID_TO            DATE,
    IS_DEFAULT          CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    VERSION_NO          NUMBER(10) DEFAULT 1 NOT NULL,
    ACTIVE_FLAG         CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_CAL2_CALENDAR_VARIANT PRIMARY KEY (CALENDAR_VARIANT_ID),
    CONSTRAINT UQ_CAL2_CAL_VARIANT_CODE UNIQUE (VARIANT_CODE),
    CONSTRAINT FK_CAL2_CV_SYSTEM FOREIGN KEY (CALENDAR_SYSTEM_ID) REFERENCES CAL2.CALENDAR_SYSTEM (CALENDAR_SYSTEM_ID),
    CONSTRAINT FK_CAL2_CV_AUTHORITY FOREIGN KEY (AUTHORITY_ID) REFERENCES CAL2.SOURCE_AUTHORITY (SOURCE_ID),
    CONSTRAINT CK_CAL2_CV_DEFAULT CHECK (IS_DEFAULT IN ('Y','N')),
    CONSTRAINT CK_CAL2_CV_ACTIVE CHECK (ACTIVE_FLAG IN ('Y','N')),
    CONSTRAINT CK_CAL2_CV_RANGE CHECK (VALID_TO IS NULL OR VALID_FROM IS NULL OR VALID_TO >= VALID_FROM)
);

CREATE TABLE CAL2.CALENDAR_MONTH (
    CALENDAR_MONTH_ID  NUMBER(19) NOT NULL,
    CALENDAR_SYSTEM_ID NUMBER(19) NOT NULL,
    MONTH_NO           NUMBER(2) NOT NULL,
    NAME_FA            VARCHAR2(100 CHAR) NOT NULL,
    NAME_EN            VARCHAR2(100 CHAR),
    SHORT_NAME_FA      VARCHAR2(30 CHAR),
    SHORT_NAME_EN      VARCHAR2(30 CHAR),
    DISPLAY_ORDER      NUMBER(3),
    CONSTRAINT PK_CAL2_CALENDAR_MONTH PRIMARY KEY (CALENDAR_MONTH_ID),
    CONSTRAINT UQ_CAL2_CAL_MONTH_NO UNIQUE (CALENDAR_SYSTEM_ID, MONTH_NO),
    CONSTRAINT FK_CAL2_CM_SYSTEM FOREIGN KEY (CALENDAR_SYSTEM_ID) REFERENCES CAL2.CALENDAR_SYSTEM (CALENDAR_SYSTEM_ID),
    CONSTRAINT CK_CAL2_CM_MONTH_NO CHECK (MONTH_NO BETWEEN 1 AND 13)
);

CREATE TABLE CAL2.WEEKDAY (
    WEEKDAY_ID        NUMBER(19) NOT NULL,
    ISO_WEEKDAY_NO    NUMBER(1) NOT NULL,
    NAME_FA           VARCHAR2(50 CHAR) NOT NULL,
    NAME_EN           VARCHAR2(50 CHAR),
    SHORT_NAME_FA     VARCHAR2(20 CHAR),
    SHORT_NAME_EN     VARCHAR2(20 CHAR),
    IR_DISPLAY_ORDER  NUMBER(1),
    CONSTRAINT PK_CAL2_WEEKDAY PRIMARY KEY (WEEKDAY_ID),
    CONSTRAINT UQ_CAL2_WEEKDAY_ISO UNIQUE (ISO_WEEKDAY_NO),
    CONSTRAINT CK_CAL2_WEEKDAY_ISO CHECK (ISO_WEEKDAY_NO BETWEEN 1 AND 7),
    CONSTRAINT CK_CAL2_WEEKDAY_IR_ORDER CHECK (IR_DISPLAY_ORDER IS NULL OR IR_DISPLAY_ORDER BETWEEN 1 AND 7)
);

CREATE TABLE CAL2.CANONICAL_DAY (
    DAY_ID          NUMBER(19) NOT NULL,
    EPOCH_DAY       NUMBER(19) NOT NULL,
    CANONICAL_DATE  DATE NOT NULL,
    ISO_DATE_TEXT   VARCHAR2(10 CHAR) NOT NULL,
    WEEKDAY_ID      NUMBER(19) NOT NULL,
    ISO_WEEK_NO     NUMBER(2),
    ISO_WEEK_YEAR   NUMBER(6),
    CREATED_AT      TIMESTAMP(6),
    CONSTRAINT PK_CAL2_CANONICAL_DAY PRIMARY KEY (DAY_ID),
    CONSTRAINT UQ_CAL2_CAN_DAY_EPOCH UNIQUE (EPOCH_DAY),
    CONSTRAINT UQ_CAL2_CAN_DAY_DATE UNIQUE (CANONICAL_DATE),
    CONSTRAINT UQ_CAL2_CAN_DAY_ISO_TEXT UNIQUE (ISO_DATE_TEXT),
    CONSTRAINT FK_CAL2_CAN_DAY_WEEKDAY FOREIGN KEY (WEEKDAY_ID) REFERENCES CAL2.WEEKDAY (WEEKDAY_ID),
    CONSTRAINT CK_CAL2_CAN_DAY_WEEK CHECK (ISO_WEEK_NO IS NULL OR ISO_WEEK_NO BETWEEN 1 AND 53)
);

CREATE TABLE CAL2.CALENDAR_DATE (
    CALENDAR_DATE_ID    NUMBER(19) NOT NULL,
    DAY_ID              NUMBER(19) NOT NULL,
    CALENDAR_VARIANT_ID NUMBER(19) NOT NULL,
    YEAR_NO             NUMBER(6) NOT NULL,
    MONTH_NO            NUMBER(2) NOT NULL,
    DAY_NO              NUMBER(2) NOT NULL,
    DAY_OF_YEAR         NUMBER(3),
    WEEKDAY_ID          NUMBER(19) NOT NULL,
    IS_LEAP_YEAR        CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    IS_LEAP_MONTH       CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    MONTH_LENGTH        NUMBER(2),
    DATA_STATUS         VARCHAR2(30 CHAR) NOT NULL,
    DATASET_VERSION_ID  NUMBER(19) NOT NULL,
    CONSTRAINT PK_CAL2_CALENDAR_DATE PRIMARY KEY (CALENDAR_DATE_ID),
    CONSTRAINT UQ_CAL2_CAL_DATE_DAY_VARIANT UNIQUE (DAY_ID, CALENDAR_VARIANT_ID),
    CONSTRAINT UQ_CAL2_CAL_DATE_YMD UNIQUE (CALENDAR_VARIANT_ID, YEAR_NO, MONTH_NO, DAY_NO),
    CONSTRAINT FK_CAL2_CD_DAY FOREIGN KEY (DAY_ID) REFERENCES CAL2.CANONICAL_DAY (DAY_ID),
    CONSTRAINT FK_CAL2_CD_VARIANT FOREIGN KEY (CALENDAR_VARIANT_ID) REFERENCES CAL2.CALENDAR_VARIANT (CALENDAR_VARIANT_ID),
    CONSTRAINT FK_CAL2_CD_WEEKDAY FOREIGN KEY (WEEKDAY_ID) REFERENCES CAL2.WEEKDAY (WEEKDAY_ID),
    CONSTRAINT FK_CAL2_CD_DATASET FOREIGN KEY (DATASET_VERSION_ID) REFERENCES CAL2.DATASET_VERSION (DATASET_VERSION_ID),
    CONSTRAINT CK_CAL2_CD_LEAP_YEAR CHECK (IS_LEAP_YEAR IN ('Y','N')),
    CONSTRAINT CK_CAL2_CD_LEAP_MONTH CHECK (IS_LEAP_MONTH IN ('Y','N')),
    CONSTRAINT CK_CAL2_CD_MONTH CHECK (MONTH_NO BETWEEN 1 AND 13),
    CONSTRAINT CK_CAL2_CD_DAY CHECK (DAY_NO BETWEEN 1 AND 31)
);

CREATE TABLE CAL2.EVENT_TYPE (
    EVENT_TYPE_ID    NUMBER(19) NOT NULL,
    EVENT_TYPE_CODE  VARCHAR2(60 CHAR) NOT NULL,
    NAME_FA          VARCHAR2(120 CHAR) NOT NULL,
    NAME_EN          VARCHAR2(120 CHAR),
    ACTIVE_FLAG      CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_CAL2_EVENT_TYPE PRIMARY KEY (EVENT_TYPE_ID),
    CONSTRAINT UQ_CAL2_EVENT_TYPE_CODE UNIQUE (EVENT_TYPE_CODE),
    CONSTRAINT CK_CAL2_EVENT_TYPE_ACTIVE CHECK (ACTIVE_FLAG IN ('Y','N'))
);

CREATE TABLE CAL2.EVENT (
    EVENT_ID                 NUMBER(19) NOT NULL,
    EVENT_CODE               VARCHAR2(80 CHAR) NOT NULL,
    EVENT_TYPE_ID            NUMBER(19) NOT NULL,
    NAME_FA                  VARCHAR2(300 CHAR) NOT NULL,
    NAME_EN                  VARCHAR2(300 CHAR),
    DESCRIPTION              VARCHAR2(2000 CHAR),
    RECURRENCE_TYPE          VARCHAR2(40 CHAR),
    BASE_CALENDAR_SYSTEM_ID  NUMBER(19),
    OFFICIAL_FLAG            CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    DEFAULT_HOLIDAY_FLAG     CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    ACTIVE_FLAG              CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_CAL2_EVENT PRIMARY KEY (EVENT_ID),
    CONSTRAINT UQ_CAL2_EVENT_CODE UNIQUE (EVENT_CODE),
    CONSTRAINT FK_CAL2_EVENT_TYPE FOREIGN KEY (EVENT_TYPE_ID) REFERENCES CAL2.EVENT_TYPE (EVENT_TYPE_ID),
    CONSTRAINT FK_CAL2_EVENT_SYSTEM FOREIGN KEY (BASE_CALENDAR_SYSTEM_ID) REFERENCES CAL2.CALENDAR_SYSTEM (CALENDAR_SYSTEM_ID),
    CONSTRAINT CK_CAL2_EVENT_OFFICIAL CHECK (OFFICIAL_FLAG IN ('Y','N')),
    CONSTRAINT CK_CAL2_EVENT_DEF_HOL CHECK (DEFAULT_HOLIDAY_FLAG IN ('Y','N')),
    CONSTRAINT CK_CAL2_EVENT_ACTIVE CHECK (ACTIVE_FLAG IN ('Y','N'))
);

CREATE TABLE CAL2.EVENT_RECURRENCE_RULE (
    EVENT_RULE_ID        NUMBER(19) NOT NULL,
    EVENT_ID             NUMBER(19) NOT NULL,
    RULE_TYPE            VARCHAR2(40 CHAR) NOT NULL,
    CALENDAR_VARIANT_ID  NUMBER(19) NOT NULL,
    YEAR_NO              NUMBER(6),
    MONTH_NO             NUMBER(2) NOT NULL,
    DAY_NO               NUMBER(2) NOT NULL,
    START_YEAR_NO        NUMBER(6),
    END_YEAR_NO          NUMBER(6),
    SOURCE_ID            NUMBER(19),
    DESCRIPTION          VARCHAR2(1000 CHAR),
    ACTIVE_FLAG          CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_CAL2_EVENT_RULE PRIMARY KEY (EVENT_RULE_ID),
    CONSTRAINT FK_CAL2_ER_EVENT FOREIGN KEY (EVENT_ID) REFERENCES CAL2.EVENT (EVENT_ID),
    CONSTRAINT FK_CAL2_ER_VARIANT FOREIGN KEY (CALENDAR_VARIANT_ID) REFERENCES CAL2.CALENDAR_VARIANT (CALENDAR_VARIANT_ID),
    CONSTRAINT FK_CAL2_ER_SOURCE FOREIGN KEY (SOURCE_ID) REFERENCES CAL2.SOURCE_AUTHORITY (SOURCE_ID),
    CONSTRAINT CK_CAL2_ER_TYPE CHECK (RULE_TYPE IN ('ANNUAL_FIXED_DATE','ONE_TIME_DATE')),
    CONSTRAINT CK_CAL2_ER_MONTH CHECK (MONTH_NO BETWEEN 1 AND 13),
    CONSTRAINT CK_CAL2_ER_DAY CHECK (DAY_NO BETWEEN 1 AND 31),
    CONSTRAINT CK_CAL2_ER_ACTIVE CHECK (ACTIVE_FLAG IN ('Y','N')),
    CONSTRAINT CK_CAL2_ER_RANGE CHECK (END_YEAR_NO IS NULL OR START_YEAR_NO IS NULL OR END_YEAR_NO >= START_YEAR_NO),
    CONSTRAINT CK_CAL2_ER_SHAPE CHECK (
        (RULE_TYPE = 'ANNUAL_FIXED_DATE' AND YEAR_NO IS NULL)
        OR
        (RULE_TYPE = 'ONE_TIME_DATE' AND YEAR_NO IS NOT NULL AND START_YEAR_NO IS NULL AND END_YEAR_NO IS NULL)
    )
);

CREATE TABLE CAL2.EVENT_OCCURRENCE (
    EVENT_OCCURRENCE_ID NUMBER(19) NOT NULL,
    EVENT_ID            NUMBER(19) NOT NULL,
    EVENT_RULE_ID       NUMBER(19),
    DAY_ID              NUMBER(19) NOT NULL,
    SOURCE_ID           NUMBER(19),
    OCCURRENCE_SOURCE   VARCHAR2(30 CHAR) DEFAULT 'MANUAL' NOT NULL,
    DATA_STATUS         VARCHAR2(30 CHAR),
    HOLIDAY_FLAG        CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    START_TIME          TIMESTAMP(6),
    END_TIME            TIMESTAMP(6),
    DESCRIPTION         VARCHAR2(2000 CHAR),
    DATASET_VERSION_ID  NUMBER(19),
    CONSTRAINT PK_CAL2_EVENT_OCC PRIMARY KEY (EVENT_OCCURRENCE_ID),
    CONSTRAINT FK_CAL2_EO_EVENT FOREIGN KEY (EVENT_ID) REFERENCES CAL2.EVENT (EVENT_ID),
    CONSTRAINT FK_CAL2_EO_RULE FOREIGN KEY (EVENT_RULE_ID) REFERENCES CAL2.EVENT_RECURRENCE_RULE (EVENT_RULE_ID),
    CONSTRAINT FK_CAL2_EO_DAY FOREIGN KEY (DAY_ID) REFERENCES CAL2.CANONICAL_DAY (DAY_ID),
    CONSTRAINT FK_CAL2_EO_SOURCE FOREIGN KEY (SOURCE_ID) REFERENCES CAL2.SOURCE_AUTHORITY (SOURCE_ID),
    CONSTRAINT FK_CAL2_EO_DATASET FOREIGN KEY (DATASET_VERSION_ID) REFERENCES CAL2.DATASET_VERSION (DATASET_VERSION_ID),
    CONSTRAINT CK_CAL2_EO_SOURCE CHECK (OCCURRENCE_SOURCE IN ('GENERATED','MANUAL','OFFICIAL')),
    CONSTRAINT CK_CAL2_EO_HOLIDAY CHECK (HOLIDAY_FLAG IN ('Y','N')),
    CONSTRAINT CK_CAL2_EO_TIME_RANGE CHECK (END_TIME IS NULL OR START_TIME IS NULL OR END_TIME >= START_TIME)
);

CREATE TABLE CAL2.BUSINESS_CALENDAR (
    BUSINESS_CALENDAR_ID NUMBER(19) NOT NULL,
    CALENDAR_CODE        VARCHAR2(80 CHAR) NOT NULL,
    NAME_FA              VARCHAR2(200 CHAR) NOT NULL,
    NAME_EN              VARCHAR2(200 CHAR),
    COUNTRY_CODE         VARCHAR2(3 CHAR),
    TIME_ZONE            VARCHAR2(80 CHAR),
    ORGANIZATION_ID      VARCHAR2(80 CHAR),
    VALID_FROM           DATE,
    VALID_TO             DATE,
    ACTIVE_FLAG          CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_CAL2_BUSINESS_CAL PRIMARY KEY (BUSINESS_CALENDAR_ID),
