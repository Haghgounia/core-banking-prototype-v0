SELECT R.EVENT_RULE_ID, E.EVENT_CODE, E.NAME_FA, R.MONTH_NO, R.DAY_NO,
       R.DAY_RESOLUTION_POLICY,
       SUM(CASE WHEN EO.OCCURRENCE_SOURCE='GENERATED' THEN 1 ELSE 0 END) AS GENERATED_OCCURRENCES,
       TO_CHAR(MIN(CASE WHEN EO.OCCURRENCE_SOURCE='GENERATED' THEN D.CANONICAL_DATE END),'YYYY-MM-DD') AS FIRST_DATE,
       TO_CHAR(MAX(CASE WHEN EO.OCCURRENCE_SOURCE='GENERATED' THEN D.CANONICAL_DATE END),'YYYY-MM-DD') AS LAST_DATE
  FROM CAL2.EVENT_RECURRENCE_RULE R
  JOIN CAL2.EVENT E ON E.EVENT_ID = R.EVENT_ID
  LEFT JOIN CAL2.EVENT_OCCURRENCE EO ON EO.EVENT_RULE_ID = R.EVENT_RULE_ID
  LEFT JOIN CAL2.CANONICAL_DAY D ON D.DAY_ID = EO.DAY_ID
 WHERE E.EVENT_CODE='IR_IMAM_REZA_MARTYRDOM'
 GROUP BY R.EVENT_RULE_ID, E.EVENT_CODE, E.NAME_FA, R.MONTH_NO, R.DAY_NO, R.DAY_RESOLUTION_POLICY;

