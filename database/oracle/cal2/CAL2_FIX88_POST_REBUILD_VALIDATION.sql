PROMPT === C. Generated occurrence counts by calendar system ===
SELECT S.CALENDAR_CODE,
       COUNT(DISTINCT R.EVENT_RULE_ID) AS RULE_COUNT,
       MIN(X.CNT) AS MIN_OCCURRENCES,
       MAX(X.CNT) AS MAX_OCCURRENCES,
       ROUND(AVG(X.CNT),2) AS AVG_OCCURRENCES,
       SUM(X.CNT) AS TOTAL_OCCURRENCES
  FROM CAL2.EVENT_RECURRENCE_RULE R
  JOIN CAL2.CALENDAR_VARIANT V ON V.CALENDAR_VARIANT_ID=R.CALENDAR_VARIANT_ID
  JOIN CAL2.CALENDAR_SYSTEM S ON S.CALENDAR_SYSTEM_ID=V.CALENDAR_SYSTEM_ID
  JOIN (
       SELECT EVENT_RULE_ID, COUNT(*) CNT
         FROM CAL2.EVENT_OCCURRENCE
        WHERE OCCURRENCE_SOURCE='GENERATED'
        GROUP BY EVENT_RULE_ID
  ) X ON X.EVENT_RULE_ID=R.EVENT_RULE_ID
 WHERE R.ACTIVE_FLAG='Y'
 GROUP BY S.CALENDAR_CODE
 ORDER BY S.CALENDAR_CODE;

