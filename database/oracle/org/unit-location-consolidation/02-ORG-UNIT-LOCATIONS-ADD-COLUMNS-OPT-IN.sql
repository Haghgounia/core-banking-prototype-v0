-- Phase R1 additive Oracle DDL. DEFAULT NO. SQL Developer F5, DBA-reviewed session.
-- Oracle DDL IMPLICITLY COMMITS. Do not run in a session with other pending work.
-- Preserves LOCATION_ID, ALL original columns, ALL original rows, legacy tables & FKs.
-- Does NOT convert units, infer GEO, normalize addresses, rename or drop anything.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET VERIFY OFF
DEFINE APPLY_CHANGES = NO
PROMPT === R1 ADDITIVE COLUMNS: DEFAULT PREVIEW. YES only after backup/DBA authorization ===
DECLARE
  v_mode VARCHAR2(3) := UPPER(TRIM('&&APPLY_CHANGES'));
  v_table_count NUMBER;
  v_existing NUMBER;
  v_wrong_types NUMBER;
BEGIN
  IF v_mode NOT IN ('NO','YES') THEN
    RAISE_APPLICATION_ERROR(-20801,'APPLY_CHANGES must be NO or YES');
  END IF;
  SELECT COUNT(*) INTO v_table_count FROM ALL_TABLES
   WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS';
  IF v_table_count<>1 THEN RAISE_APPLICATION_ERROR(-20802,'ORG.ORGANIZATION_UNIT_LOCATIONS missing or inaccessible'); END IF;
  SELECT COUNT(*) INTO v_existing FROM ALL_TAB_COLUMNS
   WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS'
     AND COLUMN_NAME IN ('GEO_ENTITY_ID','LATITUDE','LONGITUDE','COORDINATE_REFERENCE_SYSTEM_CODE','LOCATION_DESCRIPTION_FA','LOCATION_DESCRIPTION_EN','ADDRESS_TYPE_CODE','MAIN_STREET_FA','MAIN_STREET_EN','SECONDARY_STREET_FA','SECONDARY_STREET_EN','SQUARE_CROSSROAD_FA','SQUARE_CROSSROAD_EN','BUILDING_NO','POSTAL_CODE','ADDRESS_FA','ADDRESS_EN','ADDITIONAL_ADDRESS_FA','ADDITIONAL_ADDRESS_EN','LEGACY_POSTAL_ADDRESS_ID','RELOCATION_REASON_CODE','DECISION_REFERENCE','DECISION_DATE','LEGACY_BACKFILL_FLAG','LEGACY_BACKFILLED_AT','ROW_VERSION');
  DBMS_OUTPUT.PUT_LINE('R1_ADDITIVE_COLUMNS_EXISTING='||v_existing||'/26');
  IF v_existing NOT IN (0,26) THEN
    RAISE_APPLICATION_ERROR(-20803,'PARTIAL COLUMN SET. Manual schema reconciliation required; no DDL attempted');
  END IF;
  SELECT COUNT(*) INTO v_wrong_types FROM ALL_TAB_COLUMNS
    WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS'
      AND COLUMN_NAME IN ('GEO_ENTITY_ID','LATITUDE','LONGITUDE','COORDINATE_REFERENCE_SYSTEM_CODE','LOCATION_DESCRIPTION_FA','LOCATION_DESCRIPTION_EN','ADDRESS_TYPE_CODE','MAIN_STREET_FA','MAIN_STREET_EN','SECONDARY_STREET_FA','SECONDARY_STREET_EN','SQUARE_CROSSROAD_FA','SQUARE_CROSSROAD_EN','BUILDING_NO','POSTAL_CODE','ADDRESS_FA','ADDRESS_EN','ADDITIONAL_ADDRESS_FA','ADDITIONAL_ADDRESS_EN','LEGACY_POSTAL_ADDRESS_ID','RELOCATION_REASON_CODE','DECISION_REFERENCE','DECISION_DATE','LEGACY_BACKFILL_FLAG','LEGACY_BACKFILLED_AT','ROW_VERSION')
      AND NOT (
       (COLUMN_NAME='GEO_ENTITY_ID' AND DATA_TYPE='NUMBER' AND DATA_PRECISION=8 AND NVL(DATA_SCALE,0)=0)
       OR (COLUMN_NAME='LATITUDE' AND DATA_TYPE='NUMBER' AND DATA_PRECISION=10 AND NVL(DATA_SCALE,0)=7)
       OR (COLUMN_NAME='LONGITUDE' AND DATA_TYPE='NUMBER' AND DATA_PRECISION=10 AND NVL(DATA_SCALE,0)=7)
       OR (COLUMN_NAME='COORDINATE_REFERENCE_SYSTEM_CODE' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=20)
       OR (COLUMN_NAME='LOCATION_DESCRIPTION_FA' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=500)
       OR (COLUMN_NAME='LOCATION_DESCRIPTION_EN' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=500)
       OR (COLUMN_NAME='ADDRESS_TYPE_CODE' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=30)
       OR (COLUMN_NAME='MAIN_STREET_FA' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=300)
       OR (COLUMN_NAME='MAIN_STREET_EN' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=300)
       OR (COLUMN_NAME='SECONDARY_STREET_FA' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=300)
       OR (COLUMN_NAME='SECONDARY_STREET_EN' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=300)
       OR (COLUMN_NAME='SQUARE_CROSSROAD_FA' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=300)
       OR (COLUMN_NAME='SQUARE_CROSSROAD_EN' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=300)
       OR (COLUMN_NAME='BUILDING_NO' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=30)
       OR (COLUMN_NAME='POSTAL_CODE' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=20)
       OR (COLUMN_NAME='ADDRESS_FA' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=1000)
       OR (COLUMN_NAME='ADDRESS_EN' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=1000)
       OR (COLUMN_NAME='ADDITIONAL_ADDRESS_FA' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=500)
       OR (COLUMN_NAME='ADDITIONAL_ADDRESS_EN' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=500)
       OR (COLUMN_NAME='LEGACY_POSTAL_ADDRESS_ID' AND DATA_TYPE='NUMBER' AND DATA_PRECISION=8 AND NVL(DATA_SCALE,0)=0)
       OR (COLUMN_NAME='RELOCATION_REASON_CODE' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=50)
       OR (COLUMN_NAME='DECISION_REFERENCE' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=160)
       OR (COLUMN_NAME='DECISION_DATE' AND DATA_TYPE='DATE')
       OR (COLUMN_NAME='LEGACY_BACKFILL_FLAG' AND DATA_TYPE='NUMBER' AND DATA_PRECISION=1 AND NVL(DATA_SCALE,0)=0 AND NULLABLE='N')
       OR (COLUMN_NAME='LEGACY_BACKFILLED_AT' AND DATA_TYPE='TIMESTAMP(6) WITH TIME ZONE')
       OR (COLUMN_NAME='ROW_VERSION' AND DATA_TYPE='NUMBER' AND DATA_PRECISION=10 AND NVL(DATA_SCALE,0)=0 AND NULLABLE='N')
      );
  IF v_wrong_types<>0 THEN
    RAISE_APPLICATION_ERROR(-20804,'R1 staged column physical type/length mismatch. Stop and review the schema.');
  END IF;
  IF v_existing=26 THEN
    DBMS_OUTPUT.PUT_LINE('R1_ALREADY_STAGED. No DDL; verify types before applying data migration.');
    RETURN;
  END IF;
  IF v_mode='NO' THEN
    DBMS_OUTPUT.PUT_LINE('R1_ADD_COLUMNS_PREVIEW_ONLY. No DDL/DML.');
    RETURN;
  END IF;
  EXECUTE IMMEDIATE q'~ALTER TABLE ORG.ORGANIZATION_UNIT_LOCATIONS ADD (
          GEO_ENTITY_ID NUMBER(8,0),
          LATITUDE NUMBER(10,7),
          LONGITUDE NUMBER(10,7),
          COORDINATE_REFERENCE_SYSTEM_CODE VARCHAR2(20 CHAR),
          LOCATION_DESCRIPTION_FA VARCHAR2(500 CHAR),
          LOCATION_DESCRIPTION_EN VARCHAR2(500 CHAR),
          ADDRESS_TYPE_CODE VARCHAR2(30 CHAR),
          MAIN_STREET_FA VARCHAR2(300 CHAR),
          MAIN_STREET_EN VARCHAR2(300 CHAR),
          SECONDARY_STREET_FA VARCHAR2(300 CHAR),
          SECONDARY_STREET_EN VARCHAR2(300 CHAR),
          SQUARE_CROSSROAD_FA VARCHAR2(300 CHAR),
          SQUARE_CROSSROAD_EN VARCHAR2(300 CHAR),
          BUILDING_NO VARCHAR2(30 CHAR),
          POSTAL_CODE VARCHAR2(20 CHAR),
          ADDRESS_FA VARCHAR2(1000 CHAR),
          ADDRESS_EN VARCHAR2(1000 CHAR),
          ADDITIONAL_ADDRESS_FA VARCHAR2(500 CHAR),
          ADDITIONAL_ADDRESS_EN VARCHAR2(500 CHAR),
          LEGACY_POSTAL_ADDRESS_ID NUMBER(8,0),
          RELOCATION_REASON_CODE VARCHAR2(50 CHAR),
          DECISION_REFERENCE VARCHAR2(160 CHAR),
          DECISION_DATE DATE,
          LEGACY_BACKFILL_FLAG NUMBER(1,0) DEFAULT 0 NOT NULL,
          LEGACY_BACKFILLED_AT TIMESTAMP(6) WITH TIME ZONE,
          ROW_VERSION NUMBER(10,0) DEFAULT 0 NOT NULL
  )~';
  DBMS_OUTPUT.PUT_LINE('R1_ADD_COLUMNS_APPLIED. LEGACY ROWS AND LINKS REMAIN INTACT.');
END;
