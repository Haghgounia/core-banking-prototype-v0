-- Phase R1: copies historical originals into additive columns of SAME unit-location row.
-- Does NOT INSERT new rows, modify LOCATION_ID, ORG.LOCATIONS, ORG.POSTAL_ADDRESSES,
-- ORG.ORGANIZATION_UNITS, GEO or SERVICE_POINTS. No automatic COMMIT.
-- NO conflicts allowed: if any linked location has >1 postal address, STOP EVERYTHING.
-- Run in SQL Developer using F5. If YES succeeds, VERIFY in SAME CONNECTION before
-- manual COMMIT, or ROLLBACK in same connection. Never use SQL Developer auto-commit.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET VERIFY OFF
SET AUTOCOMMIT OFF
DEFINE APPLY_CHANGES = NO
PROMPT === R1 BACKFILL: DEFAULT PREVIEW. APPLY ONLY AFTER REVIEWING 01 AND 02 ===
DECLARE
  v_mode VARCHAR2(3) := UPPER(TRIM('&&APPLY_CHANGES'));
  v_column_count NUMBER;
  v_wrong_types NUMBER;
  v_table_count NUMBER;
  v_ambiguous NUMBER;
  v_orphan NUMBER;
  v_conflict NUMBER;
  v_pending NUMBER;
  v_active_triggers NUMBER;
  v_updated NUMBER;
BEGIN
  IF v_mode NOT IN ('NO','YES') THEN RAISE_APPLICATION_ERROR(-20811,'APPLY_CHANGES must be NO or YES'); END IF;
  SELECT COUNT(*) INTO v_table_count FROM ALL_TABLES
    WHERE OWNER='ORG' AND TABLE_NAME IN ('LOCATIONS','POSTAL_ADDRESSES','ORGANIZATION_UNIT_LOCATIONS');
  IF v_table_count<>3 THEN RAISE_APPLICATION_ERROR(-20812,'Required original tables not visible'); END IF;
  SELECT COUNT(*) INTO v_column_count FROM ALL_TAB_COLUMNS
    WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS'
      AND COLUMN_NAME IN ('GEO_ENTITY_ID','LATITUDE','LONGITUDE','COORDINATE_REFERENCE_SYSTEM_CODE','LOCATION_DESCRIPTION_FA','LOCATION_DESCRIPTION_EN','ADDRESS_TYPE_CODE','MAIN_STREET_FA','MAIN_STREET_EN','SECONDARY_STREET_FA','SECONDARY_STREET_EN','SQUARE_CROSSROAD_FA','SQUARE_CROSSROAD_EN','BUILDING_NO','POSTAL_CODE','ADDRESS_FA','ADDRESS_EN','ADDITIONAL_ADDRESS_FA','ADDITIONAL_ADDRESS_EN','LEGACY_POSTAL_ADDRESS_ID','RELOCATION_REASON_CODE','DECISION_REFERENCE','DECISION_DATE','LEGACY_BACKFILL_FLAG','LEGACY_BACKFILLED_AT','ROW_VERSION');
  DBMS_OUTPUT.PUT_LINE('R1_STAGED_COLUMNS='||v_column_count||'/26');
  IF v_column_count<>26 THEN
    DBMS_OUTPUT.PUT_LINE('BLOCKED: Apply 02 only after DBA review.');
    RETURN;
  END IF;
  SELECT COUNT(*) INTO v_wrong_types FROM ALL_TAB_COLUMNS
    WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS'
      AND COLUMN_NAME IN ('GEO_ENTITY_ID','LATITUDE','LONGITUDE','COORDINATE_REFERENCE_SYSTEM_CODE','LOCATION_DESCRIPTION_FA','LOCATION_DESCRIPTION_EN','ADDRESS_TYPE_CODE','MAIN_STREET_FA','MAIN_STREET_EN','SECONDARY_STREET_FA','SECONDARY_STREET_EN','SQUARE_CROSSROAD_FA','SQUARE_CROSSROAD_EN','BUILDING_NO','POSTAL_CODE','ADDRESS_FA','ADDRESS_EN','ADDITIONAL_ADDRESS_FA','ADDITIONAL_ADDRESS_EN','LEGACY_POSTAL_ADDRESS_ID','RELOCATION_REASON_CODE','DECISION_REFERENCE','DECISION_DATE','LEGACY_BACKFILL_FLAG','LEGACY_BACKFILLED_AT','ROW_VERSION')
      AND NOT (
       (COLUMN_NAME='GEO_ENTITY_ID' AND DATA_TYPE='NUMBER' AND DATA_PRECISION=8 AND NVL(DATA_SCALE,0)=0)
       OR (COLUMN_NAME='LATITUDE' AND DATA_TYPE='NUMBER' AND DATA_PRECISION=10 AND NVL(DATA_SCALE,0)=7)
       OR (COLUMN_NAME='LONGITUDE' AND DATA_TYPE='NUMBER' AND DATA_PRECISION=10 AND NVL(DATA_SCALE,0)=7)
       OR (COLUMN_NAME='COORDINATE_REFERENCE_SYSTEM_CODE' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=20)
       OR (COLUMN_NAME='LOCATION_DESCRIPTION_FA' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=500)
       OR (COLUMN_NAME='LOCATION_DESCRIPTION_EN' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=500)
       OR (COLUMN_NAME='ADDRESS_TYPE_CODE' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=30)
       OR (COLUMN_NAME='MAIN_STREET_FA' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=300)
       OR (COLUMN_NAME='MAIN_STREET_EN' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=300)
       OR (COLUMN_NAME='SECONDARY_STREET_FA' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=300)
       OR (COLUMN_NAME='SECONDARY_STREET_EN' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=300)
       OR (COLUMN_NAME='SQUARE_CROSSROAD_FA' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=300)
       OR (COLUMN_NAME='SQUARE_CROSSROAD_EN' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=300)
       OR (COLUMN_NAME='BUILDING_NO' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=30)
       OR (COLUMN_NAME='POSTAL_CODE' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=20)
       OR (COLUMN_NAME='ADDRESS_FA' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=1000)
       OR (COLUMN_NAME='ADDRESS_EN' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=1000)
       OR (COLUMN_NAME='ADDITIONAL_ADDRESS_FA' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=500)
       OR (COLUMN_NAME='ADDITIONAL_ADDRESS_EN' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=500)
       OR (COLUMN_NAME='LEGACY_POSTAL_ADDRESS_ID' AND DATA_TYPE='NUMBER' AND DATA_PRECISION=8 AND NVL(DATA_SCALE,0)=0)
       OR (COLUMN_NAME='RELOCATION_REASON_CODE' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=50)
       OR (COLUMN_NAME='DECISION_REFERENCE' AND DATA_TYPE='VARCHAR2' AND CHAR_USED='C' AND CHAR_LENGTH=160)
       OR (COLUMN_NAME='DECISION_DATE' AND DATA_TYPE='DATE')
       OR (COLUMN_NAME='LEGACY_BACKFILL_FLAG' AND DATA_TYPE='NUMBER' AND DATA_PRECISION=1 AND NVL(DATA_SCALE,0)=0 AND NULLABLE='N')
       OR (COLUMN_NAME='LEGACY_BACKFILLED_AT' AND DATA_TYPE='TIMESTAMP(6) WITH TIME ZONE')
       OR (COLUMN_NAME='ROW_VERSION' AND DATA_TYPE='NUMBER' AND DATA_PRECISION=10 AND NVL(DATA_SCALE,0)=0 AND NULLABLE='N')
      );
  IF v_wrong_types<>0 THEN
    RAISE_APPLICATION_ERROR(-20814,'R1 staged column physical type/length mismatch. Stop and review the schema.');
  END IF;
  SELECT COUNT(*) INTO v_ambiguous FROM ORG.ORGANIZATION_UNIT_LOCATIONS UL
    WHERE (SELECT COUNT(*) FROM ORG.POSTAL_ADDRESSES P
           WHERE P.LOCATION_ID=UL.LOCATION_ID)>1;
  SELECT COUNT(*) INTO v_orphan FROM ORG.ORGANIZATION_UNIT_LOCATIONS UL
    WHERE NOT EXISTS (SELECT 1 FROM ORG.LOCATIONS L WHERE L.LOCATION_ID=UL.LOCATION_ID);
  EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM ORG.ORGANIZATION_UNIT_LOCATIONS
    WHERE LEGACY_BACKFILL_FLAG=0' INTO v_pending;
  -- A previously edited/consolidated row MUST NOT be overwritten by an old snapshot.
  EXECUTE IMMEDIATE q'~SELECT COUNT(*) FROM ORG.ORGANIZATION_UNIT_LOCATIONS UL
    WHERE UL.LEGACY_BACKFILL_FLAG=0 AND (UL.GEO_ENTITY_ID IS NOT NULL OR UL.LATITUDE IS NOT NULL OR UL.LONGITUDE IS NOT NULL OR UL.COORDINATE_REFERENCE_SYSTEM_CODE IS NOT NULL OR UL.LOCATION_DESCRIPTION_FA IS NOT NULL OR UL.LOCATION_DESCRIPTION_EN IS NOT NULL OR UL.ADDRESS_TYPE_CODE IS NOT NULL OR UL.MAIN_STREET_FA IS NOT NULL OR UL.MAIN_STREET_EN IS NOT NULL OR UL.SECONDARY_STREET_FA IS NOT NULL OR UL.SECONDARY_STREET_EN IS NOT NULL OR UL.SQUARE_CROSSROAD_FA IS NOT NULL OR UL.SQUARE_CROSSROAD_EN IS NOT NULL OR UL.BUILDING_NO IS NOT NULL OR UL.POSTAL_CODE IS NOT NULL OR UL.ADDRESS_FA IS NOT NULL OR UL.ADDRESS_EN IS NOT NULL OR UL.ADDITIONAL_ADDRESS_FA IS NOT NULL OR UL.ADDITIONAL_ADDRESS_EN IS NOT NULL OR UL.LEGACY_POSTAL_ADDRESS_ID IS NOT NULL)~' INTO v_conflict;
  SELECT COUNT(*) INTO v_active_triggers FROM ALL_TRIGGERS
    WHERE TABLE_OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS' AND STATUS='ENABLED';
  DBMS_OUTPUT.PUT_LINE('TARGET_ENABLED_TRIGGERS='||v_active_triggers);
  DBMS_OUTPUT.PUT_LINE('AMBIGUOUS_ASSOCIATIONS='||v_ambiguous);
  DBMS_OUTPUT.PUT_LINE('ORPHAN_ASSOCIATIONS='||v_orphan);
  DBMS_OUTPUT.PUT_LINE('UNMIGRATED_ROWS='||v_pending);
  DBMS_OUTPUT.PUT_LINE('EXISTING_NEW_FIELD_CONTENT_ON_UNMIGRATED_ROWS='||v_conflict);
  IF v_mode='NO' THEN
    DBMS_OUTPUT.PUT_LINE('R1_BACKFILL_PREVIEW_ONLY. NO DML.');
    IF v_ambiguous+v_orphan+v_conflict+v_active_triggers>0 THEN
      DBMS_OUTPUT.PUT_LINE('R1_BACKFILL_BLOCKED_BY_DATA_REVIEW. NO AUTO ADDRESS SELECTION.');
    END IF;
    RETURN;
  END IF;
  IF v_ambiguous+v_orphan+v_conflict+v_active_triggers>0 THEN
    RAISE_APPLICATION_ERROR(-20813,'DATA BLOCKERS. Manual review before ANY backfill; zero rows updated.');
  END IF;
  SAVEPOINT ORG_UNIT_LOCATION_R1_BACKFILL;
  BEGIN
    EXECUTE IMMEDIATE q'~MERGE INTO ORG.ORGANIZATION_UNIT_LOCATIONS DST
    USING (
      SELECT UL.ORGANIZATION_UNIT_LOCATION_ID AS UNIT_LOCATION_PK,
             UL.LOCATION_ID AS SOURCE_LOCATION_ID,
             L.GEO_ENTITY_ID AS GEO_ENTITY_ID,
             L.LATITUDE AS LATITUDE,
             L.LONGITUDE AS LONGITUDE,
             L.COORDINATE_REFERENCE_SYSTEM_CODE AS COORDINATE_REFERENCE_SYSTEM_CODE,
             L.DESCRIPTION_FA AS LOCATION_DESCRIPTION_FA,
             L.DESCRIPTION_EN AS LOCATION_DESCRIPTION_EN,
             P.ADDRESS_TYPE_CODE AS ADDRESS_TYPE_CODE,
             P.MAIN_STREET_FA AS MAIN_STREET_FA,
             P.MAIN_STREET_EN AS MAIN_STREET_EN,
             P.SECONDARY_STREET_FA AS SECONDARY_STREET_FA,
             P.SECONDARY_STREET_EN AS SECONDARY_STREET_EN,
             P.SQUARE_CROSSROAD_FA AS SQUARE_CROSSROAD_FA,
             P.SQUARE_CROSSROAD_EN AS SQUARE_CROSSROAD_EN,
             P.BUILDING_NO AS BUILDING_NO,
             P.POSTAL_CODE AS POSTAL_CODE,
             P.ADDRESS_FA AS ADDRESS_FA,
             P.ADDRESS_EN AS ADDRESS_EN,
             P.ADDITIONAL_ADDRESS_FA AS ADDITIONAL_ADDRESS_FA,
             P.ADDITIONAL_ADDRESS_EN AS ADDITIONAL_ADDRESS_EN,
             P.POSTAL_ADDRESS_ID AS LEGACY_POSTAL_ADDRESS_ID
        FROM ORG.ORGANIZATION_UNIT_LOCATIONS UL
        JOIN ORG.LOCATIONS L ON L.LOCATION_ID=UL.LOCATION_ID
        LEFT JOIN ORG.POSTAL_ADDRESSES P ON P.LOCATION_ID=UL.LOCATION_ID
    ) SRC ON (DST.ORGANIZATION_UNIT_LOCATION_ID=SRC.UNIT_LOCATION_PK)
    WHEN MATCHED THEN UPDATE SET
         DST.GEO_ENTITY_ID = SRC.GEO_ENTITY_ID,
         DST.LATITUDE = SRC.LATITUDE,
         DST.LONGITUDE = SRC.LONGITUDE,
         DST.COORDINATE_REFERENCE_SYSTEM_CODE = SRC.COORDINATE_REFERENCE_SYSTEM_CODE,
         DST.LOCATION_DESCRIPTION_FA = SRC.LOCATION_DESCRIPTION_FA,
         DST.LOCATION_DESCRIPTION_EN = SRC.LOCATION_DESCRIPTION_EN,
         DST.ADDRESS_TYPE_CODE = SRC.ADDRESS_TYPE_CODE,
         DST.MAIN_STREET_FA = SRC.MAIN_STREET_FA,
         DST.MAIN_STREET_EN = SRC.MAIN_STREET_EN,
         DST.SECONDARY_STREET_FA = SRC.SECONDARY_STREET_FA,
         DST.SECONDARY_STREET_EN = SRC.SECONDARY_STREET_EN,
         DST.SQUARE_CROSSROAD_FA = SRC.SQUARE_CROSSROAD_FA,
         DST.SQUARE_CROSSROAD_EN = SRC.SQUARE_CROSSROAD_EN,
         DST.BUILDING_NO = SRC.BUILDING_NO,
         DST.POSTAL_CODE = SRC.POSTAL_CODE,
         DST.ADDRESS_FA = SRC.ADDRESS_FA,
         DST.ADDRESS_EN = SRC.ADDRESS_EN,
         DST.ADDITIONAL_ADDRESS_FA = SRC.ADDITIONAL_ADDRESS_FA,
         DST.ADDITIONAL_ADDRESS_EN = SRC.ADDITIONAL_ADDRESS_EN,
         DST.LEGACY_POSTAL_ADDRESS_ID = SRC.LEGACY_POSTAL_ADDRESS_ID,
         DST.LEGACY_BACKFILL_FLAG = 1,
         DST.LEGACY_BACKFILLED_AT = SYSTIMESTAMP
      WHERE DST.LEGACY_BACKFILL_FLAG=0~';
    v_updated:=SQL%ROWCOUNT;
    DBMS_OUTPUT.PUT_LINE('R1_BACKFILL_PENDING_SUCCESS: UPDATED_ROWS='||v_updated);
    DBMS_OUTPUT.PUT_LINE('NO AUTO COMMIT. VERIFY IN SAME CONNECTION; THEN COMMIT OR ROLLBACK.');
  EXCEPTION WHEN OTHERS THEN
    ROLLBACK TO ORG_UNIT_LOCATION_R1_BACKFILL;
    RAISE;
  END;
END;
