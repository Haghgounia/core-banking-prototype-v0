PROMPT === R1 ORG UNIT LOCATION LEGACY BASELINE: EXACT COUNTS ===
SELECT 'ORGANIZATION_UNITS' source_table, COUNT(*) exact_rows FROM ORG.ORGANIZATION_UNITS
UNION ALL SELECT 'ORGANIZATION_UNIT_LOCATIONS', COUNT(*) FROM ORG.ORGANIZATION_UNIT_LOCATIONS
UNION ALL SELECT 'LOCATIONS', COUNT(*) FROM ORG.LOCATIONS
UNION ALL SELECT 'POSTAL_ADDRESSES', COUNT(*) FROM ORG.POSTAL_ADDRESSES
UNION ALL SELECT 'SERVICE_POINTS', COUNT(*) FROM ORG.SERVICE_POINTS;

PROMPT === R1: EXISTING LINKED ROWS WITH ZERO, ONE, MULTIPLE POSTAL ADDRESSES ===
SELECT CASE WHEN address_count=0 THEN 'NO_ADDRESS'
            WHEN address_count=1 THEN 'SINGLE_ADDRESS'
            ELSE 'MULTIPLE_ADDRESSES: MANUAL REVIEW' END address_status,
       COUNT(*) assignment_count
  FROM (SELECT UL.ORGANIZATION_UNIT_LOCATION_ID,
              (SELECT COUNT(*) FROM ORG.POSTAL_ADDRESSES P
                WHERE P.LOCATION_ID=UL.LOCATION_ID) address_count
          FROM ORG.ORGANIZATION_UNIT_LOCATIONS UL)
 GROUP BY CASE WHEN address_count=0 THEN 'NO_ADDRESS'
               WHEN address_count=1 THEN 'SINGLE_ADDRESS'
               ELSE 'MULTIPLE_ADDRESSES: MANUAL REVIEW' END
 ORDER BY address_status;

PROMPT === R1: ALL AMBIGUOUS ASSIGNMENTS (DO NOT AUTOPICK AN ADDRESS) ===
SELECT UL.ORGANIZATION_UNIT_LOCATION_ID, UL.ORGANIZATION_UNIT_ID, U.UNIT_CODE,
       UL.LOCATION_ID, COUNT(P.POSTAL_ADDRESS_ID) POSTAL_ADDRESS_COUNT,
       LISTAGG(TO_CHAR(P.POSTAL_ADDRESS_ID), ',') WITHIN GROUP(ORDER BY P.POSTAL_ADDRESS_ID) POSTAL_ADDRESS_IDS
  FROM ORG.ORGANIZATION_UNIT_LOCATIONS UL
  JOIN ORG.ORGANIZATION_UNITS U ON U.ORGANIZATION_UNIT_ID=UL.ORGANIZATION_UNIT_ID
  LEFT JOIN ORG.POSTAL_ADDRESSES P ON P.LOCATION_ID=UL.LOCATION_ID
 GROUP BY UL.ORGANIZATION_UNIT_LOCATION_ID, UL.ORGANIZATION_UNIT_ID, U.UNIT_CODE, UL.LOCATION_ID
HAVING COUNT(P.POSTAL_ADDRESS_ID)>1
 ORDER BY U.UNIT_CODE, UL.ORGANIZATION_UNIT_LOCATION_ID;

PROMPT === R1: LEGACY LOCATION USAGE OUTSIDE UNIT LOCATION; DO NOT DROP LOCATIONS ===
SELECT COUNT(*) POINTS_USING_LOCATIONS FROM ORG.SERVICE_POINTS WHERE LOCATION_ID IS NOT NULL;
SELECT COUNT(*) LOCATIONS_NOT_LINKED_TO_UNITS FROM ORG.LOCATIONS L
 WHERE NOT EXISTS (SELECT 1 FROM ORG.ORGANIZATION_UNIT_LOCATIONS UL WHERE UL.LOCATION_ID=L.LOCATION_ID);
SELECT COUNT(*) POSTAL_ADDRESSES_NOT_LINKED_TO_UNITS FROM ORG.POSTAL_ADDRESSES P
 WHERE NOT EXISTS (SELECT 1 FROM ORG.ORGANIZATION_UNIT_LOCATIONS UL WHERE UL.LOCATION_ID=P.LOCATION_ID);

PROMPT === R1: POSSIBLE CONCURRENT OPEN PRIMARY LOCATIONS (MANUAL DECISION) ===
SELECT UL.ORGANIZATION_UNIT_ID, U.UNIT_CODE, COUNT(*) OPEN_PRIMARY_ROWS
 FROM ORG.ORGANIZATION_UNIT_LOCATIONS UL
 JOIN ORG.ORGANIZATION_UNITS U ON U.ORGANIZATION_UNIT_ID=UL.ORGANIZATION_UNIT_ID
 WHERE UL.LOCATION_ROLE_CODE='PRIMARY' AND UL.EFFECTIVE_TO IS NULL
 GROUP BY UL.ORGANIZATION_UNIT_ID, U.UNIT_CODE
 HAVING COUNT(*)>1 ORDER BY U.UNIT_CODE;

PROMPT === R1: ENABLED TRIGGERS ON TARGET, MUST REVIEW BEFORE DML ===
SELECT OWNER, TRIGGER_NAME, TABLE_OWNER, TABLE_NAME, STATUS FROM ALL_TRIGGERS
 WHERE TABLE_OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS'
 ORDER BY OWNER,TRIGGER_NAME;

PROMPT === R1: CONSTRAINTS THAT REFER TO LOCATIONS OR POSTAL_ADDRESSES ===
SELECT CHILD.OWNER CHILD_OWNER, CHILD.TABLE_NAME CHILD_TABLE, CHILD.CONSTRAINT_NAME,
       PARENT.TABLE_NAME REFERENCED_TABLE
 FROM ALL_CONSTRAINTS PARENT JOIN ALL_CONSTRAINTS CHILD
   ON CHILD.CONSTRAINT_TYPE='R' AND CHILD.R_OWNER=PARENT.OWNER
  AND CHILD.R_CONSTRAINT_NAME=PARENT.CONSTRAINT_NAME
 WHERE PARENT.OWNER='ORG' AND PARENT.TABLE_NAME IN ('LOCATIONS','POSTAL_ADDRESSES','ORGANIZATION_UNIT_LOCATIONS')
 ORDER BY CHILD.OWNER,CHILD.TABLE_NAME,CHILD.CONSTRAINT_NAME;

