SET SERVEROUTPUT ON;
PROMPT === A: CURRENT PLACEMENTS BY CITY / RURAL-DISTRICT GEO_ID MATCH ===
WITH ranked AS (
 SELECT l.ORGANIZATION_UNIT_ID, l.GEO_ENTITY_ID,
        ROW_NUMBER() OVER (PARTITION BY l.ORGANIZATION_UNIT_ID
            ORDER BY CASE WHEN l.LOCATION_ROLE_CODE='PRIMARY' THEN 0 ELSE 1 END,
                     l.EFFECTIVE_FROM DESC NULLS LAST, l.ORGANIZATION_UNIT_LOCATION_ID DESC) rn
   FROM ORG.ORGANIZATION_UNIT_LOCATIONS l
  WHERE (l.EFFECTIVE_FROM IS NULL OR l.EFFECTIVE_FROM <= TRUNC(SYSDATE))
    AND (l.EFFECTIVE_TO IS NULL OR l.EFFECTIVE_TO >= TRUNC(SYSDATE))
), matches AS (
 SELECT l.ORGANIZATION_UNIT_ID,l.GEO_ENTITY_ID,
        c.CITY_ID,r.RURAL_DISTRICT_ID
   FROM ranked l
   LEFT JOIN GEO.CITIES c ON c.CITY_ID=l.GEO_ENTITY_ID AND c.IS_ACTIVE=1
   LEFT JOIN GEO.RURAL_DISTRICTS r ON r.RURAL_DISTRICT_ID=l.GEO_ENTITY_ID AND r.IS_ACTIVE=1
  WHERE l.rn=1
)
SELECT COUNT(*) TOTAL_UNITS,
       SUM(CASE WHEN CITY_ID IS NOT NULL AND RURAL_DISTRICT_ID IS NULL THEN 1 ELSE 0 END) CITY_ONLY,
       SUM(CASE WHEN CITY_ID IS NULL AND RURAL_DISTRICT_ID IS NOT NULL THEN 1 ELSE 0 END) RURAL_ONLY,
       SUM(CASE WHEN CITY_ID IS NOT NULL AND RURAL_DISTRICT_ID IS NOT NULL THEN 1 ELSE 0 END) AMBIGUOUS_ID,
       SUM(CASE WHEN CITY_ID IS NULL AND RURAL_DISTRICT_ID IS NULL THEN 1 ELSE 0 END) UNMATCHED_ID
  FROM matches;

PROMPT === B: SAMPLE GEO ID COLLISIONS - A NUMERIC MATCH DOES NOT PROVE THE TYPE ===
SELECT * FROM (
 SELECT l.ORGANIZATION_UNIT_ID,u.UNIT_CODE,u.NAME_FA AS UNIT_NAME_FA,
        l.GEO_ENTITY_ID,c.CITY_NAME,
        cp.PROVINCE_NAME AS CITY_PROVINCE,
        r.RURAL_DISTRICT_NAME,rp.PROVINCE_NAME AS RURAL_PROVINCE
   FROM ORG.ORGANIZATION_UNIT_LOCATIONS l
   JOIN ORG.ORGANIZATION_UNITS u ON u.ORGANIZATION_UNIT_ID=l.ORGANIZATION_UNIT_ID
   JOIN GEO.CITIES c ON c.CITY_ID=l.GEO_ENTITY_ID AND c.IS_ACTIVE=1
   JOIN GEO.DISTRICTS cd ON cd.DISTRICT_ID=c.DISTRICT_ID
   JOIN GEO.COUNTIES cc ON cc.COUNTY_ID=cd.COUNTY_ID
   JOIN GEO.PROVINCES cp ON cp.PROVINCE_ID=cc.PROVINCE_ID
   JOIN GEO.RURAL_DISTRICTS r ON r.RURAL_DISTRICT_ID=l.GEO_ENTITY_ID AND r.IS_ACTIVE=1
   JOIN GEO.DISTRICTS rd ON rd.DISTRICT_ID=r.DISTRICT_ID
   JOIN GEO.COUNTIES rc ON rc.COUNTY_ID=rd.COUNTY_ID
   JOIN GEO.PROVINCES rp ON rp.PROVINCE_ID=rc.PROVINCE_ID
  WHERE (l.EFFECTIVE_FROM IS NULL OR l.EFFECTIVE_FROM <= TRUNC(SYSDATE))
    AND (l.EFFECTIVE_TO IS NULL OR l.EFFECTIVE_TO >= TRUNC(SYSDATE))
  ORDER BY l.ORGANIZATION_UNIT_ID,l.GEO_ENTITY_ID
) WHERE ROWNUM<=40;

