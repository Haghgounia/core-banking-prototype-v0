PROMPT === 1. CANONICAL UNIT LOCATION CONTRACT (EXPECTED 1 EACH) ===
SELECT 'LOCATION_ID_NULLABLE' AS CHECK_NAME, COUNT(*) AS ACTUAL, 1 AS EXPECTED
  FROM ALL_TAB_COLUMNS WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS'
    AND COLUMN_NAME='LOCATION_ID' AND NULLABLE='Y'
UNION ALL SELECT 'CANONICAL_MANAGED_FLAG', COUNT(*), 1
  FROM ALL_TAB_COLUMNS WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS' AND COLUMN_NAME='CANONICAL_MANAGED_FLAG'
UNION ALL SELECT 'UNIT_PRESENCE_CODE', COUNT(*), 1
  FROM ALL_TAB_COLUMNS WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS' AND COLUMN_NAME='UNIT_PRESENCE_CODE'
UNION ALL SELECT 'ADDRESS_USAGE_CODE', COUNT(*), 1
  FROM ALL_TAB_COLUMNS WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS' AND COLUMN_NAME='ADDRESS_USAGE_CODE'
UNION ALL SELECT 'AUDIT_TABLE', COUNT(*), 1
  FROM ALL_TABLES WHERE OWNER='ORG' AND TABLE_NAME='OU_LOCATION_CHANGE_AUDIT'
UNION ALL SELECT 'AUDIT_SEQUENCE', COUNT(*), 1
  FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER='ORG' AND SEQUENCE_NAME='SEQ_OU_LOCATION_AUDIT'
UNION ALL SELECT 'GEO_TYPE_CHECK', COUNT(*), 1
  FROM ALL_CONSTRAINTS WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS'
    AND CONSTRAINT_NAME='CK_OUL_R2D_GEO_TYPE' AND CONSTRAINT_TYPE='C' AND STATUS='ENABLED'
ORDER BY CHECK_NAME;
PROMPT === 2. FK TO LEGACY LOCATIONS (EXPECTED 0 FOR UNIT LOCATION ONLY) ===
SELECT C.TABLE_NAME AS CHILD_TABLE,C.CONSTRAINT_NAME,C.STATUS,
       P.TABLE_NAME AS PARENT_TABLE
  FROM ALL_CONSTRAINTS C JOIN ALL_CONSTRAINTS P
    ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
 WHERE C.OWNER='ORG' AND C.TABLE_NAME IN ('ORGANIZATION_UNIT_LOCATIONS','POSTAL_ADDRESSES','SERVICE_POINTS')
   AND C.CONSTRAINT_TYPE='R' AND P.OWNER='ORG' AND P.TABLE_NAME='LOCATIONS'
ORDER BY C.TABLE_NAME;
PROMPT === 3. CANONICAL DATA, HISTORICAL LINKAGE AND SERVICE POINT GATE ===
SELECT COUNT(*) AS UNIT_LOCATION_ROWS,
       NVL(SUM(CASE WHEN LOCATION_ID IS NOT NULL THEN 1 ELSE 0 END),0) AS HISTORICAL_LOCATION_IDS,
       NVL(SUM(CASE WHEN LEGACY_BACKFILL_FLAG=1 THEN 1 ELSE 0 END),0) AS BACKFILLED_ROWS,
       NVL(SUM(CASE WHEN CANONICAL_MANAGED_FLAG=1 THEN 1 ELSE 0 END),0) AS MANAGED_ROWS,
       NVL(SUM(CASE WHEN LOCATION_ID IS NULL THEN 1 ELSE 0 END),0) AS CANONICAL_ONLY_ROWS
  FROM ORG.ORGANIZATION_UNIT_LOCATIONS;
SELECT (SELECT COUNT(*) FROM ORG.SERVICE_POINTS) AS SERVICE_POINT_ROWS,
       (SELECT COUNT(*) FROM ORG.SERVICE_POINTS WHERE LOCATION_ID IS NOT NULL) AS SERVICE_POINT_LEGACY_LINKS,
       (SELECT COUNT(*) FROM ORG.POSTAL_ADDRESSES) AS LEGACY_POSTAL_ROWS,
       (SELECT COUNT(*) FROM ORG.LOCATIONS) AS LEGACY_LOCATION_ROWS
  FROM DUAL;
PROMPT === 4. MANAGED AUDIT COVERAGE ===
SELECT COUNT(*) AS MANAGED_WITHOUT_AUDIT
  FROM ORG.ORGANIZATION_UNIT_LOCATIONS UL
 WHERE UL.CANONICAL_MANAGED_FLAG=1
   AND NOT EXISTS (SELECT 1 FROM ORG.OU_LOCATION_CHANGE_AUDIT A
                   WHERE A.ORGANIZATION_UNIT_LOCATION_ID=UL.ORGANIZATION_UNIT_LOCATION_ID);
