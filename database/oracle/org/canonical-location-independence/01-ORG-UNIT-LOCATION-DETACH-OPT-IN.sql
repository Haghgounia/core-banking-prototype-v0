-- ORG CANONICAL LOCATION INDEPENDENCE 2026-10-31
-- Target: ORG.ORGANIZATION_UNIT_LOCATIONS is the sole operational master for
-- unit location/address. LOCATION_ID remains as OPTIONAL historical identifier.
-- Deliberately does NOT rename/drop/modify ORG.LOCATIONS, ORG.POSTAL_ADDRESSES,
-- ORG.SERVICE_POINTS, or any source rows. No DML. DDL commits implicitly.
-- Run in SQL Developer using F5; default PREVIEW. DBA backup and maintenance window.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET VERIFY OFF
DEFINE APPLY_CHANGES = NO
PROMPT ======================================================================
PROMPT ORG CANONICAL UNIT LOCATION INDEPENDENCE - PREVIEW BY DEFAULT
PROMPT R2B columns/audit plus OPTIONAL historical LOCATION_ID and FK detachment
PROMPT ======================================================================
DECLARE
  v_apply VARCHAR2(3) := UPPER(TRIM('&&APPLY_CHANGES'));
  v_rows_before NUMBER := 0;
  v_rows_after NUMBER := 0;
  v_legacy_rows NUMBER := 0;
  v_unbackfilled NUMBER := 0;
  v_incomplete NUMBER := 0;
  v_missing_location NUMBER := 0;
  v_missing_postal NUMBER := 0;
  v_pos_links NUMBER := 0;
  v_location_nullable NUMBER := 0;
  v_fk_count NUMBER := 0;
  v_named_fk NUMBER := 0;
  v_geo_check NUMBER := 0;
  v_required_cols NUMBER := 0;
  v_audit_table NUMBER := 0;
  v_audit_seq NUMBER := 0;
  v_audit_cols NUMBER := 0;
  v_blockers NUMBER := 0;
  v_changes NUMBER := 0;
  v_verify NUMBER := 0;
  FUNCTION col_count(p_name VARCHAR2) RETURN NUMBER IS
    v_count NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v_count FROM ALL_TAB_COLUMNS
     WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS' AND COLUMN_NAME=p_name;
    RETURN v_count;
  END;
  PROCEDURE run_ddl(p_sql VARCHAR2, p_label VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_sql;
    v_changes := v_changes + 1;
    DBMS_OUTPUT.PUT_LINE('DDL_APPLIED | '||p_label);
  END;
  PROCEDURE add_check(p_name VARCHAR2,p_definition VARCHAR2) IS
    v_count NUMBER;
    v_enabled NUMBER;
  BEGIN
    SELECT COUNT(*),NVL(SUM(CASE WHEN STATUS='ENABLED' THEN 1 ELSE 0 END),0)
      INTO v_count,v_enabled
      FROM ALL_CONSTRAINTS
     WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS' AND CONSTRAINT_NAME=p_name;
    IF v_count=0 THEN
      run_ddl('ALTER TABLE ORG.ORGANIZATION_UNIT_LOCATIONS ADD CONSTRAINT '||p_name||' '||p_definition,p_name);
    ELSIF v_enabled<>1 THEN
      RAISE_APPLICATION_ERROR(-20911,'Existing constraint disabled: '||p_name||'. DBA review required.');
    END IF;
  END;
BEGIN
  IF v_apply NOT IN ('YES','NO') THEN
    RAISE_APPLICATION_ERROR(-20901,'APPLY_CHANGES must be YES or NO');
  END IF;
  SELECT COUNT(*) INTO v_required_cols FROM ALL_TAB_COLUMNS
   WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS'
     AND COLUMN_NAME IN (
       'ORGANIZATION_UNIT_LOCATION_ID','ORGANIZATION_UNIT_ID','LOCATION_ID',
       'LEGACY_POSTAL_ADDRESS_ID','LEGACY_BACKFILL_FLAG','ROW_VERSION',
       'GEO_ENTITY_ID','GEO_ENTITY_TYPE_CODE','ADDRESS_TYPE_CODE',
       'COORDINATE_REFERENCE_SYSTEM_CODE','ADDRESS_FA');
  IF v_required_cols<>11 THEN
    DBMS_OUTPUT.PUT_LINE('BLOCKER | R1 columns missing: '||v_required_cols||'/11');
    RAISE_APPLICATION_ERROR(-20902,'R1 data model incomplete; STOP before any DDL');
  END IF;
  SELECT COUNT(*) INTO v_rows_before FROM ORG.ORGANIZATION_UNIT_LOCATIONS;
  SELECT COUNT(*) INTO v_legacy_rows FROM ORG.ORGANIZATION_UNIT_LOCATIONS WHERE LOCATION_ID IS NOT NULL;
  SELECT COUNT(*) INTO v_unbackfilled FROM ORG.ORGANIZATION_UNIT_LOCATIONS
   WHERE LOCATION_ID IS NOT NULL AND NVL(LEGACY_BACKFILL_FLAG,0)<>1;
  SELECT COUNT(*) INTO v_incomplete FROM ORG.ORGANIZATION_UNIT_LOCATIONS
   WHERE LEGACY_BACKFILL_FLAG=1 AND
        (GEO_ENTITY_ID IS NULL OR COORDINATE_REFERENCE_SYSTEM_CODE IS NULL
         OR (LEGACY_POSTAL_ADDRESS_ID IS NOT NULL AND ADDRESS_TYPE_CODE IS NULL));
  SELECT COUNT(*) INTO v_missing_location FROM ORG.ORGANIZATION_UNIT_LOCATIONS UL
   WHERE UL.LOCATION_ID IS NOT NULL AND NOT EXISTS
     (SELECT 1 FROM ORG.LOCATIONS L WHERE L.LOCATION_ID=UL.LOCATION_ID);
  SELECT COUNT(*) INTO v_missing_postal FROM ORG.ORGANIZATION_UNIT_LOCATIONS UL
   WHERE UL.LEGACY_POSTAL_ADDRESS_ID IS NOT NULL AND NOT EXISTS
     (SELECT 1 FROM ORG.POSTAL_ADDRESSES P
       WHERE P.POSTAL_ADDRESS_ID=UL.LEGACY_POSTAL_ADDRESS_ID);
  SELECT COUNT(*) INTO v_pos_links FROM ORG.SERVICE_POINTS WHERE LOCATION_ID IS NOT NULL;
  SELECT COUNT(*) INTO v_location_nullable FROM ALL_TAB_COLUMNS
   WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS'
     AND COLUMN_NAME='LOCATION_ID' AND NULLABLE='Y';
  SELECT COUNT(*) INTO v_fk_count FROM ALL_CONSTRAINTS C
    JOIN ALL_CONSTRAINTS P ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
   WHERE C.OWNER='ORG' AND C.TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS'
     AND C.CONSTRAINT_TYPE='R' AND P.OWNER='ORG' AND P.TABLE_NAME='LOCATIONS';
  SELECT COUNT(*) INTO v_named_fk FROM ALL_CONSTRAINTS C
    JOIN ALL_CONSTRAINTS P ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
   WHERE C.OWNER='ORG' AND C.TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS'
     AND C.CONSTRAINT_TYPE='R' AND C.CONSTRAINT_NAME='FK_ORGANIZATION_UNIT_LOCATIONS_LOCATION_ID'
     AND P.OWNER='ORG' AND P.TABLE_NAME='LOCATIONS';
  SELECT COUNT(*) INTO v_geo_check FROM ALL_CONSTRAINTS
   WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS'
     AND CONSTRAINT_NAME='CK_OUL_R2D_GEO_TYPE' AND CONSTRAINT_TYPE='C' AND STATUS='ENABLED';
  SELECT COUNT(*) INTO v_audit_table FROM ALL_TABLES
   WHERE OWNER='ORG' AND TABLE_NAME='OU_LOCATION_CHANGE_AUDIT';
  SELECT COUNT(*) INTO v_audit_seq FROM ALL_SEQUENCES
   WHERE SEQUENCE_OWNER='ORG' AND SEQUENCE_NAME='SEQ_OU_LOCATION_AUDIT';
  SELECT COUNT(*) INTO v_audit_cols FROM ALL_TAB_COLUMNS
   WHERE OWNER='ORG' AND TABLE_NAME='OU_LOCATION_CHANGE_AUDIT'
     AND COLUMN_NAME IN ('AUDIT_ID','ORGANIZATION_UNIT_LOCATION_ID','ORGANIZATION_UNIT_ID',
       'ACTION_CODE','OLD_STATE','NEW_STATE','CHANGE_REFERENCE','CHANGED_AT','CHANGED_BY');

  IF v_unbackfilled>0 THEN v_blockers:=v_blockers+1; END IF;
  IF v_incomplete>0 THEN v_blockers:=v_blockers+1; END IF;
  IF v_missing_location>0 THEN v_blockers:=v_blockers+1; END IF;
  IF v_missing_postal>0 THEN v_blockers:=v_blockers+1; END IF;
  IF v_geo_check<>1 THEN v_blockers:=v_blockers+1; END IF;
  IF v_fk_count<>v_named_fk OR v_fk_count>1 THEN v_blockers:=v_blockers+1; END IF;
  IF v_audit_table=1 AND v_audit_cols<>9 THEN v_blockers:=v_blockers+1; END IF;
  IF v_audit_table=1 AND v_audit_seq=0 THEN v_blockers:=v_blockers+1; END IF;

  DBMS_OUTPUT.PUT_LINE('APPLY_CHANGES='||v_apply||' | ROWS='||v_rows_before||' | LEGACY_LINKS='||v_legacy_rows);
  DBMS_OUTPUT.PUT_LINE('DEPENDENCIES | OU_LOCATION_TO_LOCATIONS_FK='||v_fk_count||
    ' | SERVICE_POINT_LEGACY_LINKS='||v_pos_links);
  DBMS_OUTPUT.PUT_LINE('SCHEMA | LOCATION_ID_NULLABLE='||v_location_nullable||
    ' | CANONICAL_MANAGED_FLAG='||col_count('CANONICAL_MANAGED_FLAG')||
    ' | UNIT_PRESENCE_CODE='||col_count('UNIT_PRESENCE_CODE')||
    ' | ADDRESS_USAGE_CODE='||col_count('ADDRESS_USAGE_CODE')||
    ' | AUDIT_TABLE='||v_audit_table||' | AUDIT_SEQ='||v_audit_seq);
  DBMS_OUTPUT.PUT_LINE('DATA_CHECK | UNBACKFILLED_WITH_LEGACY_ID='||v_unbackfilled||
    ' | INCOMPLETE_SNAPSHOT='||v_incomplete||
    ' | MISSING_LEGACY_LOCATION='||v_missing_location||
    ' | MISSING_LEGACY_POSTAL='||v_missing_postal);
  DBMS_OUTPUT.PUT_LINE('PRECHECK | BLOCKERS='||v_blockers||
    ' | GEO_CHECK='||v_geo_check||' | FK_NAME_MATCH='||v_named_fk);
  IF v_apply='NO' THEN
    DBMS_OUTPUT.PUT_LINE('ORG_CANONICAL_LOCATION_PREVIEW_COMPLETE | NO DDL | NO DML');
    RETURN;
  END IF;
  IF v_blockers<>0 THEN
    RAISE_APPLICATION_ERROR(-20903,'ORG canonical cutover blocked: review DATA_CHECK and PRECHECK above');
  END IF;

  IF v_location_nullable=0 THEN
    run_ddl('ALTER TABLE ORG.ORGANIZATION_UNIT_LOCATIONS MODIFY (LOCATION_ID NULL)','LOCATION_ID_OPTIONAL_HISTORICAL');
  END IF;
  IF col_count('CANONICAL_MANAGED_FLAG')=0 THEN
    run_ddl('ALTER TABLE ORG.ORGANIZATION_UNIT_LOCATIONS ADD (CANONICAL_MANAGED_FLAG NUMBER(1,0) DEFAULT 0 NOT NULL)','CANONICAL_MANAGED_FLAG');
  END IF;
  IF col_count('UNIT_PRESENCE_CODE')=0 THEN
    run_ddl('ALTER TABLE ORG.ORGANIZATION_UNIT_LOCATIONS ADD (UNIT_PRESENCE_CODE VARCHAR2(20 CHAR))','UNIT_PRESENCE_CODE');
  END IF;
  IF col_count('ADDRESS_USAGE_CODE')=0 THEN
    run_ddl('ALTER TABLE ORG.ORGANIZATION_UNIT_LOCATIONS ADD (ADDRESS_USAGE_CODE VARCHAR2(20 CHAR))','ADDRESS_USAGE_CODE');
  END IF;
  add_check('CK_OUL_R2B_MANAGED','CHECK (CANONICAL_MANAGED_FLAG IN (0,1))');
  add_check('CK_OUL_R2B_PRESENCE','CHECK (UNIT_PRESENCE_CODE IN (''PHYSICAL'',''VIRTUAL''))');
  add_check('CK_OUL_R2B_USAGE','CHECK (ADDRESS_USAGE_CODE IN (''PHYSICAL'',''REFERENCE''))');
  IF v_audit_seq=0 THEN
    run_ddl('CREATE SEQUENCE ORG.SEQ_OU_LOCATION_AUDIT START WITH 1 INCREMENT BY 1 CACHE 20 NOCYCLE','SEQ_OU_LOCATION_AUDIT');
  END IF;
  IF v_audit_table=0 THEN
    run_ddl(q'~CREATE TABLE ORG.OU_LOCATION_CHANGE_AUDIT (
      AUDIT_ID NUMBER(19,0) DEFAULT ORG.SEQ_OU_LOCATION_AUDIT.NEXTVAL NOT NULL,
      ORGANIZATION_UNIT_LOCATION_ID NUMBER(8,0) NOT NULL,
      ORGANIZATION_UNIT_ID NUMBER(8,0) NOT NULL,
      ACTION_CODE VARCHAR2(12 CHAR) NOT NULL,
      OLD_STATE CLOB,
      NEW_STATE CLOB NOT NULL,
      CHANGE_REFERENCE VARCHAR2(160 CHAR) NOT NULL,
      CHANGED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      CHANGED_BY VARCHAR2(128 CHAR) NOT NULL,
      CONSTRAINT PK_OU_LOCATION_CHANGE_AUDIT PRIMARY KEY (AUDIT_ID),
      CONSTRAINT CK_OU_LOC_AUDIT_ACTION CHECK (ACTION_CODE IN ('CREATE','UPDATE')),
      CONSTRAINT FK_OU_LOC_AUDIT_UNIT_LOCATION FOREIGN KEY (ORGANIZATION_UNIT_LOCATION_ID)
        REFERENCES ORG.ORGANIZATION_UNIT_LOCATIONS(ORGANIZATION_UNIT_LOCATION_ID)
    ) TABLESPACE TS_ORG~','OU_LOCATION_CHANGE_AUDIT');
  END IF;
  IF v_fk_count=1 THEN
    run_ddl('ALTER TABLE ORG.ORGANIZATION_UNIT_LOCATIONS DROP CONSTRAINT FK_ORGANIZATION_UNIT_LOCATIONS_LOCATION_ID',
      'DETACH_HISTORICAL_LOCATION_FK');
  END IF;
  SELECT COUNT(*) INTO v_verify FROM ALL_CONSTRAINTS C
    JOIN ALL_CONSTRAINTS P ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
   WHERE C.OWNER='ORG' AND C.TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS'
     AND C.CONSTRAINT_TYPE='R' AND P.OWNER='ORG' AND P.TABLE_NAME='LOCATIONS';
  SELECT COUNT(*) INTO v_rows_after FROM ORG.ORGANIZATION_UNIT_LOCATIONS;
  IF v_verify<>0 OR v_rows_after<>v_rows_before OR col_count('CANONICAL_MANAGED_FLAG')<>1
     OR col_count('UNIT_PRESENCE_CODE')<>1 OR col_count('ADDRESS_USAGE_CODE')<>1 THEN
    RAISE_APPLICATION_ERROR(-20904,'Post DDL verification failed. DDL cannot be rolled back; DBA review required');
  END IF;
  DBMS_OUTPUT.PUT_LINE('POST_VERIFY | OU_LOCATION_LEGACY_FK='||v_verify||
    ' | SOURCE_ROWS_BEFORE='||v_rows_before||' | SOURCE_ROWS_AFTER='||v_rows_after);
  DBMS_OUTPUT.PUT_LINE('ORG_CANONICAL_LOCATION_DETACH_PASS | DDL_COUNT='||v_changes||
    ' | NO DML | HISTORICAL IDS PRESERVED | SERVICE_POINTS_UNCHANGED');
END;
