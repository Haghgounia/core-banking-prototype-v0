SELECT C.TABLE_NAME AS CHILD_TABLE,C.CONSTRAINT_NAME,C.STATUS,
       P.TABLE_NAME AS REFERENCED_TABLE
  FROM ALL_CONSTRAINTS C JOIN ALL_CONSTRAINTS P
    ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
 WHERE C.OWNER='ORG' AND C.TABLE_NAME IN ('ORGANIZATION_UNIT_LOCATIONS','SERVICE_POINTS','POSTAL_ADDRESSES')
   AND C.CONSTRAINT_TYPE='R' AND P.OWNER='ORG' AND P.TABLE_NAME='LOCATIONS'
 ORDER BY C.TABLE_NAME,C.CONSTRAINT_NAME;
