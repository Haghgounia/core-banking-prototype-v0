-- Read-only, no contact values or DDL/DML; safe UAT coverage summary.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET VERIFY OFF
PROMPT === REGISTERED UNIT CONTACTS BY UNIT TYPE ===
SELECT t.TYPE_CODE, t.NAME_FA, COUNT(DISTINCT u.ORGANIZATION_UNIT_ID) ALL_UNITS,
       COUNT(DISTINCT a.ORGANIZATION_UNIT_ID) UNITS_WITH_REGISTERED_CONTACT,
       COUNT(a.ORGANIZATION_UNIT_CONTACT_POINT_ID) CONTACT_ASSIGNMENTS
  FROM ORG.ORGANIZATION_UNIT_TYPES t
  JOIN ORG.ORGANIZATION_UNITS u ON u.ORGANIZATION_UNIT_TYPE_ID=t.ORGANIZATION_UNIT_TYPE_ID
  LEFT JOIN ORG.ORGANIZATION_UNIT_CONTACT_POINTS a ON a.ORGANIZATION_UNIT_ID=u.ORGANIZATION_UNIT_ID
 GROUP BY t.TYPE_CODE,t.NAME_FA ORDER BY t.TYPE_CODE;
PROMPT === REGISTERED CONTACT COUNTS BY TYPE (NO PHONE VALUES) ===
SELECT m.CONTACT_TYPE_CODE, COUNT(*) REGISTERED_ASSIGNMENTS,
       COUNT(DISTINCT a.ORGANIZATION_UNIT_ID) UNITS_WITH_CONTACT
  FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS a
  JOIN ORG.CONTACT_POINTS m ON m.CONTACT_POINT_ID=a.CONTACT_POINT_ID
 GROUP BY m.CONTACT_TYPE_CODE ORDER BY m.CONTACT_TYPE_CODE;
PROMPT ORG_CONTACT_COVERAGE_READONLY_COMPLETE. NO DDL. NO DML. NO COMMIT.
