-- ORG CONTACT R2: discover where pre-existing branch phone data may live.
-- Read only. No data values are returned. Run using F5 in SQL Developer.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET VERIFY OFF
PROMPT === 01: ORG CONTACTS CURRENT ROW COUNTS (NOT EVIDENCE OF DELETION) ===
SELECT 'ORG.CONTACT_POINTS' AS SOURCE_NAME, COUNT(*) AS EXACT_COUNT FROM ORG.CONTACT_POINTS
UNION ALL
SELECT 'ORG.ORGANIZATION_UNIT_CONTACT_POINTS', COUNT(*) FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS
UNION ALL
SELECT 'ORG.SERVICE_POINT_CONTACT_POINTS', COUNT(*) FROM ORG.SERVICE_POINT_CONTACT_POINTS;
PROMPT === 02: POTENTIAL TELEPHONE/EMAIL COLUMNS ACCESSIBLE TO SESSION ===
SELECT OWNER, TABLE_NAME, COLUMN_NAME, DATA_TYPE
FROM ALL_TAB_COLUMNS
WHERE OWNER NOT IN ('SYS','SYSTEM','XDB','MDSYS','CTXSYS','DBSNMP','OUTLN','ORDSYS','WMSYS','GSMADMIN_INTERNAL')
  AND DATA_TYPE IN ('CHAR','VARCHAR2','NCHAR','NVARCHAR2','CLOB','NCLOB')
  AND REGEXP_LIKE(COLUMN_NAME, '(PHONE|TELEPHONE|TEL_|_TEL|MOBILE|FAX|EMAIL|CONTACT_VALUE|CONTACT_NO|CONTACT_NUMBER)', 'i')
ORDER BY OWNER, TABLE_NAME, COLUMN_NAME;
PROMPT === 03: POSSIBLE BRANCH DATA/STAGING SOURCES (METADATA ONLY) ===
SELECT OWNER, TABLE_NAME
FROM ALL_TABLES
WHERE OWNER NOT IN ('SYS','SYSTEM','XDB','MDSYS','CTXSYS','DBSNMP','OUTLN','ORDSYS','WMSYS','GSMADMIN_INTERNAL')
  AND REGEXP_LIKE(TABLE_NAME, '(BRANCH|MELLAT|STAG|IMPORT|CONTACT|TELEPHONE|PHONE)', 'i')
ORDER BY OWNER, TABLE_NAME;
PROMPT === 04: EXPECTED ORG UNIT PHONE COLUMNS (SCHEMA REVIEW) ===
SELECT COLUMN_NAME, DATA_TYPE FROM ALL_TAB_COLUMNS
 WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNITS'
 ORDER BY COLUMN_ID;
PROMPT ORG_LEGACY_PHONES_DISCOVERY_READONLY_COMPLETE. NO DDL. NO DML. NO COMMIT.
