-- ORG MAP R2-D FINAL ACCEPTANCE (read only). SQL Developer F5. No DDL/DML/COMMIT.
SET SERVEROUTPUT ON SIZE UNLIMITED
DECLARE
  v_branch NUMBER; v_active NUMBER; v_with_place NUMBER; v_with_coords NUMBER;
  v_no_placement NUMBER; v_city_refs NUMBER; v_rural_refs NUMBER; v_untyped_new NUMBER;
  v_mismatched NUMBER; v_city_count NUMBER;
BEGIN
  SELECT COUNT(*),NVL(SUM(CASE WHEN u.STATUS_CODE='ACTIVE' THEN 1 ELSE 0 END),0)
    INTO v_branch,v_active
    FROM ORG.ORGANIZATION_UNITS u JOIN ORG.ORGANIZATION_UNIT_TYPES t
      ON t.ORGANIZATION_UNIT_TYPE_ID=u.ORGANIZATION_UNIT_TYPE_ID
   WHERE t.TYPE_CODE='BRANCH';
  SELECT COUNT(*),NVL(SUM(CASE WHEN l.LATITUDE BETWEEN 24 AND 41
                             AND l.LONGITUDE BETWEEN 44 AND 64 THEN 1 ELSE 0 END),0),
         NVL(SUM(CASE WHEN l.GEO_ENTITY_TYPE_CODE='RURAL_DISTRICT' THEN 1 ELSE 0 END),0),
         NVL(SUM(CASE WHEN l.GEO_ENTITY_TYPE_CODE IS NULL AND NVL(l.LEGACY_BACKFILL_FLAG,0)<>1
                       THEN 1 ELSE 0 END),0)
    INTO v_with_place,v_with_coords,v_rural_refs,v_untyped_new
    FROM ORG.ORGANIZATION_UNIT_LOCATIONS l
    JOIN ORG.ORGANIZATION_UNITS u ON u.ORGANIZATION_UNIT_ID=l.ORGANIZATION_UNIT_ID
    JOIN ORG.ORGANIZATION_UNIT_TYPES t ON t.ORGANIZATION_UNIT_TYPE_ID=u.ORGANIZATION_UNIT_TYPE_ID
   WHERE t.TYPE_CODE='BRANCH' AND u.STATUS_CODE='ACTIVE'
     AND (l.EFFECTIVE_FROM IS NULL OR l.EFFECTIVE_FROM <= TRUNC(SYSDATE))
     AND (l.EFFECTIVE_TO IS NULL OR l.EFFECTIVE_TO >= TRUNC(SYSDATE));
  SELECT COUNT(*) INTO v_city_refs
    FROM ORG.ORGANIZATION_UNIT_LOCATIONS l
   WHERE l.GEO_ENTITY_ID IS NOT NULL
     AND (l.GEO_ENTITY_TYPE_CODE='CITY'
          OR (l.GEO_ENTITY_TYPE_CODE IS NULL AND l.LEGACY_BACKFILL_FLAG=1));
  SELECT COUNT(*) INTO v_mismatched
    FROM ORG.ORGANIZATION_UNIT_LOCATIONS l
   WHERE l.GEO_ENTITY_ID IS NOT NULL
     AND ((l.GEO_ENTITY_TYPE_CODE='CITY' OR
            (l.GEO_ENTITY_TYPE_CODE IS NULL AND l.LEGACY_BACKFILL_FLAG=1))
          AND NOT EXISTS(SELECT 1 FROM GEO.CITIES c
                          WHERE c.CITY_ID=l.GEO_ENTITY_ID AND c.IS_ACTIVE=1)
          OR l.GEO_ENTITY_TYPE_CODE='RURAL_DISTRICT' AND NOT EXISTS(
              SELECT 1 FROM GEO.RURAL_DISTRICTS r
               WHERE r.RURAL_DISTRICT_ID=l.GEO_ENTITY_ID AND r.IS_ACTIVE=1));
  SELECT COUNT(DISTINCT c.CITY_ID) INTO v_city_count
    FROM ORG.ORGANIZATION_UNIT_LOCATIONS l
    JOIN ORG.ORGANIZATION_UNITS u ON u.ORGANIZATION_UNIT_ID=l.ORGANIZATION_UNIT_ID
    JOIN ORG.ORGANIZATION_UNIT_TYPES t ON t.ORGANIZATION_UNIT_TYPE_ID=u.ORGANIZATION_UNIT_TYPE_ID
    JOIN GEO.CITIES c ON c.CITY_ID=l.GEO_ENTITY_ID AND c.IS_ACTIVE=1
   WHERE t.TYPE_CODE='BRANCH' AND u.STATUS_CODE='ACTIVE'
     AND (l.GEO_ENTITY_TYPE_CODE='CITY'
          OR (l.GEO_ENTITY_TYPE_CODE IS NULL AND l.LEGACY_BACKFILL_FLAG=1))
     AND (l.EFFECTIVE_FROM IS NULL OR l.EFFECTIVE_FROM <= TRUNC(SYSDATE))
     AND (l.EFFECTIVE_TO IS NULL OR l.EFFECTIVE_TO >= TRUNC(SYSDATE));
  v_no_placement:=v_branch-v_with_place;
  DBMS_OUTPUT.PUT_LINE('ALL_BRANCHES='||v_branch||'; ACTIVE_BRANCHES='||v_active);
  DBMS_OUTPUT.PUT_LINE('ACTIVE_PLACEMENT_ROWS='||v_with_place||'; VALID_IRAN_COORDINATES='||v_with_coords);
  DBMS_OUTPUT.PUT_LINE('BRANCHES_WITHOUT_PLACEMENT_APPROX='||v_no_placement||' (all statuses; assess duplicates if any)');
  DBMS_OUTPUT.PUT_LINE('CITY_TECH_REFERENCES_ALL_TYPES='||v_city_refs||'; EXPLICIT_RURAL_BRANCH_ROWS='||v_rural_refs);
  DBMS_OUTPUT.PUT_LINE('CITY_LEVELS_WITH_ACTIVE_BRANCHES='||v_city_count);
  DBMS_OUTPUT.PUT_LINE('UNCLASSIFIED_NEW_ACTIVE_BRANCH_PLACEMENTS='||v_untyped_new||'; INVALID_TYPED_GEO_REFERENCES='||v_mismatched);
  IF v_mismatched>0 OR v_untyped_new>0 THEN
    RAISE_APPLICATION_ERROR(-20898,'GEO type closure has unresolved rows. Review without modifying reference IDs.');
  END IF;
  DBMS_OUTPUT.PUT_LINE('ORG_MAP_R2D_DATA_ACCEPTANCE_PASS. NO DDL. NO DML. NO COMMIT.');
END;
