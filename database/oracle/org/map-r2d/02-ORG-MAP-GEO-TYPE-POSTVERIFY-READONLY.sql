-- R2-D post-install verification. SQL Developer F5. Never modifies data.
SET SERVEROUTPUT ON SIZE UNLIMITED
DECLARE
  v_col NUMBER; v_ck NUMBER; v_rows NUMBER; v_legacy NUMBER; v_unmatched NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_col FROM ALL_TAB_COLUMNS
   WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS' AND COLUMN_NAME='GEO_ENTITY_TYPE_CODE';
  SELECT COUNT(*) INTO v_ck FROM ALL_CONSTRAINTS
   WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS'
     AND CONSTRAINT_NAME='CK_OUL_R2D_GEO_TYPE' AND STATUS='ENABLED';
  SELECT COUNT(*) INTO v_rows FROM ORG.ORGANIZATION_UNIT_LOCATIONS;
  SELECT COUNT(*) INTO v_legacy FROM ORG.ORGANIZATION_UNIT_LOCATIONS
   WHERE LEGACY_BACKFILL_FLAG=1 AND GEO_ENTITY_ID IS NOT NULL;
  SELECT COUNT(*) INTO v_unmatched FROM ORG.ORGANIZATION_UNIT_LOCATIONS l
   WHERE l.LEGACY_BACKFILL_FLAG=1 AND l.GEO_ENTITY_ID IS NOT NULL
     AND NOT EXISTS(SELECT 1 FROM GEO.CITIES c WHERE c.CITY_ID=l.GEO_ENTITY_ID AND c.IS_ACTIVE=1);
  DBMS_OUTPUT.PUT_LINE('GEO_TYPE_COLUMN_PRESENT='||v_col||'; GEO_TYPE_CHECK_ENABLED='||v_ck);
  DBMS_OUTPUT.PUT_LINE('LOCATION_ROWS='||v_rows||'; LEGACY_CITY_REFERENCES='||v_legacy||'; UNMATCHED_CITY_REFERENCES='||v_unmatched);
  IF v_col<>1 OR v_ck<>1 OR v_unmatched<>0 THEN
     RAISE_APPLICATION_ERROR(-20895,'ORG MAP GEO TYPE postverify failed; STOP deployment.');
  END IF;
  DBMS_OUTPUT.PUT_LINE('ORG_MAP_R2D_POSTVERIFY_PASS. READONLY.');
END;
/
