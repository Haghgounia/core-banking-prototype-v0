-- ORG map closure R2-D: additive, non-destructive typed GEO reference.
-- SQL Developer F5. DEFAULT NO. YES is DDL with implicit Oracle COMMIT.
-- Does NOT update one of the 1340 existing placements or guess their actual coordinates.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET VERIFY ON
DEFINE APPLY_CHANGES = NO
DECLARE
  v_apply VARCHAR2(3) := UPPER(TRIM('&&APPLY_CHANGES'));
  v_columns NUMBER;
  v_coltype VARCHAR2(128);
  v_char_length NUMBER;
  v_constraint NUMBER;
  v_rows NUMBER;
  v_legacy_city_refs NUMBER;
  v_unmatched_legacy NUMBER;
BEGIN
  IF v_apply NOT IN ('NO','YES') THEN
    RAISE_APPLICATION_ERROR(-20891,'APPLY_CHANGES must be YES or NO');
  END IF;
  SELECT COUNT(*) INTO v_columns FROM ALL_TAB_COLUMNS
   WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS'
     AND COLUMN_NAME='GEO_ENTITY_TYPE_CODE';
  IF v_columns=1 THEN
    SELECT DATA_TYPE, CHAR_LENGTH INTO v_coltype,v_char_length FROM ALL_TAB_COLUMNS
     WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS'
       AND COLUMN_NAME='GEO_ENTITY_TYPE_CODE';
    IF v_coltype<>'VARCHAR2' OR v_char_length<>24 THEN
      RAISE_APPLICATION_ERROR(-20892,'GEO_ENTITY_TYPE_CODE type mismatch; STOP');
    END IF;
  END IF;
  SELECT COUNT(*) INTO v_constraint FROM ALL_CONSTRAINTS
   WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS'
     AND CONSTRAINT_NAME='CK_OUL_R2D_GEO_TYPE' AND CONSTRAINT_TYPE='C' AND STATUS='ENABLED';
  SELECT COUNT(*) INTO v_rows FROM ORG.ORGANIZATION_UNIT_LOCATIONS;
  SELECT COUNT(*) INTO v_legacy_city_refs
    FROM ORG.ORGANIZATION_UNIT_LOCATIONS l
   WHERE l.GEO_ENTITY_ID IS NOT NULL AND l.LEGACY_BACKFILL_FLAG=1;
  SELECT COUNT(*) INTO v_unmatched_legacy
    FROM ORG.ORGANIZATION_UNIT_LOCATIONS l
   WHERE l.GEO_ENTITY_ID IS NOT NULL AND l.LEGACY_BACKFILL_FLAG=1
     AND NOT EXISTS (SELECT 1 FROM GEO.CITIES c WHERE c.CITY_ID=l.GEO_ENTITY_ID AND c.IS_ACTIVE=1);
  DBMS_OUTPUT.PUT_LINE('R2D_PREVIEW ROWS='||v_rows||'; LEGACY_CITY_REFERENCES='||v_legacy_city_refs||'; UNMATCHED_LEGACY_CITY='||v_unmatched_legacy);
  DBMS_OUTPUT.PUT_LINE('R2D_METADATA GEO_TYPE_COLUMN='||v_columns||'; TYPE_CONSTRAINT='||v_constraint);
  IF v_unmatched_legacy>0 THEN
    RAISE_APPLICATION_ERROR(-20893,'Legacy city reference mismatch. STOP; do not change GEO IDs.');
  END IF;
  IF v_apply='NO' THEN
    DBMS_OUTPUT.PUT_LINE('R2D_PREVIEW_ONLY. NO DDL. NO DML. NO COMMIT.'); RETURN;
  END IF;
  IF v_columns=0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ORG.ORGANIZATION_UNIT_LOCATIONS ADD (GEO_ENTITY_TYPE_CODE VARCHAR2(24 CHAR))';
    DBMS_OUTPUT.PUT_LINE('ADDED ORG.ORGANIZATION_UNIT_LOCATIONS.GEO_ENTITY_TYPE_CODE');
  END IF;
  IF v_constraint=0 THEN
    EXECUTE IMMEDIATE q'~ALTER TABLE ORG.ORGANIZATION_UNIT_LOCATIONS
      ADD CONSTRAINT CK_OUL_R2D_GEO_TYPE
      CHECK (GEO_ENTITY_TYPE_CODE IN ('CITY','RURAL_DISTRICT'))~';
    DBMS_OUTPUT.PUT_LINE('ADDED CK_OUL_R2D_GEO_TYPE');
  END IF;
  DBMS_OUTPUT.PUT_LINE('R2D_GEO_TYPE_SCHEMA_APPLIED. EXISTING BUSINESS ROWS UNCHANGED.');
END;
