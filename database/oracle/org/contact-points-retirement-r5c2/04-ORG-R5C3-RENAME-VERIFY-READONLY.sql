SELECT 'ORIGINAL_MASTER' CHECK_NAME,COUNT(*) ACTUAL,0 EXPECTED FROM ALL_TABLES
 WHERE OWNER='ORG' AND TABLE_NAME='CONTACT_POINTS'
UNION ALL SELECT 'ARCHIVED_MASTER',COUNT(*),1 FROM ALL_TABLES
 WHERE OWNER='ORG' AND TABLE_NAME='DEPRECATED_CONTACT_POINTS'
UNION ALL SELECT 'CANONICAL_UNIT_TABLE',COUNT(*),1 FROM ALL_TABLES
 WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_CONTACT_POINTS'
UNION ALL SELECT 'UNMODIFIED_V2_TABLE',COUNT(*),1 FROM ALL_TABLES
 WHERE OWNER='ORG' AND TABLE_NAME='CONTACT_POINTS_V2';
PROMPT === ARCHIVED DATA AND OUCP DATA (COUNTS ONLY) ===
SELECT (SELECT COUNT(*) FROM ORG.DEPRECATED_CONTACT_POINTS) ARCHIVED_MASTER_ROWS,
       (SELECT COUNT(*) FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS) ACTIVE_UNIT_CONTACT_ROWS,
       (SELECT COUNT(*) FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS
         WHERE CONTACT_POINT_ID IS NOT NULL) HISTORICAL_LINK_IDS;
PROMPT === INBOUND FKS TO ARCHIVE (EXPECTED NO ROWS) ===
SELECT fk.OWNER,fk.TABLE_NAME,fk.CONSTRAINT_NAME
 FROM ALL_CONSTRAINTS fk JOIN ALL_CONSTRAINTS pk
   ON pk.OWNER=fk.R_OWNER AND pk.CONSTRAINT_NAME=fk.R_CONSTRAINT_NAME
 WHERE fk.CONSTRAINT_TYPE='R' AND pk.OWNER='ORG' AND pk.TABLE_NAME='DEPRECATED_CONTACT_POINTS';
