SET SERVEROUTPUT ON SIZE UNLIMITED
SET VERIFY OFF
PROMPT ================================================================
PROMPT ORG R5-C2 OUCP INDEPENDENCE VERIFY - READ ONLY
PROMPT ================================================================
SELECT 'HISTORICAL_CONTACT_POINT_ID_NULLABLE' CHECK_NAME,
       COUNT(*) ACTUAL, 1 EXPECTED
  FROM ALL_TAB_COLUMNS WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_CONTACT_POINTS'
    AND COLUMN_NAME='CONTACT_POINT_ID' AND NULLABLE='Y'
UNION ALL
SELECT 'OUCP_ROW_VERSION_NOT_NULL', COUNT(*), 1
  FROM ALL_TAB_COLUMNS WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_CONTACT_POINTS'
    AND COLUMN_NAME='ROW_VERSION' AND NULLABLE='N'
UNION ALL
SELECT 'REQUIRED_CONTACT_SNAPSHOT_COLUMNS', COUNT(*), 5
  FROM ALL_TAB_COLUMNS WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_CONTACT_POINTS'
    AND COLUMN_NAME IN ('CONTACT_TYPE_CODE','CONTACT_VALUE','DISPLAY_NAME_FA','SOURCE_CODE','SOURCE_CREATED_AT');
PROMPT === INBOUND FKS TO OLD MASTER (EXPECTED 0) ===
SELECT fk.OWNER, fk.TABLE_NAME, fk.CONSTRAINT_NAME
  FROM ALL_CONSTRAINTS fk JOIN ALL_CONSTRAINTS pk
    ON pk.OWNER=fk.R_OWNER AND pk.CONSTRAINT_NAME=fk.R_CONSTRAINT_NAME
 WHERE fk.CONSTRAINT_TYPE='R' AND pk.OWNER='ORG' AND pk.TABLE_NAME='CONTACT_POINTS';
PROMPT === OUCP DATA COVERAGE AND HISTORICAL IDS ===
SELECT COUNT(*) UNIT_ROWS, COUNT(CONTACT_POINT_ID) HISTORICAL_CONTACT_POINT_IDS,
       SUM(CASE WHEN CONTACT_TYPE_CODE IS NULL OR CONTACT_VALUE IS NULL OR SOURCE_CODE IS NULL
                 THEN 1 ELSE 0 END) SNAPSHOT_REQUIRED_MISSING
  FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS;
PROMPT === MASTER DATA AND OUCP PARITY BEFORE NEW CANONICAL WRITES ONLY ===
SELECT (SELECT COUNT(*) FROM ORG.CONTACT_POINTS) MASTER_ROWS,
       (SELECT COUNT(*) FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS a
         WHERE a.CONTACT_POINT_ID IS NOT NULL AND NOT EXISTS
          (SELECT 1 FROM ORG.CONTACT_POINTS m WHERE m.CONTACT_POINT_ID=a.CONTACT_POINT_ID)) HISTORIC_ORPHANS;
