-- ORG R5-C2: detach historical CONTACT_POINTS FK without changing data.
-- SQL Developer F5. PREVIEW by default. No DML, no automatic COMMIT commands.
-- DDL auto-commits and is not transactional: DBA backup and maintenance required.
-- CONTACT_POINTS_V2 is intentionally not changed.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET VERIFY OFF
SET DEFINE ON
DEFINE APPLY_CHANGES = NO
DEFINE CONFIRM_DBA_BACKUP = NO
DEFINE CONFIRM_APP_STOPPED = NO
DEFINE CONFIRM_APP_READ_UAT = NO
DEFINE CONFIRM_EXTERNAL_CONSUMERS = NO
PROMPT ================================================================
PROMPT ORG R5-C2 OUCP STANDALONE DETACH - PREVIEW FIRST
PROMPT PRIMARY: ORGANIZATION_UNIT_CONTACT_POINTS. NO CONTACT VALUE OUTPUT.
PROMPT CONTACT_POINTS_V2 OUT OF SCOPE. NO TABLE RENAMES IN THIS STAGE.
PROMPT ================================================================
DECLARE
  v_apply VARCHAR2(3) := UPPER(TRIM('&&APPLY_CHANGES'));
  v_backup VARCHAR2(3) := UPPER(TRIM('&&CONFIRM_DBA_BACKUP'));
  v_stopped VARCHAR2(3) := UPPER(TRIM('&&CONFIRM_APP_STOPPED'));
  v_uat VARCHAR2(3) := UPPER(TRIM('&&CONFIRM_APP_READ_UAT'));
  v_external VARCHAR2(3) := UPPER(TRIM('&&CONFIRM_EXTERNAL_CONSUMERS'));
  v_oucp_rows NUMBER; v_master_rows NUMBER; v_missing NUMBER; v_snap_required NUMBER;
  v_snap_optional NUMBER; v_drift NUMBER; v_oucp_fk NUMBER; v_sp_fk NUMBER;
  v_unknown_fk NUMBER; v_oucp_nullable NUMBER; v_nullable_count NUMBER;
  v_legacy_id_count NUMBER; v_blockers NUMBER := 0; v_ddl NUMBER := 0;
  PROCEDURE ddl(p_stmt VARCHAR2, p_label VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_stmt;
    v_ddl := v_ddl + 1;
    DBMS_OUTPUT.PUT_LINE('DDL_APPLIED | '||p_label);
  END;
  PROCEDURE load_fk IS
  BEGIN
    SELECT COUNT(*) INTO v_oucp_fk FROM ALL_CONSTRAINTS fk
      JOIN ALL_CONSTRAINTS pk ON pk.OWNER=fk.R_OWNER AND pk.CONSTRAINT_NAME=fk.R_CONSTRAINT_NAME
     WHERE fk.OWNER='ORG' AND fk.TABLE_NAME='ORGANIZATION_UNIT_CONTACT_POINTS'
       AND fk.CONSTRAINT_NAME='FK_OUCP_CONTACT_MASTER' AND fk.CONSTRAINT_TYPE='R'
       AND pk.OWNER='ORG' AND pk.TABLE_NAME='CONTACT_POINTS';
    SELECT COUNT(*) INTO v_sp_fk FROM ALL_CONSTRAINTS fk
      JOIN ALL_CONSTRAINTS pk ON pk.OWNER=fk.R_OWNER AND pk.CONSTRAINT_NAME=fk.R_CONSTRAINT_NAME
     WHERE fk.OWNER='ORG' AND fk.TABLE_NAME='SERVICE_POINT_CONTACT_POINTS'
       AND fk.CONSTRAINT_NAME='FK_SPCP_CONTACT_MASTER' AND fk.CONSTRAINT_TYPE='R'
       AND pk.OWNER='ORG' AND pk.TABLE_NAME='CONTACT_POINTS';
    SELECT COUNT(*) INTO v_unknown_fk FROM ALL_CONSTRAINTS fk
      JOIN ALL_CONSTRAINTS pk ON pk.OWNER=fk.R_OWNER AND pk.CONSTRAINT_NAME=fk.R_CONSTRAINT_NAME
     WHERE fk.CONSTRAINT_TYPE='R' AND pk.OWNER='ORG' AND pk.TABLE_NAME='CONTACT_POINTS'
       AND NOT (fk.OWNER='ORG' AND fk.TABLE_NAME='ORGANIZATION_UNIT_CONTACT_POINTS'
                  AND fk.CONSTRAINT_NAME='FK_OUCP_CONTACT_MASTER')
       AND NOT (fk.OWNER='ORG' AND fk.TABLE_NAME='SERVICE_POINT_CONTACT_POINTS'
                  AND fk.CONSTRAINT_NAME='FK_SPCP_CONTACT_MASTER');
  END;
BEGIN
  IF v_apply NOT IN ('YES','NO') OR v_backup NOT IN ('YES','NO')
     OR v_stopped NOT IN ('YES','NO') OR v_uat NOT IN ('YES','NO')
     OR v_external NOT IN ('YES','NO') THEN
    RAISE_APPLICATION_ERROR(-20821,'All flags must be exactly YES or NO.');
  END IF;
  SELECT COUNT(*) INTO v_master_rows FROM ORG.CONTACT_POINTS;
  SELECT COUNT(*), COUNT(CONTACT_POINT_ID)
    INTO v_oucp_rows, v_legacy_id_count FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS;
  SELECT COUNT(*) INTO v_missing FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS a
    LEFT JOIN ORG.CONTACT_POINTS m ON m.CONTACT_POINT_ID=a.CONTACT_POINT_ID
   WHERE a.CONTACT_POINT_ID IS NOT NULL AND m.CONTACT_POINT_ID IS NULL;
  SELECT COUNT(*) INTO v_snap_required FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS a
   WHERE a.CONTACT_TYPE_CODE IS NULL OR a.CONTACT_VALUE IS NULL OR a.SOURCE_CODE IS NULL;
  SELECT COUNT(*) INTO v_snap_optional FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS a
    JOIN ORG.CONTACT_POINTS m ON m.CONTACT_POINT_ID=a.CONTACT_POINT_ID
   WHERE (m.DISPLAY_NAME_FA IS NOT NULL AND a.DISPLAY_NAME_FA IS NULL)
      OR (m.CREATED_AT IS NOT NULL AND a.SOURCE_CREATED_AT IS NULL);
  SELECT COUNT(*) INTO v_drift FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS a
    JOIN ORG.CONTACT_POINTS m ON m.CONTACT_POINT_ID=a.CONTACT_POINT_ID
   WHERE DECODE(a.CONTACT_TYPE_CODE,m.CONTACT_TYPE_CODE,0,1)=1
      OR DECODE(a.CONTACT_VALUE,m.CONTACT_VALUE,0,1)=1
      OR DECODE(a.DISPLAY_NAME_FA,m.DISPLAY_NAME_FA,0,1)=1
      OR DECODE(a.SOURCE_CODE,m.SOURCE_CODE,0,1)=1
      OR DECODE(a.SOURCE_CREATED_AT,m.CREATED_AT,0,1)=1;
  SELECT COUNT(*) INTO v_nullable_count FROM ALL_TAB_COLUMNS
   WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_CONTACT_POINTS'
     AND COLUMN_NAME='CONTACT_POINT_ID';
  SELECT COUNT(*) INTO v_oucp_nullable FROM ALL_TAB_COLUMNS
   WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_CONTACT_POINTS'
     AND COLUMN_NAME='CONTACT_POINT_ID' AND NULLABLE='Y';
  load_fk;
  IF v_oucp_rows<1 OR v_master_rows<1 OR v_missing<>0 OR v_snap_required<>0
     OR v_snap_optional<>0 OR v_drift<>0 THEN v_blockers:=v_blockers+1; END IF;
  IF v_oucp_fk>1 OR v_sp_fk>1 OR v_unknown_fk<>0 OR v_nullable_count<>1 THEN
    v_blockers:=v_blockers+1;
  END IF;
  IF v_oucp_fk=1 AND v_legacy_id_count<>v_oucp_rows THEN v_blockers:=v_blockers+1; END IF;
  DBMS_OUTPUT.PUT_LINE('FLAGS | APPLY_CHANGES='||v_apply||' | DBA_BACKUP='||v_backup||
    ' | APP_STOPPED='||v_stopped||' | READ_UAT='||v_uat||' | EXTERNAL='||v_external);
  DBMS_OUTPUT.PUT_LINE('SOURCE | LEGACY_MASTER='||v_master_rows||' | UNIT_ASSOCIATIONS='||v_oucp_rows||
    ' | HISTORICAL_IDS='||v_legacy_id_count);
  DBMS_OUTPUT.PUT_LINE('PARITY | MISSING_MASTER='||v_missing||' | REQUIRED_MISSING='||v_snap_required||
    ' | OPTIONAL_MISSING='||v_snap_optional||' | SOURCE_DRIFT='||v_drift);
  DBMS_OUTPUT.PUT_LINE('DEPENDENCIES | UNIT_MASTER_FK='||v_oucp_fk||' | SERVICE_MASTER_FK='||v_sp_fk||
    ' | OTHER_INBOUND_FK='||v_unknown_fk||' | LEGACY_ID_NULLABLE='||v_oucp_nullable);
  DBMS_OUTPUT.PUT_LINE('PRECHECK | BLOCKERS='||v_blockers);
  IF v_apply='NO' THEN
    DBMS_OUTPUT.PUT_LINE('ORG_R5C2_DETACH_PREVIEW_COMPLETE | NO DDL | NO DML');
    RETURN;
  END IF;
  IF v_backup<>'YES' OR v_stopped<>'YES' OR v_uat<>'YES' OR v_external<>'YES' THEN
    RAISE_APPLICATION_ERROR(-20822,'DBA backup, app stop, read UAT and external consumer sign-off required.');
  END IF;
  IF v_blockers<>0 THEN
    RAISE_APPLICATION_ERROR(-20823,'Schema or data drift blockers. No detach DDL executed.');
  END IF;
  -- Keep the historic CONTACT_POINT_ID values; no DML and no orphaning of active data.
  IF v_oucp_nullable=0 THEN
    ddl('ALTER TABLE ORG.ORGANIZATION_UNIT_CONTACT_POINTS MODIFY (CONTACT_POINT_ID NULL)',
        'HISTORICAL_CONTACT_POINT_ID_OPTIONAL');
  END IF;
  IF v_oucp_fk=1 THEN
    ddl('ALTER TABLE ORG.ORGANIZATION_UNIT_CONTACT_POINTS DROP CONSTRAINT FK_OUCP_CONTACT_MASTER',
        'DETACH_UNIT_MASTER_FK');
  END IF;
  -- User approved retirement of SERVICE_POINT and SELF_SERVICE contact data.
  -- Drop only this FK; leave the service table and all its data unchanged.
  IF v_sp_fk=1 THEN
    ddl('ALTER TABLE ORG.SERVICE_POINT_CONTACT_POINTS DROP CONSTRAINT FK_SPCP_CONTACT_MASTER',
        'DETACH_EXEMPT_SERVICE_CONTACT_FK');
  END IF;
  load_fk;
  SELECT COUNT(*) INTO v_oucp_nullable FROM ALL_TAB_COLUMNS
   WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_CONTACT_POINTS'
     AND COLUMN_NAME='CONTACT_POINT_ID' AND NULLABLE='Y';
  IF v_oucp_fk<>0 OR v_sp_fk<>0 OR v_unknown_fk<>0 OR v_oucp_nullable<>1 THEN
    RAISE_APPLICATION_ERROR(-20824,'Post-DDL structural verification failed; DDL already committed.');
  END IF;
  DBMS_OUTPUT.PUT_LINE('POST_VERIFY | UNIT_MASTER_FK=0 | SERVICE_MASTER_FK=0 | OTHER_INBOUND_FK=0 | HISTORICAL_ID_NULLABLE=1');
  DBMS_OUTPUT.PUT_LINE('ORG_R5C2_OUCP_DETACH_PASS | DDL_COUNT='||v_ddl||
    ' | UNIT_ROWS_PRESERVED='||v_oucp_rows||' | NO DML | V2_UNCHANGED');
END;
