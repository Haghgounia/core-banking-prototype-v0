-- Manual restore of table name only. DDL auto-commits, no DML.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET VERIFY OFF
SET DEFINE ON
DEFINE APPLY_CHANGES = NO
DEFINE CONFIRM_DBA_APPROVAL = NO
DEFINE CONFIRM_APP_STOPPED = NO
PROMPT ================================================================
PROMPT ORG R5-C3 RESTORE MASTER TABLE NAME - PREVIEW FIRST
PROMPT ================================================================
DECLARE
  v_apply VARCHAR2(3):=UPPER(TRIM('&&APPLY_CHANGES'));
  v_dba VARCHAR2(3):=UPPER(TRIM('&&CONFIRM_DBA_APPROVAL'));
  v_stop VARCHAR2(3):=UPPER(TRIM('&&CONFIRM_APP_STOPPED'));
  v_old NUMBER; v_arch NUMBER; v_fk NUMBER;
BEGIN
  IF v_apply NOT IN ('YES','NO') OR v_dba NOT IN ('YES','NO') OR v_stop NOT IN ('YES','NO') THEN
    RAISE_APPLICATION_ERROR(-20841,'YES/NO flags only.'); END IF;
  SELECT COUNT(*) INTO v_old FROM ALL_TABLES WHERE OWNER='ORG' AND TABLE_NAME='CONTACT_POINTS';
  SELECT COUNT(*) INTO v_arch FROM ALL_TABLES WHERE OWNER='ORG' AND TABLE_NAME='DEPRECATED_CONTACT_POINTS';
  SELECT COUNT(*) INTO v_fk FROM ALL_CONSTRAINTS fk JOIN ALL_CONSTRAINTS pk
    ON pk.OWNER=fk.R_OWNER AND pk.CONSTRAINT_NAME=fk.R_CONSTRAINT_NAME
   WHERE fk.CONSTRAINT_TYPE='R' AND pk.OWNER='ORG' AND pk.TABLE_NAME='DEPRECATED_CONTACT_POINTS';
  DBMS_OUTPUT.PUT_LINE('PREVIEW | ORIGINAL='||v_old||' | ARCHIVED='||v_arch||' | INBOUND_FK='||v_fk);
  IF v_apply='NO' THEN DBMS_OUTPUT.PUT_LINE('ORG_R5C3_MASTER_RESTORE_PREVIEW_COMPLETE | NO DDL'); RETURN; END IF;
  IF v_dba<>'YES' OR v_stop<>'YES' OR v_old<>0 OR v_arch<>1 OR v_fk<>0 THEN
    RAISE_APPLICATION_ERROR(-20842,'Restore blocked; DBA/app-stop/metadata checks failed.'); END IF;
  EXECUTE IMMEDIATE 'ALTER TABLE ORG.DEPRECATED_CONTACT_POINTS RENAME TO CONTACT_POINTS';
  DBMS_OUTPUT.PUT_LINE('ORG_R5C3_MASTER_RESTORE_PASS | NO DML');
END;
/
