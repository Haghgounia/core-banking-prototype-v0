-- R6 emergency name restore ONLY. Oracle auto-commits DDL.
-- Source code must also be restored separately; this script cannot restore API routes.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET VERIFY OFF
SET DEFINE ON
DEFINE APPLY_CHANGES = NO
DEFINE CONFIRM_DBA_APPROVAL = NO
DEFINE CONFIRM_EXTERNAL_CONSUMERS = NO
PROMPT ==============================================================
PROMPT ORG R6 RULES TABLE NAME RESTORE - PREVIEW FIRST
PROMPT ==============================================================
DECLARE
  v_apply VARCHAR2(3) := UPPER(TRIM('&&APPLY_CHANGES'));
  v_dba VARCHAR2(3) := UPPER(TRIM('&&CONFIRM_DBA_APPROVAL'));
  v_external VARCHAR2(3) := UPPER(TRIM('&&CONFIRM_EXTERNAL_CONSUMERS'));
  v_old NUMBER; v_arch NUMBER; v_rows NUMBER; v_after NUMBER;
  v_object_id NUMBER; v_after_id NUMBER; v_deps NUMBER;
BEGIN
  IF v_apply NOT IN ('YES','NO') OR v_dba NOT IN ('YES','NO')
     OR v_external NOT IN ('YES','NO') THEN
    RAISE_APPLICATION_ERROR(-20831,'Flags must be YES or NO.');
  END IF;
  SELECT COUNT(*) INTO v_old FROM ALL_TABLES WHERE OWNER='ORG'
    AND TABLE_NAME='ORGANIZATION_UNIT_RELATIONSHIP_RULES';
  SELECT COUNT(*) INTO v_arch FROM ALL_TABLES WHERE OWNER='ORG'
    AND TABLE_NAME='DEPRECATED_ORGANIZATION_UNIT_RELATIONSHIP_RULES';
  IF v_old+v_arch<>1 THEN
    RAISE_APPLICATION_ERROR(-20832,'Expected one original or deprecated table.');
  END IF;
  IF v_old=1 THEN
    DBMS_OUTPUT.PUT_LINE('ORG_R6_RULES_RESTORE_ALREADY_ORIGINAL | NO DDL');
    RETURN;
  END IF;
  SELECT COUNT(*) INTO v_rows FROM ORG.DEPRECATED_ORGANIZATION_UNIT_RELATIONSHIP_RULES;
  SELECT OBJECT_ID INTO v_object_id FROM ALL_OBJECTS WHERE OWNER='ORG'
     AND OBJECT_NAME='DEPRECATED_ORGANIZATION_UNIT_RELATIONSHIP_RULES' AND OBJECT_TYPE='TABLE';
  SELECT COUNT(*) INTO v_deps FROM ALL_DEPENDENCIES WHERE REFERENCED_OWNER='ORG'
     AND REFERENCED_NAME='DEPRECATED_ORGANIZATION_UNIT_RELATIONSHIP_RULES'
     AND TYPE<>'SYNONYM';
  DBMS_OUTPUT.PUT_LINE('FLAGS | APPLY_CHANGES='||v_apply||' | DBA='||v_dba||
     ' | EXTERNAL='||v_external);
  DBMS_OUTPUT.PUT_LINE('PRECHECK | ARCHIVED_ROWS='||v_rows||' | STORED_DEPENDENCIES='||v_deps);
  IF v_apply='NO' THEN
    DBMS_OUTPUT.PUT_LINE('ORG_R6_RULES_RESTORE_PREVIEW_COMPLETE | NO DDL');
    RETURN;
  END IF;
  IF v_dba<>'YES' OR v_external<>'YES' OR v_deps<>0 THEN
    RAISE_APPLICATION_ERROR(-20833,'Restore requires DBA and external approvals and no stored dependencies.');
  END IF;
  EXECUTE IMMEDIATE 'ALTER TABLE ORG.DEPRECATED_ORGANIZATION_UNIT_RELATIONSHIP_RULES RENAME TO ORGANIZATION_UNIT_RELATIONSHIP_RULES';
  SELECT COUNT(*) INTO v_after FROM ORG.ORGANIZATION_UNIT_RELATIONSHIP_RULES;
  SELECT OBJECT_ID INTO v_after_id FROM ALL_OBJECTS WHERE OWNER='ORG'
     AND OBJECT_NAME='ORGANIZATION_UNIT_RELATIONSHIP_RULES' AND OBJECT_TYPE='TABLE';
  IF v_rows<>v_after OR v_object_id<>v_after_id THEN
    RAISE_APPLICATION_ERROR(-20834,'Post-restore row or object identity mismatch.');
  END IF;
  DBMS_OUTPUT.PUT_LINE('ORG_R6_RULES_RESTORE_PASS | NO DML | ROWS='||v_after);
END;
