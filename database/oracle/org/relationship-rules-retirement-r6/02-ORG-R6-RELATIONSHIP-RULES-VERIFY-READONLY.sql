SET SERVEROUTPUT ON SIZE UNLIMITED
SET VERIFY OFF
PROMPT ==============================================================
PROMPT ORG R6 RELATIONSHIP RULES ARCHIVAL VERIFICATION - READ ONLY
PROMPT ==============================================================
PROMPT === TABLE NAME CONTRACT ===
WITH expected AS (
  SELECT 'ORGANIZATION_UNIT_RELATIONSHIP_RULES' AS TABLE_NAME, 0 AS EXPECTED FROM DUAL
  UNION ALL
  SELECT 'DEPRECATED_ORGANIZATION_UNIT_RELATIONSHIP_RULES', 1 FROM DUAL
)
SELECT e.TABLE_NAME, COUNT(t.TABLE_NAME) AS ACTUAL, e.EXPECTED
  FROM expected e LEFT JOIN ALL_TABLES t
   ON t.OWNER='ORG' AND t.TABLE_NAME=e.TABLE_NAME
 GROUP BY e.TABLE_NAME,e.EXPECTED ORDER BY e.TABLE_NAME;
PROMPT === PRESERVED HISTORICAL DATA AND INTEGRITY ===
SELECT COUNT(*) AS ARCHIVED_RULE_ROWS
  FROM ORG.DEPRECATED_ORGANIZATION_UNIT_RELATIONSHIP_RULES;
SELECT CONSTRAINT_TYPE, STATUS, VALIDATED, COUNT(*) AS CONSTRAINT_COUNT
  FROM ALL_CONSTRAINTS
 WHERE OWNER='ORG' AND TABLE_NAME='DEPRECATED_ORGANIZATION_UNIT_RELATIONSHIP_RULES'
 GROUP BY CONSTRAINT_TYPE, STATUS, VALIDATED ORDER BY CONSTRAINT_TYPE;
PROMPT === INBOUND FK TO ARCHIVED RULES; EXPECT 0 ===
SELECT fk.OWNER AS CHILD_OWNER, fk.TABLE_NAME AS CHILD_TABLE,
       fk.CONSTRAINT_NAME, fk.STATUS
  FROM ALL_CONSTRAINTS fk
  JOIN ALL_CONSTRAINTS pk
    ON pk.OWNER=fk.R_OWNER AND pk.CONSTRAINT_NAME=fk.R_CONSTRAINT_NAME
 WHERE fk.CONSTRAINT_TYPE='R' AND pk.OWNER='ORG'
   AND pk.TABLE_NAME='DEPRECATED_ORGANIZATION_UNIT_RELATIONSHIP_RULES';
PROMPT === ACTIVE RELATIONSHIP TABLES REMAIN PRESENT ===
SELECT TABLE_NAME FROM ALL_TABLES WHERE OWNER='ORG'
  AND TABLE_NAME IN ('ORGANIZATION_UNIT_RELATIONSHIPS',
    'ORGANIZATION_UNIT_RELATIONSHIP_TYPES') ORDER BY TABLE_NAME;
DECLARE
  v_old NUMBER; v_arch NUMBER; v_active NUMBER;
  v_cols NUMBER; v_pk NUMBER; v_uk NUMBER; v_out NUMBER; v_in NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_old FROM ALL_TABLES WHERE OWNER='ORG'
    AND TABLE_NAME='ORGANIZATION_UNIT_RELATIONSHIP_RULES';
  SELECT COUNT(*) INTO v_arch FROM ALL_TABLES WHERE OWNER='ORG'
    AND TABLE_NAME='DEPRECATED_ORGANIZATION_UNIT_RELATIONSHIP_RULES';
  SELECT COUNT(*) INTO v_active FROM ALL_TABLES WHERE OWNER='ORG'
    AND TABLE_NAME IN ('ORGANIZATION_UNIT_RELATIONSHIPS','ORGANIZATION_UNIT_RELATIONSHIP_TYPES');
  SELECT COUNT(DISTINCT COLUMN_NAME) INTO v_cols FROM ALL_TAB_COLUMNS
    WHERE OWNER='ORG' AND TABLE_NAME='DEPRECATED_ORGANIZATION_UNIT_RELATIONSHIP_RULES'
      AND COLUMN_NAME IN ('ORGANIZATION_UNIT_RELATIONSHIP_RULE_ID',
        'ORGANIZATION_UNIT_RELATIONSHIP_TYPE_ID', 'SOURCE_ORGANIZATION_UNIT_TYPE_ID',
        'TARGET_ORGANIZATION_UNIT_TYPE_ID', 'OPERATION_TYPE_CODE','SUBSYSTEM_CODE');
  SELECT COUNT(*) INTO v_pk FROM ALL_CONSTRAINTS WHERE OWNER='ORG'
    AND TABLE_NAME='DEPRECATED_ORGANIZATION_UNIT_RELATIONSHIP_RULES'
    AND CONSTRAINT_TYPE='P' AND STATUS='ENABLED' AND VALIDATED='VALIDATED';
  SELECT COUNT(*) INTO v_uk FROM ALL_CONSTRAINTS WHERE OWNER='ORG'
    AND TABLE_NAME='DEPRECATED_ORGANIZATION_UNIT_RELATIONSHIP_RULES'
    AND CONSTRAINT_TYPE='U' AND STATUS='ENABLED' AND VALIDATED='VALIDATED';
  SELECT COUNT(*) INTO v_out FROM ALL_CONSTRAINTS fk JOIN ALL_CONSTRAINTS pk
    ON pk.OWNER=fk.R_OWNER AND pk.CONSTRAINT_NAME=fk.R_CONSTRAINT_NAME
    WHERE fk.OWNER='ORG' AND fk.TABLE_NAME='DEPRECATED_ORGANIZATION_UNIT_RELATIONSHIP_RULES'
      AND fk.CONSTRAINT_TYPE='R' AND fk.STATUS='ENABLED' AND fk.VALIDATED='VALIDATED'
      AND pk.OWNER='ORG' AND pk.TABLE_NAME IN
        ('ORGANIZATION_UNIT_TYPES','ORGANIZATION_UNIT_RELATIONSHIP_TYPES');
  SELECT COUNT(*) INTO v_in FROM ALL_CONSTRAINTS fk JOIN ALL_CONSTRAINTS pk
    ON pk.OWNER=fk.R_OWNER AND pk.CONSTRAINT_NAME=fk.R_CONSTRAINT_NAME
    WHERE fk.CONSTRAINT_TYPE='R' AND pk.OWNER='ORG'
      AND pk.TABLE_NAME='DEPRECATED_ORGANIZATION_UNIT_RELATIONSHIP_RULES';
  DBMS_OUTPUT.PUT_LINE('CHECK | ORIGINAL='||v_old||' | ARCHIVED='||v_arch||
     ' | ACTIVE_RELATION_TABLES='||v_active||'/2 | COLUMNS='||v_cols||'/6');
  DBMS_OUTPUT.PUT_LINE('CONSTRAINTS | PK='||v_pk||' | UK='||v_uk||
     ' | OUTBOUND_FK='||v_out||'/3 | INBOUND_FK='||v_in);
  IF v_old=0 AND v_arch=1 AND v_active=2 AND v_cols=6
     AND v_pk=1 AND v_uk=1 AND v_out=3 AND v_in=0 THEN
    DBMS_OUTPUT.PUT_LINE('ORG_R6_RULES_VERIFY_PASS | NO DDL | NO DML');
  ELSE
    RAISE_APPLICATION_ERROR(-20821,'R6 table rename or constraint verification failed.');
  END IF;
END;
