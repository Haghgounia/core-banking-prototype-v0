-- ORG CONTACT R1: an independent master for organizational/public contact endpoints.
-- PRESERVATION: No existing ORG/CIF rows are updated/deleted. No auto-DROP and no auto-import.
-- Prerequisites: DBA-reviewed database backup, approved deployment window.
-- Oracle DDL commits implicitly. PREVIEW is the default.
SET SERVEROUTPUT ON SIZE UNLIMITED
DEFINE APPLY_CHANGES = NO

DECLARE
  v_apply VARCHAR2(10) := UPPER(TRIM('&&APPLY_CHANGES'));
  v_table_count NUMBER;
  v_seq_count NUMBER;
  v_unit_fk NUMBER;
  v_point_fk NUMBER;
  v_rows NUMBER;
  v_orphans NUMBER;
  v_row_version NUMBER;
  v_master_columns NUMBER;
  PROCEDURE ddl(p_sql CLOB) IS
  BEGIN
    EXECUTE IMMEDIATE p_sql;
  END;
BEGIN
  IF v_apply NOT IN ('YES','NO') THEN
    RAISE_APPLICATION_ERROR(-20941, 'APPLY_CHANGES must be YES or NO.');
  END IF;
  SELECT COUNT(*) INTO v_table_count FROM ALL_TABLES
   WHERE OWNER='ORG' AND TABLE_NAME='CONTACT_POINTS';
  SELECT COUNT(*) INTO v_seq_count FROM ALL_SEQUENCES
   WHERE SEQUENCE_OWNER='ORG' AND SEQUENCE_NAME='SEQ_CONTACT_POINTS';
  SELECT COUNT(*) INTO v_unit_fk FROM ALL_CONSTRAINTS
   WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_CONTACT_POINTS'
     AND CONSTRAINT_NAME='FK_OUCP_CONTACT_MASTER' AND CONSTRAINT_TYPE='R';
  SELECT COUNT(*) INTO v_point_fk FROM ALL_CONSTRAINTS
   WHERE OWNER='ORG' AND TABLE_NAME='SERVICE_POINT_CONTACT_POINTS'
     AND CONSTRAINT_NAME='FK_SPCP_CONTACT_MASTER' AND CONSTRAINT_TYPE='R';
  SELECT COUNT(*) INTO v_row_version FROM ALL_TAB_COLUMNS
   WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_CONTACT_POINTS'
     AND COLUMN_NAME='ROW_VERSION';
  IF v_table_count=1 THEN
    SELECT COUNT(*) INTO v_master_columns FROM ALL_TAB_COLUMNS
     WHERE OWNER='ORG' AND TABLE_NAME='CONTACT_POINTS'
       AND COLUMN_NAME IN ('CONTACT_POINT_ID','CONTACT_TYPE_CODE','CONTACT_VALUE',
         'DISPLAY_NAME_FA','SOURCE_CODE','CREATED_AT');
    IF v_master_columns<>6 THEN
      RAISE_APPLICATION_ERROR(-20945, 'CONTACT_POINTS exists with different columns; STOP for schema review.');
    END IF;
  END IF;
  SELECT (SELECT COUNT(*) FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS)
       + (SELECT COUNT(*) FROM ORG.SERVICE_POINT_CONTACT_POINTS)
    INTO v_rows FROM DUAL;
  DBMS_OUTPUT.PUT_LINE('=== ORG CONTACT R1: PREVIEW; DEFAULT NO ===');
  DBMS_OUTPUT.PUT_LINE('CONTACT_MASTER_PRESENT=' || v_table_count ||
    '; SEQUENCE_PRESENT=' || v_seq_count ||
    '; UNIT_FK_PRESENT=' || v_unit_fk ||
    '; SERVICE_POINT_FK_PRESENT=' || v_point_fk);
  DBMS_OUTPUT.PUT_LINE('EXISTING_ASSOCIATIONS=' || v_rows || '; UNIT_ROW_VERSION_PRESENT=' || v_row_version);
  IF v_apply = 'NO' THEN
    DBMS_OUTPUT.PUT_LINE('ORG_CONTACT_MASTER_PREVIEW_ONLY. NO DDL/DML.');
    RETURN;
  END IF;

  -- Existing data must not be silently assigned to an invented master record.
  IF v_table_count=0 AND v_rows<>0 THEN
    RAISE_APPLICATION_ERROR(-20942, 'Contact association data exists; STOP and reconcile owner IDs before creating new master.');
  END IF;
  IF v_seq_count=0 AND v_table_count<>0 THEN
    RAISE_APPLICATION_ERROR(-20943, 'CONTACT_POINTS already exists without expected sequence; STOP for DBA review.');
  END IF;
  IF v_seq_count=0 THEN
    ddl('CREATE SEQUENCE ORG.SEQ_CONTACT_POINTS START WITH 1 INCREMENT BY 1 NOMAXVALUE NOCYCLE CACHE 20');
    DBMS_OUTPUT.PUT_LINE('CREATED ORG.SEQ_CONTACT_POINTS');
  END IF;
  IF v_table_count=0 THEN
    ddl(q'~CREATE TABLE ORG.CONTACT_POINTS (
      CONTACT_POINT_ID NUMBER(8,0) DEFAULT ORG.SEQ_CONTACT_POINTS.NEXTVAL NOT NULL,
      CONTACT_TYPE_CODE VARCHAR2(24 CHAR) NOT NULL,
      CONTACT_VALUE VARCHAR2(320 CHAR) NOT NULL,
      DISPLAY_NAME_FA VARCHAR2(150 CHAR),
      SOURCE_CODE VARCHAR2(24 CHAR) DEFAULT 'MANUAL' NOT NULL,
      CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PK_ORG_CONTACT_POINTS PRIMARY KEY (CONTACT_POINT_ID),
      CONSTRAINT CK_ORG_CP_TYPE CHECK (CONTACT_TYPE_CODE IN
        ('PHONE','FAX','MOBILE','EMAIL','WEBSITE','CALL_CENTER','SOCIAL','OTHER')),
      CONSTRAINT CK_ORG_CP_SOURCE CHECK (SOURCE_CODE IN ('MANUAL','OFFICIAL','IMPORTED')),
      CONSTRAINT CK_ORG_CP_VALUE CHECK (LENGTH(TRIM(CONTACT_VALUE)) > 0)
    ) TABLESPACE TS_ORG~');
    DBMS_OUTPUT.PUT_LINE('CREATED ORG.CONTACT_POINTS');
  END IF;
  -- Be strict when completing a previously interrupted deployment.
  -- IMPORTANT: the master does not exist during the first PREVIEW/APPLY parse.
  -- The lookup must be dynamic; a static SQL reference causes ORA-00942
  -- at anonymous-block compilation even when a preceding IF creates the table.
  EXECUTE IMMEDIATE q'~
    SELECT COUNT(*) FROM (
      SELECT CONTACT_POINT_ID FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS
      UNION ALL
      SELECT CONTACT_POINT_ID FROM ORG.SERVICE_POINT_CONTACT_POINTS
    ) a WHERE NOT EXISTS
      (SELECT 1 FROM ORG.CONTACT_POINTS m WHERE m.CONTACT_POINT_ID=a.CONTACT_POINT_ID)
  ~' INTO v_orphans;
  IF v_orphans > 0 THEN
    RAISE_APPLICATION_ERROR(-20944, 'Orphan CONTACT_POINT_ID associations exist. No FK will be added.');
  END IF;
  IF v_row_version=0 THEN
    ddl('ALTER TABLE ORG.ORGANIZATION_UNIT_CONTACT_POINTS ADD (ROW_VERSION NUMBER(12,0) DEFAULT 0 NOT NULL)');
    DBMS_OUTPUT.PUT_LINE('ADDED UNIT CONTACT ROW_VERSION');
  END IF;
  IF v_unit_fk=0 THEN
    ddl('ALTER TABLE ORG.ORGANIZATION_UNIT_CONTACT_POINTS ADD CONSTRAINT FK_OUCP_CONTACT_MASTER FOREIGN KEY (CONTACT_POINT_ID) REFERENCES ORG.CONTACT_POINTS(CONTACT_POINT_ID)');
    DBMS_OUTPUT.PUT_LINE('ADDED FK_OUCP_CONTACT_MASTER');
  END IF;
  IF v_point_fk=0 THEN
    ddl('ALTER TABLE ORG.SERVICE_POINT_CONTACT_POINTS ADD CONSTRAINT FK_SPCP_CONTACT_MASTER FOREIGN KEY (CONTACT_POINT_ID) REFERENCES ORG.CONTACT_POINTS(CONTACT_POINT_ID)');
    DBMS_OUTPUT.PUT_LINE('ADDED FK_SPCP_CONTACT_MASTER');
  END IF;
  DBMS_OUTPUT.PUT_LINE('ORG_CONTACT_MASTER_APPLIED. NO LEGACY/CIF DATA WAS CHANGED.');
END;
