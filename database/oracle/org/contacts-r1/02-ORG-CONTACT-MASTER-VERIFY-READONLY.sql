-- Read-only verification. Expects 1 ORG.CONTACT_POINTS table, its sequence and two FKs.
SET SERVEROUTPUT ON
SELECT 'ORG_CONTACT_POINTS_TABLE' AS CHECK_ITEM, COUNT(*) AS EXACT_COUNT
 FROM ALL_TABLES WHERE OWNER='ORG' AND TABLE_NAME='CONTACT_POINTS'
UNION ALL
SELECT 'ORG_CONTACT_POINTS_SEQUENCE',COUNT(*) FROM ALL_SEQUENCES
 WHERE SEQUENCE_OWNER='ORG' AND SEQUENCE_NAME='SEQ_CONTACT_POINTS'
UNION ALL
SELECT 'ORG_CONTACT_FKS', COUNT(*) FROM ALL_CONSTRAINTS
 WHERE OWNER='ORG' AND CONSTRAINT_NAME IN ('FK_OUCP_CONTACT_MASTER','FK_SPCP_CONTACT_MASTER') AND CONSTRAINT_TYPE='R'
UNION ALL
SELECT 'ORG_UNIT_CONTACT_ROW_VERSION', COUNT(*) FROM ALL_TAB_COLUMNS WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_CONTACT_POINTS' AND COLUMN_NAME='ROW_VERSION'
UNION ALL
SELECT 'ORG_CONTACT_POINTS_ROWS', COUNT(*) FROM ORG.CONTACT_POINTS
UNION ALL
SELECT 'ORG_UNIT_CONTACT_ASSOCIATIONS', COUNT(*) FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS
UNION ALL
SELECT 'ORG_SERVICE_CONTACT_ASSOCIATIONS', COUNT(*) FROM ORG.SERVICE_POINT_CONTACT_POINTS;
SELECT a.CONTACT_POINT_ID, COUNT(*) AS UNIT_REFERENCES
 FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS a
 LEFT JOIN ORG.CONTACT_POINTS c ON c.CONTACT_POINT_ID=a.CONTACT_POINT_ID
 WHERE c.CONTACT_POINT_ID IS NULL
 GROUP BY a.CONTACT_POINT_ID;
PROMPT ORG_CONTACT_R1_VERIFY_COMPLETE. NO WRITES.
