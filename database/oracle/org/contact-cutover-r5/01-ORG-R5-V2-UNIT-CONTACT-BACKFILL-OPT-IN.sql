-- ORG R5-A: reconcile remaining legacy unit associations into CONTACT_POINTS_V2.
-- PREVIEW DEFAULT; data-only MERGE on explicit opt-in; no DDL, no auto COMMIT.
-- Run in a dedicated SQL Developer session while legacy writers are stopped.
-- Never run after canonical writes have begun. Never use this script to drop or rename tables.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET VERIFY OFF
SET AUTOCOMMIT OFF
DEFINE APPLY_CHANGES = NO
DEFINE CONFIRM_BACKUP = NO
DEFINE CONFIRM_SOURCE_QUIESCED = NO

PROMPT ====================================================================
PROMPT ORG R5-A UNIT CONTACT V2 BACKFILL - PREVIEW BY DEFAULT
PROMPT NO DDL; NO AUTOMATIC COMMIT - no contact values displayed
PROMPT ====================================================================

DECLARE
  v_apply VARCHAR2(8) := UPPER(TRIM('&&APPLY_CHANGES'));
  v_backup VARCHAR2(8) := UPPER(TRIM('&&CONFIRM_BACKUP'));
  v_quiesced VARCHAR2(8) := UPPER(TRIM('&&CONFIRM_SOURCE_QUIESCED'));
  v_legacy NUMBER;
  v_v2 NUMBER;
  v_missing NUMBER;
  v_bad_master NUMBER;
  v_orphan_v2 NUMBER;
  v_existing_drift NUMBER;
  v_native NUMBER;
  v_service NUMBER;
  v_required_constraints NUMBER;
  v_columns NUMBER;
  v_sequence NUMBER;
  v_seq_last NUMBER;
  v_max_id NUMBER;
  v_next_id NUMBER;
  v_inserts NUMBER := 0;
  v_post_missing NUMBER;
  v_post_total NUMBER;
  v_blockers NUMBER := 0;
  v_started BOOLEAN := FALSE;

  PROCEDURE refresh_counts IS
  BEGIN
    SELECT COUNT(*) INTO v_legacy FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS;
    SELECT COUNT(*) INTO v_v2 FROM ORG.CONTACT_POINTS_V2;
    SELECT COUNT(*) INTO v_missing FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS a
     WHERE NOT EXISTS (SELECT 1 FROM ORG.CONTACT_POINTS_V2 v
        WHERE v.LEGACY_ASSOCIATION_ID=a.ORGANIZATION_UNIT_CONTACT_POINT_ID);
    SELECT COUNT(*) INTO v_bad_master FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS a
     WHERE NOT EXISTS (SELECT 1 FROM ORG.CONTACT_POINTS m
        WHERE m.CONTACT_POINT_ID=a.CONTACT_POINT_ID);
    SELECT COUNT(*) INTO v_orphan_v2 FROM ORG.CONTACT_POINTS_V2 v
     WHERE v.LEGACY_ASSOCIATION_ID IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS a
        WHERE a.ORGANIZATION_UNIT_CONTACT_POINT_ID=v.LEGACY_ASSOCIATION_ID);
    SELECT COUNT(*) INTO v_native FROM ORG.CONTACT_POINTS_V2
     WHERE LEGACY_ASSOCIATION_ID IS NULL;
    SELECT COUNT(*) INTO v_service FROM ORG.SERVICE_POINT_CONTACT_POINTS;
    SELECT COUNT(*) INTO v_existing_drift
      FROM ORG.CONTACT_POINTS_V2 v
      JOIN ORG.ORGANIZATION_UNIT_CONTACT_POINTS a
        ON a.ORGANIZATION_UNIT_CONTACT_POINT_ID=v.LEGACY_ASSOCIATION_ID
      JOIN ORG.CONTACT_POINTS m ON m.CONTACT_POINT_ID=a.CONTACT_POINT_ID
     WHERE v.LEGACY_CONTACT_POINT_ID<>a.CONTACT_POINT_ID
        OR v.ORGANIZATION_UNIT_ID<>a.ORGANIZATION_UNIT_ID
        OR v.CONTACT_ROLE_ID<>a.CONTACT_ROLE_ID
        OR v.PRIMARY_FLAG<>a.PRIMARY_FLAG
        OR DECODE(v.EFFECTIVE_FROM,a.EFFECTIVE_FROM,0,1)=1
        OR DECODE(v.EFFECTIVE_TO,a.EFFECTIVE_TO,0,1)=1
        OR DECODE(v.CONTACT_TYPE_CODE,m.CONTACT_TYPE_CODE,0,1)=1
        OR DECODE(v.CONTACT_VALUE,m.CONTACT_VALUE,0,1)=1
        OR DECODE(v.DISPLAY_NAME_FA,m.DISPLAY_NAME_FA,0,1)=1
        OR DECODE(v.SOURCE_CODE,m.SOURCE_CODE,0,1)=1
        OR DECODE(v.LEGACY_ASSOCIATION_ROW_VERSION,a.ROW_VERSION,0,1)=1;
  END;
BEGIN
  IF v_apply NOT IN ('YES','NO') OR v_backup NOT IN ('YES','NO')
     OR v_quiesced NOT IN ('YES','NO') THEN
    RAISE_APPLICATION_ERROR(-20951,'R5 flags must be YES or NO.');
  END IF;
  SELECT COUNT(DISTINCT COLUMN_NAME) INTO v_columns FROM ALL_TAB_COLUMNS
   WHERE OWNER='ORG' AND TABLE_NAME='CONTACT_POINTS_V2'
     AND COLUMN_NAME IN (
       'CONTACT_POINT_ID','ORGANIZATION_UNIT_ID','CONTACT_TYPE_CODE','CONTACT_VALUE',
       'DISPLAY_NAME_FA','CONTACT_ROLE_ID','PRIMARY_FLAG','EFFECTIVE_FROM','EFFECTIVE_TO',
       'SOURCE_CODE','CREATED_AT','CREATED_BY','UPDATED_AT','UPDATED_BY','ROW_VERSION',
       'LEGACY_CONTACT_POINT_ID','LEGACY_ASSOCIATION_ID','LEGACY_ASSOCIATION_ROW_VERSION',
       'LEGACY_MASTER_CREATED_AT','MIGRATED_AT');
  SELECT COUNT(*) INTO v_required_constraints FROM ALL_CONSTRAINTS
   WHERE OWNER='ORG' AND TABLE_NAME='CONTACT_POINTS_V2'
     AND CONSTRAINT_NAME IN ('PK_ORG_CONTACT_POINTS_V2','UK_ORG_CPV2_LEGACY_LINK',
          'CK_ORG_CPV2_LEGACY_PAIR','FK_ORG_CPV2_UNIT','FK_ORG_CPV2_ROLE')
     AND STATUS='ENABLED' AND VALIDATED='VALIDATED';
  SELECT COUNT(*),NVL(MAX(LAST_NUMBER),0) INTO v_sequence,v_seq_last FROM ALL_SEQUENCES
   WHERE SEQUENCE_OWNER='ORG' AND SEQUENCE_NAME='SEQ_CONTACT_POINTS_V2';
  SELECT NVL(MAX(CONTACT_POINT_ID),0) INTO v_max_id FROM ORG.CONTACT_POINTS_V2;

  refresh_counts;
  IF v_columns<>20 THEN v_blockers:=v_blockers+1; END IF;
  IF v_required_constraints<>5 THEN v_blockers:=v_blockers+1; END IF;
  IF v_sequence<>1 THEN v_blockers:=v_blockers+1; END IF;
  IF v_bad_master<>0 THEN v_blockers:=v_blockers+1; END IF;
  IF v_orphan_v2<>0 THEN v_blockers:=v_blockers+1; END IF;
  IF v_existing_drift<>0 THEN v_blockers:=v_blockers+1; END IF;
  IF v_native<>0 THEN v_blockers:=v_blockers+1; END IF;
  IF v_service<>0 THEN v_blockers:=v_blockers+1; END IF;

  DBMS_OUTPUT.PUT_LINE('FLAGS | APPLY_CHANGES='||v_apply||' CONFIRM_BACKUP='||v_backup||
    ' CONFIRM_SOURCE_QUIESCED='||v_quiesced);
  DBMS_OUTPUT.PUT_LINE('COUNTS | LEGACY_UNIT='||v_legacy||' V2='||v_v2||' MISSING='||v_missing);
  DBMS_OUTPUT.PUT_LINE('SAFETY | MISSING_MASTER='||v_bad_master||' V2_ORPHANS='||v_orphan_v2||
    ' EXISTING_DRIFT='||v_existing_drift||' V2_NATIVE='||v_native||' SERVICE_CONTACTS='||v_service);
  DBMS_OUTPUT.PUT_LINE('SCHEMA | COLUMNS='||v_columns||'/20 CONSTRAINTS='||v_required_constraints||
    '/5 SEQUENCE='||v_sequence||' SEQUENCE_LAST_NUMBER='||v_seq_last||' MAX_V2_ID='||v_max_id);
  DBMS_OUTPUT.PUT_LINE('PRECHECK | BLOCKERS='||v_blockers);
  IF v_apply='NO' THEN
    DBMS_OUTPUT.PUT_LINE('ORG_R5A_PREVIEW_COMPLETE | NO DDL | NO DML | NO COMMIT');
    RETURN;
  END IF;
  IF v_backup<>'YES' OR v_quiesced<>'YES' THEN
    RAISE_APPLICATION_ERROR(-20952,'Apply requires backup and writer-quiescence confirmations.');
  END IF;
  IF v_blockers<>0 THEN
    RAISE_APPLICATION_ERROR(-20953,'R5A precheck has blockers. NO DML performed.');
  END IF;

  -- The caller must have no unrelated pending work in this dedicated session.
  SAVEPOINT ORG_R5A_BEFORE_MERGE;
  v_started := TRUE;
  EXECUTE IMMEDIATE 'LOCK TABLE ORG.ORGANIZATION_UNIT_CONTACT_POINTS IN EXCLUSIVE MODE NOWAIT';
  EXECUTE IMMEDIATE 'LOCK TABLE ORG.CONTACT_POINTS IN SHARE MODE NOWAIT';
  EXECUTE IMMEDIATE 'LOCK TABLE ORG.CONTACT_POINTS_V2 IN EXCLUSIVE MODE NOWAIT';
  refresh_counts;
  IF v_bad_master<>0 OR v_orphan_v2<>0 OR v_existing_drift<>0 OR v_native<>0 OR v_service<>0 THEN
    RAISE_APPLICATION_ERROR(-20954,'Contact source changed or drifted before locking. NO MERGE.');
  END IF;
  SELECT NVL(MAX(CONTACT_POINT_ID),0) INTO v_max_id FROM ORG.CONTACT_POINTS_V2;
  SELECT ORG.SEQ_CONTACT_POINTS_V2.NEXTVAL INTO v_next_id FROM DUAL;
  IF v_next_id<=v_max_id THEN
    RAISE_APPLICATION_ERROR(-20955,'V2 sequence not above max ID; DBA must align before backfill.');
  END IF;

  MERGE INTO ORG.CONTACT_POINTS_V2 v
  USING (
    SELECT a.ORGANIZATION_UNIT_CONTACT_POINT_ID AS ASSOCIATION_ID,
           a.ORGANIZATION_UNIT_ID AS UNIT_ID,
           a.CONTACT_POINT_ID AS MASTER_ID,
           a.CONTACT_ROLE_ID AS ROLE_ID,
           a.PRIMARY_FLAG AS PRIMARY_FLAG,
           a.EFFECTIVE_FROM AS EFFECTIVE_FROM,
           a.EFFECTIVE_TO AS EFFECTIVE_TO,
           a.ROW_VERSION AS SOURCE_VERSION,
           m.CONTACT_TYPE_CODE AS CONTACT_TYPE_CODE,
           m.CONTACT_VALUE AS CONTACT_VALUE,
           m.DISPLAY_NAME_FA AS DISPLAY_NAME_FA,
           m.SOURCE_CODE AS SOURCE_CODE,
           m.CREATED_AT AS MASTER_CREATED_AT
      FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS a
      JOIN ORG.CONTACT_POINTS m ON m.CONTACT_POINT_ID=a.CONTACT_POINT_ID
     WHERE NOT EXISTS (SELECT 1 FROM ORG.CONTACT_POINTS_V2 v2
                       WHERE v2.LEGACY_ASSOCIATION_ID=a.ORGANIZATION_UNIT_CONTACT_POINT_ID)
  ) src ON (v.LEGACY_ASSOCIATION_ID=src.ASSOCIATION_ID)
  WHEN NOT MATCHED THEN INSERT (
       CONTACT_POINT_ID,ORGANIZATION_UNIT_ID,CONTACT_TYPE_CODE,CONTACT_VALUE,
       DISPLAY_NAME_FA,CONTACT_ROLE_ID,PRIMARY_FLAG,EFFECTIVE_FROM,EFFECTIVE_TO,
       SOURCE_CODE,CREATED_BY,ROW_VERSION,LEGACY_CONTACT_POINT_ID,
       LEGACY_ASSOCIATION_ID,LEGACY_ASSOCIATION_ROW_VERSION,
       LEGACY_MASTER_CREATED_AT,MIGRATED_AT)
    VALUES (ORG.SEQ_CONTACT_POINTS_V2.NEXTVAL,src.UNIT_ID,src.CONTACT_TYPE_CODE,
       src.CONTACT_VALUE,src.DISPLAY_NAME_FA,src.ROLE_ID,src.PRIMARY_FLAG,
       src.EFFECTIVE_FROM,src.EFFECTIVE_TO,src.SOURCE_CODE,'ORG_R5A_MIGRATION',
       src.SOURCE_VERSION,src.MASTER_ID,src.ASSOCIATION_ID,src.SOURCE_VERSION,
       src.MASTER_CREATED_AT,SYSTIMESTAMP);
  v_inserts := SQL%ROWCOUNT;

  SELECT COUNT(*) INTO v_post_missing FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS a
   WHERE NOT EXISTS (SELECT 1 FROM ORG.CONTACT_POINTS_V2 v
      WHERE v.LEGACY_ASSOCIATION_ID=a.ORGANIZATION_UNIT_CONTACT_POINT_ID);
  SELECT COUNT(*) INTO v_post_total FROM ORG.CONTACT_POINTS_V2;
  IF v_inserts<>v_missing OR v_post_missing<>0 OR v_post_total<>v_v2+v_inserts THEN
    RAISE_APPLICATION_ERROR(-20956,'Post-merge parity failed; pending DML rolled back.');
  END IF;
  DBMS_OUTPUT.PUT_LINE('ORG_R5A_PENDING_SUCCESS | INSERTED='||v_inserts||
    ' | V2_TOTAL='||v_post_total||' | MISSING='||v_post_missing||
    ' | NO DDL | NO AUTO_COMMIT');
  DBMS_OUTPUT.PUT_LINE('IMPORTANT | Review success, then COMMIT manually in THIS SAME session.');
EXCEPTION WHEN OTHERS THEN
  IF v_started THEN
    ROLLBACK TO ORG_R5A_BEFORE_MERGE;
    DBMS_OUTPUT.PUT_LINE('ORG_R5A_TRANSACTION_ROLLED_BACK_TO_SAVEPOINT');
  END IF;
  RAISE;
END;
/

PROMPT === READ-ONLY CURRENT SESSION COVERAGE; PENDING IS NOT COMMITTED ===
SELECT (SELECT COUNT(*) FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS) LEGACY_UNIT_CONTACTS,
       (SELECT COUNT(*) FROM ORG.CONTACT_POINTS_V2) V2_CONTACTS,
       (SELECT COUNT(*) FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS a
         WHERE NOT EXISTS (SELECT 1 FROM ORG.CONTACT_POINTS_V2 v
           WHERE v.LEGACY_ASSOCIATION_ID=a.ORGANIZATION_UNIT_CONTACT_POINT_ID)) UNMIGRATED
  FROM DUAL;
