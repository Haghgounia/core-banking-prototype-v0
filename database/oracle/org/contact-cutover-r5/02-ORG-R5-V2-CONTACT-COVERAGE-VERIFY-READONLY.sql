    OR DECODE(v.EFFECTIVE_TO,a.EFFECTIVE_TO,0,1)=1
    OR DECODE(v.CONTACT_TYPE_CODE,m.CONTACT_TYPE_CODE,0,1)=1
    OR DECODE(v.CONTACT_VALUE,m.CONTACT_VALUE,0,1)=1
    OR DECODE(v.DISPLAY_NAME_FA,m.DISPLAY_NAME_FA,0,1)=1
