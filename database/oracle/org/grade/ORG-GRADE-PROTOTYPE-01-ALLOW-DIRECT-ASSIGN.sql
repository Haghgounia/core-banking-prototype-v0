-- ORG GRADE prototype: allow direct grade assignment with RECORD_STATE='ACTIVE'.
-- Run once in SQL Developer (F5) as an Oracle account authorized to modify ORG.
-- This DOES NOT drop tables, delete records, migrate legacy data, or generate approvals.
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
  v_table_count NUMBER;
  v_old_state_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_table_count FROM ALL_TABLES
    WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_GRADE_PERIODS';
  IF v_table_count <> 1 THEN
    RAISE_APPLICATION_ERROR(-20001, 'ORG grade period table is missing. Install P2 first.');
  END IF;
  SELECT COUNT(*) INTO v_old_state_count FROM ALL_CONSTRAINTS
    WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_GRADE_PERIODS'
      AND CONSTRAINT_NAME='CK_OU_GRADE_PERIODS_STATE';
  IF v_old_state_count <> 1 THEN
    RAISE_APPLICATION_ERROR(-20002, 'Expected P2 state constraint not found. Stop and review schema.');
  END IF;
  DBMS_OUTPUT.PUT_LINE('ORG-GRADE PROTOTYPE preflight OK');
END;
/

-- The extra index prevents two simultaneously open grades, including existing APPROVED rows.
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM ALL_INDEXES
   WHERE OWNER='ORG' AND INDEX_NAME='UX_OU_GRADE_ONE_EFFECTIVE_OPEN';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE UNIQUE INDEX ORG.UX_OU_GRADE_ONE_EFFECTIVE_OPEN
      ON ORG.ORGANIZATION_UNIT_GRADE_PERIODS
      (CASE WHEN RECORD_STATE IN ('ACTIVE','APPROVED') AND EFFECTIVE_TO IS NULL
            THEN ORGANIZATION_UNIT_ID END)
    ]';
    DBMS_OUTPUT.PUT_LINE('Created unique grade index');
  ELSE
    DBMS_OUTPUT.PUT_LINE('Grade index already exists');
  END IF;
END;
/

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM ALL_CONSTRAINTS
   WHERE OWNER='ORG' AND CONSTRAINT_NAME='CK_OU_GRADE_PERIODS_STATE'
     AND SEARCH_CONDITION_VC LIKE '%''ACTIVE''%';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ORG.ORGANIZATION_UNIT_GRADE_PERIODS DROP CONSTRAINT CK_OU_GRADE_PERIODS_STATE';
    EXECUTE IMMEDIATE q'[
      ALTER TABLE ORG.ORGANIZATION_UNIT_GRADE_PERIODS
      ADD CONSTRAINT CK_OU_GRADE_PERIODS_STATE
      CHECK (RECORD_STATE IN ('DRAFT','PENDING_APPROVAL','APPROVED','REJECTED','CANCELLED','ACTIVE'))
    ]';
    DBMS_OUTPUT.PUT_LINE('Allowed direct ACTIVE grade periods');
  ELSE
    DBMS_OUTPUT.PUT_LINE('Direct ACTIVE grade periods already allowed');
  END IF;
END;
/

COMMENT ON TABLE ORG.ORGANIZATION_UNIT_GRADE_PERIODS IS
 'تاریخچه درجه‌بندی واحدهای سازمانی؛ ثبت مستقیم درجه با بازه اعتبار در نسخه پروتوتایپ.';

SELECT CONSTRAINT_NAME, STATUS FROM ALL_CONSTRAINTS
 WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_GRADE_PERIODS'
   AND CONSTRAINT_NAME='CK_OU_GRADE_PERIODS_STATE';
SELECT INDEX_NAME, STATUS FROM ALL_INDEXES
 WHERE OWNER='ORG' AND INDEX_NAME='UX_OU_GRADE_ONE_EFFECTIVE_OPEN';
