SET SERVEROUTPUT ON SIZE UNLIMITED
SET VERIFY OFF
PROMPT === R2B 01: INSTALLATION STRUCTURE ===
SELECT 'CANONICAL_MANAGED_FLAG' CHECK_ITEM, COUNT(*) EXACT_COUNT
 FROM ALL_TAB_COLUMNS WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS' AND COLUMN_NAME='CANONICAL_MANAGED_FLAG'
UNION ALL SELECT 'LOCATION_ID_NULLABLE',COUNT(*) FROM ALL_TAB_COLUMNS WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS' AND COLUMN_NAME='LOCATION_ID' AND NULLABLE='Y'
UNION ALL SELECT 'UNIT_PRESENCE_CODE',COUNT(*) FROM ALL_TAB_COLUMNS WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS' AND COLUMN_NAME='UNIT_PRESENCE_CODE'
UNION ALL SELECT 'ADDRESS_USAGE_CODE',COUNT(*) FROM ALL_TAB_COLUMNS WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS' AND COLUMN_NAME='ADDRESS_USAGE_CODE'
UNION ALL SELECT 'LOCATION_AUDIT_TABLE',COUNT(*) FROM ALL_TABLES WHERE OWNER='ORG' AND TABLE_NAME='OU_LOCATION_CHANGE_AUDIT'
UNION ALL SELECT 'LOCATION_AUDIT_SEQUENCE',COUNT(*) FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER='ORG' AND SEQUENCE_NAME='SEQ_OU_LOCATION_AUDIT';
PROMPT === R2B 02: LEGACY SNAPSHOT COVERAGE AND MANAGED ROWS ===
SELECT COUNT(*) AS ALL_LOCATIONS,
       SUM(CASE WHEN LOCATION_ID IS NOT NULL THEN 1 ELSE 0 END) AS STILL_LINKED_LEGACY_ROWS,
       SUM(CASE WHEN LEGACY_BACKFILL_FLAG=1 THEN 1 ELSE 0 END) AS LEGACY_BACKFILL_RECORDS,
       SUM(CASE WHEN CANONICAL_MANAGED_FLAG=1 THEN 1 ELSE 0 END) AS R2B_MANAGED_ROWS,
       SUM(CASE WHEN LOCATION_ID IS NULL AND CANONICAL_MANAGED_FLAG=1 THEN 1 ELSE 0 END) AS R2B_NEW_CANONICAL_ONLY,
       SUM(CASE WHEN CANONICAL_MANAGED_FLAG=0 AND LOCATION_ID IS NULL THEN 1 ELSE 0 END) AS UNCLASSIFIED_NEW_ROWS
 FROM ORG.ORGANIZATION_UNIT_LOCATIONS;
PROMPT === R2B 03: ORPHANS, INVALID RANGES, OPEN PRIMARY DUPLICATES ===
SELECT 'MISSING_LEGACY_LOCATION' CHECK_ITEM,COUNT(*) EXACT_COUNT
 FROM ORG.ORGANIZATION_UNIT_LOCATIONS l
 WHERE l.LOCATION_ID IS NOT NULL AND NOT EXISTS
  (SELECT 1 FROM ORG.LOCATIONS x WHERE x.LOCATION_ID=l.LOCATION_ID)
UNION ALL
SELECT 'INVALID_EFFECTIVE_PERIOD',COUNT(*) FROM ORG.ORGANIZATION_UNIT_LOCATIONS
 WHERE EFFECTIVE_FROM IS NOT NULL AND EFFECTIVE_TO IS NOT NULL AND EFFECTIVE_TO<EFFECTIVE_FROM
UNION ALL
SELECT 'OPEN_PRIMARY_DUPLICATE_UNITS',COUNT(*) FROM (
 SELECT ORGANIZATION_UNIT_ID FROM ORG.ORGANIZATION_UNIT_LOCATIONS
 WHERE LOCATION_ROLE_CODE='PRIMARY' AND EFFECTIVE_TO IS NULL
 GROUP BY ORGANIZATION_UNIT_ID HAVING COUNT(*)>1)
UNION ALL
SELECT 'MANAGED_CHANGES_WITHOUT_AUDIT',COUNT(*) FROM ORG.ORGANIZATION_UNIT_LOCATIONS l
 WHERE CANONICAL_MANAGED_FLAG=1 AND NOT EXISTS
  (SELECT 1 FROM ORG.OU_LOCATION_CHANGE_AUDIT a WHERE a.ORGANIZATION_UNIT_LOCATION_ID=l.ORGANIZATION_UNIT_LOCATION_ID)
UNION ALL
SELECT 'ORPHAN_AUDIT_RECORDS',COUNT(*) FROM ORG.OU_LOCATION_CHANGE_AUDIT a
 WHERE NOT EXISTS (SELECT 1 FROM ORG.ORGANIZATION_UNIT_LOCATIONS l
 WHERE l.ORGANIZATION_UNIT_LOCATION_ID=a.ORGANIZATION_UNIT_LOCATION_ID);
