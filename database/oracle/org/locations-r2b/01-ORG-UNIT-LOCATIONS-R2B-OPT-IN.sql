-- ORG R2-B opt-in: canonical location CRUD readiness and history, with zero legacy-row modification.
-- Run in SQL Developer with F5. Default NO is read-only. Review DBA backup and DDL implicit COMMIT.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET VERIFY ON
DEFINE APPLY_CHANGES = NO
DECLARE
  v_apply VARCHAR2(3) := UPPER(TRIM('&&APPLY_CHANGES'));
  v_legacy_count NUMBER;
  v_nul NUMBER;
  v_flag NUMBER;
  v_presence NUMBER;
  v_usage NUMBER;
  v_audit NUMBER;
  v_seq NUMBER;
  v_ref_cols NUMBER;
  v_audit_cols NUMBER;
  v_old_count NUMBER;
  FUNCTION col_exists(p_name VARCHAR2) RETURN NUMBER IS v_count NUMBER; BEGIN
    SELECT COUNT(*) INTO v_count FROM ALL_TAB_COLUMNS
     WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS' AND COLUMN_NAME=p_name;
    RETURN v_count;
  END;
  PROCEDURE run_ddl(p_ddl VARCHAR2) IS BEGIN EXECUTE IMMEDIATE p_ddl; END;
BEGIN
  IF v_apply NOT IN ('NO','YES') THEN RAISE_APPLICATION_ERROR(-20871,'APPLY_CHANGES must be YES or NO'); END IF;
  SELECT COUNT(*) INTO v_old_count FROM ORG.ORGANIZATION_UNIT_LOCATIONS;
  SELECT COUNT(*) INTO v_legacy_count FROM ORG.ORGANIZATION_UNIT_LOCATIONS WHERE LOCATION_ID IS NOT NULL;
  SELECT COUNT(*) INTO v_nul FROM ALL_TAB_COLUMNS
   WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS' AND COLUMN_NAME='LOCATION_ID' AND NULLABLE='Y';
  v_flag := col_exists('CANONICAL_MANAGED_FLAG');
  v_presence := col_exists('UNIT_PRESENCE_CODE');
  v_usage := col_exists('ADDRESS_USAGE_CODE');
  SELECT COUNT(*) INTO v_audit FROM ALL_TABLES WHERE OWNER='ORG' AND TABLE_NAME='OU_LOCATION_CHANGE_AUDIT';
  SELECT COUNT(*) INTO v_seq FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER='ORG' AND SEQUENCE_NAME='SEQ_OU_LOCATION_AUDIT';
  SELECT COUNT(*) INTO v_audit_cols FROM ALL_TAB_COLUMNS
   WHERE OWNER='ORG' AND TABLE_NAME='OU_LOCATION_CHANGE_AUDIT'
     AND COLUMN_NAME IN ('AUDIT_ID','ORGANIZATION_UNIT_LOCATION_ID','ORGANIZATION_UNIT_ID',
       'ACTION_CODE','OLD_STATE','NEW_STATE','CHANGE_REFERENCE','CHANGED_AT','CHANGED_BY');
  SELECT COUNT(*) INTO v_ref_cols FROM ALL_TAB_COLUMNS
   WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS'
     AND COLUMN_NAME IN ('LEGACY_BACKFILL_FLAG','ROW_VERSION','GEO_ENTITY_ID','ADDRESS_FA','POSTAL_CODE','LEGACY_POSTAL_ADDRESS_ID');
  DBMS_OUTPUT.PUT_LINE('R2B_PREVIEW ROWS='||v_old_count||'; WITH_LEGACY_LOCATION_ID='||v_legacy_count);
  DBMS_OUTPUT.PUT_LINE('R2B_METADATA LOCATION_ID_NULLABLE='||v_nul||'; MANAGED_FLAG='||v_flag||'; PRESENCE='||v_presence||'; USAGE='||v_usage||'; AUDIT='||v_audit||'; AUDIT_SEQ='||v_seq||'; R1_COLUMNS='||v_ref_cols||'/6');
  IF v_ref_cols<>6 THEN RAISE_APPLICATION_ERROR(-20872,'R1 canonical columns missing; STOP'); END IF;
  IF v_audit=1 AND v_audit_cols<>9 THEN
    RAISE_APPLICATION_ERROR(-20873,'Audit table exists with unexpected structure; STOP for DBA review');
  END IF;
  IF v_audit=1 AND v_seq=0 THEN
    RAISE_APPLICATION_ERROR(-20874,'Audit table exists without its sequence; STOP for DBA review');
  END IF;
  IF v_apply='NO' THEN DBMS_OUTPUT.PUT_LINE('R2B_PREVIEW_ONLY. NO DDL. NO DML.'); RETURN; END IF;
  IF v_nul=0 THEN
    run_ddl('ALTER TABLE ORG.ORGANIZATION_UNIT_LOCATIONS MODIFY (LOCATION_ID NULL)');
    DBMS_OUTPUT.PUT_LINE('LOCATION_ID NOW NULLABLE; ALL EXISTING FK LINKS UNCHANGED');
  END IF;
  IF v_flag=0 THEN
    run_ddl('ALTER TABLE ORG.ORGANIZATION_UNIT_LOCATIONS ADD (CANONICAL_MANAGED_FLAG NUMBER(1,0) DEFAULT 0 NOT NULL)');
  END IF;
  IF v_presence=0 THEN
    run_ddl('ALTER TABLE ORG.ORGANIZATION_UNIT_LOCATIONS ADD (UNIT_PRESENCE_CODE VARCHAR2(20 CHAR))');
  END IF;
  IF v_usage=0 THEN
    run_ddl('ALTER TABLE ORG.ORGANIZATION_UNIT_LOCATIONS ADD (ADDRESS_USAGE_CODE VARCHAR2(20 CHAR))');
  END IF;
  FOR c IN (SELECT 'CK_OUL_R2B_MANAGED' n,'CHECK (CANONICAL_MANAGED_FLAG IN (0,1))' d FROM DUAL
            UNION ALL SELECT 'CK_OUL_R2B_PRESENCE','CHECK (UNIT_PRESENCE_CODE IN (''PHYSICAL'',''VIRTUAL''))' FROM DUAL
            UNION ALL SELECT 'CK_OUL_R2B_USAGE','CHECK (ADDRESS_USAGE_CODE IN (''PHYSICAL'',''REFERENCE''))' FROM DUAL)
  LOOP
    DECLARE v_exists NUMBER; BEGIN
      SELECT COUNT(*) INTO v_exists FROM ALL_CONSTRAINTS
       WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS' AND CONSTRAINT_NAME=c.n;
      IF v_exists=0 THEN run_ddl('ALTER TABLE ORG.ORGANIZATION_UNIT_LOCATIONS ADD CONSTRAINT '||c.n||' '||c.d); END IF;
    END;
  END LOOP;
  IF v_seq=0 THEN run_ddl('CREATE SEQUENCE ORG.SEQ_OU_LOCATION_AUDIT START WITH 1 INCREMENT BY 1 CACHE 20 NOCYCLE'); END IF;
  IF v_audit=0 THEN
    run_ddl(q'~CREATE TABLE ORG.OU_LOCATION_CHANGE_AUDIT (
      AUDIT_ID NUMBER(19,0) DEFAULT ORG.SEQ_OU_LOCATION_AUDIT.NEXTVAL NOT NULL,
      ORGANIZATION_UNIT_LOCATION_ID NUMBER(8,0) NOT NULL,
      ORGANIZATION_UNIT_ID NUMBER(8,0) NOT NULL,
      ACTION_CODE VARCHAR2(12 CHAR) NOT NULL,
      OLD_STATE CLOB,
      NEW_STATE CLOB NOT NULL,
      CHANGE_REFERENCE VARCHAR2(160 CHAR) NOT NULL,
      CHANGED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      CHANGED_BY VARCHAR2(128 CHAR) NOT NULL,
      CONSTRAINT PK_OU_LOCATION_CHANGE_AUDIT PRIMARY KEY (AUDIT_ID),
      CONSTRAINT CK_OU_LOC_AUDIT_ACTION CHECK (ACTION_CODE IN ('CREATE','UPDATE')),
      CONSTRAINT FK_OU_LOC_AUDIT_UNIT_LOCATION FOREIGN KEY (ORGANIZATION_UNIT_LOCATION_ID)
        REFERENCES ORG.ORGANIZATION_UNIT_LOCATIONS(ORGANIZATION_UNIT_LOCATION_ID)
    ) TABLESPACE TS_ORG~');
  END IF;
  DBMS_OUTPUT.PUT_LINE('R2B_DDL_APPLIED. NO EXISTING ORG ROWS MODIFIED. LEGACY FK PRESERVED. VERIFY IN NEW CONNECTION.');
END;
