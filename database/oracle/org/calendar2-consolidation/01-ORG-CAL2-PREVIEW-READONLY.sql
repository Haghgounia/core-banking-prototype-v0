PROMPT === ORG-CAL2 01: EIGHT LEGACY TABLES (PRESENT/MISSING) ===
WITH targets AS (
 SELECT 'OPERATING_SCHEDULES' name FROM dual UNION ALL
 SELECT 'OPERATING_SCHEDULE_INTERVALS' FROM dual UNION ALL
 SELECT 'ORGANIZATION_UNIT_OPERATING_SCHEDULES' FROM dual UNION ALL
 SELECT 'ORGANIZATION_UNIT_OPERATING_EXCEPTIONS' FROM dual UNION ALL
 SELECT 'ORGANIZATION_UNIT_OPERATING_EXCEPTION_INTERVALS' FROM dual UNION ALL
 SELECT 'SERVICE_POINT_OPERATING_SCHEDULES' FROM dual UNION ALL
 SELECT 'SERVICE_POINT_OPERATING_EXCEPTIONS' FROM dual UNION ALL
 SELECT 'SERVICE_POINT_OPERATING_EXCEPTION_INTERVALS' FROM dual
)
SELECT t.name table_name, CASE WHEN a.table_name IS NULL THEN 'MISSING' ELSE 'PRESENT' END object_status
FROM targets t LEFT JOIN all_tables a ON a.owner='ORG' AND a.table_name=t.name
ORDER BY t.name;

PROMPT === ORG-CAL2 01: EXACT ROW COUNT (NOT ESTIMATES) ===
DECLARE
  v_name VARCHAR2(128);
  v_count NUMBER;
  v_exists NUMBER;
  TYPE t_names IS TABLE OF VARCHAR2(128) INDEX BY PLS_INTEGER;
  v_names t_names;
BEGIN
  v_names(1):='OPERATING_SCHEDULES';
  v_names(2):='OPERATING_SCHEDULE_INTERVALS';
  v_names(3):='ORGANIZATION_UNIT_OPERATING_SCHEDULES';
  v_names(4):='ORGANIZATION_UNIT_OPERATING_EXCEPTIONS';
  v_names(5):='ORGANIZATION_UNIT_OPERATING_EXCEPTION_INTERVALS';
  v_names(6):='SERVICE_POINT_OPERATING_SCHEDULES';
  v_names(7):='SERVICE_POINT_OPERATING_EXCEPTIONS';
  v_names(8):='SERVICE_POINT_OPERATING_EXCEPTION_INTERVALS';
  FOR i IN 1..8 LOOP
    v_name:=v_names(i);
    SELECT COUNT(*) INTO v_exists FROM all_tables WHERE owner='ORG' AND table_name=v_name;
    IF v_exists=1 THEN
      EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM ORG.'||v_name INTO v_count;
      DBMS_OUTPUT.PUT_LINE('ROW_COUNT | ORG.'||v_name||' | '||v_count);
    ELSE
      DBMS_OUTPUT.PUT_LINE('MISSING | ORG.'||v_name);
    END IF;
  END LOOP;
  DBMS_OUTPUT.PUT_LINE('ORG_CAL2_PREVIEW_READONLY_COMPLETE. NO WRITES.');
END;
/

PROMPT === ORG-CAL2 01: FOREIGN KEYS FROM TABLES OUTSIDE RETIREMENT SCOPE ===
WITH target_names AS (
 SELECT 'OPERATING_SCHEDULES' name FROM dual UNION ALL
 SELECT 'OPERATING_SCHEDULE_INTERVALS' FROM dual UNION ALL
 SELECT 'ORGANIZATION_UNIT_OPERATING_SCHEDULES' FROM dual UNION ALL
 SELECT 'ORGANIZATION_UNIT_OPERATING_EXCEPTIONS' FROM dual UNION ALL
 SELECT 'ORGANIZATION_UNIT_OPERATING_EXCEPTION_INTERVALS' FROM dual UNION ALL
 SELECT 'SERVICE_POINT_OPERATING_SCHEDULES' FROM dual UNION ALL
 SELECT 'SERVICE_POINT_OPERATING_EXCEPTIONS' FROM dual UNION ALL
 SELECT 'SERVICE_POINT_OPERATING_EXCEPTION_INTERVALS' FROM dual
)
SELECT child.owner, child.table_name, child.constraint_name, parent.table_name referenced_table
FROM all_constraints parent JOIN all_constraints child
  ON child.constraint_type='R' AND child.r_owner=parent.owner AND child.r_constraint_name=parent.constraint_name
WHERE parent.owner='ORG' AND parent.table_name IN (SELECT name FROM target_names)
  AND (child.owner <> 'ORG' OR child.table_name NOT IN (SELECT name FROM target_names))
ORDER BY child.owner, child.table_name, child.constraint_name;

PROMPT === ORG-CAL2 01: DEPENDENT PROGRAMS/VIEWS (REVIEW IF ANY) ===
SELECT owner, name, type, referenced_name
FROM all_dependencies
WHERE referenced_owner='ORG' AND referenced_name IN (
 'OPERATING_SCHEDULES','OPERATING_SCHEDULE_INTERVALS',
 'ORGANIZATION_UNIT_OPERATING_SCHEDULES','ORGANIZATION_UNIT_OPERATING_EXCEPTIONS',
 'ORGANIZATION_UNIT_OPERATING_EXCEPTION_INTERVALS',
 'SERVICE_POINT_OPERATING_SCHEDULES','SERVICE_POINT_OPERATING_EXCEPTIONS',
 'SERVICE_POINT_OPERATING_EXCEPTION_INTERVALS')
AND type IN ('VIEW','MATERIALIZED VIEW','PACKAGE','PACKAGE BODY','PROCEDURE','FUNCTION','TRIGGER','TYPE','TYPE BODY','SYNONYM')
ORDER BY owner,name;

