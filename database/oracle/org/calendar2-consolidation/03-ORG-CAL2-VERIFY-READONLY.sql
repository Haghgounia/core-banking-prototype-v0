-- ORG -> CAL2 consolidation post-verify, read-only, SQL Developer F5.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET VERIFY OFF
DECLARE
 v_tables NUMBER;
 v_sequences NUMBER;
 v_cal2 NUMBER;
 v_external_fk NUMBER;
BEGIN
 SELECT COUNT(*) INTO v_tables FROM all_tables
 WHERE owner='ORG' AND table_name IN
 ('OPERATING_SCHEDULES','OPERATING_SCHEDULE_INTERVALS',
  'ORGANIZATION_UNIT_OPERATING_SCHEDULES','ORGANIZATION_UNIT_OPERATING_EXCEPTIONS',
  'ORGANIZATION_UNIT_OPERATING_EXCEPTION_INTERVALS',
  'SERVICE_POINT_OPERATING_SCHEDULES','SERVICE_POINT_OPERATING_EXCEPTIONS',
  'SERVICE_POINT_OPERATING_EXCEPTION_INTERVALS');
 SELECT COUNT(*) INTO v_sequences FROM all_sequences
 WHERE sequence_owner='ORG' AND sequence_name IN
 ('SEQ_OPERATING_SCHEDULES','SEQ_OPERATING_SCHEDULE_INTERVALS',
  'SEQ_ORGANIZATION_UNIT_OPERATING_SCHEDULES','SEQ_ORGANIZATION_UNIT_OPERATING_EXCEPTIONS',
  'SEQ_ORGANIZATION_UNIT_OPERATING_EXCEPTION_INTERVALS',
  'SEQ_POINT_OF_SERVICE_OPERATING_SCHEDULES','SEQ_POINT_OF_SERVICE_OPERATING_EXCEPTIONS',
  'SEQ_POINT_OF_SERVICE_OPERATING_EXCEPTION_INTERVALS');
 SELECT COUNT(*) INTO v_cal2 FROM all_tables WHERE owner='CAL2'
  AND table_name IN ('BUSINESS_CALENDAR','BUSINESS_CALENDAR_SCHEDULE',
  'BUSINESS_CALENDAR_SCHEDULE_DAY','BUSINESS_CALENDAR_EXCEPTION','BUSINESS_CALENDAR_DAY');
 SELECT COUNT(*) INTO v_external_fk FROM all_constraints
  WHERE owner='ORG' AND constraint_type='R' AND table_name IN
  ('OPERATING_SCHEDULES','OPERATING_SCHEDULE_INTERVALS',
   'ORGANIZATION_UNIT_OPERATING_SCHEDULES','ORGANIZATION_UNIT_OPERATING_EXCEPTIONS',
   'ORGANIZATION_UNIT_OPERATING_EXCEPTION_INTERVALS',
   'SERVICE_POINT_OPERATING_SCHEDULES','SERVICE_POINT_OPERATING_EXCEPTIONS',
   'SERVICE_POINT_OPERATING_EXCEPTION_INTERVALS');
 DBMS_OUTPUT.PUT_LINE('LEGACY_ORG_TABLES_REMAINING='||v_tables);
 DBMS_OUTPUT.PUT_LINE('LEGACY_ORG_SEQUENCES_REMAINING='||v_sequences);
 DBMS_OUTPUT.PUT_LINE('CAL2_CANONICAL_TABLES='||v_cal2);
 IF v_tables=0 AND v_sequences=0 AND v_cal2=5 AND v_external_fk=0 THEN
   DBMS_OUTPUT.PUT_LINE('ORG_CAL2_POST_VERIFY_PASS');
 ELSE
   RAISE_APPLICATION_ERROR(-20702,'ORG_CAL2_POST_VERIFY_FAIL: inspect remaining objects.');
 END IF;
END;
