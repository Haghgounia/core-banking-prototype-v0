-- ORG -> CAL2 working-calendar ownership consolidation; DBA-only.
-- SQL Developer F5 / Run Script. DEFAULT IS PREVIEW (APPLY_CHANGES=NO).
-- Preconditions for APPLY: CAL2 canonical model present; ALL EIGHT legacy tables
-- must be empty (exact COUNT); no external FK, synonym, view/program dependency,
-- or trigger; verify other applications/dynamic SQL outside this repository.
-- Oracle DDL commits implicitly. NEVER run on populated legacy tables.
-- DROP TABLE is intentionally WITHOUT CASCADE CONSTRAINTS and WITHOUT PURGE.
-- No re-creation or modification of business data is performed.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET VERIFY OFF
DEFINE APPLY_CHANGES = NO
PROMPT === ORG-CAL2: DEFAULT PREVIEW. CHANGE APPLY_CHANGES TO YES ONLY AFTER UAT/DBA APPROVAL ===
DECLARE
  v_mode VARCHAR2(8) := UPPER(TRIM('&&APPLY_CHANGES'));
  TYPE t_names IS TABLE OF VARCHAR2(128) INDEX BY PLS_INTEGER;
  v_tables t_names;
  v_sequences t_names;
  v_count NUMBER;
  v_existing NUMBER;
  v_bad NUMBER := 0;
  v_inbound NUMBER;
  v_dependent NUMBER;
  v_synonyms NUMBER;
  v_triggers NUMBER;
  v_seqdeps NUMBER;
  v_cal2 NUMBER;
  v_collision NUMBER;
BEGIN
  -- Children first; known table/sequence names are literals, never request parameters.
  v_tables(1):='ORGANIZATION_UNIT_OPERATING_EXCEPTION_INTERVALS';
  v_tables(2):='SERVICE_POINT_OPERATING_EXCEPTION_INTERVALS';
  v_tables(3):='OPERATING_SCHEDULE_INTERVALS';
  v_tables(4):='ORGANIZATION_UNIT_OPERATING_SCHEDULES';
  v_tables(5):='SERVICE_POINT_OPERATING_SCHEDULES';
  v_tables(6):='ORGANIZATION_UNIT_OPERATING_EXCEPTIONS';
  v_tables(7):='SERVICE_POINT_OPERATING_EXCEPTIONS';
  v_tables(8):='OPERATING_SCHEDULES';
  v_sequences(1):='SEQ_ORGANIZATION_UNIT_OPERATING_EXCEPTION_INTERVALS';
  v_sequences(2):='SEQ_POINT_OF_SERVICE_OPERATING_EXCEPTION_INTERVALS';
  v_sequences(3):='SEQ_OPERATING_SCHEDULE_INTERVALS';
  v_sequences(4):='SEQ_ORGANIZATION_UNIT_OPERATING_SCHEDULES';
  v_sequences(5):='SEQ_POINT_OF_SERVICE_OPERATING_SCHEDULES';
  v_sequences(6):='SEQ_ORGANIZATION_UNIT_OPERATING_EXCEPTIONS';
  v_sequences(7):='SEQ_POINT_OF_SERVICE_OPERATING_EXCEPTIONS';
  v_sequences(8):='SEQ_OPERATING_SCHEDULES';

  IF v_mode NOT IN ('YES','NO') THEN
    RAISE_APPLICATION_ERROR(-20700,'APPLY_CHANGES must be NO or YES');
  END IF;
  SELECT COUNT(*) INTO v_cal2 FROM all_tables
    WHERE owner='CAL2' AND table_name IN
    ('BUSINESS_CALENDAR','BUSINESS_CALENDAR_SCHEDULE','BUSINESS_CALENDAR_SCHEDULE_DAY',
     'BUSINESS_CALENDAR_EXCEPTION','BUSINESS_CALENDAR_DAY');
  DBMS_OUTPUT.PUT_LINE('CAL2_CANONICAL_TABLE_COUNT='||v_cal2||'/5');
  IF v_cal2<>5 THEN v_bad:=v_bad+1; DBMS_OUTPUT.PUT_LINE('BLOCKER: required CAL2 tables missing or not visible.'); END IF;

  FOR i IN 1..8 LOOP
    SELECT COUNT(*) INTO v_existing FROM all_tables WHERE owner='ORG' AND table_name=v_tables(i);
    IF v_existing=1 THEN
      EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM ORG.'||v_tables(i) INTO v_count;
      DBMS_OUTPUT.PUT_LINE('ORG.'||v_tables(i)||' ROWS='||v_count);
      IF v_count<>0 THEN v_bad:=v_bad+1; DBMS_OUTPUT.PUT_LINE('BLOCKER: nonempty table '||v_tables(i)); END IF;
    ELSE
      DBMS_OUTPUT.PUT_LINE('ORG.'||v_tables(i)||' ALREADY_ABSENT');
      SELECT COUNT(*) INTO v_collision FROM all_objects
        WHERE owner='ORG' AND object_name=v_tables(i) AND object_type<>'TABLE';
      IF v_collision<>0 THEN v_bad:=v_bad+1; DBMS_OUTPUT.PUT_LINE('BLOCKER: name collision: '||v_tables(i)); END IF;
    END IF;
  END LOOP;

  -- Inbound foreign keys outside the eight retired tables must never be cascaded.
  SELECT COUNT(*) INTO v_inbound
  FROM all_constraints p JOIN all_constraints c
    ON c.constraint_type='R' AND c.r_owner=p.owner AND c.r_constraint_name=p.constraint_name
  WHERE p.owner='ORG' AND p.table_name IN
     ('OPERATING_SCHEDULES','OPERATING_SCHEDULE_INTERVALS','ORGANIZATION_UNIT_OPERATING_SCHEDULES',
      'ORGANIZATION_UNIT_OPERATING_EXCEPTIONS','ORGANIZATION_UNIT_OPERATING_EXCEPTION_INTERVALS',
      'SERVICE_POINT_OPERATING_SCHEDULES','SERVICE_POINT_OPERATING_EXCEPTIONS',
      'SERVICE_POINT_OPERATING_EXCEPTION_INTERVALS')
    AND (c.owner<>'ORG' OR c.table_name NOT IN
     ('OPERATING_SCHEDULES','OPERATING_SCHEDULE_INTERVALS','ORGANIZATION_UNIT_OPERATING_SCHEDULES',
      'ORGANIZATION_UNIT_OPERATING_EXCEPTIONS','ORGANIZATION_UNIT_OPERATING_EXCEPTION_INTERVALS',
      'SERVICE_POINT_OPERATING_SCHEDULES','SERVICE_POINT_OPERATING_EXCEPTIONS',
      'SERVICE_POINT_OPERATING_EXCEPTION_INTERVALS'));
  DBMS_OUTPUT.PUT_LINE('EXTERNAL_INBOUND_FK='||v_inbound);
  IF v_inbound>0 THEN v_bad:=v_bad+1; END IF;

  SELECT COUNT(*) INTO v_dependent FROM all_dependencies
  WHERE referenced_owner='ORG'
    AND referenced_name IN
      ('OPERATING_SCHEDULES','OPERATING_SCHEDULE_INTERVALS','ORGANIZATION_UNIT_OPERATING_SCHEDULES',
       'ORGANIZATION_UNIT_OPERATING_EXCEPTIONS','ORGANIZATION_UNIT_OPERATING_EXCEPTION_INTERVALS',
       'SERVICE_POINT_OPERATING_SCHEDULES','SERVICE_POINT_OPERATING_EXCEPTIONS',
       'SERVICE_POINT_OPERATING_EXCEPTION_INTERVALS')
    AND type IN ('VIEW','MATERIALIZED VIEW','PACKAGE','PACKAGE BODY','PROCEDURE','FUNCTION','TRIGGER','TYPE','TYPE BODY','SYNONYM');
  DBMS_OUTPUT.PUT_LINE('DEPENDENT_PROGRAM_OR_VIEW='||v_dependent);
  IF v_dependent>0 THEN v_bad:=v_bad+1; END IF;

  SELECT COUNT(*) INTO v_synonyms FROM all_synonyms
  WHERE table_owner='ORG' AND table_name IN
    ('OPERATING_SCHEDULES','OPERATING_SCHEDULE_INTERVALS','ORGANIZATION_UNIT_OPERATING_SCHEDULES',
     'ORGANIZATION_UNIT_OPERATING_EXCEPTIONS','ORGANIZATION_UNIT_OPERATING_EXCEPTION_INTERVALS',
     'SERVICE_POINT_OPERATING_SCHEDULES','SERVICE_POINT_OPERATING_EXCEPTIONS',
     'SERVICE_POINT_OPERATING_EXCEPTION_INTERVALS');
  DBMS_OUTPUT.PUT_LINE('DEPENDENT_SYNONYMS='||v_synonyms);
  IF v_synonyms>0 THEN v_bad:=v_bad+1; END IF;

  SELECT COUNT(*) INTO v_triggers FROM all_triggers
  WHERE table_owner='ORG' AND table_name IN
    ('OPERATING_SCHEDULES','OPERATING_SCHEDULE_INTERVALS','ORGANIZATION_UNIT_OPERATING_SCHEDULES',
     'ORGANIZATION_UNIT_OPERATING_EXCEPTIONS','ORGANIZATION_UNIT_OPERATING_EXCEPTION_INTERVALS',
     'SERVICE_POINT_OPERATING_SCHEDULES','SERVICE_POINT_OPERATING_EXCEPTIONS',
     'SERVICE_POINT_OPERATING_EXCEPTION_INTERVALS');
  DBMS_OUTPUT.PUT_LINE('TARGET_TABLE_TRIGGERS='||v_triggers);
  IF v_triggers>0 THEN v_bad:=v_bad+1; END IF;

  -- A sequence must not be used by any remaining object.
  SELECT COUNT(*) INTO v_seqdeps FROM all_dependencies d
  WHERE d.referenced_owner='ORG' AND d.referenced_type='SEQUENCE'
    AND d.referenced_name IN
      ('SEQ_OPERATING_SCHEDULES','SEQ_OPERATING_SCHEDULE_INTERVALS',
       'SEQ_ORGANIZATION_UNIT_OPERATING_SCHEDULES','SEQ_ORGANIZATION_UNIT_OPERATING_EXCEPTIONS',
       'SEQ_ORGANIZATION_UNIT_OPERATING_EXCEPTION_INTERVALS',
       'SEQ_POINT_OF_SERVICE_OPERATING_SCHEDULES','SEQ_POINT_OF_SERVICE_OPERATING_EXCEPTIONS',
       'SEQ_POINT_OF_SERVICE_OPERATING_EXCEPTION_INTERVALS')
    AND NOT (d.owner='ORG' AND d.type='TABLE' AND d.name IN
      ('OPERATING_SCHEDULES','OPERATING_SCHEDULE_INTERVALS','ORGANIZATION_UNIT_OPERATING_SCHEDULES',
       'ORGANIZATION_UNIT_OPERATING_EXCEPTIONS','ORGANIZATION_UNIT_OPERATING_EXCEPTION_INTERVALS',
       'SERVICE_POINT_OPERATING_SCHEDULES','SERVICE_POINT_OPERATING_EXCEPTIONS',
       'SERVICE_POINT_OPERATING_EXCEPTION_INTERVALS'));
  DBMS_OUTPUT.PUT_LINE('EXTERNAL_SEQUENCE_DEPENDENCIES='||v_seqdeps);
  IF v_seqdeps>0 THEN v_bad:=v_bad+1; END IF;

  DBMS_OUTPUT.PUT_LINE('BLOCKER_GROUP_COUNT='||v_bad);
  IF v_mode='NO' THEN
    DBMS_OUTPUT.PUT_LINE('ORG_CAL2_PREVIEW_READY. NO WRITES.');
    IF v_bad>0 THEN DBMS_OUTPUT.PUT_LINE('ORG_CAL2_PREVIEW_BLOCKED. DO NOT APPLY.'); END IF;
    RETURN;
  END IF;
  IF v_bad>0 THEN
    RAISE_APPLICATION_ERROR(-20701,'ABORT BEFORE ANY DDL: data or dependencies present; review PREVIEW.');
  END IF;

  -- DDL is NOT transactional. Abort on any error; verify before any manual retry.
  FOR i IN 1..8 LOOP
    SELECT COUNT(*) INTO v_existing FROM all_tables WHERE owner='ORG' AND table_name=v_tables(i);
    IF v_existing=1 THEN
      EXECUTE IMMEDIATE 'DROP TABLE ORG.'||v_tables(i);
      DBMS_OUTPUT.PUT_LINE('DROPPED_TABLE='||v_tables(i));
    ELSE
      DBMS_OUTPUT.PUT_LINE('SKIP_TABLE_ALREADY_ABSENT='||v_tables(i));
    END IF;
  END LOOP;
  FOR i IN 1..8 LOOP
    SELECT COUNT(*) INTO v_existing FROM all_sequences WHERE sequence_owner='ORG' AND sequence_name=v_sequences(i);
    IF v_existing=1 THEN
      EXECUTE IMMEDIATE 'DROP SEQUENCE ORG.'||v_sequences(i);
      DBMS_OUTPUT.PUT_LINE('DROPPED_SEQUENCE='||v_sequences(i));
    ELSE
      DBMS_OUTPUT.PUT_LINE('SKIP_SEQUENCE_ALREADY_ABSENT='||v_sequences(i));
    END IF;
  END LOOP;
  DBMS_OUTPUT.PUT_LINE('ORG_CAL2_APPLY_COMPLETE. RUN THE READONLY POST-VERIFY SCRIPT.');
END;
