DECLARE
  v_v2            NUMBER := 0;
  v_v2_archive    NUMBER := 0;
  v_oucp          NUMBER := 0;
  v_old_master    NUMBER := 0;
  v_old_archive   NUMBER := 0;
  v_v2_rows       NUMBER := -1;
  v_oucp_rows     NUMBER := -1;
  v_v2_historic   NUMBER := -1;
  v_v2_native     NUMBER := -1;
  v_v2_orphan     NUMBER := -1;
  v_oucp_no_v2    NUMBER := -1;
  v_v2_cols       NUMBER := 0;
  v_oucp_cols     NUMBER := 0;
  v_v2_object_id  NUMBER := -1;
  v_fk            NUMBER := 0;
  v_stored        NUMBER := 0;
  v_synonyms      NUMBER := 0;
  v_triggers      NUMBER := 0;
  v_source        NUMBER := 0;
  v_jobs          NUMBER := 0;
  v_programs      NUMBER := 0;
  v_grants        NUMBER := 0;
  v_db_blockers   NUMBER := 0;
  v_data_review   NUMBER := 0;
BEGIN
  SELECT COUNT(*) INTO v_v2 FROM ALL_TABLES
   WHERE OWNER='ORG' AND TABLE_NAME='CONTACT_POINTS_V2';
  SELECT COUNT(*) INTO v_v2_archive FROM ALL_TABLES
   WHERE OWNER='ORG' AND TABLE_NAME='DEPRECATED_CONTACT_POINTS_V2';
  SELECT COUNT(*) INTO v_oucp FROM ALL_TABLES
   WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_CONTACT_POINTS';
  SELECT COUNT(*) INTO v_old_master FROM ALL_TABLES
   WHERE OWNER='ORG' AND TABLE_NAME='CONTACT_POINTS';
  SELECT COUNT(*) INTO v_old_archive FROM ALL_TABLES
   WHERE OWNER='ORG' AND TABLE_NAME='DEPRECATED_CONTACT_POINTS';
  IF v_v2=1 THEN
    SELECT OBJECT_ID INTO v_v2_object_id FROM ALL_OBJECTS
     WHERE OWNER='ORG' AND OBJECT_NAME='CONTACT_POINTS_V2' AND OBJECT_TYPE='TABLE';
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM ORG.CONTACT_POINTS_V2'
      INTO v_v2_rows;
    SELECT COUNT(*) INTO v_v2_cols FROM ALL_TAB_COLUMNS
     WHERE OWNER='ORG' AND TABLE_NAME='CONTACT_POINTS_V2'
       AND COLUMN_NAME IN ('CONTACT_POINT_ID','LEGACY_ASSOCIATION_ID');
    IF v_v2_cols=2 THEN
      EXECUTE IMMEDIATE
        'SELECT COUNT(LEGACY_ASSOCIATION_ID), COUNT(*) - COUNT(LEGACY_ASSOCIATION_ID) '
        ||'FROM ORG.CONTACT_POINTS_V2' INTO v_v2_historic,v_v2_native;
    END IF;
  END IF;
  IF v_oucp=1 THEN
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS'
      INTO v_oucp_rows;
    SELECT COUNT(*) INTO v_oucp_cols FROM ALL_TAB_COLUMNS
     WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_CONTACT_POINTS'
       AND COLUMN_NAME IN ('ORGANIZATION_UNIT_CONTACT_POINT_ID',
                           'CONTACT_TYPE_CODE','CONTACT_VALUE','SOURCE_CODE');
  END IF;
  -- These are diagnostics, not migration parity gates.  Legitimate post-R5-C2
  -- OUCP inserts/edits can make historical V2 coverage diverge.
  IF v_v2=1 AND v_oucp=1 AND v_v2_cols=2 AND v_oucp_cols=4 THEN
    EXECUTE IMMEDIATE
      'SELECT COUNT(*) FROM ORG.CONTACT_POINTS_V2 v '
      ||'WHERE v.LEGACY_ASSOCIATION_ID IS NOT NULL AND NOT EXISTS '
      ||'(SELECT 1 FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS a '
      ||' WHERE a.ORGANIZATION_UNIT_CONTACT_POINT_ID=v.LEGACY_ASSOCIATION_ID)'
      INTO v_v2_orphan;
    EXECUTE IMMEDIATE
      'SELECT COUNT(*) FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS a '
      ||'WHERE NOT EXISTS (SELECT 1 FROM ORG.CONTACT_POINTS_V2 v '
      ||'WHERE v.LEGACY_ASSOCIATION_ID=a.ORGANIZATION_UNIT_CONTACT_POINT_ID)'
      INTO v_oucp_no_v2;
  END IF;
  SELECT COUNT(*) INTO v_fk FROM ALL_CONSTRAINTS c
    JOIN ALL_CONSTRAINTS p ON p.OWNER=c.R_OWNER
                          AND p.CONSTRAINT_NAME=c.R_CONSTRAINT_NAME
   WHERE c.CONSTRAINT_TYPE='R'
     AND p.OWNER='ORG' AND p.TABLE_NAME='CONTACT_POINTS_V2';
  SELECT COUNT(*) INTO v_stored FROM ALL_DEPENDENCIES
   WHERE REFERENCED_OWNER='ORG' AND REFERENCED_NAME='CONTACT_POINTS_V2'
     AND TYPE<>'SYNONYM';
  SELECT COUNT(*) INTO v_synonyms FROM ALL_SYNONYMS
   WHERE TABLE_OWNER='ORG' AND TABLE_NAME='CONTACT_POINTS_V2';
  SELECT COUNT(*) INTO v_triggers FROM ALL_TRIGGERS
   WHERE TABLE_OWNER='ORG' AND TABLE_NAME='CONTACT_POINTS_V2';
  SELECT COUNT(*) INTO v_source FROM ALL_SOURCE
   WHERE REGEXP_LIKE(UPPER(TEXT),
      '(^|[^A-Z0-9_])CONTACT_POINTS_V2([^A-Z0-9_]|$)');
  SELECT COUNT(*) INTO v_jobs FROM ALL_SCHEDULER_JOBS
   WHERE REGEXP_LIKE(UPPER(JOB_ACTION),
      '(^|[^A-Z0-9_])CONTACT_POINTS_V2([^A-Z0-9_]|$)');
  SELECT COUNT(*) INTO v_programs FROM ALL_SCHEDULER_PROGRAMS
   WHERE REGEXP_LIKE(UPPER(PROGRAM_ACTION),
      '(^|[^A-Z0-9_])CONTACT_POINTS_V2([^A-Z0-9_]|$)');
  SELECT COUNT(*) INTO v_grants FROM ALL_TAB_PRIVS
   WHERE TABLE_SCHEMA='ORG' AND TABLE_NAME='CONTACT_POINTS_V2'
     AND GRANTEE<>'ORG';
  v_db_blockers := CASE WHEN v_v2<>1 OR v_v2_archive<>0 THEN 1 ELSE 0 END
                 + CASE WHEN v_oucp<>1 OR v_old_master<>0 OR v_old_archive<>1 THEN 1 ELSE 0 END
                 + CASE WHEN v_fk<>0 THEN 1 ELSE 0 END
                 + CASE WHEN v_stored<>0 OR v_synonyms<>0 OR v_triggers<>0 THEN 1 ELSE 0 END
                 + CASE WHEN v_source<>0 OR v_jobs<>0 OR v_programs<>0 THEN 1 ELSE 0 END;
  v_data_review := CASE WHEN v_v2_cols<>2 OR v_oucp_cols<>4 THEN 1 ELSE 0 END
                 + CASE WHEN v_v2_orphan>0 OR v_v2_native>0 THEN 1 ELSE 0 END
                 + CASE WHEN v_grants>0 THEN 1 ELSE 0 END;
  DBMS_OUTPUT.PUT_LINE('TABLES | V2_ACTIVE='||v_v2||' | V2_ARCHIVED='||v_v2_archive
     ||' | OUCP_ACTIVE='||v_oucp||' | OLD_MASTER='||v_old_master
     ||' | OLD_ARCHIVED='||v_old_archive);
  DBMS_OUTPUT.PUT_LINE('DATA | V2_ROWS='||v_v2_rows||' | OUCP_ROWS='||v_oucp_rows
     ||' | V2_HISTORICAL_LINKS='||v_v2_historic||' | V2_NATIVE='||v_v2_native
     ||' | V2_ORPHAN_LINKS='||v_v2_orphan
     ||' | OUCP_WITHOUT_V2_LINK='||v_oucp_no_v2);
  DBMS_OUTPUT.PUT_LINE('IDENTITY | V2_OBJECT_ID='||v_v2_object_id
     ||' | V2_KEY_COLUMNS='||v_v2_cols||'/2'
     ||' | OUCP_KEY_COLUMNS='||v_oucp_cols||'/4');
  DBMS_OUTPUT.PUT_LINE('DB_REFERENCES | INBOUND_FK='||v_fk||' | STORED='||v_stored
     ||' | SYNONYMS='||v_synonyms||' | TRIGGERS='||v_triggers
     ||' | SOURCE_LINES='||v_source||' | JOBS='||v_jobs
     ||' | SCHEDULER_PROGRAMS='||v_programs||' | GRANTS='||v_grants);
  DBMS_OUTPUT.PUT_LINE('ASSESSMENT | DB_BLOCKER_CATEGORIES='||v_db_blockers
     ||' | DATA_OR_GRANT_REVIEW_CATEGORIES='||v_data_review);
  DBMS_OUTPUT.PUT_LINE('IMPORTANT | OUCP_WITHOUT_V2_LINK is expected after legitimate canonical writes and is not a blocker.');
  DBMS_OUTPUT.PUT_LINE('IMPORTANT | Source/runtime API and external-consumer approval require separate evidence.');
  DBMS_OUTPUT.PUT_LINE('ORG_R5C4_DB_AUDIT_COMPLETE | READ_ONLY=YES | NO DDL | NO DML | NO COMMIT');
  DBMS_OUTPUT.PUT_LINE('STOP | DO NOT RENAME CONTACT_POINTS_V2 BASED ON DB AUDIT ALONE');
EXCEPTION
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('ORG_R5C4_DB_AUDIT_FAILED | '||SQLCODE||' | '||SUBSTR(SQLERRM,1,300));
    RAISE;
END;
