-- R5-C5 post-rename verification. READ-ONLY; no DDL/DML/COMMIT.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET DEFINE OFF
PROMPT ================================================================
PROMPT ORG R5-C5 V2 RENAME VERIFY - READ ONLY
PROMPT ================================================================
DECLARE
  v_old NUMBER; v_arch NUMBER; v_oucp NUMBER; v_old_archive NUMBER;
  v_rows NUMBER := -1; v_unit_rows NUMBER := -1; v_obj NUMBER := -1;
  v_historical NUMBER := -1; v_native NUMBER := -1;
  v_fk NUMBER; v_dep NUMBER; v_synonyms NUMBER; v_grants NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_old FROM ALL_TABLES
   WHERE OWNER='ORG' AND TABLE_NAME='CONTACT_POINTS_V2';
  SELECT COUNT(*) INTO v_arch FROM ALL_TABLES
   WHERE OWNER='ORG' AND TABLE_NAME='DEPRECATED_CONTACT_POINTS_V2';
  SELECT COUNT(*) INTO v_oucp FROM ALL_TABLES
   WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_CONTACT_POINTS';
  SELECT COUNT(*) INTO v_old_archive FROM ALL_TABLES
   WHERE OWNER='ORG' AND TABLE_NAME='DEPRECATED_CONTACT_POINTS';
  IF v_arch=1 THEN
    EXECUTE IMMEDIATE 'SELECT COUNT(*),COUNT(LEGACY_ASSOCIATION_ID) '
      ||'FROM ORG.DEPRECATED_CONTACT_POINTS_V2' INTO v_rows,v_historical;
    v_native:=v_rows-v_historical;
    SELECT OBJECT_ID INTO v_obj FROM ALL_OBJECTS
     WHERE OWNER='ORG' AND OBJECT_NAME='DEPRECATED_CONTACT_POINTS_V2' AND OBJECT_TYPE='TABLE';
  END IF;
  IF v_oucp=1 THEN
    SELECT COUNT(*) INTO v_unit_rows FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS;
  END IF;
  SELECT COUNT(*) INTO v_fk FROM ALL_CONSTRAINTS fk JOIN ALL_CONSTRAINTS pk
   ON pk.OWNER=fk.R_OWNER AND pk.CONSTRAINT_NAME=fk.R_CONSTRAINT_NAME
   WHERE fk.CONSTRAINT_TYPE='R' AND pk.OWNER='ORG'
     AND pk.TABLE_NAME='DEPRECATED_CONTACT_POINTS_V2';
  SELECT COUNT(*) INTO v_dep FROM ALL_DEPENDENCIES
   WHERE REFERENCED_OWNER='ORG' AND REFERENCED_NAME='DEPRECATED_CONTACT_POINTS_V2'
    AND TYPE<>'SYNONYM';
  SELECT COUNT(*) INTO v_synonyms FROM ALL_SYNONYMS
   WHERE TABLE_OWNER='ORG' AND TABLE_NAME='DEPRECATED_CONTACT_POINTS_V2';
  SELECT COUNT(*) INTO v_grants FROM ALL_TAB_PRIVS
   WHERE TABLE_SCHEMA='ORG' AND TABLE_NAME='DEPRECATED_CONTACT_POINTS_V2' AND GRANTEE<>'ORG';
  DBMS_OUTPUT.PUT_LINE('NAMES | V2_ACTIVE='||v_old||' | V2_ARCHIVED='||v_arch||
    ' | OUCP_ACTIVE='||v_oucp||' | ORIGINAL_ARCHIVED='||v_old_archive);
  DBMS_OUTPUT.PUT_LINE('ROWS | V2_ARCHIVED='||v_rows||' | HISTORICAL='||v_historical||
    ' | NATIVE='||v_native||' | OUCP='||v_unit_rows||' | V2_OBJECT_ID='||v_obj);
  DBMS_OUTPUT.PUT_LINE('DEPENDENCIES | INBOUND_FK='||v_fk||' | STORED='||v_dep||
    ' | SYNONYMS='||v_synonyms||' | GRANTS='||v_grants);
  IF v_old<>0 OR v_arch<>1 OR v_oucp<>1 OR v_old_archive<>1
     OR v_rows<>6930 OR v_historical<>6930 OR v_native<>0
     OR v_unit_rows<6930 OR v_obj<>121823 OR v_fk<>0 OR v_dep<>0 OR v_synonyms<>0 OR v_grants<>0 THEN
    RAISE_APPLICATION_ERROR(-20947, 'R5-C5 V2 archive verify failed.');
  END IF;
  DBMS_OUTPUT.PUT_LINE('ORG_R5C5_V2_RENAME_VERIFY_PASS | NO DDL | NO DML | NO COMMIT');
EXCEPTION
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('ORG_R5C5_V2_RENAME_VERIFY_FAILED | '||SQLCODE);
    RAISE;
END;
/
PROMPT === POST RENAME TABLE INVENTORY ===
SELECT OBJECT_NAME AS TABLE_NAME,OBJECT_ID FROM ALL_OBJECTS WHERE OWNER='ORG' AND OBJECT_TYPE='TABLE'
 AND OBJECT_NAME IN ('CONTACT_POINTS_V2','DEPRECATED_CONTACT_POINTS_V2',
  'DEPRECATED_CONTACT_POINTS','ORGANIZATION_UNIT_CONTACT_POINTS') ORDER BY OBJECT_NAME;
