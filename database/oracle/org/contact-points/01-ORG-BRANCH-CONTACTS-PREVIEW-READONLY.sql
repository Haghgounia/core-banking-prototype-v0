-- ORG contact model baseline - strictly read only.
-- Run as a user with SELECT access to ORG. Does not require privileged catalog access.
-- A CIF query is OPTIONAL, aggregate-only, and catches insufficient privileges.
-- CONTACT_POINT_ID equality to CIF.CONTACT_POINT is NOT a validated ownership mapping.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET VERIFY OFF
SET FEEDBACK ON
SET PAGESIZE 200
SET LINESIZE 230
COLUMN CHECK_ITEM FORMAT A60
COLUMN TYPE_CODE FORMAT A28
COLUMN NAME_FA FORMAT A44
COLUMN ROLE_CODE FORMAT A30
COLUMN TABLE_NAME FORMAT A38
COLUMN COLUMN_NAME FORMAT A28
COLUMN OWNER FORMAT A12

PROMPT === ORG CONTACT R0: BASELINE COUNTS (READ ONLY) ===
SELECT '01_CONTACT_ROLES' CHECK_ITEM, COUNT(*) EXACT_COUNT FROM ORG.CONTACT_ROLES
UNION ALL
SELECT '02_ORGANIZATION_UNITS', COUNT(*) FROM ORG.ORGANIZATION_UNITS
UNION ALL
SELECT '03_UNIT_CONTACT_ASSIGNMENT_ROWS', COUNT(*) FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS
UNION ALL
SELECT '04_UNITS_WITH_CONTACT_ASSIGNMENTS', COUNT(DISTINCT ORGANIZATION_UNIT_ID) FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS
UNION ALL
SELECT '05_DISTINCT_CONTACT_POINT_IDS', COUNT(DISTINCT CONTACT_POINT_ID) FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS
UNION ALL
SELECT '06_SERVICE_POINT_CONTACT_ROWS', COUNT(*) FROM ORG.SERVICE_POINT_CONTACT_POINTS
UNION ALL
SELECT '07_CONTACT_ROLES_REFERENCED', COUNT(DISTINCT CONTACT_ROLE_ID) FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS
UNION ALL
SELECT '08_UNIT_CONTACT_ASSIGNMENTS_PRIMARY_FLAG_1', COUNT(*) FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS WHERE PRIMARY_FLAG=1
UNION ALL
SELECT '09_CONTACT_ASSIGNMENTS_CURRENT', COUNT(*) FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS WHERE (EFFECTIVE_FROM IS NULL OR EFFECTIVE_FROM<=SYSDATE) AND (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO>=SYSDATE)
UNION ALL
SELECT '10_CONTACT_ASSIGNMENTS_INVALID_DATES', COUNT(*) FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS WHERE EFFECTIVE_FROM>EFFECTIVE_TO
UNION ALL
SELECT '11_MULTIPLE_CURRENT_PRIMARY_PER_UNIT_AND_ROLE', COUNT(*) FROM (
  SELECT ORGANIZATION_UNIT_ID, CONTACT_ROLE_ID
  FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS
  WHERE PRIMARY_FLAG=1
    AND (EFFECTIVE_FROM IS NULL OR EFFECTIVE_FROM<=SYSDATE)
    AND (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO>=SYSDATE)
  GROUP BY ORGANIZATION_UNIT_ID, CONTACT_ROLE_ID HAVING COUNT(*)>1
)
UNION ALL
SELECT '12_DUPLICATE_UNIT_CONTACT_ROLE_CURRENT_GROUPS', COUNT(*) FROM (
  SELECT ORGANIZATION_UNIT_ID, CONTACT_POINT_ID, CONTACT_ROLE_ID
  FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS
  WHERE (EFFECTIVE_FROM IS NULL OR EFFECTIVE_FROM<=SYSDATE)
    AND (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO>=SYSDATE)
  GROUP BY ORGANIZATION_UNIT_ID, CONTACT_POINT_ID, CONTACT_ROLE_ID HAVING COUNT(*)>1
)
UNION ALL
SELECT '13_SHARED_CONTACT_IDS_ACROSS_UNITS', COUNT(*) FROM (
  SELECT CONTACT_POINT_ID FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS
  GROUP BY CONTACT_POINT_ID HAVING COUNT(DISTINCT ORGANIZATION_UNIT_ID)>1
)
UNION ALL
SELECT '14_ORG_CONTACT_ID_FK_COLUMNS', COUNT(*) FROM ALL_CONS_COLUMNS cc
  JOIN ALL_CONSTRAINTS c ON c.OWNER=cc.OWNER AND c.CONSTRAINT_NAME=cc.CONSTRAINT_NAME
  WHERE cc.OWNER='ORG' AND cc.TABLE_NAME IN ('ORGANIZATION_UNIT_CONTACT_POINTS','SERVICE_POINT_CONTACT_POINTS')
    AND cc.COLUMN_NAME='CONTACT_POINT_ID' AND c.CONSTRAINT_TYPE='R'
ORDER BY CHECK_ITEM;

PROMPT === ORG CONTACT R0: CONTACT ROLES AND USAGE ===
SELECT R.CONTACT_ROLE_ID, R.ROLE_CODE, R.NAME_FA, R.ACTIVE_FLAG,
       COUNT(C.ORGANIZATION_UNIT_CONTACT_POINT_ID) UNIT_ASSIGNMENTS,
       COUNT(DISTINCT C.ORGANIZATION_UNIT_ID) DISTINCT_UNITS
FROM ORG.CONTACT_ROLES R
LEFT JOIN ORG.ORGANIZATION_UNIT_CONTACT_POINTS C ON C.CONTACT_ROLE_ID=R.CONTACT_ROLE_ID
GROUP BY R.CONTACT_ROLE_ID, R.ROLE_CODE, R.NAME_FA, R.ACTIVE_FLAG
ORDER BY R.ROLE_CODE;

PROMPT === ORG CONTACT R0: CONTACT COVERAGE BY UNIT TYPE ===
SELECT T.ORGANIZATION_UNIT_TYPE_ID, T.TYPE_CODE, T.NAME_FA,
       COUNT(DISTINCT U.ORGANIZATION_UNIT_ID) ALL_UNITS,
       COUNT(DISTINCT C.ORGANIZATION_UNIT_ID) UNITS_WITH_CONTACTS,
       COUNT(C.ORGANIZATION_UNIT_CONTACT_POINT_ID) CONTACT_ASSIGNMENTS
FROM ORG.ORGANIZATION_UNIT_TYPES T
LEFT JOIN ORG.ORGANIZATION_UNITS U ON U.ORGANIZATION_UNIT_TYPE_ID=T.ORGANIZATION_UNIT_TYPE_ID
LEFT JOIN ORG.ORGANIZATION_UNIT_CONTACT_POINTS C ON C.ORGANIZATION_UNIT_ID=U.ORGANIZATION_UNIT_ID
GROUP BY T.ORGANIZATION_UNIT_TYPE_ID, T.TYPE_CODE, T.NAME_FA
ORDER BY T.TYPE_CODE;

PROMPT === ORG CONTACT R0: CANDIDATE CONTACT ID OWNERS BY METADATA (NO DATA VALUES) ===
SELECT C.OWNER, C.TABLE_NAME, C.COLUMN_NAME, C.DATA_TYPE, C.DATA_PRECISION
FROM ALL_TAB_COLUMNS C
WHERE C.COLUMN_NAME='CONTACT_POINT_ID' AND C.OWNER IN ('ORG','CIF')
ORDER BY C.OWNER,C.TABLE_NAME;

PROMPT === ORG CONTACT R0: ACTUAL ORG CONTACT ID FOREIGN KEYS (EMPTY EXPECTED FROM DDL) ===
SELECT C.OWNER, C.TABLE_NAME, CC.COLUMN_NAME, C.CONSTRAINT_NAME,
       C.R_OWNER AS REFERENCED_OWNER, RC.TABLE_NAME AS REFERENCED_TABLE
FROM ALL_CONSTRAINTS C
JOIN ALL_CONS_COLUMNS CC ON CC.OWNER=C.OWNER AND CC.CONSTRAINT_NAME=C.CONSTRAINT_NAME
LEFT JOIN ALL_CONSTRAINTS RC ON RC.OWNER=C.R_OWNER AND RC.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
WHERE C.OWNER='ORG' AND C.TABLE_NAME IN ('ORGANIZATION_UNIT_CONTACT_POINTS','SERVICE_POINT_CONTACT_POINTS')
  AND C.CONSTRAINT_TYPE='R' AND CC.COLUMN_NAME='CONTACT_POINT_ID'
ORDER BY C.TABLE_NAME;

PROMPT === ORG CONTACT R0: CIF ID MATCH CHECK IS DIAGNOSTIC ONLY, NOT AN OWNERSHIP DECISION ===
DECLARE
  V_CIF_TABLES NUMBER;
  V_MATCHED NUMBER;
BEGIN
  SELECT COUNT(*) INTO V_CIF_TABLES FROM ALL_TABLES WHERE OWNER='CIF' AND TABLE_NAME='CONTACT_POINT';
  IF V_CIF_TABLES=0 THEN
    DBMS_OUTPUT.PUT_LINE('CIF_CONTACT_POINT_NOT_VISIBLE. DO NOT ASSUME ORG CONTACT ID SOURCE.');
  ELSE
    BEGIN
      EXECUTE IMMEDIATE
        'SELECT COUNT(*) FROM (SELECT DISTINCT CONTACT_POINT_ID FROM ORG.ORGANIZATION_UNIT_CONTACT_POINTS) ORGCP JOIN CIF.CONTACT_POINT CIFCP ON CIFCP.CONTACT_POINT_ID=ORGCP.CONTACT_POINT_ID'
        INTO V_MATCHED;
      DBMS_OUTPUT.PUT_LINE('MATCHED_DISTINCT_IDS_IN_CIF='||V_MATCHED||'; ID MATCH IS NOT PROOF OF OWNER OR VALID ASSOCIATION.');
    EXCEPTION WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('CIF_CONTACT_POINT_SELECT_NOT_AVAILABLE: '||SQLCODE);
    END;
  END IF;
END;
