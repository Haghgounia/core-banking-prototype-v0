PROMPT === REQUIRED COLUMN CONTRACT (expected all rows ACTUAL = 1) ===
SELECT 'CANONICAL_COLUMN_NUMBER8_NOT_NULL' CHECK_NAME, COUNT(*) ACTUAL, 1 EXPECTED
  FROM ALL_TAB_COLUMNS WHERE OWNER='ORG' AND TABLE_NAME='SERVICE_POINTS'
    AND COLUMN_NAME='ORGANIZATION_UNIT_LOCATION_ID' AND DATA_TYPE='NUMBER'
    AND DATA_PRECISION=8 AND DATA_SCALE=0 AND NULLABLE='N'
UNION ALL SELECT 'LEGACY_LOCATION_OPTIONAL', COUNT(*),1
  FROM ALL_TAB_COLUMNS WHERE OWNER='ORG' AND TABLE_NAME='SERVICE_POINTS'
   AND COLUMN_NAME='LOCATION_ID' AND NULLABLE='Y'
UNION ALL SELECT 'LEGACY_WRITES_BLOCKED', COUNT(*),1
  FROM ALL_CONSTRAINTS WHERE OWNER='ORG' AND TABLE_NAME='SERVICE_POINTS'
    AND CONSTRAINT_NAME='CK_SP_R4_NO_LEGACY' AND STATUS='ENABLED' AND VALIDATED='VALIDATED'
UNION ALL SELECT 'CANONICAL_INDEX', COUNT(*),1
  FROM ALL_IND_COLUMNS WHERE INDEX_OWNER='ORG' AND INDEX_NAME='IX_SP_R4_CANON_LOC'
    AND TABLE_NAME='SERVICE_POINTS' AND COLUMN_NAME='ORGANIZATION_UNIT_LOCATION_ID' AND COLUMN_POSITION=1
ORDER BY CHECK_NAME;
PROMPT === FK TO CANONICAL: 1; FK TO LEGACY: 0 ===
SELECT P.TABLE_NAME PARENT_TABLE, C.CONSTRAINT_NAME, C.STATUS, C.VALIDATED
  FROM ALL_CONSTRAINTS C JOIN ALL_CONSTRAINTS P
    ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
 WHERE C.OWNER='ORG' AND C.TABLE_NAME='SERVICE_POINTS' AND C.CONSTRAINT_TYPE='R'
   AND P.OWNER='ORG' AND P.TABLE_NAME IN ('LOCATIONS','ORGANIZATION_UNIT_LOCATIONS')
ORDER BY P.TABLE_NAME;
PROMPT === SERVICE POINT DATA PRESERVATION ===
SELECT COUNT(*) SERVICE_POINT_ROWS,
       NVL(SUM(CASE WHEN LOCATION_ID IS NOT NULL THEN 1 ELSE 0 END),0) LEGACY_LINKS,
       NVL(SUM(CASE WHEN ORGANIZATION_UNIT_LOCATION_ID IS NULL THEN 1 ELSE 0 END),0) MISSING_CANONICAL_IDS
  FROM ORG.SERVICE_POINTS;
