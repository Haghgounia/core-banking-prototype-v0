SELECT TABLE_NAME FROM ALL_TABLES WHERE OWNER='ORG' AND TABLE_NAME IN
  ('LOCATIONS','POSTAL_ADDRESSES','DEPRECATED_LOCATIONS','DEPRECATED_POSTAL_ADDRESSES')
