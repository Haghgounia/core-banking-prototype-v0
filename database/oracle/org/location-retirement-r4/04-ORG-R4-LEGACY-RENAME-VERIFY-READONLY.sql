SET SERVEROUTPUT ON SIZE UNLIMITED
PROMPT === R4-B ORIGINAL NAMES (EXPECTED 0) AND ARCHIVE NAMES (EXPECTED 1) ===
SELECT 'ORIGINAL_LOCATIONS' CHECK_NAME,COUNT(*) ACTUAL,0 EXPECTED FROM ALL_TABLES
 WHERE OWNER='ORG' AND TABLE_NAME='LOCATIONS'
UNION ALL SELECT 'ORIGINAL_POSTAL_ADDRESSES',COUNT(*),0 FROM ALL_TABLES
 WHERE OWNER='ORG' AND TABLE_NAME='POSTAL_ADDRESSES'
UNION ALL SELECT 'DEPRECATED_LOCATIONS',COUNT(*),1 FROM ALL_TABLES
 WHERE OWNER='ORG' AND TABLE_NAME='DEPRECATED_LOCATIONS'
UNION ALL SELECT 'DEPRECATED_POSTAL_ADDRESSES',COUNT(*),1 FROM ALL_TABLES
 WHERE OWNER='ORG' AND TABLE_NAME='DEPRECATED_POSTAL_ADDRESSES'
ORDER BY CHECK_NAME;
PROMPT === THE ONLY REMAINING LEGACY FK: DEPRECATED_POSTAL_ADDRESSES TO DEPRECATED_LOCATIONS ===
SELECT C.OWNER CHILD_OWNER,C.TABLE_NAME CHILD_TABLE,C.CONSTRAINT_NAME,
       C.STATUS,C.VALIDATED,P.TABLE_NAME PARENT_TABLE
  FROM ALL_CONSTRAINTS C JOIN ALL_CONSTRAINTS P
    ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
 WHERE P.OWNER='ORG' AND P.TABLE_NAME IN ('DEPRECATED_LOCATIONS','DEPRECATED_POSTAL_ADDRESSES')
   AND C.CONSTRAINT_TYPE='R'
ORDER BY C.OWNER,C.TABLE_NAME;
PROMPT === CANONICAL SERVICE POINT FK ===
SELECT C.TABLE_NAME,C.CONSTRAINT_NAME,C.STATUS,C.VALIDATED,P.TABLE_NAME PARENT_TABLE
  FROM ALL_CONSTRAINTS C JOIN ALL_CONSTRAINTS P
    ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
 WHERE C.OWNER='ORG' AND C.TABLE_NAME='SERVICE_POINTS' AND C.CONSTRAINT_TYPE='R'
   AND P.OWNER='ORG' AND P.TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS';
PROMPT === CANONICAL UNIT LOCATION ROWS (HISTORICAL IDS STILL PRESENT) ===
SELECT COUNT(*) UNIT_LOCATION_ROWS,
       NVL(SUM(CASE WHEN LEGACY_BACKFILL_FLAG=1 THEN 1 ELSE 0 END),0) BACKFILLED_ROWS,
       NVL(SUM(CASE WHEN LOCATION_ID IS NOT NULL THEN 1 ELSE 0 END),0) HISTORICAL_LOCATION_ID_ROWS
 FROM ORG.ORGANIZATION_UNIT_LOCATIONS;
