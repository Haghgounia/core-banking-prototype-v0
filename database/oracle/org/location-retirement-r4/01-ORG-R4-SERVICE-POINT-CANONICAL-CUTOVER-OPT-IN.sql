-- ORG R4-A / 2026-10-31. Oracle SQL Developer F5.
-- Canonical-only SERVICE_POINTS location: ORG.ORGANIZATION_UNIT_LOCATIONS.
-- Safeguards: PREVIEW by default, zero-row service points only, no DML, no legacy data edits.
-- Independent/unhosted service-point geography is NOT silently mapped to an ORG unit.
-- Existing locations and postal addresses are NEVER renamed in this phase.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET VERIFY OFF
DEFINE APPLY_CHANGES = NO
PROMPT ================================================================
PROMPT ORG R4-A SERVICE POINT CANONICAL LOCATION CUTOVER
PROMPT NO by default; DBA approval, maintenance, and application stop required.
PROMPT ================================================================
DECLARE
  v_apply VARCHAR2(3) := UPPER(TRIM('&&APPLY_CHANGES'));
  v_pos_rows NUMBER := 0;
  v_legacy_rows NUMBER := 0;
  v_unit_rows NUMBER := 0;
  v_legacy_unit_fk NUMBER := 0;
  v_legacy_fk NUMBER := 0;
  v_named_legacy_fk NUMBER := 0;
  v_canonical_fk NUMBER := 0;
  v_named_canonical_fk NUMBER := 0;
  v_can_col NUMBER := 0;
  v_can_nullable NUMBER := 0;
  v_old_nullable NUMBER := 0;
  v_new_col_type NUMBER := 0;
  v_r3_ready NUMBER := 0;
  v_check_count NUMBER := 0;
  v_check_good NUMBER := 0;
  v_index_count NUMBER := 0;
  v_index_good NUMBER := 0;
  v_legacy_sources NUMBER := 0;
  v_blockers NUMBER := 0;
  v_ddl NUMBER := 0;
  v_after_rows NUMBER := 0;
  PROCEDURE ddl(p_statement VARCHAR2, p_label VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_statement;
    v_ddl := v_ddl + 1;
    DBMS_OUTPUT.PUT_LINE('DDL_APPLIED | '||p_label);
  END;
  PROCEDURE load_metadata IS
  BEGIN
    SELECT COUNT(*) INTO v_can_col FROM ALL_TAB_COLUMNS
     WHERE OWNER='ORG' AND TABLE_NAME='SERVICE_POINTS' AND COLUMN_NAME='ORGANIZATION_UNIT_LOCATION_ID';
    SELECT COUNT(*) INTO v_new_col_type FROM ALL_TAB_COLUMNS
     WHERE OWNER='ORG' AND TABLE_NAME='SERVICE_POINTS' AND COLUMN_NAME='ORGANIZATION_UNIT_LOCATION_ID'
       AND DATA_TYPE='NUMBER' AND DATA_PRECISION=8 AND DATA_SCALE=0;
    SELECT COUNT(*) INTO v_can_nullable FROM ALL_TAB_COLUMNS
     WHERE OWNER='ORG' AND TABLE_NAME='SERVICE_POINTS' AND COLUMN_NAME='ORGANIZATION_UNIT_LOCATION_ID'
       AND NULLABLE='Y';
    SELECT COUNT(*) INTO v_old_nullable FROM ALL_TAB_COLUMNS
     WHERE OWNER='ORG' AND TABLE_NAME='SERVICE_POINTS' AND COLUMN_NAME='LOCATION_ID' AND NULLABLE='Y';
    SELECT COUNT(*) INTO v_legacy_fk FROM ALL_CONSTRAINTS C JOIN ALL_CONSTRAINTS P
      ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
     WHERE C.OWNER='ORG' AND C.TABLE_NAME='SERVICE_POINTS' AND C.CONSTRAINT_TYPE='R'
       AND P.OWNER='ORG' AND P.TABLE_NAME='LOCATIONS';
    SELECT COUNT(*) INTO v_named_legacy_fk FROM ALL_CONSTRAINTS C JOIN ALL_CONSTRAINTS P
      ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
     WHERE C.OWNER='ORG' AND C.TABLE_NAME='SERVICE_POINTS' AND C.CONSTRAINT_TYPE='R'
       AND C.CONSTRAINT_NAME='FK_POINTS_OF_SERVICE_LOCATION_ID'
       AND P.OWNER='ORG' AND P.TABLE_NAME='LOCATIONS';
    SELECT COUNT(*) INTO v_canonical_fk FROM ALL_CONSTRAINTS C JOIN ALL_CONSTRAINTS P
      ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
     WHERE C.OWNER='ORG' AND C.TABLE_NAME='SERVICE_POINTS' AND C.CONSTRAINT_TYPE='R'
       AND P.OWNER='ORG' AND P.TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS';
    SELECT COUNT(*) INTO v_named_canonical_fk FROM ALL_CONSTRAINTS C JOIN ALL_CONSTRAINTS P
      ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
     WHERE C.OWNER='ORG' AND C.TABLE_NAME='SERVICE_POINTS' AND C.CONSTRAINT_TYPE='R'
       AND C.CONSTRAINT_NAME='FK_SP_R4_CANONICAL_LOCATION'
       AND C.STATUS='ENABLED' AND C.VALIDATED='VALIDATED'
       AND P.OWNER='ORG' AND P.TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS';
    SELECT COUNT(*) INTO v_check_count FROM ALL_CONSTRAINTS
     WHERE OWNER='ORG' AND TABLE_NAME='SERVICE_POINTS' AND CONSTRAINT_NAME='CK_SP_R4_NO_LEGACY';
    SELECT COUNT(*) INTO v_check_good FROM ALL_CONSTRAINTS
     WHERE OWNER='ORG' AND TABLE_NAME='SERVICE_POINTS' AND CONSTRAINT_NAME='CK_SP_R4_NO_LEGACY'
       AND STATUS='ENABLED' AND VALIDATED='VALIDATED';
    SELECT COUNT(*) INTO v_index_count FROM ALL_INDEXES
     WHERE OWNER='ORG' AND INDEX_NAME='IX_SP_R4_CANON_LOC';
    SELECT COUNT(*) INTO v_index_good FROM ALL_IND_COLUMNS
     WHERE INDEX_OWNER='ORG' AND INDEX_NAME='IX_SP_R4_CANON_LOC'
       AND TABLE_OWNER='ORG' AND TABLE_NAME='SERVICE_POINTS'
       AND COLUMN_NAME='ORGANIZATION_UNIT_LOCATION_ID' AND COLUMN_POSITION=1;
  END;
BEGIN
  IF v_apply NOT IN ('YES','NO') THEN
    RAISE_APPLICATION_ERROR(-20931,'APPLY_CHANGES must be YES or NO');
  END IF;
  SELECT COUNT(*) INTO v_pos_rows FROM ORG.SERVICE_POINTS;
  SELECT COUNT(*) INTO v_legacy_rows FROM ORG.SERVICE_POINTS WHERE LOCATION_ID IS NOT NULL;
  SELECT COUNT(*) INTO v_unit_rows FROM ORG.ORGANIZATION_UNIT_LOCATIONS;
  SELECT COUNT(*) INTO v_legacy_sources FROM ORG.LOCATIONS;
  SELECT COUNT(*) INTO v_r3_ready FROM ALL_TAB_COLUMNS
   WHERE OWNER='ORG' AND TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS'
     AND COLUMN_NAME='LOCATION_ID' AND NULLABLE='Y';
  SELECT COUNT(*) INTO v_legacy_unit_fk FROM ALL_CONSTRAINTS C JOIN ALL_CONSTRAINTS P
    ON P.OWNER=C.R_OWNER AND P.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME
   WHERE C.OWNER='ORG' AND C.TABLE_NAME='ORGANIZATION_UNIT_LOCATIONS' AND C.CONSTRAINT_TYPE='R'
     AND P.OWNER='ORG' AND P.TABLE_NAME='LOCATIONS';
  load_metadata;
  IF v_pos_rows<>0 OR v_legacy_rows<>0 THEN v_blockers:=v_blockers+1; END IF;
  IF v_unit_rows=0 OR v_legacy_sources=0 OR v_r3_ready<>1 OR v_legacy_unit_fk<>0 THEN v_blockers:=v_blockers+1; END IF;
  IF v_legacy_fk<>v_named_legacy_fk OR v_legacy_fk>1 THEN v_blockers:=v_blockers+1; END IF;
  IF v_canonical_fk<>v_named_canonical_fk OR v_canonical_fk>1 THEN v_blockers:=v_blockers+1; END IF;
  IF v_can_col<>v_new_col_type OR v_can_col>1 THEN v_blockers:=v_blockers+1; END IF;
  IF v_check_count<>v_check_good OR v_check_count>1 THEN v_blockers:=v_blockers+1; END IF;
  IF v_index_count<>v_index_good OR v_index_count>1 THEN v_blockers:=v_blockers+1; END IF;
  DBMS_OUTPUT.PUT_LINE('APPLY_CHANGES='||v_apply||' | POINTS='||v_pos_rows||
    ' | LEGACY_LINKS='||v_legacy_rows||' | CANONICAL_UNIT_LOCATIONS='||v_unit_rows);
  DBMS_OUTPUT.PUT_LINE('SCHEMA | CANONICAL_COLUMN='||v_can_col||' | CANONICAL_NULLABLE='||v_can_nullable||
    ' | LEGACY_NULLABLE='||v_old_nullable||' | UNIT_R3_READY='||v_r3_ready);
  DBMS_OUTPUT.PUT_LINE('DEPENDENCIES | UNIT_TO_LEGACY_FK='||v_legacy_unit_fk||
    ' | SERVICE_POINT_TO_LEGACY_FK='||v_legacy_fk||' | SERVICE_POINT_TO_CANONICAL_FK='||v_canonical_fk);
  DBMS_OUTPUT.PUT_LINE('PRECHECK | BLOCKERS='||v_blockers||' | CHECK='||v_check_count||
    ' | INDEX='||v_index_count);
  IF v_apply='NO' THEN
    DBMS_OUTPUT.PUT_LINE('ORG_R4A_SERVICE_POINT_PREVIEW_COMPLETE | NO DDL | NO DML');
    RETURN;
  END IF;
  IF v_blockers<>0 THEN
    RAISE_APPLICATION_ERROR(-20932,'R4-A blocked. Inspect PRECHECK, ensure zero service-point rows and R3 completion.');
  END IF;
  IF v_can_col=0 THEN
    ddl('ALTER TABLE ORG.SERVICE_POINTS ADD (ORGANIZATION_UNIT_LOCATION_ID NUMBER(8,0))',
        'ADD_CANONICAL_LOCATION_ID');
  END IF;
  IF v_can_col=0 OR v_can_nullable=1 THEN
    ddl('ALTER TABLE ORG.SERVICE_POINTS MODIFY (ORGANIZATION_UNIT_LOCATION_ID NOT NULL)',
        'REQUIRE_CANONICAL_LOCATION_ID');
  END IF;
  IF v_old_nullable=0 THEN
    ddl('ALTER TABLE ORG.SERVICE_POINTS MODIFY (LOCATION_ID NULL)',
        'LEGACY_LOCATION_ID_OPTIONAL');
  END IF;
  IF v_index_count=0 THEN
    ddl('CREATE INDEX ORG.IX_SP_R4_CANON_LOC ON ORG.SERVICE_POINTS (ORGANIZATION_UNIT_LOCATION_ID)',
        'CANONICAL_FK_INDEX');
  END IF;
  IF v_canonical_fk=0 THEN
    ddl('ALTER TABLE ORG.SERVICE_POINTS ADD CONSTRAINT FK_SP_R4_CANONICAL_LOCATION '
      ||'FOREIGN KEY (ORGANIZATION_UNIT_LOCATION_ID) REFERENCES '
      ||'ORG.ORGANIZATION_UNIT_LOCATIONS (ORGANIZATION_UNIT_LOCATION_ID) ENABLE VALIDATE',
        'CANONICAL_LOCATION_FK');
  END IF;
  IF v_legacy_fk=1 THEN
    ddl('ALTER TABLE ORG.SERVICE_POINTS DROP CONSTRAINT FK_POINTS_OF_SERVICE_LOCATION_ID',
        'DETACH_LEGACY_LOCATION_FK');
  END IF;
  IF v_check_count=0 THEN
    ddl('ALTER TABLE ORG.SERVICE_POINTS ADD CONSTRAINT CK_SP_R4_NO_LEGACY '
      ||'CHECK (LOCATION_ID IS NULL) ENABLE VALIDATE',
        'PROHIBIT_NEW_LEGACY_LOCATION_LINKS');
  END IF;
  load_metadata;
  SELECT COUNT(*) INTO v_after_rows FROM ORG.SERVICE_POINTS;
  IF v_after_rows<>v_pos_rows OR v_can_col<>1 OR v_can_nullable<>0 OR v_old_nullable<>1
     OR v_legacy_fk<>0 OR v_named_canonical_fk<>1 OR v_check_good<>1 OR v_index_good<>1 THEN
    RAISE_APPLICATION_ERROR(-20933,'R4-A post verification failed; DDL implicitly committed. DBA investigation required.');
  END IF;
  DBMS_OUTPUT.PUT_LINE('POST_VERIFY | SERVICE_POINTS='||v_after_rows||
    ' | LEGACY_FK='||v_legacy_fk||' | CANONICAL_FK='||v_named_canonical_fk);
  DBMS_OUTPUT.PUT_LINE('ORG_R4A_SERVICE_POINT_CANONICAL_PASS | DDL_COUNT='||v_ddl||
    ' | NO DML | NO LEGACY TABLE RENAMES');
END;
