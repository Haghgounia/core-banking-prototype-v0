-- IAM-R1.5.1 physical baseline verification (SQL*Plus / SQLcl).
-- READ-ONLY METADATA ONLY. NO DDL, NO DML, NO COMMIT.
-- ALL_* reports only objects visible to the executing Oracle user.
-- Failure to see objects is not proof of absence; validate permissions with DBA.
SET PAGESIZE 100
SET LINESIZE 180
SET FEEDBACK ON
PROMPT IAM_R1_5_1_A_VISIBLE_COUNTS
SELECT 'TABLES' AS OBJECT_TYPE, COUNT(*) AS VISIBLE_COUNT
  FROM ALL_TABLES WHERE OWNER = 'IAM'
UNION ALL
SELECT 'COLUMNS', COUNT(*) FROM ALL_TAB_COLUMNS WHERE OWNER = 'IAM'
UNION ALL
SELECT 'SEQUENCES', COUNT(*) FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER = 'IAM'
UNION ALL
SELECT 'PRIMARY_KEYS', COUNT(*) FROM ALL_CONSTRAINTS WHERE OWNER = 'IAM' AND CONSTRAINT_TYPE = 'P'
UNION ALL
SELECT 'FOREIGN_KEYS', COUNT(*) FROM ALL_CONSTRAINTS WHERE OWNER = 'IAM' AND CONSTRAINT_TYPE = 'R'
UNION ALL
SELECT 'UNIQUE_CONSTRAINTS', COUNT(*) FROM ALL_CONSTRAINTS WHERE OWNER = 'IAM' AND CONSTRAINT_TYPE = 'U'
UNION ALL
SELECT 'CHECK_CONSTRAINTS', COUNT(*) FROM ALL_CONSTRAINTS WHERE OWNER = 'IAM' AND CONSTRAINT_TYPE = 'C';

PROMPT IAM_R1_5_1_B_CRITICAL_COLUMNS
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_LENGTH, NULLABLE
  FROM ALL_TAB_COLUMNS
 WHERE OWNER = 'IAM'
   AND (
       (TABLE_NAME = 'USER_ACCOUNTS' AND COLUMN_NAME IN
           ('USER_ACCOUNT_ID', 'PRINCIPAL_ID', 'SECURITY_DOMAIN_ID', 'USERNAME', 'USERNAME_NORMALIZED', 'ACCOUNT_STATUS_CODE', 'IDENTITY_CONTEXT_CODE'))
    OR (TABLE_NAME = 'PRINCIPALS' AND COLUMN_NAME IN ('PRINCIPAL_ID', 'PRINCIPAL_UID', 'IDENTITY_CONTEXT_CODE'))
    OR (TABLE_NAME = 'IDENTITY_PROVIDERS' AND COLUMN_NAME IN ('NAME_FA','NAME_EN'))
    OR (TABLE_NAME = 'IDENTITY_LINKS' AND COLUMN_NAME IN ('VERIFIED_AT','VERIFIED_BY_PRINCIPAL_ID','EVIDENCE_REFERENCE'))
    OR (TABLE_NAME = 'FEDERATED_IDENTITIES' AND COLUMN_NAME IN ('VERIFIED_AT','LINKED_BY_PRINCIPAL_ID','LINK_EVIDENCE_REFERENCE'))
   )
 ORDER BY TABLE_NAME, COLUMN_NAME;

PROMPT IAM_R1_5_1_C_CRITICAL_UNIQUENESS
SELECT TABLE_NAME, CONSTRAINT_NAME, STATUS, VALIDATED
  FROM ALL_CONSTRAINTS
 WHERE OWNER = 'IAM'
   AND TABLE_NAME IN ('USER_ACCOUNTS','IDENTITY_LINKS','FEDERATED_IDENTITIES')
   AND CONSTRAINT_TYPE IN ('U','P')
 ORDER BY TABLE_NAME, CONSTRAINT_NAME;

PROMPT IAM_R1_5_1_D_SEQUENCE_CONFIGURATION
SELECT SEQUENCE_NAME, CACHE_SIZE, ORDER_FLAG
  FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER = 'IAM'
 ORDER BY SEQUENCE_NAME;

