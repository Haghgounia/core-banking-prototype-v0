-- ---------------------------------------------------------------------------
-- 3) NORMALIZATION FUNCTION
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION GEO.FN_NORMALIZE_NAME (
    P_NAME IN VARCHAR2
) RETURN VARCHAR2 DETERMINISTIC IS
    V_NAME VARCHAR2(4000);
BEGIN
    V_NAME := TRIM(P_NAME);
    V_NAME := REPLACE(V_NAME, 'ي', 'ی');
    V_NAME := REPLACE(V_NAME, 'ى', 'ی');
    V_NAME := REPLACE(V_NAME, 'ك', 'ک');
    V_NAME := REPLACE(V_NAME, 'ة', 'ه');
    V_NAME := REPLACE(V_NAME, 'ۀ', 'ه');
    V_NAME := REPLACE(V_NAME, UNISTR('\200C'), ' ');
    V_NAME := REPLACE(V_NAME, 'ـ', '');
    V_NAME := REGEXP_REPLACE(V_NAME, '[[:space:]]+', ' ');
    RETURN TRIM(V_NAME);
END;
