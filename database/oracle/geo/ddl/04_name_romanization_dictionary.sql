-- ---------------------------------------------------------------------------
-- 5) AUTO-FILL VIEW
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW GEO.V_NAME_ROMANIZATION_AUTOFILL AS
SELECT
    NAME_ROMANIZATION_ID,
    PERSIAN_NAME,
    NORMALIZED_PERSIAN_NAME,
    COALESCE(CANONICAL_ENGLISH_NAME, SUGGESTED_ENGLISH_NAME) AS ENGLISH_NAME,
    CONFIDENCE_SCORE,
    ROMANIZATION_METHOD_CODE,
    GOVERNANCE_STATUS_CODE,
    SOURCE_CODE
FROM GEO.NAME_ROMANIZATION_DICTIONARY
WHERE IS_ACTIVE = 1
  AND AUTO_FILL_ALLOWED = 1;

-- ---------------------------------------------------------------------------
-- 6) DATABASE RESOLVER PACKAGE
-- ---------------------------------------------------------------------------
CREATE OR REPLACE PACKAGE GEO.PKG_NAME_ROMANIZATION AS
    PROCEDURE RESOLVE_NAME(
        P_PERSIAN_NAME       IN  VARCHAR2,
        O_NORMALIZED_NAME    OUT VARCHAR2,
        O_ENGLISH_NAME       OUT VARCHAR2,
        O_METHOD_CODE        OUT VARCHAR2,
        O_CONFIDENCE_SCORE   OUT NUMBER,
        O_AUTO_FILL_ALLOWED  OUT NUMBER,
        O_REQUIRES_REVIEW    OUT NUMBER
    );
END PKG_NAME_ROMANIZATION;
/

CREATE OR REPLACE PACKAGE BODY GEO.PKG_NAME_ROMANIZATION AS
    PROCEDURE RESOLVE_NAME(
        P_PERSIAN_NAME       IN  VARCHAR2,
        O_NORMALIZED_NAME    OUT VARCHAR2,
        O_ENGLISH_NAME       OUT VARCHAR2,
        O_METHOD_CODE        OUT VARCHAR2,
        O_CONFIDENCE_SCORE   OUT NUMBER,
        O_AUTO_FILL_ALLOWED  OUT NUMBER,
        O_REQUIRES_REVIEW    OUT NUMBER
    ) IS
        V_CORE       VARCHAR2(4000);
        V_CORE_EN    VARCHAR2(500);
        V_CORE_CONF  NUMBER;
    BEGIN
        O_NORMALIZED_NAME := GEO.FN_NORMALIZE_NAME(P_PERSIAN_NAME);

        -- A) Exact dictionary match has first priority.
        BEGIN
            SELECT
                COALESCE(CANONICAL_ENGLISH_NAME, SUGGESTED_ENGLISH_NAME),
                ROMANIZATION_METHOD_CODE,
                CONFIDENCE_SCORE,
                AUTO_FILL_ALLOWED
            INTO
                O_ENGLISH_NAME,
                O_METHOD_CODE,
                O_CONFIDENCE_SCORE,
                O_AUTO_FILL_ALLOWED
            FROM GEO.NAME_ROMANIZATION_DICTIONARY
            WHERE NORMALIZED_PERSIAN_NAME = O_NORMALIZED_NAME
              AND IS_ACTIVE = 1;

            O_REQUIRES_REVIEW := CASE WHEN O_AUTO_FILL_ALLOWED = 1 THEN 0 ELSE 1 END;
            RETURN;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN NULL;
        END;

        -- B) Prefix composition. Auto-fill is allowed only for an affix rule
        --    explicitly approved for automatic application.
        FOR R IN (
            SELECT PERSIAN_AFFIX, ENGLISH_AFFIX, CONTEXT_SENSITIVE, AUTO_APPLY_ALLOWED
            FROM GEO.NAME_AFFIX_DICTIONARY
            WHERE RECORD_STATUS_CODE = 'ACTIVE'
              AND POSITION_CODE IN ('PREFIX','ANY')
            ORDER BY PRIORITY_NO
        ) LOOP
            IF O_NORMALIZED_NAME LIKE R.PERSIAN_AFFIX || ' %' THEN
                V_CORE := TRIM(SUBSTR(O_NORMALIZED_NAME, LENGTH(R.PERSIAN_AFFIX) + 1));
            ELSIF SUBSTR(O_NORMALIZED_NAME, 1, LENGTH(R.PERSIAN_AFFIX)) = R.PERSIAN_AFFIX
               AND LENGTH(O_NORMALIZED_NAME) > LENGTH(R.PERSIAN_AFFIX) THEN
                V_CORE := TRIM(SUBSTR(O_NORMALIZED_NAME, LENGTH(R.PERSIAN_AFFIX) + 1));
            ELSE
                V_CORE := NULL;
            END IF;

            IF V_CORE IS NOT NULL THEN
                BEGIN
                    SELECT
                        COALESCE(CANONICAL_ENGLISH_NAME, SUGGESTED_ENGLISH_NAME),
                        CONFIDENCE_SCORE
                    INTO V_CORE_EN, V_CORE_CONF
                    FROM GEO.NAME_ROMANIZATION_DICTIONARY
                    WHERE NORMALIZED_PERSIAN_NAME = V_CORE
                      AND IS_ACTIVE = 1
                      AND AUTO_FILL_ALLOWED = 1;

                    O_ENGLISH_NAME := R.ENGLISH_AFFIX || ' ' || V_CORE_EN;
                    O_METHOD_CODE := 'AFFIX_PREFIX_COMPOSITION';
                    O_CONFIDENCE_SCORE := LEAST(
                        V_CORE_CONF,
                        CASE WHEN R.CONTEXT_SENSITIVE = 0 THEN 0.95 ELSE 0.85 END
                    );
                    O_AUTO_FILL_ALLOWED := CASE WHEN R.AUTO_APPLY_ALLOWED = 1 THEN 1 ELSE 0 END;
                    O_REQUIRES_REVIEW := CASE WHEN O_AUTO_FILL_ALLOWED = 1 THEN 0 ELSE 1 END;
                    RETURN;
                EXCEPTION
                    WHEN NO_DATA_FOUND THEN NULL;
                END;
            END IF;
        END LOOP;

        -- C) Suffix composition. Context-sensitive suffixes remain review-only.
        FOR R IN (
            SELECT PERSIAN_AFFIX, ENGLISH_AFFIX, CONTEXT_SENSITIVE, AUTO_APPLY_ALLOWED
            FROM GEO.NAME_AFFIX_DICTIONARY
            WHERE RECORD_STATUS_CODE = 'ACTIVE'
              AND POSITION_CODE IN ('SUFFIX','ANY')
            ORDER BY PRIORITY_NO
        ) LOOP
            IF O_NORMALIZED_NAME LIKE '% ' || R.PERSIAN_AFFIX THEN
                V_CORE := TRIM(
                    SUBSTR(
                        O_NORMALIZED_NAME,
                        1,
                        LENGTH(O_NORMALIZED_NAME) - LENGTH(R.PERSIAN_AFFIX)
                    )
                );

                BEGIN
                    SELECT
                        COALESCE(CANONICAL_ENGLISH_NAME, SUGGESTED_ENGLISH_NAME),
                        CONFIDENCE_SCORE
                    INTO V_CORE_EN, V_CORE_CONF
                    FROM GEO.NAME_ROMANIZATION_DICTIONARY
                    WHERE NORMALIZED_PERSIAN_NAME = V_CORE
                      AND IS_ACTIVE = 1
                      AND AUTO_FILL_ALLOWED = 1;

                    O_ENGLISH_NAME := V_CORE_EN || ' ' || R.ENGLISH_AFFIX;
                    O_METHOD_CODE := 'AFFIX_SUFFIX_COMPOSITION';
                    O_CONFIDENCE_SCORE := LEAST(
                        V_CORE_CONF,
                        CASE WHEN R.CONTEXT_SENSITIVE = 0 THEN 0.95 ELSE 0.85 END
                    );
                    O_AUTO_FILL_ALLOWED := CASE WHEN R.AUTO_APPLY_ALLOWED = 1 THEN 1 ELSE 0 END;
                    O_REQUIRES_REVIEW := CASE WHEN O_AUTO_FILL_ALLOWED = 1 THEN 0 ELSE 1 END;
                    RETURN;
                EXCEPTION
                    WHEN NO_DATA_FOUND THEN NULL;
                END;
            END IF;
        END LOOP;

        O_ENGLISH_NAME := NULL;
        O_METHOD_CODE := 'NOT_RESOLVED';
        O_CONFIDENCE_SCORE := 0;
        O_AUTO_FILL_ALLOWED := 0;
        O_REQUIRES_REVIEW := 1;
    END RESOLVE_NAME;
END PKG_NAME_ROMANIZATION;
/

-- ---------------------------------------------------------------------------
-- 7) SIMPLE FUNCTION WRAPPER FOR APPLICATION/SQL USE
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION GEO.FN_ROMANIZE_NAME (
    P_PERSIAN_NAME IN VARCHAR2
) RETURN VARCHAR2 IS
    V_NORMALIZED       VARCHAR2(4000);
    V_ENGLISH          VARCHAR2(500);
    V_METHOD           VARCHAR2(50);
    V_CONFIDENCE       NUMBER;
    V_AUTO_FILL        NUMBER;
    V_REQUIRES_REVIEW  NUMBER;
BEGIN
    GEO.PKG_NAME_ROMANIZATION.RESOLVE_NAME(
        P_PERSIAN_NAME       => P_PERSIAN_NAME,
        O_NORMALIZED_NAME    => V_NORMALIZED,
        O_ENGLISH_NAME       => V_ENGLISH,
        O_METHOD_CODE        => V_METHOD,
        O_CONFIDENCE_SCORE   => V_CONFIDENCE,
        O_AUTO_FILL_ALLOWED  => V_AUTO_FILL,
        O_REQUIRES_REVIEW    => V_REQUIRES_REVIEW
    );

    IF V_AUTO_FILL = 1 THEN
        RETURN V_ENGLISH;
    END IF;

    RETURN NULL;
END FN_ROMANIZE_NAME;
