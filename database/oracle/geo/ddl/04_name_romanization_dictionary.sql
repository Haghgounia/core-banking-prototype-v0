CREATE SEQUENCE GEO.SEQ_NAME_ROMANIZATION_DICT
    START WITH 1 INCREMENT BY 1 CACHE 1000 NOCYCLE;

CREATE TABLE GEO.NAME_ROMANIZATION_DICTIONARY (
    NAME_ROMANIZATION_ID          NUMBER(19) DEFAULT GEO.SEQ_NAME_ROMANIZATION_DICT.NEXTVAL NOT NULL,
    PERSIAN_NAME                  VARCHAR2(400 CHAR) NOT NULL,
    NORMALIZED_PERSIAN_NAME       VARCHAR2(400 CHAR) NOT NULL,
    CANONICAL_ENGLISH_NAME        VARCHAR2(500 CHAR),
    SUGGESTED_ENGLISH_NAME        VARCHAR2(500 CHAR) NOT NULL,
    ENTRY_TYPE_CODE               VARCHAR2(40 CHAR) DEFAULT 'NAME' NOT NULL,
    ROMANIZATION_METHOD_CODE      VARCHAR2(50 CHAR) NOT NULL,
    GOVERNANCE_STATUS_CODE        VARCHAR2(50 CHAR) NOT NULL,
    CONFIDENCE_SCORE              NUMBER(5,4) DEFAULT 0 NOT NULL,
    AUTO_FILL_ALLOWED             NUMBER(1) DEFAULT 0 NOT NULL,
    IS_ACTIVE                     NUMBER(1) DEFAULT 1 NOT NULL,
    SOURCE_CODE                   VARCHAR2(500 CHAR),
    SOURCE_EVIDENCE_COUNT         NUMBER(12) DEFAULT 0 NOT NULL,
    D3_COUNT                      NUMBER(12) DEFAULT 0 NOT NULL,
    D4_COUNT                      NUMBER(12) DEFAULT 0 NOT NULL,
    D5_COUNT                      NUMBER(12) DEFAULT 0 NOT NULL,
    QUALITY_FLAGS                 VARCHAR2(1000 CHAR),
    DETECTED_COMPONENTS           VARCHAR2(1000 CHAR),
    UNRESOLVED_COMPONENTS         VARCHAR2(1000 CHAR),
    CREATED_AT                    TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY                    VARCHAR2(200 CHAR) DEFAULT 'NAME_ROMANIZATION_SEED' NOT NULL,
    UPDATED_AT                    TIMESTAMP(6),
    UPDATED_BY                    VARCHAR2(200 CHAR),
    RECORD_VERSION                NUMBER(10) DEFAULT 1 NOT NULL,

    CONSTRAINT PK_NAME_ROMANIZATION_DICT
        PRIMARY KEY (NAME_ROMANIZATION_ID),
    CONSTRAINT UK_NAME_ROMANIZATION_NORM
        UNIQUE (NORMALIZED_PERSIAN_NAME),
    CONSTRAINT CK_NAME_ROM_CONF
        CHECK (CONFIDENCE_SCORE BETWEEN 0 AND 1),
    CONSTRAINT CK_NAME_ROM_AUTO
        CHECK (AUTO_FILL_ALLOWED IN (0,1)),
    CONSTRAINT CK_NAME_ROM_ACTIVE
        CHECK (IS_ACTIVE IN (0,1))
);

CREATE INDEX GEO.IX_NAME_ROM_ENGLISH
    ON GEO.NAME_ROMANIZATION_DICTIONARY (CANONICAL_ENGLISH_NAME);

CREATE INDEX GEO.IX_NAME_ROM_STATUS
    ON GEO.NAME_ROMANIZATION_DICTIONARY
       (GOVERNANCE_STATUS_CODE, AUTO_FILL_ALLOWED, IS_ACTIVE);

CREATE INDEX GEO.IX_NAME_ROM_PERSIAN
    ON GEO.NAME_ROMANIZATION_DICTIONARY (PERSIAN_NAME);

COMMENT ON TABLE GEO.NAME_ROMANIZATION_DICTIONARY IS
'Governed Persian-name Romanization dictionary used for English-name suggestion and controlled auto-fill.';

COMMENT ON COLUMN GEO.NAME_ROMANIZATION_DICTIONARY.CANONICAL_ENGLISH_NAME IS
'Governed canonical Romanized name. An official identity-document spelling for a customer has precedence.';

COMMENT ON COLUMN GEO.NAME_ROMANIZATION_DICTIONARY.SUGGESTED_ENGLISH_NAME IS
'Candidate Romanized spelling. Generated or review-required values are not automatically authoritative.';

COMMENT ON COLUMN GEO.NAME_ROMANIZATION_DICTIONARY.AUTO_FILL_ALLOWED IS
'1 means the entry is approved for automatic form population; 0 means suggestion/review only.';

