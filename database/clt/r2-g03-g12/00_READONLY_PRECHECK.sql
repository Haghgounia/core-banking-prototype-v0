-- CLT R2 G-03/G-12: read-only physical readiness, no DDL or DML.
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, NULLABLE
  FROM ALL_TAB_COLUMNS
 WHERE OWNER='CLT' AND (
       (TABLE_NAME='COLLATERAL_TYPE' AND COLUMN_NAME IN ('HAS_MULTIPLICITY','IS_COUNTABLE_FLAG'))
    OR (TABLE_NAME IN ('CLT_INTRODUCTION_DRAFT_SERIAL_RANGE','CLT_COLLATERAL_SERIAL_RANGE')))
 ORDER BY TABLE_NAME,COLUMN_ID;
-- If the new column does not appear, the G-12 extension is still unapplied.
