-- G-03: immutable, normalized range rows belonging to an immutable staged draft.
-- No mutable final collateral or registration number is generated by this schema.
CREATE TABLE CLT.CLT_INTRODUCTION_DRAFT_SERIAL_RANGE (
  DRAFT_ID          NUMBER(19,0) NOT NULL,
  ROW_NO            NUMBER(3,0)  NOT NULL,
  SERIAL_FROM       VARCHAR2(100 CHAR) NOT NULL,
  SERIAL_TO         VARCHAR2(100 CHAR) NOT NULL,
  TOTAL_AMOUNT_IRR  NUMBER(16,0) NOT NULL,
  CREATED_AT        TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY        VARCHAR2(100 CHAR) NOT NULL,
  RECORD_VERSION    NUMBER(10,0) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_CLT_DRAFT_SERIAL_RANGE PRIMARY KEY (DRAFT_ID, ROW_NO),
  CONSTRAINT FK_CLT_DRAFT_SERIAL_RANGE FOREIGN KEY (DRAFT_ID)
    REFERENCES CLT.CLT_INTRODUCTION_DRAFT (DRAFT_ID),
  CONSTRAINT CK_CLT_DRAFT_RANGE_ROW CHECK (ROW_NO BETWEEN 1 AND 80),
  CONSTRAINT CK_CLT_DRAFT_RANGE_FROM CHECK (REGEXP_LIKE(SERIAL_FROM, '^[0-9]{1,100}$')),
  CONSTRAINT CK_CLT_DRAFT_RANGE_TO CHECK (REGEXP_LIKE(SERIAL_TO, '^[0-9]{1,100}$')),
  CONSTRAINT CK_CLT_DRAFT_RANGE_AMOUNT CHECK (TOTAL_AMOUNT_IRR > 0),
  CONSTRAINT CK_CLT_DRAFT_RANGE_VERSION CHECK (RECORD_VERSION >= 1)
);
-- Only the application service can issue normalized, non-overlapping, <=20 item rows;
-- these checks are repeated in Java and verified against JSON snapshot on readback.
CREATE INDEX CLT.IX_CLT_DRAFT_RANGE_DRAFT ON CLT.CLT_INTRODUCTION_DRAFT_SERIAL_RANGE (DRAFT_ID, SERIAL_FROM);

