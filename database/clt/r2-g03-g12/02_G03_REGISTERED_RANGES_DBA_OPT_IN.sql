-- CLT G-03 registered-asset range table, PROPOSED EXTENSION ONLY.
-- Do NOT apply before final registration design G-14/G-17 and migration approval.
-- No implementation in this delivery writes to this table.
SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
CREATE TABLE CLT.CLT_COLLATERAL_SERIAL_RANGE (
  COLLATERAL_ID     NUMBER(19,0) NOT NULL,
  ROW_NO            NUMBER(3,0) NOT NULL,
  SERIAL_FROM       VARCHAR2(100 CHAR) NOT NULL,
  SERIAL_TO         VARCHAR2(100 CHAR) NOT NULL,
  TOTAL_AMOUNT_IRR  NUMBER(16,0) NOT NULL,
  CREATED_AT        TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY        VARCHAR2(100 CHAR) NOT NULL,
  UPDATED_AT        TIMESTAMP(6),
  UPDATED_BY        VARCHAR2(100 CHAR),
  RECORD_VERSION    NUMBER(10,0) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_CLT_COLL_SERIAL_RANGE PRIMARY KEY (COLLATERAL_ID, ROW_NO),
  CONSTRAINT FK_CLT_COLL_SERIAL_RANGE FOREIGN KEY (COLLATERAL_ID)
    REFERENCES CLT.COLLATERAL (COLLATERAL_ID),
  CONSTRAINT CK_CLT_COLL_RANGE_ROW CHECK (ROW_NO BETWEEN 1 AND 80),
  CONSTRAINT CK_CLT_COLL_RANGE_FROM CHECK (REGEXP_LIKE(SERIAL_FROM, '^[0-9]{1,100}$')),
  CONSTRAINT CK_CLT_COLL_RANGE_TO CHECK (REGEXP_LIKE(SERIAL_TO, '^[0-9]{1,100}$')),
  CONSTRAINT CK_CLT_COLL_RANGE_AMOUNT CHECK (TOTAL_AMOUNT_IRR > 0),
  CONSTRAINT CK_CLT_COLL_RANGE_VERSION CHECK (RECORD_VERSION >= 1),
  CONSTRAINT CK_CLT_COLL_RANGE_UPDATED_PAIR CHECK (
    (UPDATED_AT IS NULL AND UPDATED_BY IS NULL) OR
    (UPDATED_AT IS NOT NULL AND UPDATED_BY IS NOT NULL))
);
CREATE INDEX CLT.IX_CLT_COLL_RANGE_SERIAL ON CLT.CLT_COLLATERAL_SERIAL_RANGE(COLLATERAL_ID, SERIAL_FROM);
