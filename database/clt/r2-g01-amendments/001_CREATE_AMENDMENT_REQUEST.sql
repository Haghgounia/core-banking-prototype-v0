-- CLT R2 / G-01: forward-only proposed Oracle extension.
-- Run ONCE as the authorized schema migration, separately from source install.
-- Never drops/recreates existing CLT tables or changes their constraints.
-- Prerequisite: CLT.COLLATERAL is present. This is not an amendment to the EA XML itself.
CREATE SEQUENCE CLT.SEQ_CLT_COLLATERAL_AMENDMENT START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE CLT.CLT_COLLATERAL_AMENDMENT (
  AMENDMENT_ID NUMBER(19,0) NOT NULL,
  COLLATERAL_ID NUMBER(19,0) NOT NULL,
  BRANCH_CODE VARCHAR2(30 CHAR) NOT NULL,
  MAKER_SUBJECT VARCHAR2(100 CHAR) NOT NULL,
  BASE_RECORD_VERSION NUMBER(10,0) NOT NULL,
  BEFORE_JSON CLOB NOT NULL,
  AFTER_JSON CLOB NOT NULL,
  CHANGES_JSON CLOB NOT NULL,
  REQUEST_HASH VARCHAR2(64 CHAR) NOT NULL,
  REQUEST_REASON VARCHAR2(500 CHAR) NOT NULL,
  IDEMPOTENCY_KEY VARCHAR2(100 CHAR) NOT NULL,
  CORRELATION_ID VARCHAR2(100 CHAR),
  STATUS VARCHAR2(20 CHAR) DEFAULT 'PENDING_REVIEW' NOT NULL,
  CHECKER_SUBJECT VARCHAR2(100 CHAR),
  DECISION_REASON VARCHAR2(500 CHAR),
  DECISION_KEY VARCHAR2(100 CHAR),
  DECIDED_AT TIMESTAMP(6),
  APPLIED_RECORD_VERSION NUMBER(10,0),
  CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  RECORD_VERSION NUMBER(10,0) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_CLT_COLLATERAL_AMENDMENT PRIMARY KEY (AMENDMENT_ID),
  CONSTRAINT FK_CLT_AMEND_COLLATERAL FOREIGN KEY (COLLATERAL_ID)
    REFERENCES CLT.COLLATERAL (COLLATERAL_ID),
  CONSTRAINT UQ_CLT_AMEND_IDEMP UNIQUE (MAKER_SUBJECT, BRANCH_CODE, IDEMPOTENCY_KEY),
  CONSTRAINT CK_CLT_AMEND_STATUS CHECK (STATUS IN ('PENDING_REVIEW','APPROVED','REJECTED')),
  CONSTRAINT CK_CLT_AMEND_BASE_VER CHECK (BASE_RECORD_VERSION >= 1),
  CONSTRAINT CK_CLT_AMEND_VERSION CHECK (RECORD_VERSION >= 1),
  CONSTRAINT CK_CLT_AMEND_BEFORE_JSON CHECK (BEFORE_JSON IS JSON),
  CONSTRAINT CK_CLT_AMEND_AFTER_JSON CHECK (AFTER_JSON IS JSON),
  CONSTRAINT CK_CLT_AMEND_CHANGES_JSON CHECK (CHANGES_JSON IS JSON),
  CONSTRAINT CK_CLT_AMEND_DECISION_PAIR CHECK
    ((STATUS = 'PENDING_REVIEW' AND CHECKER_SUBJECT IS NULL AND DECIDED_AT IS NULL
       AND DECISION_KEY IS NULL AND APPLIED_RECORD_VERSION IS NULL)
      OR (STATUS = 'REJECTED' AND CHECKER_SUBJECT IS NOT NULL AND DECIDED_AT IS NOT NULL
       AND DECISION_KEY IS NOT NULL AND APPLIED_RECORD_VERSION IS NULL)
      OR (STATUS = 'APPROVED' AND CHECKER_SUBJECT IS NOT NULL AND DECIDED_AT IS NOT NULL
       AND DECISION_KEY IS NOT NULL AND APPLIED_RECORD_VERSION IS NOT NULL))
);

-- A collateral can have only ONE pending proposal; historical decisions remain append-only.
CREATE UNIQUE INDEX CLT.UX_CLT_AMEND_PENDING ON CLT.CLT_COLLATERAL_AMENDMENT
  (CASE WHEN STATUS = 'PENDING_REVIEW' THEN COLLATERAL_ID ELSE NULL END);
CREATE INDEX CLT.IX_CLT_AMEND_COLLATERAL ON CLT.CLT_COLLATERAL_AMENDMENT (COLLATERAL_ID, CREATED_AT);

CREATE TABLE CLT.CLT_COLLATERAL_AMENDMENT_AUDIT (
  AUDIT_ID NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  AMENDMENT_ID NUMBER(19,0) NOT NULL,
  EVENT_CODE VARCHAR2(30 CHAR) NOT NULL,
  EVENT_SUBJECT VARCHAR2(100 CHAR) NOT NULL,
  CORRELATION_ID VARCHAR2(100 CHAR),
  REQUEST_HASH VARCHAR2(64 CHAR) NOT NULL,
  EVENT_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_CLT_AMENDMENT_AUDIT PRIMARY KEY (AUDIT_ID),
  CONSTRAINT FK_CLT_AMENDMENT_AUDIT FOREIGN KEY (AMENDMENT_ID)
     REFERENCES CLT.CLT_COLLATERAL_AMENDMENT (AMENDMENT_ID),
  CONSTRAINT CK_CLT_AMEND_AUDIT_EVENT CHECK (EVENT_CODE IN ('AMENDMENT_SUBMITTED','AMENDMENT_APPROVED','AMENDMENT_REJECTED'))
);
CREATE INDEX CLT.IX_CLT_AMEND_AUDIT ON CLT.CLT_COLLATERAL_AMENDMENT_AUDIT (AMENDMENT_ID, EVENT_AT);

-- No DML, no DELETE, no backfill; never execute automatically by the patch installer.
